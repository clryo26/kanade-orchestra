// Shared audio output manager (window.PortalAudioLib.outputManager).
//
// Design 4 (docs/METRONOME_DESIGN.md#output): one owner of the output
// AudioContext per page, shared by the metronome and the tuner
// (getPageManager). Consumers never get a reference they could close; they
// get a lease with its own bus (GainNode), generation and permit stream.
//
// Rules:
// - The AudioContext is created and resumed synchronously inside the user's
//   tap (unlockFromGesture) — iOS Safari only starts audio there.
// - Leases are exclusive by default; a second consumer gets OUTPUT_BUSY
//   instead of silently stopping the first one. Concurrent output needs the
//   explicit page-level choice setConcurrentAllowed(true).
// - Gain budget: master MASTER_LIMIT (0.25, tuning value). Each consumer
//   keeps its own peak <= 1 at its bus input; with n concurrent leases every
//   bus is scaled to 1/n, so the sum stays within the master budget. The
//   tuner's former absolute 0.25 limit is the same number (not relaxed).
// - Cross-tab: one tab of this origin plays at a time.
//   * Web Locks: exclusive "portal-audio-output", requested with ifAvailable
//     when a consumer prepares (never awaited inside the tap). A lock granted
//     after the request was withdrawn (leave / hidden) is released at once.
//   * Without Web Locks: IndexedDB "portalAudioControl" (store "claim",
//     keys: the claim record, a monotonic counter, stop acknowledgements).
//     Takeover of an unresponsive tab needs the user's confirmation and is a
//     compare-and-set against the exact owner / generation / heartbeat that
//     was shown. The new owner may sound only after the old tab acknowledged
//     its stop, or after the old tab's last recorded permit expired (plus a
//     drain margin) AND that tab reported a verified time guard. A fixed wait
//     alone is never enough (data design 3.1).
// - Output permits are issued only while the ownership is verified (for
//   IndexedDB: after the record update committed). A permit carries a
//   sequence number, the claim generation and a wall-clock expiry; the
//   backends refuse to sound without a current permit. Losing the claim, or
//   the context leaving "running" (the frame clock stops while suspended),
//   revokes every permit, so an old tab or a resumed context cannot bring
//   back scheduled clicks.
(function (globalObj) {
    'use strict';

    var AUDIO_RELEASE_ID = 'a-bab6e0cd35e7'; // audio-release-id (generated by scripts/generate_metronome_release.mjs)
    var MASTER_LIMIT = 0.25;
    var LOCK_NAME = 'portal-audio-output';
    var CLAIM_DB = 'portalAudioControl';
    var COUNTER_KEY = 'counter';
    // Tuning values (design 15, data design 3.1).
    var HEARTBEAT_MS = 2000;
    var STALE_MS = 15000;
    var PERMIT_MS = 2000;
    var PERMIT_RENEW_MS = 500;
    var DRAIN_MS = 250;
    var IDLE_RELEASE_MS = 60000;
    var TAKEOVER_WAIT_MS = 4000; // how long a takeover request waits before reporting "still waiting"

    function randomId() {
        var c = globalObj.crypto;
        if (c && typeof c.randomUUID === 'function') return c.randomUUID();
        return 'tab-' + Date.now().toString(36) + '-' + Math.floor(Math.random() * 1e9).toString(36);
    }

    // ----- claim via Web Locks -------------------------------------------------

    function createLockClaim(env) {
        var locks = env.locks;
        var held = null; // { release(), generation }
        var requestEpoch = 0;
        var pending = null;
        var localGeneration = 0;

        function acquire() {
            if (held) return Promise.resolve({ ok: true, held: true });
            if (pending) return pending;
            requestEpoch += 1;
            var epoch = requestEpoch;
            pending = new Promise(function (resolve) {
                var releaseLock;
                var holdPromise = new Promise(function (r) { releaseLock = r; });
                var request;
                try {
                    request = locks.request(LOCK_NAME, { mode: 'exclusive', ifAvailable: true }, function (lock) {
                        if (!lock) {
                            resolve({ ok: false, reason: 'busy' });
                            return undefined;
                        }
                        if (epoch !== requestEpoch) {
                            // Withdrawn while waiting (leave / hidden): give it back at once.
                            resolve({ ok: false, reason: 'withdrawn' });
                            return undefined;
                        }
                        localGeneration += 1;
                        held = { release: releaseLock, generation: localGeneration };
                        resolve({ ok: true });
                        return holdPromise; // the lock is held until releaseLock()
                    });
                } catch (_) {
                    resolve({ ok: false, reason: 'unavailable' });
                    return;
                }
                if (request && typeof request.catch === 'function') request.catch(function () { resolve({ ok: false, reason: 'unavailable' }); });
            }).then(function (r) {
                pending = null;
                return r;
            });
            return pending;
        }

        function release() {
            requestEpoch += 1; // a grant arriving later is released by its callback
            if (held) {
                var h = held;
                held = null;
                h.release();
            }
        }

        return {
            kind: 'web-locks',
            acquire: acquire,
            release: release,
            isHeld: function () { return Boolean(held); },
            generation: function () { return held ? held.generation : 0; },
            // Holding the lock is the proof of ownership; the permit only
            // limits how long output continues if this page stops running.
            renew: function (expiresAtUtcMs) { return Promise.resolve(held ? { ok: true, claimGeneration: held.generation, expiresAtUtcMs: expiresAtUtcMs } : { ok: false, reason: 'not-held' }); },
            takeover: function () { return Promise.resolve({ ok: false, reason: 'not-supported' }); },
            verify: function () { return Promise.resolve({ ok: Boolean(held) }); },
            setGuard: function () {},
            dispose: release,
        };
    }

    // ----- claim via IndexedDB (fallback without Web Locks) ----------------------

    function createIdbClaim(env) {
        var factory = env.indexedDB;
        var tabId = env.tabId || randomId();
        var state = 'none'; // none | held | pending-owner
        var generation = 0;
        var previous = null; // the owner being taken over
        var heartbeat = null;
        var dbPromise = null;
        var guard = 'unverified';
        var lastPermitExpiry = 0;
        // Raised by release(): an acquire / takeover whose transaction commits
        // after the tab already gave the claim up removes its own record
        // instead of holding it (round 3, R-02; same rule as Web Locks).
        var requestEpoch = 0;

        function open() {
            if (dbPromise) return dbPromise;
            dbPromise = new Promise(function (resolve, reject) {
                var req = factory.open(CLAIM_DB, 1);
                req.onupgradeneeded = function () { req.result.createObjectStore('claim', { keyPath: 'name' }); };
                req.onsuccess = function () { resolve(req.result); };
                req.onerror = function () { dbPromise = null; reject(req.error); };
            });
            return dbPromise;
        }

        // One readwrite transaction over the claim record, the counter and
        // (optionally) an acknowledgement record. fn(records) -> { puts, deletes, result }.
        function transact(extraKeys, fn) {
            return open().then(function (db) {
                return new Promise(function (resolve, reject) {
                    var tx = db.transaction(['claim'], 'readwrite');
                    var store = tx.objectStore('claim');
                    var keys = [LOCK_NAME, COUNTER_KEY].concat(extraKeys || []);
                    var records = {};
                    var left = keys.length;
                    var result = null;
                    keys.forEach(function (k) {
                        var r = store.get(k);
                        r.onsuccess = function () {
                            records[k] = r.result || null;
                            left -= 1;
                            if (left === 0) {
                                var out = fn(records) || {};
                                (out.puts || []).forEach(function (rec) { store.put(rec); });
                                (out.deletes || []).forEach(function (key) { store.delete(key); });
                                result = out.result || null;
                            }
                        };
                    });
                    tx.oncomplete = function () { resolve(result); };
                    tx.onerror = function () { /* onabort reports */ };
                    tx.onabort = function () { reject(tx.error || new Error('claim-transaction-aborted')); };
                });
            });
        }

        function nextGeneration(records) {
            var c = records[COUNTER_KEY];
            var used = Math.max(c ? c.value : 0, records[LOCK_NAME] ? records[LOCK_NAME].claimGeneration : 0);
            return used + 1; // never reused, also after the claim record was deleted
        }

        // Returns a Promise that resolves when the output really stopped
        // (onLost may return one); it rejects when that cannot be confirmed.
        function lost(reason) {
            var wasMine = state !== 'none';
            state = 'none';
            stopBeat();
            if (!wasMine || typeof env.onLost !== 'function') return Promise.resolve();
            try {
                return Promise.resolve(env.onLost(reason));
            } catch (error) {
                return Promise.reject(error);
            }
        }

        function ackKey(id) {
            return 'ack:' + id;
        }

        // Periodic check of the record: heartbeat for the owner, readiness for
        // a pending owner, loss detection for a former owner.
        function beat() {
            if (state === 'none') return Promise.resolve(null);
            var t = env.now();
            var prevKey = previous ? [ackKey(previous.ownerTabId)] : [];
            var expected = generation;
            return transact(prevKey, function (records) {
                var rec = records[LOCK_NAME];
                if (!rec || rec.ownerTabId !== tabId || rec.claimGeneration !== expected) {
                    // Another tab owns the claim now: acknowledge the stop of our
                    // generation (after the consumers stopped, see onLost order).
                    return { result: { lost: true } };
                }
                var next = Object.assign({}, rec, { heartbeatAtUtcMs: t, guard: guard });
                var ready = false;
                if (rec.state === 'pending-owner' && previous) {
                    var ack = records[ackKey(previous.ownerTabId)];
                    var acked = Boolean(ack && ack.generation >= previous.claimGeneration);
                    var expired = previous.guard === 'verified' && t >= previous.lastPermitExpiresAtUtcMs + DRAIN_MS;
                    if (acked || expired) {
                        next.state = 'running';
                        ready = true;
                    }
                }
                return { puts: [next], result: { ok: true, ready: ready, state: next.state } };
            }).then(function (r) {
                if (!r) return null;
                if (r.lost) {
                    // The ack says "the old tab's sound has stopped", so it is
                    // written only after the stop completed (round 3, R-02):
                    // being told is not enough, the output must be silent.
                    // If that cannot be confirmed no ack is written and the new
                    // owner waits (verified guard + permit expiry, or nothing).
                    // The heartbeat itself reports the loss at once; the ack
                    // follows whenever the stop completes.
                    var oldGeneration = expected;
                    lost('taken-over').then(function () {
                        return transact([], function () { return { puts: [{ name: ackKey(tabId), generation: oldGeneration, at: env.now() }] }; });
                    }, function () { return null; }).catch(function () { return null; });
                    return { lost: true };
                }
                if (r.ready) {
                    state = 'held';
                    previous = null;
                    if (typeof env.onReady === 'function') env.onReady();
                }
                return r;
            }, function () {
                // A failed heartbeat must not keep permits alive (renew checks again).
                return { ok: false, reason: 'db-failed' };
            });
        }

        function startBeat() {
            stopBeat();
            heartbeat = env.setInterval(beat, HEARTBEAT_MS);
        }

        function stopBeat() {
            if (heartbeat !== null) env.clearInterval(heartbeat);
            heartbeat = null;
        }

        // Removes the record a late request wrote (only that generation).
        function dropLate(g) {
            return transact([], function (records) {
                var rec = records[LOCK_NAME];
                if (rec && rec.ownerTabId === tabId && rec.claimGeneration === g) return { deletes: [LOCK_NAME] };
                return null;
            }).catch(function () { /* stale detection covers it */ });
        }

        function acquire() {
            if (state === 'held') return Promise.resolve({ ok: true, held: true });
            if (state === 'pending-owner') return Promise.resolve({ ok: false, reason: 'pending-owner' });
            var epoch = requestEpoch;
            var t = env.now();
            return transact([], function (records) {
                var rec = records[LOCK_NAME];
                if (!rec || rec.ownerTabId === tabId) {
                    var g = nextGeneration(records);
                    return {
                        puts: [
                            { name: COUNTER_KEY, value: g },
                            { name: LOCK_NAME, ownerTabId: tabId, claimGeneration: g, state: 'running', heartbeatAtUtcMs: t, lastPermitExpiresAtUtcMs: 0, guard: guard },
                        ],
                        result: { ok: true, generation: g },
                    };
                }
                var observed = { ownerTabId: rec.ownerTabId, claimGeneration: rec.claimGeneration, heartbeatAtUtcMs: rec.heartbeatAtUtcMs, lastPermitExpiresAtUtcMs: rec.lastPermitExpiresAtUtcMs || 0, guard: rec.guard || 'unverified' };
                // A heartbeat in the future (clock change) counts as alive.
                if (t - rec.heartbeatAtUtcMs > STALE_MS) return { result: { ok: false, reason: 'stale', observed: observed } };
                return { result: { ok: false, reason: 'busy', observed: observed } };
            }).then(function (r) {
                if (r && r.ok && epoch !== requestEpoch) {
                    dropLate(r.generation);
                    return { ok: false, reason: 'released' };
                }
                if (r && r.ok) {
                    generation = r.generation;
                    state = 'held';
                    startBeat();
                }
                return r || { ok: false, reason: 'unavailable' };
            }, function () { return { ok: false, reason: 'unavailable' }; });
        }

        // Only after the user confirmed taking over the exact owner shown
        // (observed). Resolves { ok: true } when this tab may sound, or
        // { ok: false, reason } (changed / waiting-old-tab / unavailable).
        function takeover(observed) {
            if (!observed) return Promise.resolve({ ok: false, reason: 'no-observation' });
            var epoch = requestEpoch;
            var t = env.now();
            return transact([], function (records) {
                var rec = records[LOCK_NAME];
                if (!rec) {
                    var g0 = nextGeneration(records);
                    return { puts: [{ name: COUNTER_KEY, value: g0 }, { name: LOCK_NAME, ownerTabId: tabId, claimGeneration: g0, state: 'running', heartbeatAtUtcMs: t, lastPermitExpiresAtUtcMs: 0, guard: guard }], result: { ok: true, generation: g0, direct: true } };
                }
                var same = rec.ownerTabId === observed.ownerTabId && rec.claimGeneration === observed.claimGeneration && rec.heartbeatAtUtcMs === observed.heartbeatAtUtcMs;
                if (!same) return { result: { ok: false, reason: 'changed' } }; // the old owner came back or a third tab took it
                if (t - rec.heartbeatAtUtcMs <= STALE_MS) return { result: { ok: false, reason: 'changed' } };
                var g = nextGeneration(records);
                var prev = { ownerTabId: rec.ownerTabId, claimGeneration: rec.claimGeneration, lastPermitExpiresAtUtcMs: rec.lastPermitExpiresAtUtcMs || 0, guard: rec.guard || 'unverified' };
                return {
                    puts: [
                        { name: COUNTER_KEY, value: g },
                        { name: LOCK_NAME, ownerTabId: tabId, claimGeneration: g, state: 'pending-owner', heartbeatAtUtcMs: t, lastPermitExpiresAtUtcMs: 0, guard: guard, previous: prev },
                    ],
                    result: { ok: true, generation: g, previous: prev },
                };
            }).then(function (r) {
                if (!r || !r.ok) return r || { ok: false, reason: 'unavailable' };
                if (epoch !== requestEpoch) {
                    dropLate(r.generation);
                    return { ok: false, reason: 'released' };
                }
                generation = r.generation;
                if (r.direct) {
                    state = 'held';
                    startBeat();
                    return { ok: true };
                }
                state = 'pending-owner';
                previous = r.previous;
                startBeat();
                // Readiness is checked on every heartbeat; report back after a
                // bounded wait so the screen can say what it is waiting for.
                return new Promise(function (resolve) {
                    var deadline = env.now() + TAKEOVER_WAIT_MS;
                    var check = function () {
                        beat().then(function () {
                            if (state === 'held') resolve({ ok: true });
                            else if (state === 'none') resolve({ ok: false, reason: 'changed' });
                            else if (env.now() >= deadline) resolve({ ok: false, reason: previous && previous.guard === 'verified' ? 'waiting-old-permit' : 'waiting-old-tab' });
                            else env.setTimeout(check, PERMIT_RENEW_MS);
                        });
                    };
                    check();
                });
            }, function () { return { ok: false, reason: 'unavailable' }; });
        }

        // Permit renewal: written to the record first; the permit is handed
        // to the backends only after this transaction committed.
        function renew(expiresAtUtcMs) {
            if (state !== 'held') return Promise.resolve({ ok: false, reason: state === 'pending-owner' ? 'pending-owner' : 'not-held' });
            var expected = generation;
            return transact([], function (records) {
                var rec = records[LOCK_NAME];
                if (!rec || rec.ownerTabId !== tabId || rec.claimGeneration !== expected || rec.state !== 'running') return { result: { ok: false, reason: 'lost' } };
                return { puts: [Object.assign({}, rec, { lastPermitExpiresAtUtcMs: Math.max(rec.lastPermitExpiresAtUtcMs || 0, expiresAtUtcMs), heartbeatAtUtcMs: env.now(), guard: guard })], result: { ok: true } };
            }).then(function (r) {
                if (!r || !r.ok) {
                    if (r && r.reason === 'lost') beat();
                    return r || { ok: false, reason: 'lost' };
                }
                lastPermitExpiry = Math.max(lastPermitExpiry, expiresAtUtcMs);
                return { ok: true, claimGeneration: expected, expiresAtUtcMs: expiresAtUtcMs };
            }, function () { return { ok: false, reason: 'db-failed' }; });
        }

        function release() {
            requestEpoch += 1;
            var wasHeld = state !== 'none';
            var expected = generation;
            state = 'none';
            previous = null;
            stopBeat();
            if (!wasHeld) return;
            // Only our own generation is removed; the counter stays (no reuse).
            transact([], function (records) {
                var rec = records[LOCK_NAME];
                if (rec && rec.ownerTabId === tabId && rec.claimGeneration === expected) return { deletes: [LOCK_NAME] };
                return null;
            }).catch(function () { /* stale detection covers it */ });
        }

        return {
            kind: 'indexeddb',
            tabId: tabId,
            acquire: acquire,
            release: release,
            takeover: takeover,
            renew: renew,
            verify: function () {
                return beat().then(function (r) { return { ok: state === 'held' && !(r && r.lost) }; });
            },
            setGuard: function (g) { guard = g === 'verified' ? 'verified' : 'unverified'; },
            isHeld: function () { return state === 'held'; },
            isPending: function () { return state === 'pending-owner'; },
            generation: function () { return generation; },
            lastPermitExpiry: function () { return lastPermitExpiry; },
            dispose: release,
        };
    }

    function createNoClaim() {
        // No cross-tab coordination available: single-tab behaviour only,
        // reported as "uncoordinated" so the screen can say so.
        var held = false;
        return {
            kind: 'none',
            acquire: function () { held = true; return Promise.resolve({ ok: true, uncoordinated: true }); },
            release: function () { held = false; },
            takeover: function () { return Promise.resolve({ ok: false, reason: 'not-supported' }); },
            renew: function (expiresAtUtcMs) { return Promise.resolve(held ? { ok: true, claimGeneration: 1, expiresAtUtcMs: expiresAtUtcMs, uncoordinated: true } : { ok: false, reason: 'not-held' }); },
            verify: function () { return Promise.resolve({ ok: held }); },
            setGuard: function () {},
            isHeld: function () { return held; },
            generation: function () { return held ? 1 : 0; },
            dispose: function () { held = false; },
        };
    }

    // ----- manager -----------------------------------------------------------------

    // env: { AudioContext, locks, indexedDB, audioSession, now() (UTC ms),
    //        setTimeout, clearTimeout, setInterval, clearInterval,
    //        onLost(reason), onInterrupted(state), tabId? }
    function createOutputManager(env) {
        var ctx = null;
        var master = null;
        var lastState = null;
        var leases = {};
        var leaseSeq = 0;
        var outputEpoch = 0;
        var retained = {}; // consumer -> true while it is on its screen
        var listeners = { lost: [], interrupted: [], ready: [] };
        var permit = null; // { seq, claimGeneration, expiresAtUtcMs }
        var permitSeq = 0;
        var revokedSeq = 0;
        var renewTimer = null;
        var idleTimer = null;
        var concurrentAllowed = false;
        var silencing = false; // the context is being suspended because the claim was lost

        function fire(type, value) {
            listeners[type].slice().forEach(function (fn) { try { fn(value); } catch (_) { /* consumers never break the manager */ } });
        }

        var claimEnv = Object.assign({}, env, {
            // Resolves when the output is silent: every consumer's own stop
            // (onRevoke may return a Promise) and the shared context suspended
            // (the audio thread then renders nothing for it).
            onLost: function (reason) {
                var stops = revokeAll('claim-lost');
                if (typeof env.onLost === 'function') {
                    try { env.onLost(reason); } catch (_) { /* consumer */ }
                }
                fire('lost', reason);
                return Promise.all([stops, silenceOutput()]);
            },
            onReady: function () { fire('ready', null); },
        });
        var claim = env.locks && typeof env.locks.request === 'function'
            ? createLockClaim(claimEnv)
            : (env.indexedDB && typeof env.indexedDB.open === 'function' ? createIdbClaim(claimEnv) : createNoClaim());

        function setSession(type) {
            var s = env.audioSession;
            if (!s) return false;
            try {
                s.type = type;
                return true;
            } catch (_) {
                return false;
            }
        }

        // Every lease is told to stop; old permits can never be used again.
        // Returns a Promise of the consumers' stop completions.
        function revokeAll(reason) {
            revokedSeq = permitSeq;
            permit = null;
            var stops = [];
            Object.keys(leases).forEach(function (id) {
                var l = leases[id];
                if (typeof l.onRevoke === 'function') {
                    try {
                        stops.push(Promise.resolve(l.onRevoke(reason, revokedSeq)));
                    } catch (error) {
                        stops.push(Promise.reject(error));
                    }
                }
            });
            return Promise.all(stops);
        }

        // Claim lost: the master is muted at once and the context suspended;
        // the Promise resolves when the browser confirmed the suspension.
        // Without suspend() the stop cannot be confirmed (rejects). Playing
        // again needs a new tap (unlockFromGesture restores the master).
        function silenceOutput() {
            if (!ctx || ctx.state === 'closed') return Promise.resolve();
            silencing = true;
            try {
                master.gain.cancelScheduledValues(0);
            } catch (_) { /* not supported */ }
            master.gain.value = 0;
            if (typeof ctx.suspend !== 'function') return Promise.reject(new Error('suspend-unsupported'));
            try {
                return Promise.resolve(ctx.suspend());
            } catch (error) {
                return Promise.reject(error);
            }
        }

        function stopRenew() {
            if (renewTimer !== null) env.clearInterval(renewTimer);
            renewTimer = null;
        }

        // Permit renewal (every PERMIT_RENEW_MS while a lease exists).
        function renewPermit() {
            if (!Object.keys(leases).length) return Promise.resolve(null);
            if (!ctx || ctx.state !== 'running') return Promise.resolve(null);
            var expires = env.now() + PERMIT_MS;
            var floor = revokedSeq;
            return claim.renew(expires).then(function (r) {
                if (!r || !r.ok) {
                    if (permit) revokeAll(r && r.reason ? r.reason : 'not-held');
                    return null;
                }
                if (revokedSeq !== floor) return null; // revoked meanwhile: no late permit
                permitSeq += 1;
                permit = { seq: permitSeq, claimGeneration: r.claimGeneration, expiresAtUtcMs: r.expiresAtUtcMs, uncoordinated: Boolean(r.uncoordinated) };
                return permit;
            });
        }

        function startRenew() {
            if (renewTimer === null) renewTimer = env.setInterval(renewPermit, PERMIT_RENEW_MS);
        }

        function cancelIdle() {
            if (idleTimer !== null) env.clearTimeout(idleTimer);
            idleTimer = null;
        }

        // No lease for IDLE_RELEASE_MS: close the context and give the claim
        // back (another tab may then play). Paused / waiting consumers keep
        // their lease, so they are not idle.
        function scheduleIdle() {
            cancelIdle();
            if (Object.keys(leases).length) return;
            idleTimer = env.setTimeout(function () {
                idleTimer = null;
                if (!Object.keys(leases).length) closeContext(true);
            }, IDLE_RELEASE_MS);
        }

        function closeContext(releaseClaim) {
            stopRenew();
            permit = null;
            if (ctx) {
                var c = ctx;
                ctx = null;
                master = null;
                lastState = null;
                c.onstatechange = null;
                try {
                    var r = c.close();
                    if (r && typeof r.catch === 'function') r.catch(function () {});
                } catch (_) { /* already */ }
            }
            setSession('auto');
            if (releaseClaim) claim.release();
        }

        // Synchronous, inside the tap: create/resume before any await.
        function unlockFromGesture() {
            if (!ctx || ctx.state === 'closed') {
                if (typeof env.AudioContext !== 'function') return { ok: false, reason: 'unsupported' };
                try {
                    ctx = new env.AudioContext({ latencyHint: 'interactive' });
                } catch (_) {
                    ctx = null;
                    return { ok: false, reason: 'unsupported' };
                }
                master = ctx.createGain();
                master.gain.value = MASTER_LIMIT;
                master.connect(ctx.destination);
                outputEpoch += 1;
                lastState = ctx.state;
                var mine = ctx;
                ctx.onstatechange = function () {
                    if (ctx !== mine) return;
                    var before = lastState;
                    lastState = mine.state;
                    // Leaving "running": the frame clock stops, so frame-based
                    // permits would survive the pause. Everything is revoked;
                    // playing again needs a new tap (design 3 step 6).
                    if (before === 'running' && (mine.state === 'interrupted' || mine.state === 'suspended')) {
                        if (silencing) return; // suspended by the claim loss itself (already revoked and reported)
                        revokeAll('context-' + mine.state);
                        if (typeof env.onInterrupted === 'function') env.onInterrupted(mine.state);
                        fire('interrupted', mine.state);
                    }
                };
            }
            setSession('playback');
            if (silencing) {
                silencing = false;
                master.gain.value = MASTER_LIMIT;
            }
            try {
                var r = ctx.resume();
                if (r && typeof r.catch === 'function') r.catch(function () {});
            } catch (_) { /* reported by state */ }
            return { ok: true, context: ctx, outputEpoch: outputEpoch };
        }

        function others(consumer) {
            return Object.keys(leases).map(function (id) { return leases[id]; }).filter(function (l) { return l.consumer !== consumer; });
        }

        // The claim record may say "verified" only when every active lease has
        // a verified time guard (worklet); tuner tones and the main-thread
        // backend cannot silence themselves, so a takeover then needs the
        // old tab's stop acknowledgement.
        function updateGuard() {
            var list = Object.keys(leases).map(function (id) { return leases[id]; });
            claim.setGuard(list.length && list.every(function (l) { return l.guard === 'verified'; }) ? 'verified' : 'unverified');
        }

        function rebalance() {
            var list = Object.keys(leases).map(function (id) { return leases[id]; });
            var share = 1 / Math.max(1, list.length);
            list.forEach(function (l) {
                var v = share / l.voices;
                try { l.bus.gain.setTargetAtTime(v, ctx.currentTime, 0.005); } catch (_) { l.bus.gain.value = v; }
                l.share = share;
            });
        }

        // voices: maximum simultaneous voices of this consumer at peak 1.
        // options: { onRevoke(reason, seq), concurrent }
        function acquire(consumer, voices, options) {
            var o = options || {};
            if (!ctx || ctx.state === 'closed') return { ok: false, code: 'NO_CONTEXT' };
            var busy = others(consumer);
            if (busy.length && !(concurrentAllowed && o.concurrent && busy.every(function (l) { return l.concurrent; }))) return { ok: false, code: 'OUTPUT_BUSY' };
            cancelIdle();
            leaseSeq += 1;
            var bus = ctx.createGain();
            var v = Math.max(1, voices || 1);
            bus.gain.value = 1 / v;
            bus.connect(master);
            var lease = { id: 'lease-' + leaseSeq, consumer: consumer, generation: leaseSeq, outputEpoch: outputEpoch, bus: bus, voices: v, context: ctx, onRevoke: o.onRevoke || null, concurrent: Boolean(o.concurrent), share: 1, guard: o.guard === 'verified' ? 'verified' : 'unverified' };
            leases[lease.id] = lease;
            rebalance();
            updateGuard();
            startRenew();
            renewPermit();
            return { ok: true, lease: lease };
        }

        function setVoices(lease, voices) {
            if (!leases[lease.id]) return;
            lease.voices = Math.max(1, voices || 1);
            rebalance();
        }

        function release(lease) {
            if (!lease || !leases[lease.id]) return;
            delete leases[lease.id];
            try { lease.bus.disconnect(); } catch (_) { /* already */ }
            updateGuard();
            if (Object.keys(leases).length) rebalance();
            else {
                stopRenew();
                permit = null;
                scheduleIdle();
            }
        }

        // A consumer is on its screen: the claim is prepared for it. The
        // claim is given back when no consumer retains it any more.
        function retain(consumer) {
            retained[consumer] = true;
            return claim.acquire();
        }

        function drop(consumer) {
            delete retained[consumer];
            Object.keys(leases).forEach(function (id) { if (leases[id].consumer === consumer) release(leases[id]); });
            if (!Object.keys(retained).length) {
                cancelIdle();
                closeContext(true);
            }
        }

        // Full stop (logout, page hide): leases end, context closes, claim goes.
        function shutdown() {
            revokeAll('shutdown');
            Object.keys(leases).forEach(function (id) { release(leases[id]); });
            retained = {};
            concurrentAllowed = false;
            cancelIdle();
            closeContext(true);
        }

        // The current permit, only while still valid and not revoked.
        function currentPermit() {
            if (!permit || permit.seq <= revokedSeq) return null;
            if (env.now() > permit.expiresAtUtcMs) return null;
            if (!ctx || ctx.state !== 'running') return null;
            return Object.assign({}, permit);
        }

        return {
            MASTER_LIMIT: MASTER_LIMIT,
            claimKind: claim.kind,
            tabId: claim.tabId || null,
            on: function (type, fn) {
                listeners[type].push(fn);
                return function () { listeners[type] = listeners[type].filter(function (x) { return x !== fn; }); };
            },
            retain: retain,
            drop: drop,
            prepareClaim: function () { return claim.acquire(); },
            releaseClaim: function () {
                if (!Object.keys(retained).length) claim.release();
            },
            takeoverClaim: function (observed) { return claim.takeover(observed); },
            verifyClaim: function () { return claim.verify(); },
            hasClaim: function () { return claim.isHeld(); },
            claimPending: function () { return Boolean(claim.isPending && claim.isPending()); },
            claimGeneration: function () { return claim.generation(); },
            setGuard: function (g) { claim.setGuard(g); },
            setLeaseGuard: function (lease, g) {
                if (!lease || !leases[lease.id]) return;
                lease.guard = g === 'verified' ? 'verified' : 'unverified';
                updateGuard();
            },
            // The user's explicit choice (tuner: simultaneous + earphones).
            // Turned off while several leases play: every lease but the
            // oldest is revoked, so one consumer is left.
            setConcurrentAllowed: function (on) {
                concurrentAllowed = Boolean(on);
                if (concurrentAllowed) return;
                var list = Object.keys(leases).map(function (id) { return leases[id]; }).sort(function (a, b) { return a.generation - b.generation; });
                list.slice(1).forEach(function (l) {
                    if (typeof l.onRevoke === 'function') {
                        try { l.onRevoke('concurrency-off', revokedSeq); } catch (_) { /* consumer */ }
                    }
                    release(l);
                });
            },
            concurrentAllowed: function () { return concurrentAllowed; },
            unlockFromGesture: unlockFromGesture,
            acquire: acquire,
            setVoices: setVoices,
            release: release,
            shutdown: shutdown,
            renewPermit: renewPermit,
            permit: currentPermit,
            revokedSeq: function () { return revokedSeq; },
            hasLeases: function () { return Object.keys(leases).length > 0; },
            consumers: function () { return Object.keys(leases).map(function (id) { return leases[id].consumer; }); },
            context: function () { return ctx; },
            outputTimestamp: function () {
                if (!ctx || typeof ctx.getOutputTimestamp !== 'function') return null;
                try {
                    var ts = ctx.getOutputTimestamp();
                    return ts && ts.contextTime > 0 && ts.performanceTime > 0 ? ts : null;
                } catch (_) {
                    return null;
                }
            },
        };
    }

    // One manager per page for every consumer (tuner and metronome). The
    // browser's coordination APIs are this module's own concern: missing
    // fields are taken from the page (consumers need not touch IndexedDB).
    function getPageManager(envFactory) {
        var lib = globalObj.PortalAudioLib = globalObj.PortalAudioLib || {};
        if (!lib.pageManager) {
            var env = Object.assign({}, typeof envFactory === 'function' ? envFactory() : envFactory);
            var nav = globalObj.navigator || {};
            if (!env.AudioContext) env.AudioContext = globalObj.AudioContext || globalObj.webkitAudioContext;
            if (env.locks === undefined) env.locks = nav.locks;
            if (env.indexedDB === undefined) env.indexedDB = globalObj.indexedDB;
            if (env.audioSession === undefined) env.audioSession = nav.audioSession;
            if (typeof env.now !== 'function') env.now = function () { return Date.now(); };
            lib.pageManager = createOutputManager(env);
        }
        return lib.pageManager;
    }

    var api = {
        MASTER_LIMIT: MASTER_LIMIT,
        LOCK_NAME: LOCK_NAME,
        CLAIM_DB: CLAIM_DB,
        HEARTBEAT_MS: HEARTBEAT_MS,
        STALE_MS: STALE_MS,
        PERMIT_MS: PERMIT_MS,
        PERMIT_RENEW_MS: PERMIT_RENEW_MS,
        DRAIN_MS: DRAIN_MS,
        IDLE_RELEASE_MS: IDLE_RELEASE_MS,
        createOutputManager: createOutputManager,
        getPageManager: getPageManager,
        createIdbClaim: createIdbClaim,
        createLockClaim: createLockClaim,
    };

    var lib = globalObj.PortalAudioLib = globalObj.PortalAudioLib || {};
    lib.releases = lib.releases || {};
    lib.outputManager = api;
    lib.releases.output_manager = AUDIO_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
