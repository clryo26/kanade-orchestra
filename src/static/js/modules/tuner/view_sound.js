        function targetForLinked(v) {
            var base = ctx.body.getTargetConfig();
            if (v.temperament) return Object.assign({}, base, { temperament: v.temperament, rootMidi: v.rootMidi, seventh: v.seventh || base.seventh, fixedMidi: null });
            return Object.assign({}, base, { fixedMidi: null });
        }

        function currentVoices() {
            var a4 = ctx.body.getA4();
            var resolved = state.voices.map(function (v) {
                var c = { lib: L, a4Hz: a4, target: targetForLinked(v) };
                return resolveVoices([v], c);
            });
            var errors = [];
            var list = [];
            resolved.forEach(function (r, i) {
                if (!r.ok) r.errors.forEach(function (e) { errors.push(e.replace(/^1音目/, (i + 1) + '音目')); });
                else list.push(r.voices[0]);
            });
            return { ok: errors.length === 0, voices: list, errors: errors };
        }

        function patternFromInputs() {
            var kind = patternKind.value;
            var rep = repeats.value === '' ? null : Number(repeats.value);
            return { kind: kind, seconds: Number(seconds.value), gapSeconds: Number(gap.value), repeats: rep, bpm: Number(bpm.value), beatsPerBar: Number(beats.value) };
        }

        function coefficients() {
            if (state.waveform !== 'harmonic') return null;
            if (coefPreset.value === 'custom') return parseCoefficients(coefText.value);
            return COEFFICIENT_PRESETS[coefPreset.value].coefficients;
        }

        function showSummary() {
            var playing = ctx.body.isPlaying();
            var freqs = ctx.body.getPlayingFrequencies();
            if (playing && freqs.length) summary.textContent = '再生中：' + freqs.map(function (f) { return f.toFixed(2) + ' Hz'; }).join('、');
            else {
                var r = currentVoices();
                summary.textContent = r.ok ? '鳴らす音：' + r.voices.map(function (v) { return v.label + ' ' + v.frequency.toFixed(2) + ' Hz'; }).join('、') : '';
            }
            play.disabled = playing;
            stop.disabled = !playing;
        }

        function showError(messages) {
            errorText.hidden = !messages.length;
            errorText.textContent = messages.join(' ');
        }

