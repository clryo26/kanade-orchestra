            var pattern = patternFromInputs();
            var specs = r.voices.map(function (v, i) {
                return { frequency: v.frequency, waveform: state.waveform, coefficients: coef, group: pattern.kind === 'alternate' && i > 0 ? 1 : 0, label: v.label };
            });
            var result = ctx.body.startVoicesFromTap(specs, pattern);
