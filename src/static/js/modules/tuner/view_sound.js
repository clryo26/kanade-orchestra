    function parseCoefficients(text) {
        var parts = String(text || '').normalize('NFKC').split(/[\s,、]+/).filter(Boolean);
        if (!parts.length || parts.length > 40) return null;
        var values = parts.map(Number);
        if (!values.every(function (v) { return Number.isFinite(v) && v >= 0 && v <= 1; })) return null;
        if (!values.some(function (v) { return v > 0; })) return null;
        return values;
    }

    // Resolves the voice specs of the panel to frequencies (pure).
    // voice: { source: 'hz'|'note'|'linked', hz, midi, role }
    function resolveVoices(voices, ctx) {
        var tm = ctx.lib.targetModel;
        var music = ctx.lib.music;
        var pb = ctx.lib.playback;
        var a4 = ctx.a4Hz;
        var errors = [];
        var list = voices.map(function (v, i) {
            var hz = null;
            var label = '';
            if (v.source === 'hz') {
                var parsed = pb.parseHzInput(v.hzText);
                if (!parsed.ok) errors.push((i + 1) + '音目：' + parsed.message);
                else { hz = parsed.value; label = hz.toFixed(1) + ' Hz（固定）'; }
            } else if (v.source === 'note') {
                hz = music.noteFrequency(v.midi, a4);
                label = music.describeNote(v.midi).label + '（A4連動）';
            } else {
                var resolved = tm.resolve(Object.assign({}, ctx.target, { a4Hz: a4, a4Tenths: undefined, role: v.role, fixedMidi: v.midi }), null);
                if (!resolved) errors.push((i + 1) + '音目：この役割の音は設計音域外です。');
                else { hz = resolved.targetHz; label = (resolved.spelling ? resolved.spelling.label : '') + '（音律連動・' + (resolved.roleLabel || '音律') + '）'; }
            }
            if (hz !== null && !pb.isPlayableFrequency(hz)) {
                errors.push((i + 1) + '音目：再生範囲（28.0～4,700.0 Hz）外です。');
                hz = null;
            }
            return { frequency: hz, label: label };
        });
        return { ok: errors.length === 0 && list.length > 0, voices: list, errors: errors };
    }

    function chordVoices(chordId, rootMidi, useJust) {
        var chord = CHORDS[chordId];
        if (!chord) return [];
        if (useJust && chord.just) {
            return chord.roles.map(function (role) { return { source: 'linked', role: role, midi: null, rootMidi: rootMidi, temperament: chord.just, seventh: chord.seventh || null }; });
        }
        return chord.semitones.map(function (s) { return { source: 'note', midi: rootMidi + s }; });
    }

