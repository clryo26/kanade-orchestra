// Tuner: radix-2 FFT shared by the pitch (YIN) and spectrum analysers.
// Runs in the analysis Worker via importScripts and in Vitest via require,
// so it must stay dependency-free and must not touch the DOM.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-e8d471ab55a0'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var tableCache = {};

    function isPowerOfTwo(n) {
        return n > 0 && (n & (n - 1)) === 0;
    }

    function nextPowerOfTwo(n) {
        var size = 1;
        while (size < n) size *= 2;
        return size;
    }

    // Twiddle factors and bit-reversal indices are cached per size because the
    // worker calls the FFT ~30 times per second with the same few sizes.
    function tablesFor(size) {
        if (tableCache[size]) return tableCache[size];
        var half = size / 2;
        var cos = new Float64Array(half);
        var sin = new Float64Array(half);
        for (var i = 0; i < half; i += 1) {
            cos[i] = Math.cos((2 * Math.PI * i) / size);
            sin[i] = Math.sin((2 * Math.PI * i) / size);
        }
        var reverse = new Uint32Array(size);
        var bits = Math.round(Math.log2(size));
        for (var k = 0; k < size; k += 1) {
            var r = 0;
            var v = k;
            for (var b = 0; b < bits; b += 1) {
                r = (r << 1) | (v & 1);
                v >>= 1;
            }
            reverse[k] = r;
        }
        tableCache[size] = { cos: cos, sin: sin, reverse: reverse };
        return tableCache[size];
    }

    // In-place complex FFT. inverse=true computes the unscaled inverse
    // (callers divide by size), which keeps the forward path allocation-free.
    function transform(re, im, inverse) {
        var size = re.length;
        if (!isPowerOfTwo(size) || im.length !== size) {
            throw new Error('FFT size must be a power of two and re/im lengths must match');
        }
        var tables = tablesFor(size);
        var reverse = tables.reverse;
        for (var i = 0; i < size; i += 1) {
            var j = reverse[i];
            if (j > i) {
                var tr = re[i]; re[i] = re[j]; re[j] = tr;
                var ti = im[i]; im[i] = im[j]; im[j] = ti;
            }
        }
        var sign = inverse ? 1 : -1;
        for (var len = 2; len <= size; len *= 2) {
            var halfLen = len / 2;
            var step = size / len;
            for (var start = 0; start < size; start += len) {
                for (var k = 0; k < halfLen; k += 1) {
                    var wr = tables.cos[k * step];
                    var wi = sign * tables.sin[k * step];
                    var a = start + k;
                    var b2 = a + halfLen;
                    var xr = re[b2] * wr - im[b2] * wi;
                    var xi = re[b2] * wi + im[b2] * wr;
                    re[b2] = re[a] - xr;
                    im[b2] = im[a] - xi;
                    re[a] += xr;
                    im[a] += xi;
                }
            }
        }
    }

    var api = {
        isPowerOfTwo: isPowerOfTwo,
        nextPowerOfTwo: nextPowerOfTwo,
        transform: transform,
    };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.fft = api;
    lib.releases.fft = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
