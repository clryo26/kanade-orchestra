// Tuner: note onset / offset detection from the 10 ms RMS envelope.
//
// Pitch frames cannot see the first ~100 ms of a note (the analysis window
// must contain the new note first), so note boundaries come from the level
// envelope instead (docs/TUNER_ADVANCED_DESIGN.md 8.2). All thresholds are
// tuning values to be confirmed with real instruments:
// - onset: level >= threshold (calibrated noise floor + 12 dB, or the manual
//   input threshold) and at least riseDb above the median of the previous
//   50 ms, confirmed when the level stays above the threshold for 20 ms.
// - offset: below the threshold for 30 ms.
// - re-attack inside a note (repeated notes without silence): a dip of at
//   least reattackDipDb below the recent peak followed by a fast rise of
//   riseDb within reattackRiseMs. A slow amplitude wobble (tremolo) is
//   slower than that and does not split the note.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-e9e90e4b853c'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var DEFAULTS = {
        hopMs: 10,
        thresholdDbfs: -60,
        riseDb: 6,
        riseWindowMs: 50,
        confirmMs: 20,
        offsetMs: 30,
        reattackDipDb: 10,
        reattackRiseMs: 30,
        peakWindowMs: 200,
        minNoteMs: 40,
    };

    function median(values) {
        if (!values.length) return -Infinity;
        var sorted = values.slice().sort(function (a, b) { return a - b; });
        var mid = Math.floor(sorted.length / 2);
        return sorted.length % 2 ? sorted[mid] : (sorted[mid - 1] + sorted[mid]) / 2;
    }

    // Streaming detector. push(frame) with { effectiveFrame2, rmsDbfs }
    // (10 ms hop, in time order) returns 0..2 events:
    // { type: 'onset' | 'offset', effectiveFrame2, rmsDbfs, cause }.
    function createOnsetDetector(options) {
        var opts = Object.assign({}, DEFAULTS, options || {});
        var history = []; // recent levels while off (for the 50 ms median)
        var riseFrames = Math.max(1, Math.round(opts.riseWindowMs / opts.hopMs));
        var confirmFrames = Math.max(1, Math.round(opts.confirmMs / opts.hopMs));
        var offsetFrames = Math.max(1, Math.round(opts.offsetMs / opts.hopMs));
        var peakFrames = Math.max(1, Math.round(opts.peakWindowMs / opts.hopMs));
        var reattackFrames = Math.max(1, Math.round(opts.reattackRiseMs / opts.hopMs));
        var state = 'off';
        var candidate = null;
        var aboveCount = 0;
        var belowCount = 0;
        var belowStart = null;
        var recent = []; // { frame2, db } while on
        var dip = null;
        var noteStart = null;

        function reset() {
            history = [];
            state = 'off';
            candidate = null;
            aboveCount = 0;
            belowCount = 0;
            belowStart = null;
            recent = [];
            dip = null;
            noteStart = null;
        }

        function setThreshold(dbfs) {
            if (typeof dbfs === 'number' && Number.isFinite(dbfs)) opts.thresholdDbfs = dbfs;
        }

        function push(frame) {
            var db = frame.rmsDbfs;
            var t2 = frame.effectiveFrame2;
            var events = [];
            if (state === 'off') {
                var base = median(history.slice(-riseFrames));
                if (candidate === null) {
                    if (db >= opts.thresholdDbfs && (history.length === 0 || db >= base + opts.riseDb)) {
                        candidate = { effectiveFrame2: t2, rmsDbfs: db };
                        aboveCount = 1;
                    }
                } else if (db >= opts.thresholdDbfs) {
                    aboveCount += 1;
                } else {
                    candidate = null;
                    aboveCount = 0;
                }
                if (candidate && aboveCount >= confirmFrames) {
                    events.push({ type: 'onset', effectiveFrame2: candidate.effectiveFrame2, rmsDbfs: candidate.rmsDbfs, cause: 'level' });
                    state = 'on';
                    noteStart = candidate.effectiveFrame2;
                    recent = [];
                    dip = null;
                    belowCount = 0;
                    candidate = null;
                }
                history.push(db);
                if (history.length > riseFrames * 4) history.shift();
                return events;
            }
            // state === 'on'
            if (db < opts.thresholdDbfs) {
                if (belowCount === 0) belowStart = t2;
                belowCount += 1;
                if (belowCount >= offsetFrames) {
                    events.push({ type: 'offset', effectiveFrame2: belowStart, rmsDbfs: db, cause: 'level' });
                    state = 'off';
                    history = [db];
                    candidate = null;
                    belowCount = 0;
                    recent = [];
                    dip = null;
                }
                return events;
            }
            belowCount = 0;
            recent.push({ frame2: t2, db: db });
            if (recent.length > peakFrames) recent.shift();
            var peak = -Infinity;
            for (var i = 0; i < recent.length; i += 1) if (recent[i].db > peak) peak = recent[i].db;
            if (dip === null) {
                if (db <= peak - opts.reattackDipDb) dip = { frame2: t2, db: db, frames: 0 };
            } else {
                // The dip may last any time; what must be fast is the rise
                // out of it (counted from the first frame above the dip).
                if (db < dip.db) dip = { frame2: t2, db: db, frames: 0 };
                else if (db > dip.db + 1 || dip.frames > 0) dip.frames += 1;
                if (db >= dip.db + opts.riseDb && dip.frames <= reattackFrames) {
                    var duration2 = dip.frame2 - noteStart;
                    events.push({ type: 'offset', effectiveFrame2: dip.frame2, rmsDbfs: dip.db, cause: 'reattack' });
                    events.push({ type: 'onset', effectiveFrame2: t2, rmsDbfs: db, cause: 'reattack', previousDuration2: duration2 });
                    noteStart = t2;
                    recent = [{ frame2: t2, db: db }];
                    dip = null;
                } else if (dip.frames > reattackFrames) {
                    dip = null; // slow recovery: amplitude wobble, not a new note
                }
            }
            return events;
        }

        // End of input (session end / gap): close an open note.
        function flush(lastFrame2) {
            if (state !== 'on') { reset(); return []; }
            var events = [{ type: 'offset', effectiveFrame2: lastFrame2, rmsDbfs: null, cause: 'end' }];
            reset();
            return events;
        }

        return { push: push, flush: flush, reset: reset, setThreshold: setThreshold, getState: function () { return state; }, options: opts };
    }

    // Convenience: whole envelope array -> [{ startFrame2, endFrame2, cause }].
    // gaps: sorted effectiveFrame2 values where the input was discontinuous.
    function detectNotes(envelope, options, gaps) {
        var det = createOnsetDetector(options);
        var notes = [];
        var open = null;
        var gapList = (gaps || []).slice().sort(function (a, b) { return a - b; });
        var g = 0;
        var last = null;
        function handle(events) {
            events.forEach(function (ev) {
                if (ev.type === 'onset') open = { startFrame2: ev.effectiveFrame2, cause: ev.cause };
                else if (open) {
                    notes.push({ startFrame2: open.startFrame2, endFrame2: ev.effectiveFrame2, startCause: open.cause, endCause: ev.cause });
                    open = null;
                }
            });
        }
        for (var i = 0; i < envelope.length; i += 1) {
            var f = envelope[i];
            while (g < gapList.length && gapList[g] <= f.effectiveFrame2) {
                // Never bridge a gap: close the note at the last frame before it.
                if (last !== null) handle(det.flush(last).map(function (ev) { ev.cause = 'gap'; return ev; }));
                det.reset();
                g += 1;
            }
            handle(det.push(f));
            last = f.effectiveFrame2;
        }
        if (last !== null) handle(det.flush(last));
        return notes;
    }

    var api = { DEFAULTS: DEFAULTS, createOnsetDetector: createOnsetDetector, detectNotes: detectNotes, median: median };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.onset = api;
    lib.releases.onset = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
