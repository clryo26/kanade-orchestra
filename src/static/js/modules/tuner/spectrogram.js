// Tuner: spectrogram (time x log frequency x level) of the last 5 minutes.
// Columns arrive with the 10 Hz display spectra (512 log-spaced points,
// already reduced in the Worker). Levels are quantised to 8 bits for the
// display only (analysis values stay in dBFS); 3,000 columns x 512 rows =
// 1.536 MB is the fixed upper bound. Nothing is saved: a past session can
// only show its pitch series and harmonic summaries, never this image.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-5c2ad5661ae9'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var ROWS = 512;
    var COLUMNS = 3000; // 5 minutes at 10 columns per second
    var FLOOR_DB = -100;
    var CEILING_DB = 0;

    function quantize(db) {
        if (!Number.isFinite(db)) return 0; // not measurable (above Nyquist)
        var v = (Math.max(FLOOR_DB, Math.min(CEILING_DB, db)) - FLOOR_DB) / (CEILING_DB - FLOOR_DB);
        return 1 + Math.round(v * 254);
    }

    function createSpectrogramStore() {
        var data = new Uint8Array(ROWS * COLUMNS);
        var times = new Float64Array(COLUMNS);
        var axisIds = new Int32Array(COLUMNS);
        var start = 0;
        var length = 0;

        function push(column, timeSec, axisId) {
            if (!column || column.length !== ROWS) return false;
            var index;
            if (length < COLUMNS) {
                index = (start + length) % COLUMNS;
                length += 1;
            } else {
                index = start;
                start = (start + 1) % COLUMNS;
            }
            var offset = index * ROWS;
            for (var r = 0; r < ROWS; r += 1) data[offset + r] = quantize(column[r]);
            times[index] = timeSec;
            axisIds[index] = axisId || 0;
            return true;
        }

        function clear() {
            start = 0;
            length = 0;
        }

        return {
            push: push,
            clear: clear,
            length: function () { return length; },
            bytes: function () { return data.byteLength; },
            // k = 0 oldest .. length-1 newest
            column: function (k) {
                var index = (start + k) % COLUMNS;
                return { time: times[index], axisId: axisIds[index], values: data.subarray(index * ROWS, index * ROWS + ROWS) };
            },
        };
    }

    // Colour scale with lightness order (readable in grey scale too).
    function paletteColor(v) {
        if (v === 0) return [0, 0, 0, 0];
        var t = (v - 1) / 254;
        var r = Math.round(255 * Math.min(1, Math.max(0, 1.5 * t - 0.2)));
        var g = Math.round(255 * Math.min(1, Math.max(0, 1.6 * t - 0.6)));
        var b = Math.round(255 * Math.min(1, Math.max(0, 0.6 + 0.4 * t - 1.2 * Math.max(0, t - 0.6))));
        return [r, g, b, 255];
    }

    function drawSpectrogram(canvas, store, options) {
        var ctx2d = canvas.getContext ? canvas.getContext('2d') : null;
        if (!ctx2d || typeof ctx2d.createImageData !== 'function') return;
        var opts = options || {};
        var w = Math.max(1, Math.round(canvas.clientWidth || 320));
        var h = Math.max(1, Math.round(canvas.clientHeight || 160));
        if (canvas.width !== w) canvas.width = w;
        if (canvas.height !== h) canvas.height = h;
        var image = ctx2d.createImageData(w, h);
        var n = store.length();
        var seconds = opts.seconds || 60;
        var visible = Math.min(n, Math.round(seconds * 10));
        var first = n - visible;
        for (var x = 0; x < w; x += 1) {
            if (!visible) break;
            var k = first + Math.floor((x / w) * visible);
            if (k < 0 || k >= n) continue;
            var col = store.column(k);
            if (opts.axisId !== undefined && col.axisId !== opts.axisId) continue;
            for (var y = 0; y < h; y += 1) {
                var row = Math.floor(((h - 1 - y) / h) * ROWS);
                var rgba = paletteColor(col.values[row]);
                var p = (y * w + x) * 4;
                image.data[p] = rgba[0];
                image.data[p + 1] = rgba[1];
                image.data[p + 2] = rgba[2];
                image.data[p + 3] = rgba[3];
            }
        }
        ctx2d.putImageData(image, 0, 0);
    }

    var api = { ROWS: ROWS, COLUMNS: COLUMNS, quantize: quantize, createSpectrogramStore: createSpectrogramStore, paletteColor: paletteColor, drawSpectrogram: drawSpectrogram };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.spectrogram = api;
    lib.releases.spectrogram = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
