// Tuner: bounded store of raw measurement frames (main thread).
//
// - Pitch frames and 10 ms envelope frames are kept in columnar ring buffers
//   (default: 30 minutes at 40 pitch frames/s and 100 envelope frames/s).
//   When the ring is full the oldest data is overwritten and counted
//   (lostPitchFrames) so the screen can say the detail is gone.
// - Results from windows of different length arrive out of order: a
//   reorder buffer (150 ms) releases frames in effective-time order; a frame
//   older than the watermark is kept but marked late and is not fed to the
//   live consumers twice.
// - Capture epochs (one per microphone start) carry their sample rate and
//   clock correspondence points; frames are never compared across epochs
//   without them, and nothing is interpolated across epoch boundaries/gaps.
// - Playback intervals, target/condition boundaries and gaps are stored as
//   annotations; they never rewrite the raw values.
// Snapshots are fresh copies (safe to transfer to a Worker): the live ring
// buffers are never detached.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-5c2ad5661ae9'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var DEFAULTS = {
        pitchCapacity: 30 * 60 * 40,
        envelopeCapacity: 30 * 60 * 100,
        reorderMs: 150,
    };

    var LATE_FLAG = 0; // late frames are tracked in their own column (flag bit7 stays reserved)

    function createRing(capacity, columns) {
        var cols = {};
        Object.keys(columns).forEach(function (name) { cols[name] = new columns[name](capacity); });
        return { capacity: capacity, start: 0, length: 0, total: 0, lost: 0, cols: cols };
    }

    function ringPush(ring, values) {
        var index;
        if (ring.length < ring.capacity) {
            index = (ring.start + ring.length) % ring.capacity;
            ring.length += 1;
        } else {
            index = ring.start;
            ring.start = (ring.start + 1) % ring.capacity;
            ring.lost += 1;
        }
        Object.keys(values).forEach(function (name) { if (ring.cols[name]) ring.cols[name][index] = values[name]; });
        ring.total += 1;
    }

    function ringIndex(ring, k) {
        return (ring.start + k) % ring.capacity;
    }

    function createMeasurementStore(options) {
        var opts = Object.assign({}, DEFAULTS, options || {});
        var pitch = createRing(opts.pitchCapacity, {
            epoch: Uint32Array, frame2: Float64Array, hz: Float32Array, conf: Float32Array, rms: Float32Array,
            reason: Uint8Array, flags: Uint8Array, late: Uint8Array, windowSamples: Uint16Array, revision: Uint32Array,
        });
        var envelope = createRing(opts.envelopeCapacity, {
            epoch: Uint32Array, frame2: Float64Array, rms: Float32Array, peak: Float32Array, clipped: Uint8Array,
        });
        var epochs = {};
        var currentEpoch = null;
        var pending = []; // reorder buffer (pitch frames of the current epoch)
        var watermark2 = -Infinity;
        var listeners = [];
        var intervals = []; // { kind, epoch, startFrame2, endFrame2, marginFrames2, meta }
        var boundaries = []; // { epoch, frame2, type, meta }
        var gaps = []; // { epoch, frame2, droppedFrames }
        var harmonics = []; // bounded list of harmonic frames { epoch, frame2, window, ... }
        var maxHarmonics = 3000;

        function beginEpoch(info) {
            flush();
            var id = info.captureEpoch;
            epochs[id] = {
                captureEpoch: id,
                sampleRate: info.sampleRate,
                startedAtPerformance: typeof info.performanceTime === 'number' ? info.performanceTime : null,
                startedAtUtc: typeof info.utcMs === 'number' ? info.utcMs : null,
                clock: [],
                microphone: info.microphone || null,
                profile: info.profile || null,
                // Longest analysis window of this epoch: a frame ending at E has
                // its effective time 2E - N, so later results can still land
                // that far back.
                maxWindowSamples: info.maxWindowSamples > 0 ? info.maxWindowSamples : 9000,
            };
            currentEpoch = id;
            watermark2 = -Infinity;
            return epochs[id];
        }

        function addClockPoint(point) {
            var e = epochs[point.captureEpoch];
            if (!e) return;
            e.clock.push({ contextTime: point.contextTime, performanceTime: point.performanceTime, utcMs: point.utcMs, source: point.source });
            if (e.clock.length > 400) e.clock.splice(1, 1); // keep the first point and the recent ones
        }

        function store(frame, late) {
            ringPush(pitch, {
                epoch: frame.captureEpoch,
                frame2: frame.effectiveFrame2,
                hz: frame.frequencyHz === null || frame.frequencyHz === undefined ? NaN : frame.frequencyHz,
                conf: typeof frame.confidence === 'number' ? frame.confidence : NaN,
                rms: typeof frame.rmsDbfs === 'number' ? frame.rmsDbfs : NaN,
                reason: frame.invalidReason || 0,
                flags: frame.qualityFlags || 0,
                late: late ? 1 : 0,
                windowSamples: Math.min(65535, frame.windowSamples || 0),
                revision: frame.settingsRevision || 0,
            });
            if (!late) listeners.forEach(function (fn) { try { fn({ type: 'pitch', frame: frame }); } catch (_) { /* listener errors never stop capture */ } });
        }

        function release(upTo2) {
            pending.sort(function (a, b) { return a.effectiveFrame2 - b.effectiveFrame2; });
            while (pending.length && pending[0].effectiveFrame2 <= upTo2) {
                var f = pending.shift();
                watermark2 = Math.max(watermark2, f.effectiveFrame2);
                store(f, false);
            }
        }

        function pushPitch(frame) {
            if (!frame || frame.captureEpoch !== currentEpoch || !epochs[currentEpoch]) return false;
            var sr = epochs[currentEpoch].sampleRate;
            if (frame.effectiveFrame2 <= watermark2) {
                store(frame, true); // arrived after its slot was released
                return true;
            }
            pending.push(frame);
            var latest = frame.analysisEndFrameExclusive ? 2 * frame.analysisEndFrameExclusive : frame.effectiveFrame2;
            release(latest - epochs[currentEpoch].maxWindowSamples - (opts.reorderMs / 1000) * sr * 2);
            return true;
        }

        function pushEnvelope(frames, epochId) {
            var id = epochId === undefined ? currentEpoch : epochId;
            if (id !== currentEpoch || !Array.isArray(frames)) return;
            frames.forEach(function (f) {
                ringPush(envelope, { epoch: id, frame2: f.effectiveFrame2, rms: f.rmsDbfs, peak: f.peak || 0, clipped: f.clipped ? 1 : 0 });
            });
            listeners.forEach(function (fn) { try { fn({ type: 'envelope', frames: frames }); } catch (_) { /* ignore */ } });
        }

        function pushHarmonics(frame, epochId) {
            if (!frame || !Array.isArray(frame.harmonics)) return;
            harmonics.push({ epoch: epochId === undefined ? currentEpoch : epochId, frame2: frame.effectiveFrame2, window: frame.window || frame.harmonicsWindow || null, fundamental: frame.fundamental, harmonics: frame.harmonics, clipped: Boolean(frame.clipped) });
            if (harmonics.length > maxHarmonics) harmonics.splice(0, harmonics.length - maxHarmonics);
        }

        function markGap(epochId, frame2, droppedFrames) {
            flush();
            gaps.push({ epoch: epochId === undefined ? currentEpoch : epochId, frame2: frame2, droppedFrames: droppedFrames || 0 });
            if (gaps.length > 5000) gaps.shift();
            listeners.forEach(function (fn) { try { fn({ type: 'gap', frame2: frame2 }); } catch (_) { /* ignore */ } });
        }

        function addBoundary(type, frame2, meta) {
            boundaries.push({ epoch: currentEpoch, frame2: frame2, type: type, meta: meta || null });
            if (boundaries.length > 5000) boundaries.shift();
        }

        // Output (playback/metronome) interval in capture frames of an epoch,
        // with a margin (after-sound) and the clock-mapping uncertainty.
        function addInterval(kind, startFrame2, endFrame2, meta) {
            var item = { kind: kind, epoch: currentEpoch, startFrame2: startFrame2, endFrame2: endFrame2, meta: meta || null };
            intervals.push(item);
            if (intervals.length > 5000) intervals.shift();
            return item;
        }

        function closeInterval(item, endFrame2) {
            if (item) item.endFrame2 = endFrame2;
        }

        function flush() {
            if (pending.length) release(Infinity);
        }

        function frameCount() {
            return pitch.length;
        }

        // Copy of one epoch's frames within [from2, to2] (frame2 units).
        function snapshot(range) {
            var r = range || {};
            var epochId = r.epoch === undefined ? currentEpoch : r.epoch;
            var from2 = r.from2 === undefined ? -Infinity : r.from2;
            var to2 = r.to2 === undefined ? Infinity : r.to2;
            var idx = [];
            for (var k = 0; k < pitch.length; k += 1) {
                var i = ringIndex(pitch, k);
                if (pitch.cols.epoch[i] !== epochId) continue;
                var t = pitch.cols.frame2[i];
                if (t < from2 || t > to2) continue;
                idx.push(i);
            }
            // Late frames are stored out of order; sort by time.
            idx.sort(function (a, b) { return pitch.cols.frame2[a] - pitch.cols.frame2[b]; });
            var n = idx.length;
            var out = {
                epoch: epochId,
                sampleRate: epochs[epochId] ? epochs[epochId].sampleRate : null,
                frame2: new Float64Array(n), hz: new Float32Array(n), conf: new Float32Array(n), rms: new Float32Array(n),
                reason: new Uint8Array(n), flags: new Uint8Array(n), late: new Uint8Array(n), windowSamples: new Uint16Array(n), revision: new Uint32Array(n),
            };
            idx.forEach(function (i, j) {
                out.frame2[j] = pitch.cols.frame2[i];
                out.hz[j] = pitch.cols.hz[i];
                out.conf[j] = pitch.cols.conf[i];
                out.rms[j] = pitch.cols.rms[i];
                out.reason[j] = pitch.cols.reason[i];
                out.flags[j] = pitch.cols.flags[i];
                out.late[j] = pitch.cols.late[i];
                out.windowSamples[j] = pitch.cols.windowSamples[i];
                out.revision[j] = pitch.cols.revision[i];
            });
            var env = [];
            for (var e = 0; e < envelope.length; e += 1) {
                var ei = ringIndex(envelope, e);
                if (envelope.cols.epoch[ei] !== epochId) continue;
                var et = envelope.cols.frame2[ei];
                if (et < from2 || et > to2) continue;
                env.push({ effectiveFrame2: et, rmsDbfs: envelope.cols.rms[ei], peak: envelope.cols.peak[ei], clipped: Boolean(envelope.cols.clipped[ei]) });
            }
            return {
                series: out,
                envelope: env,
                gaps: gaps.filter(function (g) { return g.epoch === epochId && g.frame2 >= from2 && g.frame2 <= to2; }).map(function (g) { return g.frame2; }),
                intervals: intervals.filter(function (it) { return it.epoch === epochId && it.endFrame2 >= from2 && it.startFrame2 <= to2; }).map(function (it) { return Object.assign({}, it); }),
                // 'conditions' entries only carry the conditions in effect
                // (epoch start); they never split notes.
                boundaries: boundaries.filter(function (b) { return b.type !== 'conditions' && b.epoch === epochId && b.frame2 >= from2 && b.frame2 <= to2; }).map(function (b) { return Object.assign({}, b); }),
                // Judging conditions in the range, plus the one already in
                // effect at its start, so every frame can be judged against
                // the conditions of its own time.
                conditions: (function () {
                    var withMeta = boundaries.filter(function (b) { return b.epoch === epochId && b.meta && b.meta.conditions; });
                    var before = null;
                    var inside = [];
                    withMeta.forEach(function (b) {
                        if (b.frame2 < from2) { if (!before || b.frame2 >= before.frame2) before = b; } else if (b.frame2 <= to2) inside.push(b);
                    });
                    return (before ? [before] : []).concat(inside).map(function (b) { return { frame2: b.frame2, type: b.type, conditions: JSON.parse(JSON.stringify(b.meta.conditions)) }; });
                })(),
                harmonics: harmonics.filter(function (h) { return h.epoch === epochId && h.frame2 >= from2 && h.frame2 <= to2; }),
                epochInfo: epochs[epochId] ? JSON.parse(JSON.stringify(epochs[epochId])) : null,
                lostPitchFrames: pitch.lost,
            };
        }

        // Latest frames for live graphs: last `seconds` of the current epoch.
        function recent(seconds) {
            var e = epochs[currentEpoch];
            if (!e) return null;
            var last = null;
            for (var k = pitch.length - 1; k >= 0; k -= 1) {
                var i = ringIndex(pitch, k);
                if (pitch.cols.epoch[i] === currentEpoch) { last = pitch.cols.frame2[i]; break; }
            }
            if (last === null) return snapshot({ epoch: currentEpoch, from2: Infinity, to2: Infinity });
            return snapshot({ epoch: currentEpoch, from2: last - seconds * e.sampleRate * 2, to2: Infinity });
        }

        function clear() {
            pitch = createRing(opts.pitchCapacity, {
                epoch: Uint32Array, frame2: Float64Array, hz: Float32Array, conf: Float32Array, rms: Float32Array,
                reason: Uint8Array, flags: Uint8Array, late: Uint8Array, windowSamples: Uint16Array, revision: Uint32Array,
            });
            envelope = createRing(opts.envelopeCapacity, {
                epoch: Uint32Array, frame2: Float64Array, rms: Float32Array, peak: Float32Array, clipped: Uint8Array,
            });
            pending = [];
            watermark2 = -Infinity;
            intervals = [];
            boundaries = [];
            gaps = [];
            harmonics = [];
            epochs = {};
            currentEpoch = null;
        }

        return {
            beginEpoch: beginEpoch,
            addClockPoint: addClockPoint,
            pushPitch: pushPitch,
            pushEnvelope: pushEnvelope,
            pushHarmonics: pushHarmonics,
            markGap: markGap,
            addBoundary: addBoundary,
            addInterval: addInterval,
            closeInterval: closeInterval,
            flush: flush,
            snapshot: snapshot,
            recent: recent,
            clear: clear,
            frameCount: frameCount,
            getEpoch: function (id) { return epochs[id === undefined ? currentEpoch : id] || null; },
            currentEpoch: function () { return currentEpoch; },
            lostPitchFrames: function () { return pitch.lost; },
            totalPitchFrames: function () { return pitch.total; },
            onConfirmed: function (fn) {
                listeners.push(fn);
                return function () { listeners = listeners.filter(function (x) { return x !== fn; }); };
            },
            options: opts,
        };
    }

    var api = { DEFAULTS: DEFAULTS, LATE_FLAG: LATE_FLAG, createMeasurementStore: createMeasurementStore };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.measurementStore = api;
    lib.releases.measurement_store = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
