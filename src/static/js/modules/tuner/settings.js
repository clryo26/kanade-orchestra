// Tuner: device settings (TunerSettings, schemaVersion 1).
//
// - A4 is held as an integer number of tenths of a hertz (a4Tenths,
//   3900..4800 = 390.0..480.0 Hz, default 4420) and is always saved on this
//   device, as the previous integer A4 was.
// - Every other display/analysis preference is saved only after the user
//   chose "save settings on this device" (persistSettings). Practice history
//   is NOT handled here (storage_local.js, opt-in, separate).
// - Migration: the legacy key portalTunerReferenceA4Hz (integer 430..450) is
//   read once and multiplied by 10. The new value is never written back to the
//   legacy key (no decimals in the old format).
// - An unknown schemaVersion is never overwritten: the store becomes
//   read-only for that key and works with defaults in memory.
// Storage is injected (a blocked or throwing localStorage must never stop the
// tuner); the value then lives only in memory for the current screen. The
// keys are device/browser scoped and intentionally NOT removed on logout.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-b0635dde6c4d'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var SCHEMA_VERSION = 1;
    var STORAGE_KEY = 'portalTunerReferenceA4Hz'; // legacy (read-only migration source)
    var SETTINGS_KEY = 'portalTunerSettings';
    var LEGACY_MIN_HZ = 430;
    var LEGACY_MAX_HZ = 450;
    var MIN_TENTHS = 3900;
    var MAX_TENTHS = 4800;
    var DEFAULT_TENTHS = 4420;
    var MIN_HZ = MIN_TENTHS / 10;
    var MAX_HZ = MAX_TENTHS / 10;
    var DEFAULT_HZ = DEFAULT_TENTHS / 10;
    var PRESETS_TENTHS = [4400, 4410, 4420, 4430];

    // Display response presets (design "ui"): smoothing ms, confirm count, hold ms.
    var RESPONSE_PRESETS = {
        fast: { smoothingMs: 40, confirmFrames: 1, holdMs: 500, label: '高速' },
        standard: { smoothingMs: 120, confirmFrames: 2, holdMs: 1000, label: '標準' },
        stable: { smoothingMs: 240, confirmFrames: 3, holdMs: 1500, label: '安定重視' },
    };
    var METER_RANGES = [10, 25, 50, 100];
    var REGISTER_PROFILES = ['full', 'low', 'high', 'vibrato'];

    var DEFAULT_PREFS = {
        noteNaming: 'both', // 'both' | 'en' | 'solfege'
        spelling: 'temperament', // 'temperament' | 'sharp' | 'flat'
        toleranceCents: 3,
        meterRangeCents: 50,
        responsePreset: 'standard', // 'fast' | 'standard' | 'stable' | 'custom'
        smoothingMs: 120,
        inputThreshold: { mode: 'manual', dbfs: -60, calibratedDbfs: null },
        registerProfile: 'full',
        displayMode: 'normal', // 'normal' | 'detail'
        theme: 'auto', // 'auto' | 'light' | 'dark'
        highContrast: false,
        meterLevel: true,
        judgment: null, // normalized by target_model when used
        // M-010 / D-008: named presets (temperament settings, sound settings).
        // Saved with the other display settings only when the user enabled
        // "save settings on this device"; otherwise kept in memory.
        presets: { temperament: [], sound: [] },
    };
    var MAX_PRESETS = 20;
    var MAX_PRESET_BYTES = 8192;

    function isValidTenths(value) {
        return typeof value === 'number' && Number.isInteger(value) && value >= MIN_TENTHS && value <= MAX_TENTHS;
    }

    // Legacy key: the whole stored string must be a plain integer 430..450:
    // "442.0", " 442", "4.42e2" and "0442" are rejected.
    function parseStoredReference(raw) {
        if (typeof raw !== 'string' || !/^[1-9][0-9]{2}$/.test(raw)) return null;
        var value = Number(raw);
        return value >= LEGACY_MIN_HZ && value <= LEGACY_MAX_HZ ? value : null;
    }

    // Typed A4: 390.0..480.0 Hz with at most one decimal; full-width digits accepted.
    function parseA4Input(text) {
        var raw = String(text == null ? '' : text).normalize('NFKC').trim();
        if (raw === '') return { ok: false, reason: 'empty', message: '基準周波数を入力してください。' };
        if (!/^[0-9]{3}(\.[0-9])?$/.test(raw)) return { ok: false, reason: 'format', message: '390.0～480.0 の数字で入力してください（小数は1桁まで）。' };
        var tenths = Math.round(Number(raw) * 10);
        if (!isValidTenths(tenths)) return { ok: false, reason: 'range', message: '390.0～480.0 Hz の範囲で入力してください。' };
        return { ok: true, tenths: tenths };
    }

    function formatA4(tenths) {
        return (tenths / 10).toFixed(1);
    }

    function clampTenths(value) {
        return Math.max(MIN_TENTHS, Math.min(MAX_TENTHS, value));
    }

    function clampStep(current, delta) {
        var base = isValidTenths(current) ? current : DEFAULT_TENTHS;
        return clampTenths(base + delta);
    }

    function pick(value, allowed, fallback) {
        return allowed.indexOf(value) >= 0 ? value : fallback;
    }

    function normalizeTolerance(value) {
        var v = Math.round(Number(value) * 2) / 2; // 0.5 cent steps
        if (!Number.isFinite(v)) return DEFAULT_PREFS.toleranceCents;
        return Math.max(0.5, Math.min(25, v));
    }

    function normalizeThreshold(value) {
        var t = value && typeof value === 'object' ? value : {};
        var dbfs = Math.round(Number(t.dbfs));
        var calibrated = t.calibratedDbfs === null || t.calibratedDbfs === undefined ? null : Number(t.calibratedDbfs);
        return {
            mode: t.mode === 'auto' ? 'auto' : 'manual',
            dbfs: Number.isFinite(dbfs) ? Math.max(-90, Math.min(-20, dbfs)) : -60,
            calibratedDbfs: Number.isFinite(calibrated) ? Math.max(-90, Math.min(-20, calibrated)) : null,
        };
    }

    // A preset is { id, name, savedAt, data }. Invalid entries are dropped;
    // data is checked by the module that applies it (target_model / playback).
    function normalizePresetList(list) {
        if (!Array.isArray(list)) return [];
        var seen = {};
        return list.filter(function (item) {
            if (!item || typeof item !== 'object' || typeof item.id !== 'string' || !/^[A-Za-z0-9-]{1,64}$/.test(item.id) || seen[item.id]) return false;
            if (typeof item.name !== 'string' || !item.data || typeof item.data !== 'object') return false;
            var text;
            try { text = JSON.stringify(item.data); } catch (_) { return false; }
            if (text.length > MAX_PRESET_BYTES) return false;
            seen[item.id] = true;
            return true;
        }).slice(0, MAX_PRESETS).map(function (item) {
            var name = item.name.replace(/[\u0000-\u001f\u007f]/g, '').trim().slice(0, 40);
            return { id: item.id, name: name || '名前なし', savedAt: typeof item.savedAt === 'number' && Number.isFinite(item.savedAt) ? item.savedAt : null, data: JSON.parse(JSON.stringify(item.data)) };
        });
    }

    function normalizePresets(value) {
        var v = value && typeof value === 'object' ? value : {};
        return { temperament: normalizePresetList(v.temperament), sound: normalizePresetList(v.sound) };
    }

    function normalizePrefs(input) {
        var p = input && typeof input === 'object' ? input : {};
        var preset = pick(p.responsePreset, ['fast', 'standard', 'stable', 'custom'], 'standard');
        var smoothing = Math.round(Number(p.smoothingMs) / 10) * 10;
        if (!Number.isFinite(smoothing)) smoothing = RESPONSE_PRESETS.standard.smoothingMs;
        smoothing = Math.max(0, Math.min(500, smoothing));
        if (preset !== 'custom') smoothing = RESPONSE_PRESETS[preset].smoothingMs;
        return {
            noteNaming: pick(p.noteNaming, ['both', 'en', 'solfege'], 'both'),
            spelling: pick(p.spelling, ['temperament', 'sharp', 'flat'], 'temperament'),
            toleranceCents: normalizeTolerance(p.toleranceCents === undefined ? DEFAULT_PREFS.toleranceCents : p.toleranceCents),
            meterRangeCents: METER_RANGES.indexOf(Number(p.meterRangeCents)) >= 0 ? Number(p.meterRangeCents) : 50,
            responsePreset: preset,
            smoothingMs: smoothing,
            inputThreshold: normalizeThreshold(p.inputThreshold),
            registerProfile: pick(p.registerProfile, REGISTER_PROFILES, 'full'),
            displayMode: pick(p.displayMode, ['normal', 'detail'], 'normal'),
            theme: pick(p.theme, ['auto', 'light', 'dark'], 'auto'),
            highContrast: p.highContrast === true,
            meterLevel: p.meterLevel !== false,
            judgment: p.judgment && typeof p.judgment === 'object' ? p.judgment : null,
            presets: normalizePresets(p.presets),
        };
    }

    // Display-filter options for the chosen response preset (display only).
    function displayOptions(prefs) {
        var p = normalizePrefs(prefs);
        var base = p.responsePreset === 'custom' ? RESPONSE_PRESETS.standard : RESPONSE_PRESETS[p.responsePreset];
        return {
            smoothingTimeMs: p.smoothingMs,
            onsetConfirmFrames: base.confirmFrames,
            holdMs: base.holdMs,
            enterInTuneCents: p.toleranceCents,
            exitInTuneCents: p.toleranceCents + 1,
            meterRangeCents: p.meterRangeCents,
        };
    }

    function createSettingsStore(storage) {
        var current = DEFAULT_TENTHS;
        var prefs = normalizePrefs(null);
        var persist = false;
        var lastSaveFailed = false;
        var readOnly = false; // unknown schema found: never overwrite it

        function readKey(key) {
            try {
                return storage ? storage.getItem(key) : null;
            } catch (_) {
                return null;
            }
        }

        function load() {
            readOnly = false;
            var raw = readKey(SETTINGS_KEY);
            var parsed = null;
            if (typeof raw === 'string' && raw) {
                try { parsed = JSON.parse(raw); } catch (_) { parsed = null; }
            }
            if (parsed && typeof parsed === 'object' && parsed.schemaVersion !== SCHEMA_VERSION) {
                // A newer (or unknown) format written by another release:
                // work with defaults in memory and leave the stored data untouched.
                readOnly = true;
                current = DEFAULT_TENTHS;
                prefs = normalizePrefs(null);
                persist = false;
                return current / 10;
            }
            if (parsed && isValidTenths(parsed.a4Tenths)) {
                current = parsed.a4Tenths;
                persist = parsed.persistSettings === true;
                prefs = normalizePrefs(persist ? parsed.prefs : null);
                return current / 10;
            }
            var legacy = parseStoredReference(readKey(STORAGE_KEY));
            current = legacy === null ? DEFAULT_TENTHS : legacy * 10;
            prefs = normalizePrefs(null);
            persist = false;
            return current / 10;
        }

        function write() {
            if (readOnly) return false;
            try {
                if (!storage) return false;
                var payload = { schemaVersion: SCHEMA_VERSION, a4Tenths: current, persistSettings: persist };
                if (persist) payload.prefs = prefs;
                storage.setItem(SETTINGS_KEY, JSON.stringify(payload));
                return true;
            } catch (_) {
                return false;
            }
        }

        function setTenths(value) {
            if (!isValidTenths(value)) return { value: current / 10, tenths: current, saved: false, changed: false };
            var changed = value !== current;
            current = value;
            var saved = write();
            lastSaveFailed = !saved;
            return { value: current / 10, tenths: current, saved: saved, changed: changed };
        }

        function setPrefs(partial) {
            prefs = normalizePrefs(Object.assign({}, prefs, partial || {}));
            // Without "save settings on this device" the change stays in memory.
            var saved = persist ? write() : false;
            if (persist) lastSaveFailed = !saved;
            return { prefs: getPrefs(), saved: saved, persisted: persist };
        }

        function getPrefs() {
            return JSON.parse(JSON.stringify(prefs));
        }

        return {
            load: load,
            // Hz (for calculations); tenths is the stored integer.
            get: function () { return current / 10; },
            getTenths: function () { return current; },
            setTenths: setTenths,
            set: function (hz) {
                var tenths = Math.round(Number(hz) * 10);
                if (!(Math.abs(tenths - Number(hz) * 10) < 1e-6)) return { value: current / 10, tenths: current, saved: false, changed: false };
                return setTenths(tenths);
            },
            step: function (deltaTenths) { return setTenths(clampStep(current, deltaTenths)); },
            canDecrease: function () { return current > MIN_TENTHS; },
            canIncrease: function () { return current < MAX_TENTHS; },
            lastSaveFailed: function () { return lastSaveFailed; },
            isReadOnly: function () { return readOnly; },
            getPrefs: getPrefs,
            setPrefs: setPrefs,
            isPersisting: function () { return persist; },
            // "Save settings on this device" (separate from practice history).
            setPersist: function (value) {
                persist = Boolean(value);
                var saved = write();
                lastSaveFailed = !saved;
                return saved;
            },
            // "Back to defaults" resets the settings, not the user's named presets.
            resetPrefs: function () {
                prefs = normalizePrefs({ presets: prefs.presets });
                var saved = write();
                if (persist) lastSaveFailed = !saved;
                return getPrefs();
            },
        };
    }

    var api = {
        SCHEMA_VERSION: SCHEMA_VERSION,
        STORAGE_KEY: STORAGE_KEY,
        SETTINGS_KEY: SETTINGS_KEY,
        MIN_TENTHS: MIN_TENTHS,
        MAX_TENTHS: MAX_TENTHS,
        DEFAULT_TENTHS: DEFAULT_TENTHS,
        MIN_HZ: MIN_HZ,
        MAX_HZ: MAX_HZ,
        MAX_PRESETS: MAX_PRESETS,
        normalizePresets: normalizePresets,
        DEFAULT_HZ: DEFAULT_HZ,
        LEGACY_MIN_HZ: LEGACY_MIN_HZ,
        LEGACY_MAX_HZ: LEGACY_MAX_HZ,
        PRESETS_TENTHS: PRESETS_TENTHS,
        RESPONSE_PRESETS: RESPONSE_PRESETS,
        METER_RANGES: METER_RANGES,
        REGISTER_PROFILES: REGISTER_PROFILES,
        DEFAULT_PREFS: DEFAULT_PREFS,
        isValidTenths: isValidTenths,
        parseStoredReference: parseStoredReference,
        parseA4Input: parseA4Input,
        formatA4: formatA4,
        clampStep: clampStep,
        normalizePrefs: normalizePrefs,
        displayOptions: displayOptions,
        createSettingsStore: createSettingsStore,
    };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.settings = api;
    lib.releases.settings = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
