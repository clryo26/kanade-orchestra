// Tuner: reference A4 setting (integer 430-450 Hz, default 442).
// Storage is injected rather than read at load time so that a blocked or
// throwing localStorage (private mode, Safari data eviction) never stops the
// tuner; the value then lives only in memory for the current screen.
// The key is device/browser scoped and intentionally NOT removed on logout.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-e8d471ab55a0'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var STORAGE_KEY = 'portalTunerReferenceA4Hz';
    var MIN_HZ = 430;
    var MAX_HZ = 450;
    var DEFAULT_HZ = 442;

    function isValidReference(value) {
        return typeof value === 'number' && Number.isInteger(value) && value >= MIN_HZ && value <= MAX_HZ;
    }

    // The whole stored string must be a plain integer: "442.0", " 442",
    // "4.42e2" and "0442" are all rejected and fall back to the default.
    function parseStoredReference(raw) {
        if (typeof raw !== 'string' || !/^[1-9][0-9]{2}$/.test(raw)) return null;
        var value = Number(raw);
        return isValidReference(value) ? value : null;
    }

    function clampStep(current, delta) {
        var base = isValidReference(current) ? current : DEFAULT_HZ;
        return Math.max(MIN_HZ, Math.min(MAX_HZ, base + delta));
    }

    function createSettingsStore(storage) {
        var current = DEFAULT_HZ;
        var lastSaveFailed = false;

        function load() {
            var stored = null;
            try {
                stored = storage ? storage.getItem(STORAGE_KEY) : null;
            } catch (_) {
                stored = null;
            }
            var parsed = parseStoredReference(stored);
            current = parsed === null ? DEFAULT_HZ : parsed;
            return current;
        }

        function set(value) {
            if (!isValidReference(value)) return { value: current, saved: false, changed: false };
            var changed = value !== current;
            current = value;
            var saved = false;
            try {
                if (storage) {
                    storage.setItem(STORAGE_KEY, String(value));
                    saved = true;
                }
            } catch (_) {
                saved = false;
            }
            lastSaveFailed = !saved;
            return { value: current, saved: saved, changed: changed };
        }

        return {
            load: load,
            get: function () { return current; },
            set: set,
            step: function (delta) { return set(clampStep(current, delta)); },
            canDecrease: function () { return current > MIN_HZ; },
            canIncrease: function () { return current < MAX_HZ; },
            lastSaveFailed: function () { return lastSaveFailed; },
        };
    }

    var api = {
        STORAGE_KEY: STORAGE_KEY,
        MIN_HZ: MIN_HZ,
        MAX_HZ: MAX_HZ,
        DEFAULT_HZ: DEFAULT_HZ,
        isValidReference: isValidReference,
        parseStoredReference: parseStoredReference,
        clampStep: clampStep,
        createSettingsStore: createSettingsStore,
    };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.settings = api;
    lib.releases.settings = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
