// Tuner: audio session coordinator (design 4). Orthogonal states instead of
// one large enum:
//   visibility:   visible | hidden
//   capture:      stopped | starting | running | paused (mic released) | resume-required | unavailable
//   output:       idle | playing | stopping
//   displayFrozen, practice (trainer state), persistence (idle | recording | saving | blocked)
// and the identifiers it hands out (never mixed up):
//   captureEpoch (one microphone start), playbackGeneration (one output),
//   ownerEpoch (signed-in owner), saveGeneration (one save operation).
// The coordinator only validates and records; audio objects are owned by
// controller.js (input) and playback.js (output).
//
// Rule: capture=running together with output=playing is allowed only in
// the explicit simultaneous mode (earphones declared for this entry). In
// that mode the output intervals are recorded so statistics can exclude them.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-b0635dde6c4d'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var CAPTURE = ['stopped', 'starting', 'running', 'paused', 'resume-required', 'unavailable'];
    var OUTPUT = ['idle', 'playing', 'stopping'];

    function createSessionCoordinator(options) {
        var opts = options || {};
        var state = {
            visibility: 'visible',
            capture: 'stopped',
            output: 'idle',
            displayFrozen: false,
            practice: 'idle',
            persistence: 'idle',
            simultaneous: false, // explicit mode, reset on every entry
            earphonesDeclared: false,
        };
        var ids = { captureEpoch: 0, playbackGeneration: 0, ownerEpoch: 0, saveGeneration: 0 };
        var listeners = [];
        var log = [];

        function emit(change) {
            log.push(Object.assign({ at: typeof opts.now === 'function' ? opts.now() : 0 }, change));
            if (log.length > 200) log.shift();
            var snapshot = get();
            listeners.forEach(function (fn) { try { fn(snapshot, change); } catch (_) { /* ignore */ } });
        }

        function get() {
            return Object.assign({}, state, { ids: Object.assign({}, ids) });
        }

        function setCapture(next, info) {
            if (CAPTURE.indexOf(next) < 0) return false;
            if (next === 'running' && state.output === 'playing' && !state.simultaneous) return false;
            if (next === 'starting') ids.captureEpoch += 1;
            state.capture = next;
            emit({ type: 'capture', value: next, info: info || null });
            return true;
        }

        // May the output start now? In exclusive mode the capture must stop.
        function outputPolicy() {
            if (state.simultaneous && state.earphonesDeclared) return { allowed: true, stopCapture: false, simultaneous: true };
            return { allowed: true, stopCapture: true, simultaneous: false };
        }

        function setOutput(next) {
            if (OUTPUT.indexOf(next) < 0) return null;
            if (next === 'playing') {
                if (state.capture === 'running' && !(state.simultaneous && state.earphonesDeclared)) return null;
                ids.playbackGeneration += 1;
            }
            state.output = next;
            emit({ type: 'output', value: next });
            return ids.playbackGeneration;
        }

        function setSimultaneous(enabled, earphonesDeclared) {
            state.simultaneous = Boolean(enabled);
            state.earphonesDeclared = Boolean(enabled && earphonesDeclared);
            emit({ type: 'simultaneous', value: state.simultaneous, earphones: state.earphonesDeclared });
            return get();
        }

        function setVisibility(next) {
            state.visibility = next === 'hidden' ? 'hidden' : 'visible';
            emit({ type: 'visibility', value: state.visibility });
        }

        function setDisplayFrozen(value) {
            state.displayFrozen = Boolean(value);
            emit({ type: 'display', value: state.displayFrozen });
        }

        function setPractice(value) {
            state.practice = String(value || 'idle');
            emit({ type: 'practice', value: state.practice });
        }

        function setPersistence(value) {
            state.persistence = String(value || 'idle');
            emit({ type: 'persistence', value: state.persistence });
        }

        function nextSaveGeneration() {
            ids.saveGeneration += 1;
            return ids.saveGeneration;
        }

        function nextOwnerEpoch() {
            ids.ownerEpoch += 1;
            emit({ type: 'owner', value: ids.ownerEpoch });
            return ids.ownerEpoch;
        }

        // Leaving the tuner (portal tab, background, logout): everything
        // stops; the simultaneous mode must be declared again next time.
        function leave(reason) {
            state.capture = 'stopped';
            state.output = 'idle';
            state.displayFrozen = false;
            state.simultaneous = false;
            state.earphonesDeclared = false;
            if (state.practice === 'performing' || state.practice === 'countdown') state.practice = 'interrupted';
            ids.playbackGeneration += 1;
            ids.saveGeneration += 1;
            emit({ type: 'leave', value: reason || 'leave' });
        }

        return {
            get: get,
            setCapture: setCapture,
            setOutput: setOutput,
            outputPolicy: outputPolicy,
            setSimultaneous: setSimultaneous,
            setVisibility: setVisibility,
            setDisplayFrozen: setDisplayFrozen,
            setPractice: setPractice,
            setPersistence: setPersistence,
            nextSaveGeneration: nextSaveGeneration,
            nextOwnerEpoch: nextOwnerEpoch,
            isCurrentSave: function (gen) { return gen === ids.saveGeneration; },
            isCurrentPlayback: function (gen) { return gen === ids.playbackGeneration; },
            leave: leave,
            onChange: function (fn) { listeners.push(fn); return function () { listeners = listeners.filter(function (x) { return x !== fn; }); }; },
            history: function () { return log.slice(); },
        };
    }

    var api = { CAPTURE: CAPTURE, OUTPUT: OUTPUT, createSessionCoordinator: createSessionCoordinator };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.sessionCoordinator = api;
    lib.releases.session_coordinator = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
