// Tuner: internal tabs inside #systemTunerHost (design 3). Switching tabs
// only changes what is visible inside the tuner root, so the launcher's
// visibility guard (the host itself) stays true and the microphone keeps
// running. Leaving the portal tab still releases everything as before.
// Tabs follow the WAI-ARIA tab pattern (arrow keys, Home/End).
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-5c2ad5661ae9'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var TABS = [
        { id: 'measure', label: '測定' },
        { id: 'sound', label: '音源' },
        { id: 'analyzer', label: '解析' },
        { id: 'trainer', label: '練習' },
        { id: 'diagnosis', label: '診断' },
    ];
    var MENU = { id: 'menu', label: '履歴・楽器・設定' };

    function createTabs(root, handlers) {
        var doc = globalObj.document;
        if (root.querySelector('[data-tuner-tabbar]')) return root._tunerTabs;
        var bar = doc.createElement('div');
        bar.className = 'tuner-tabbar';
        bar.setAttribute('role', 'tablist');
        bar.setAttribute('aria-label', 'チューナーの画面');
        bar.dataset.tunerTabbar = 'true';
        var panels = {};
        var buttons = {};
        var current = 'measure';
        var all = TABS.concat([MENU]);

        all.forEach(function (tab) {
            var button = doc.createElement('button');
            button.type = 'button';
            button.className = 'tuner-tab' + (tab.id === 'menu' ? ' tuner-tab-menu' : '');
            button.id = 'tunerTab-' + tab.id;
            button.setAttribute('role', 'tab');
            button.setAttribute('aria-controls', 'tunerPanel-' + tab.id);
            button.dataset.tunerTab = tab.id;
            button.textContent = tab.label;
            bar.appendChild(button);
            buttons[tab.id] = button;
            var panel = doc.createElement('section');
            panel.className = 'tuner-panel';
            panel.id = 'tunerPanel-' + tab.id;
            panel.setAttribute('role', 'tabpanel');
            panel.setAttribute('aria-labelledby', button.id);
            panel.dataset.tunerPanel = tab.id;
            panels[tab.id] = panel;
        });

        // Existing measuring content moves into the measuring panel; the
        // reference-tone section moves into the sound panel. The state chips
        // and the status box (with "tap to resume") stay above the panels so
        // the microphone / output state is visible and actionable on every tab.
        var playback = root.querySelector('.tuner-playback');
        var announcer = root.querySelector('[data-tuner-announcer]');
        var common = Array.prototype.filter.call(root.children, function (child) {
            return child.matches && (child.matches('[data-tuner-statusbar]') || child.matches('[data-tuner-status]'));
        });
        Array.prototype.slice.call(root.children).forEach(function (child) {
            if (child === playback || child === announcer || common.indexOf(child) >= 0) return;
            panels.measure.appendChild(child);
        });
        if (playback) panels.sound.appendChild(playback);
        // Order: tab bar, common state elements (left in place), panels, announcer.
        root.insertBefore(bar, root.firstChild);
        all.forEach(function (tab) { root.insertBefore(panels[tab.id], announcer || null); });

        function select(id, focus) {
            if (!panels[id]) return;
            current = id;
            all.forEach(function (tab) {
                var active = tab.id === id;
                buttons[tab.id].setAttribute('aria-selected', String(active));
                buttons[tab.id].tabIndex = active ? 0 : -1;
                panels[tab.id].hidden = !active;
            });
            root.dataset.tab = id;
            if (focus) buttons[id].focus();
            if (handlers && typeof handlers.onTab === 'function') handlers.onTab(id);
        }

        bar.addEventListener('click', function (event) {
            var b = event.target && event.target.closest ? event.target.closest('[data-tuner-tab]') : null;
            if (b) select(b.dataset.tunerTab, false);
        });
        bar.addEventListener('keydown', function (event) {
            var ids = all.map(function (t) { return t.id; });
            var index = ids.indexOf(current);
            var next = null;
            if (event.key === 'ArrowRight') next = ids[(index + 1) % ids.length];
            else if (event.key === 'ArrowLeft') next = ids[(index - 1 + ids.length) % ids.length];
            else if (event.key === 'Home') next = ids[0];
            else if (event.key === 'End') next = ids[ids.length - 1];
            if (next) {
                event.preventDefault();
                select(next, true);
            }
        });
        var api = {
            select: select,
            current: function () { return current; },
            panel: function (id) { return panels[id] || null; },
            isVisible: function (id) { return current === id; },
        };
        select('measure', false);
        root._tunerTabs = api;
        return api;
    }

    var api = { TABS: TABS, MENU: MENU, createTabs: createTabs };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.viewTabs = api;
    lib.releases.view_tabs = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
