// Tuner: Hann-windowed magnitude spectrum, display reduction and harmonic
// band power. Runs in the analysis Worker; also loaded by Vitest.
//
// Level definitions (all dBFS, i.e. relative to digital full scale, NOT sound
// pressure, because phone microphones and gain are uncalibrated):
// - Bin level:   20*log10(2*|X[k]| / sum(w)) -> a full-scale sine on a bin centre reads 0 dB.
// - Band power:  P = 2*sum(|X[k]|^2) / (N * sum(w^2)) is the mean power of the
//                component (A^2/2 for a sine of amplitude A, by Parseval);
//                reported as 10*log10(2P) so a full-scale sine is again 0 dB
//                regardless of where it falls between bins.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-b0635dde6c4d'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    var fft = lib.fft || (typeof require === 'function' ? require('./fft.js') : null);
    if (!fft) throw new Error('tuner spectrum.js requires fft.js to be loaded first');

    var DEFAULTS = {
        fftSize: 16384,
        // Default display axis ("倍音重視"). The axis is a display concern only:
        // the FFT always covers 0 Hz..Nyquist and the pitch detector is separate.
        displayMinFrequency: 500,
        displayMaxFrequency: 16000,
        displayPoints: 512,
        floorDb: -100,
        ceilingDb: 0,
        // Analysis data keeps a bounded harmonic list (up to Nyquist, independent
        // of the display axis); the graph draws its own markers.
        maxHarmonics: 40,
        // A fundamental band at or below this level has no defined relative
        // harmonic strength (relDb = null).
        detectionLimitDb: -100,
        // Octave-ambiguity threshold for subharmonicEvidence (tuning value).
        ambiguityDb: -20,
        // Candidate band this far below the total frame power = absent.
        absentFundamentalDb: -40,
    };

    // True when the evidence says the octave cannot be identified.
    function isOctaveAmbiguous(evidence, ambiguityDb) {
        if (!evidence) return false;
        if (evidence.absentFundamental) return true;
        var limit = typeof ambiguityDb === 'number' ? ambiguityDb : DEFAULTS.ambiguityDb;
        return evidence.strongestDb !== null && evidence.strongestDb > limit;
    }

    var FLOOR_DB = -160;

    function hannWindow(size) {
        var w = new Float64Array(size);
        for (var i = 0; i < size; i += 1) w[i] = 0.5 - 0.5 * Math.cos((2 * Math.PI * i) / size);
        return w;
    }

    // Log-spaced display frequencies. Points above Nyquist are kept in the
    // axis but marked not displayable so the graph never invents data there.
    function displayFrequencies(minFrequency, maxFrequency, points) {
        var freqs = new Float64Array(points);
        var ratio = Math.log(maxFrequency / minFrequency);
        for (var i = 0; i < points; i += 1) {
            freqs[i] = minFrequency * Math.exp((ratio * i) / (points - 1));
        }
        return freqs;
    }

    function createSpectrumAnalyzer(options) {
        var opts = Object.assign({}, DEFAULTS, options || {});
        var sampleRate = Number(opts.sampleRate);
        if (!(sampleRate > 0)) throw new Error('sampleRate is required');
        var size = opts.fftSize;
        if (!fft.isPowerOfTwo(size)) throw new Error('fftSize must be a power of two');
        var taper = hannWindow(size);
        var windowSum = 0;
        var windowSquareSum = 0;
        for (var i = 0; i < size; i += 1) {
            windowSum += taper[i];
            windowSquareSum += taper[i] * taper[i];
        }
        var binHz = sampleRate / size;
        var nyquist = sampleRate / 2;
        var re = new Float64Array(size);
        var im = new Float64Array(size);
        var power = new Float64Array(size / 2 + 1);
        var binDb = new Float32Array(size / 2 + 1);
        var defaultAxis = displayFrequencies(opts.displayMinFrequency, opts.displayMaxFrequency, opts.displayPoints);
        // Hann main lobe spans +/-2 bins; a band narrower than that loses power.
        var mainLobeBins = 2;

        function analyze(samples) {
            if (!samples || samples.length < size) throw new Error('need ' + size + ' samples');
            var offset = samples.length - size;
            var mean = 0;
            var k;
            for (k = 0; k < size; k += 1) mean += samples[offset + k];
            mean /= size;
            for (k = 0; k < size; k += 1) {
                re[k] = (samples[offset + k] - mean) * taper[k];
                im[k] = 0;
            }
            fft.transform(re, im, false);
            for (k = 0; k <= size / 2; k += 1) {
                var magSquared = re[k] * re[k] + im[k] * im[k];
                power[k] = magSquared;
                var amplitude = (2 * Math.sqrt(magSquared)) / windowSum;
                binDb[k] = amplitude > 0 ? Math.max(FLOOR_DB, 20 * Math.log10(amplitude)) : FLOOR_DB;
            }
            return { binHz: binHz, binDb: binDb };
        }

        // Reduce ~8k bins to the log-spaced display points: the loudest bin in
        // each point's span (so narrow peaks survive) or, where points are
        // closer than one bin (low end), linear interpolation between bins.
        // `axis` (optional) is a display axis from displayFrequencies(); the
        // analyser's default axis is used when omitted.
        function reduceForDisplay(out, axis) {
            var freqs = axis || defaultAxis;
            var points = freqs.length;
            var display = out || new Float32Array(points);
            for (var p = 0; p < points; p += 1) {
                var f = freqs[p];
                if (f >= nyquist) {
                    display[p] = NaN;
                    continue;
                }
                var lo = p === 0 ? f : Math.sqrt(freqs[p - 1] * f);
                var hi = p === points - 1 ? f : Math.sqrt(f * freqs[p + 1]);
                var kLo = Math.ceil(lo / binHz);
                var kHi = Math.min(Math.floor(hi / binHz), size / 2);
                if (kHi >= kLo) {
                    var best = FLOOR_DB;
                    for (var k = kLo; k <= kHi; k += 1) if (binDb[k] > best) best = binDb[k];
                    display[p] = best;
                } else {
                    var pos = f / binHz;
                    var k0 = Math.floor(pos);
                    var frac = pos - k0;
                    display[p] = binDb[k0] * (1 - frac) + binDb[Math.min(k0 + 1, size / 2)] * frac;
                }
            }
            return display;
        }

        function bandPowerDb(center, halfWidth) {
            var kLo = Math.max(1, Math.ceil((center - halfWidth) / binHz));
            var kHi = Math.min(size / 2 - 1, Math.floor((center + halfWidth) / binHz));
            var sum = 0;
            for (var k = kLo; k <= kHi; k += 1) sum += power[k];
            var meanPower = (2 * sum) / (size * windowSquareSum);
            return meanPower > 0 ? Math.max(FLOOR_DB, 10 * Math.log10(2 * meanPower)) : FLOOR_DB;
        }

        // Harmonic strengths from band power around n * f0. A harmonic is only
        // marked valid when its band can hold the Hann main lobe without
        // overlapping the neighbouring harmonic and lies below Nyquist; invalid
        // entries still carry a value but must not be used as a measurement.
        // relDb = harmonic - fundamental (dB); undefined (null) when the
        // fundamental band is at or below the detection limit.
        function harmonics(fundamental, limitFrequency) {
            var list = [];
            if (!(fundamental > 0)) return list;
            var limit = Math.min(limitFrequency || nyquist, nyquist);
            var halfWidth = Math.min(fundamental / 2, (mainLobeBins + 1) * binHz);
            var separable = fundamental / 2 >= (mainLobeBins + 1) * binHz;
            var fundamentalDb = null;
            for (var n = 1; n <= opts.maxHarmonics; n += 1) {
                var frequency = fundamental * n;
                if (frequency > limit) break;
                var belowNyquist = frequency + halfWidth < nyquist;
                var power = bandPowerDb(frequency, halfWidth);
                var valid = separable && belowNyquist;
                if (n === 1) fundamentalDb = valid && power > opts.detectionLimitDb ? power : null;
                list.push({
                    number: n,
                    frequency: frequency,
                    powerDbfs: power,
                    relDb: fundamentalDb !== null && valid ? power - fundamentalDb : null,
                    valid: valid,
                });
            }
            return list;
        }

        // Quality check for the YIN candidate (never a replacement): band
        // power at 0.5 * f0 and 1.5 * f0 relative to the f0 band. A strong
        // component there means the true period may be twice as long (e.g. a
        // tone without its fundamental): the octave is ambiguous.
        function subharmonicEvidence(fundamental) {
            if (!(fundamental > 0)) return null;
            var halfWidth = Math.min(fundamental / 4, (mainLobeBins + 1) * binHz);
            if (fundamental / 4 < (mainLobeBins + 1) * binHz) return null; // not resolvable with this window
            var base = bandPowerDb(fundamental, halfWidth);
            // No energy at the candidate itself (relative to the whole frame):
            // the "fundamental" is only implied by its partials.
            var absent = !(base > opts.detectionLimitDb) || base - totalPowerDb() < opts.absentFundamentalDb;
            if (absent) return { halfDb: null, threeHalvesDb: null, strongestDb: null, absentFundamental: true };
            var half = fundamental * 0.5 >= 20 ? bandPowerDb(fundamental * 0.5, halfWidth) - base : null;
            var threeHalves = fundamental * 1.5 + halfWidth < nyquist ? bandPowerDb(fundamental * 1.5, halfWidth) - base : null;
            var strongest = Math.max(half === null ? -Infinity : half, threeHalves === null ? -Infinity : threeHalves);
            return { halfDb: half, threeHalvesDb: threeHalves, strongestDb: Number.isFinite(strongest) ? strongest : null, absentFundamental: false };
        }

        // Band power at arbitrary frequencies (playback leakage estimate).
        function bandsDb(frequencies, halfWidthHz) {
            var width = halfWidthHz || (mainLobeBins + 1) * binHz;
            return (frequencies || []).map(function (f) {
                return f > 0 && f + width < nyquist ? bandPowerDb(f, width) : null;
            });
        }

        function totalPowerDb() {
            var sum = 0;
            for (var k = 1; k < size / 2; k += 1) sum += power[k];
            var meanPower = (2 * sum) / (size * windowSquareSum);
            return meanPower > 0 ? Math.max(FLOOR_DB, 10 * Math.log10(2 * meanPower)) : FLOOR_DB;
        }

        return {
            sampleRate: sampleRate,
            fftSize: size,
            binHz: binHz,
            nyquist: nyquist,
            window: 'hann',
            displayFrequencies: defaultAxis,
            options: opts,
            analyze: analyze,
            reduceForDisplay: reduceForDisplay,
            bandPowerDb: bandPowerDb,
            harmonics: harmonics,
            subharmonicEvidence: subharmonicEvidence,
            bandsDb: bandsDb,
            totalPowerDb: totalPowerDb,
        };
    }

    var api = {
        DEFAULTS: DEFAULTS,
        hannWindow: hannWindow,
        displayFrequencies: displayFrequencies,
        createSpectrumAnalyzer: createSpectrumAnalyzer,
        isOctaveAmbiguous: isOctaveAmbiguous,
    };

    lib.releases = lib.releases || {};
    lib.spectrum = api;
    lib.releases.spectrum = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
