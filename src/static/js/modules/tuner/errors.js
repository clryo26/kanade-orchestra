// Tuner: single place that turns start-up failures into user guidance.
// Browsers do not always reveal *why* the microphone is unavailable
// (e.g. "in use by another app" vs. an OS restriction), so the messages only
// state what can actually be confirmed.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-e945264406d5'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var MESSAGES = {
        'not-found': {
            title: 'マイクが見つかりません',
            detail: 'マイクが接続されているか確認してから、もう一度お試しください。',
            action: 'retry',
        },
        denied: {
            title: 'マイクの使用が許可されていません',
            detail: 'iPhoneでは、アドレスバーの「ぁあ」（または「…」）→「Webサイトの設定」→「マイク」で「許可」を選ぶか、「設定」→「アプリ」→「Safari」→「マイク」を確認してください。PCでは、アドレスバーのマイクまたは鍵のアイコンから許可してください。許可を変えたら「もう一度試す」を押してください。',
            action: 'retry',
        },
        unsupported: {
            title: 'このブラウザーはチューナーに対応していません',
            detail: '必要な音声処理を利用できません。最新のSafariまたはChromeでお試しください。',
            action: 'none',
        },
        insecure: {
            title: '安全な接続ではないため、マイクを利用できません',
            detail: 'マイクは https で始まるアドレスで開いた場合だけ利用できます。',
            action: 'none',
        },
        unreadable: {
            title: 'マイクを読み取れません',
            detail: 'ほかのアプリで使用中、または端末側で利用できません。ほかのアプリを閉じてから、もう一度お試しください。',
            action: 'retry',
        },
        'load-failed': {
            title: 'チューナーを読み込めませんでした',
            detail: '通信状態を確認してから、もう一度お試しください。',
            action: 'retry',
        },
        'version-mismatch': {
            title: 'チューナーが更新されています',
            detail: '古い部品と新しい部品が混在しているため開始できません。ページを再読み込みしてください。',
            action: 'reload',
        },
        'resume-required': {
            title: '測定を一時停止しています',
            detail: 'ボタンを押すと測定を再開します。',
            action: 'resume',
        },
    };

    function makeError(code, cause) {
        var error = new Error(code);
        error.tunerCode = code;
        if (cause) error.cause = cause;
        return error;
    }

    // env: { isSecureContext, hasGetUserMedia, hasAudioContext, hasAudioWorklet, hasWorker, hasMessageChannel }
    function checkEnvironment(env) {
        if (!env.isSecureContext) return 'insecure';
        if (!env.hasGetUserMedia || !env.hasAudioContext || !env.hasAudioWorklet || !env.hasWorker || !env.hasMessageChannel) {
            return 'unsupported';
        }
        return null;
    }

    function classifyStartError(error, env) {
        if (error && error.tunerCode && MESSAGES[error.tunerCode]) return error.tunerCode;
        var name = error && error.name ? String(error.name) : '';
        if (name === 'NotAllowedError' || name === 'PermissionDeniedError') return 'denied';
        if (name === 'SecurityError') return env && env.isSecureContext === false ? 'insecure' : 'denied';
        if (name === 'NotFoundError' || name === 'DevicesNotFoundError' || name === 'OverconstrainedError') return 'not-found';
        if (name === 'NotReadableError' || name === 'TrackStartError' || name === 'AbortError') return 'unreadable';
        if (name === 'NotSupportedError' || name === 'TypeError') return 'unsupported';
        return 'unreadable';
    }

    function messageFor(code) {
        return MESSAGES[code] || MESSAGES.unreadable;
    }

    var api = {
        MESSAGES: MESSAGES,
        makeError: makeError,
        checkEnvironment: checkEnvironment,
        classifyStartError: classifyStartError,
        messageFor: messageFor,
    };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.errors = api;
    lib.releases.errors = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
