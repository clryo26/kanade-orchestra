// Tuner: analysis Worker (classic Worker, dependencies via importScripts).
// Receives audio chunks directly from the capture AudioWorklet over a
// MessagePort (the main thread never relays audio), runs YIN pitch detection
// and the FFT spectrum, and posts compact results to the main thread.
// Audio and full FFT data stay inside this Worker and are never stored.
'use strict';

var TUNER_RELEASE_ID = 't-e8d471ab55a0'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)
var TUNER_PROTOCOL = 1;

var PITCH_INTERVAL_SECONDS = 1 / 20;
var SPECTRUM_INTERVAL_SECONDS = 1 / 10;
// A spectrum uses the latest valid pitch only if it is this recent.
var FUNDAMENTAL_MAX_AGE_SECONDS = 0.25;

var depsLoaded = false;
(function loadDependencies() {
    // Same ?rev= query as this worker, so dependencies come from the same release.
    var query = self.location && self.location.search ? self.location.search : '';
    try {
        importScripts('fft.js' + query, 'pitch.js' + query, 'spectrum.js' + query);
        depsLoaded = true;
    } catch (error) {
        depsLoaded = false;
    }
})();

var session = null;

function dependencyReleasesMatch() {
    var lib = self.PortalTunerLib;
    if (!lib || !lib.releases) return false;
    return ['fft', 'pitch', 'spectrum'].every(function (name) {
        return lib.releases[name] === TUNER_RELEASE_ID;
    });
}

function post(message, transfer) {
    message.release = TUNER_RELEASE_ID;
    message.protocol = TUNER_PROTOCOL;
    if (session) message.generation = session.generation;
    self.postMessage(message, transfer || []);
}

// Display axis requested by the main thread (e.g. 500 Hz-16 kHz or
// 25 Hz-16 kHz). It only changes how the full FFT is reduced for drawing; the
// FFT itself, the harmonic analysis (up to Nyquist) and the pitch detector
// (31-4,400 Hz) are unaffected, so switching it never stops low-note detection.
function buildAxis(range, fallback) {
    var min = range && Number(range.min);
    var max = range && Number(range.max);
    if (!(min >= 10 && max > min && max <= 48000)) {
        min = fallback.min;
        max = fallback.max;
    }
    var points = self.PortalTunerLib.spectrum.DEFAULTS.displayPoints;
    return {
        axisId: range && Number.isInteger(range.axisId) ? range.axisId : 0,
        min: min,
        max: max,
        frequencies: self.PortalTunerLib.spectrum.displayFrequencies(min, max, points),
    };
}

function postAxis(s) {
    post({
        type: 'display-axis',
        axis: {
            axisId: s.axis.axisId,
            min: s.axis.min,
            max: s.axis.max,
            nyquist: s.spectrum.nyquist,
            frequencies: Array.prototype.slice.call(s.axis.frequencies),
        },
    });
}

function createSession(init) {
    var pitchDetector = self.PortalTunerLib.pitch.createPitchDetector({ sampleRate: init.sampleRate });
    var spectrumAnalyzer = self.PortalTunerLib.spectrum.createSpectrumAnalyzer({ sampleRate: init.sampleRate });
    var capacity = Math.max(pitchDetector.frameLength, spectrumAnalyzer.fftSize);
    var defaults = self.PortalTunerLib.spectrum.DEFAULTS;
    return {
        axis: buildAxis(init.displayRange, { min: defaults.displayMinFrequency, max: defaults.displayMaxFrequency }),
        generation: init.generation,
        sampleRate: init.sampleRate,
        port: init.port,
        pitch: pitchDetector,
        spectrum: spectrumAnalyzer,
        ring: new Float32Array(capacity),
        writeIndex: 0,
        filled: 0,
        pitchScratch: new Float32Array(pitchDetector.frameLength),
        spectrumScratch: new Float32Array(spectrumAnalyzer.fftSize),
        pitchInterval: Math.round(init.sampleRate * PITCH_INTERVAL_SECONDS),
        spectrumInterval: Math.round(init.sampleRate * SPECTRUM_INTERVAL_SECONDS),
        nextPitchAt: null,
        nextSpectrumAt: null,
        lastValidPitch: null,
        expectedStartFrame: null,
        versionReported: false,
    };
}

function resetContinuity(s) {
    s.writeIndex = 0;
    s.filled = 0;
    s.nextPitchAt = null;
    s.nextSpectrumAt = null;
    s.lastValidPitch = null;
}

function writeSamples(s, samples) {
    var ring = s.ring;
    for (var i = 0; i < samples.length; i += 1) {
        ring[s.writeIndex] = samples[i];
        s.writeIndex = (s.writeIndex + 1) % ring.length;
    }
    s.filled = Math.min(ring.length, s.filled + samples.length);
}

function copyLatest(s, target) {
    var ring = s.ring;
    var start = (s.writeIndex - target.length + ring.length) % ring.length;
    for (var i = 0; i < target.length; i += 1) target[i] = ring[(start + i) % ring.length];
    return target;
}

function analysePitch(s, endFrame) {
    var result = s.pitch.detect(copyLatest(s, s.pitchScratch));
    var frame = {
        startFrame: endFrame - s.pitch.frameLength,
        endFrame: endFrame,
        time: endFrame / s.sampleRate,
        frequency: result.valid ? result.frequency : 0,
        confidence: result.confidence,
        valid: result.valid,
        reason: result.reason,
        rmsDbfs: result.rmsDbfs,
    };
    if (result.valid) s.lastValidPitch = frame;
    post({ type: 'pitch', frame: frame });
}

function analyseSpectrum(s, endFrame) {
    s.spectrum.analyze(copyLatest(s, s.spectrumScratch));
    var display = s.spectrum.reduceForDisplay(new Float32Array(s.axis.frequencies.length), s.axis.frequencies);
    var fundamental = 0;
    if (s.lastValidPitch && (endFrame - s.lastValidPitch.endFrame) / s.sampleRate <= FUNDAMENTAL_MAX_AGE_SECONDS) {
        fundamental = s.lastValidPitch.frequency;
    }
    var frame = {
        startFrame: endFrame - s.spectrum.fftSize,
        endFrame: endFrame,
        time: endFrame / s.sampleRate,
        fundamental: fundamental,
        // Analysis harmonics up to Nyquist (not limited by the display axis).
        harmonics: fundamental ? s.spectrum.harmonics(fundamental) : [],
        axisId: s.axis.axisId,
        display: display,
    };
    post({ type: 'spectrum', frame: frame }, [display.buffer]);
}

function dueAt(s, key, interval, endFrame) {
    if (s[key] === null) {
        s[key] = endFrame + interval;
        return true;
    }
    if (endFrame < s[key]) return false;
    s[key] += interval;
    if (s[key] <= endFrame) s[key] = endFrame + 1;
    return true;
}

function handleAudio(message) {
    var s = session;
    if (!s || !message || message.type !== 'audio') return;
    if (message.release !== TUNER_RELEASE_ID || message.protocol !== TUNER_PROTOCOL) {
        if (!s.versionReported) post({ type: 'version-mismatch', source: 'worklet' });
        s.versionReported = true;
        return;
    }
    if (message.generation !== s.generation || !(message.buffer instanceof ArrayBuffer)) return;
    var samples = new Float32Array(message.buffer);
    // Continuity is also checked from the timestamps, so a discontinuity is
    // never stitched together even if a chunk arrives without the gap flag.
    var discontinuous = s.expectedStartFrame !== null && message.startFrame !== s.expectedStartFrame;
    if (message.gap || discontinuous) {
        // Audio was dropped (or this is the first chunk): never treat the
        // samples before and after as one continuous waveform.
        resetContinuity(s);
        var dropped = message.droppedFrames || (discontinuous ? Math.max(0, message.startFrame - s.expectedStartFrame) : 0);
        post({ type: 'gap', droppedFrames: dropped });
    }
    s.expectedStartFrame = message.startFrame + samples.length;
    writeSamples(s, samples);
    var endFrame = message.startFrame + samples.length;
    // Hand the buffer back to the worklet's fixed pool as soon as it is copied.
    try {
        s.port.postMessage({ type: 'return', buffer: message.buffer }, [message.buffer]);
    } catch (_) { /* port closed during shutdown */ }

    // Analysis runs on a schedule in audio-frame time (not per chunk), so
    // 2,048-sample chunks (~43 ms) still give up to 20 pitch updates/s. At most
    // one analysis of each kind runs per chunk; when behind, the schedule
    // restarts from now instead of queueing up catch-up work.
    if (dueAt(s, 'nextPitchAt', s.pitchInterval, endFrame)) {
        if (s.filled >= s.pitch.frameLength) analysePitch(s, endFrame);
        else post({ type: 'status', state: 'buffering' }); // keeps the main-thread watchdog fed
    }
    if (s.filled >= s.spectrum.fftSize && dueAt(s, 'nextSpectrumAt', s.spectrumInterval, endFrame)) {
        analyseSpectrum(s, endFrame);
    }
}

function stopSession() {
    if (session && session.port) {
        try { session.port.onmessage = null; session.port.close(); } catch (_) { /* already closed */ }
    }
    session = null;
}

self.onmessage = function (event) {
    var message = event.data || {};
    if (message.type === 'init') {
        stopSession();
        if (!depsLoaded) {
            self.postMessage({ type: 'load-failed', release: TUNER_RELEASE_ID, protocol: TUNER_PROTOCOL, generation: message.generation });
            return;
        }
        if (message.release !== TUNER_RELEASE_ID || message.protocol !== TUNER_PROTOCOL || !dependencyReleasesMatch()) {
            self.postMessage({ type: 'version-mismatch', source: 'worker', release: TUNER_RELEASE_ID, protocol: TUNER_PROTOCOL, generation: message.generation });
            return;
        }
        if (!(message.sampleRate > 0) || !message.port) {
            self.postMessage({ type: 'error', release: TUNER_RELEASE_ID, protocol: TUNER_PROTOCOL, generation: message.generation });
            return;
        }
        session = createSession(message);
        session.port.onmessage = function (portEvent) { handleAudio(portEvent.data); };
        post({
            type: 'ready',
            session: {
                sampleRate: session.sampleRate,
                pitchFrameLength: session.pitch.frameLength,
                pitchWindowLength: session.pitch.windowLength,
                fftSize: session.spectrum.fftSize,
                window: session.spectrum.window,
                binHz: session.spectrum.binHz,
                nyquist: session.spectrum.nyquist,
                floorDb: session.spectrum.options.floorDb,
                ceilingDb: session.spectrum.options.ceilingDb,
                displayMinFrequency: session.axis.min,
                displayMaxFrequency: session.axis.max,
            },
        });
        postAxis(session);
    } else if (message.type === 'display-range') {
        if (!session || message.generation !== session.generation) return;
        session.axis = buildAxis(message.range, session.axis);
        postAxis(session);
    } else if (message.type === 'stop') {
        stopSession();
        self.close();
    }
};

// Exposed for Vitest, which evaluates this file with a stubbed `self`.
if (typeof module !== 'undefined' && module.exports) {
    module.exports = { handleAudio: handleAudio, getSession: function () { return session; } };
}
