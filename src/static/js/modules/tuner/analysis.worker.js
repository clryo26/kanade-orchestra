// Tuner: analysis Worker (classic Worker, dependencies via importScripts).
// Receives audio chunks directly from the capture AudioWorklet over a
// MessagePort (the main thread never relays audio), runs YIN pitch detection,
// the RMS envelope and the FFT spectrum, and posts compact results to the
// main thread. Audio and full FFT data stay inside this Worker and are never
// stored or sent anywhere.
//
// Protocol 2 (docs/TUNER_ADVANCED_DATA_API_DESIGN.md 1.1/1.2):
// - pitch frames carry analysisStartFrame (inclusive), analysisEndFrameExclusive
//   and the effective time effectiveFrame2 = start + end - 1 (twice the mean
//   sample index of the analysed samples, an integer). frequencyHz is null for
//   invalid frames; 0 Hz never stands for "no value".
// - envelope frames: 10 ms RMS windows (10 ms hop) for onset detection.
// - quality flags / invalid reasons as in pitch.js FLAGS / INVALID_REASON.
'use strict';

var TUNER_RELEASE_ID = 't-b0635dde6c4d'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)
var TUNER_PROTOCOL = 2;
var ENGINE_VERSION = 'yin-2';

var SPECTRUM_INTERVAL_SECONDS = 1 / 10;
var SHORT_FFT_SIZE = 4096;
var SHORT_FFT_INTERVAL_SECONDS = 1 / 20;
var ENVELOPE_WINDOW_SECONDS = 0.01;
// A spectrum uses the latest valid pitch only if it is this recent.
var FUNDAMENTAL_MAX_AGE_SECONDS = 0.25;

// Analysis profiles (design "capture" 5.1). Ranges are clamped to Nyquist.
var PROFILES = {
    full: { window: 'long', minHz: 28, maxHz: 4700, rateHz: 30 },
    low: { window: 'long', minHz: 28, maxHz: 880, rateHz: 20 },
    high: { window: 'short', minHz: 110, maxHz: 4700, rateHz: 40 },
    vibrato: { window: 'short', minHz: 110, maxHz: 4700, rateHz: 40 },
};
// Adaptive long->short switching (tuning values; off unless configured).
var ADAPTIVE = { toShortHz: 140, toShortFrames: 3, toLongHz: 120, toLongFrames: 2, monitorLongHz: 5, lowConfidenceMs: 100 };

var depsLoaded = false;
(function loadDependencies() {
    // Same ?rev= query as this worker, so dependencies come from the same release.
    var query = self.location && self.location.search ? self.location.search : '';
    try {
        importScripts('fft.js' + query, 'pitch.js' + query, 'spectrum.js' + query);
        depsLoaded = true;
    } catch (error) {
        depsLoaded = false;
    }
})();

var session = null;

function dependencyReleasesMatch() {
    var lib = self.PortalTunerLib;
    if (!lib || !lib.releases) return false;
    return ['fft', 'pitch', 'spectrum'].every(function (name) {
        return lib.releases[name] === TUNER_RELEASE_ID;
    });
}

function post(message, transfer) {
    message.release = TUNER_RELEASE_ID;
    message.protocol = TUNER_PROTOCOL;
    if (session) {
        message.generation = session.generation;
        message.captureEpoch = session.generation;
        message.settingsRevision = session.settingsRevision;
    }
    self.postMessage(message, transfer || []);
}

// Display axis requested by the main thread (e.g. 500 Hz-16 kHz or
// 25 Hz-16 kHz). It only changes how the full FFT is reduced for drawing; the
// FFT itself, the harmonic analysis (up to Nyquist) and the pitch detector
// are unaffected, so switching it never stops low-note detection.
function buildAxis(range, fallback) {
    var min = range && Number(range.min);
    var max = range && Number(range.max);
    if (!(min >= 10 && max > min && max <= 48000)) {
        min = fallback.min;
        max = fallback.max;
    }
    var points = self.PortalTunerLib.spectrum.DEFAULTS.displayPoints;
    return {
        axisId: range && Number.isInteger(range.axisId) ? range.axisId : 0,
        min: min,
        max: max,
        frequencies: self.PortalTunerLib.spectrum.displayFrequencies(min, max, points),
    };
}

function postAxis(s) {
    post({
        type: 'display-axis',
        axis: {
            axisId: s.axis.axisId,
            min: s.axis.min,
            max: s.axis.max,
            nyquist: s.spectrum.nyquist,
            frequencies: Array.prototype.slice.call(s.axis.frequencies),
        },
    });
}

function profileRange(name, sampleRate) {
    var profile = PROFILES[name] || PROFILES.full;
    var nyquist = sampleRate / 2;
    // Keep the search a little below Nyquist; a low sample rate narrows the
    // usable range instead of pretending to cover the design range.
    var maxHz = Math.min(profile.maxHz, nyquist * 0.45);
    return { window: profile.window, minHz: profile.minHz, maxHz: maxHz, rateHz: profile.rateHz };
}

function createDetectors(s) {
    var lib = self.PortalTunerLib;
    var range = profileRange(s.profileName, s.sampleRate);
    var silence = s.silenceDbfs;
    var longMin = range.window === 'long' ? range.minHz : PROFILES.full.minHz;
    var longMax = range.window === 'long' ? range.maxHz : profileRange('full', s.sampleRate).maxHz;
    s.range = range;
    s.longDetector = lib.pitch.createPitchDetector({ sampleRate: s.sampleRate, minFrequency: longMin, maxFrequency: longMax, silenceDbfs: silence });
    s.shortDetector = lib.pitch.createPitchDetector({ sampleRate: s.sampleRate, minFrequency: PROFILES.high.minHz, maxFrequency: profileRange('high', s.sampleRate).maxHz, silenceDbfs: silence });
    s.longScratch = new Float32Array(s.longDetector.frameLength);
    s.shortScratch = new Float32Array(s.shortDetector.frameLength);
    s.activeWindow = range.window;
    s.pitchInterval = Math.max(1, Math.round(s.sampleRate / range.rateHz));
    s.monitorInterval = Math.max(1, Math.round(s.sampleRate / ADAPTIVE.monitorLongHz));
    s.nextPitchAt = null;
    s.nextMonitorAt = null;
    s.adaptiveCount = 0;
    s.transitionFrames = 0;
}

function createSession(init) {
    var lib = self.PortalTunerLib;
    var spectrumAnalyzer = lib.spectrum.createSpectrumAnalyzer({ sampleRate: init.sampleRate });
    var shortAnalyzer = lib.spectrum.createSpectrumAnalyzer({ sampleRate: init.sampleRate, fftSize: SHORT_FFT_SIZE });
    var defaults = lib.spectrum.DEFAULTS;
    var config = init.config || {};
    var s = {
        axis: buildAxis(init.displayRange, { min: defaults.displayMinFrequency, max: defaults.displayMaxFrequency }),
        generation: init.generation,
        sampleRate: init.sampleRate,
        port: init.port,
        spectrum: spectrumAnalyzer,
        shortSpectrum: shortAnalyzer,
        spectrumScratch: new Float32Array(spectrumAnalyzer.fftSize),
        shortSpectrumScratch: new Float32Array(SHORT_FFT_SIZE),
        spectrumInterval: Math.round(init.sampleRate * SPECTRUM_INTERVAL_SECONDS),
        shortInterval: Math.round(init.sampleRate * SHORT_FFT_INTERVAL_SECONDS),
        nextSpectrumAt: null,
        nextShortAt: null,
        lastValidPitch: null,
        expectedStartFrame: null,
        expectedSequence: null,
        versionReported: false,
        settingsRevision: Number.isInteger(config.settingsRevision) ? config.settingsRevision : 0,
        profileName: PROFILES[config.profile] ? config.profile : 'full',
        adaptive: config.adaptive === true,
        silenceDbfs: typeof config.silenceDbfs === 'number' ? Math.max(-90, Math.min(-20, config.silenceDbfs)) : -60,
        playback: { active: false, frequencies: [] },
        envelopeLength: Math.max(1, Math.round(init.sampleRate * ENVELOPE_WINDOW_SECONDS)),
        envelopeSum: 0,
        envelopePeak: 0,
        envelopeCount: 0,
        envelopeStart: null,
        envelopeClipRun: 0,
        envelopeClipped: false,
    };
    createDetectors(s);
    var capacity = Math.max(s.longDetector.frameLength, s.shortDetector.frameLength, spectrumAnalyzer.fftSize);
    s.ring = new Float32Array(capacity);
    s.writeIndex = 0;
    s.filled = 0;
    return s;
}

function resetContinuity(s) {
    s.writeIndex = 0;
    s.filled = 0;
    s.nextPitchAt = null;
    s.nextMonitorAt = null;
    s.nextSpectrumAt = null;
    s.nextShortAt = null;
    s.lastValidPitch = null;
    s.envelopeSum = 0;
    s.envelopePeak = 0;
    s.envelopeCount = 0;
    s.envelopeStart = null;
    s.envelopeClipRun = 0;
    s.envelopeClipped = false;
}

function writeSamples(s, samples) {
    var ring = s.ring;
    for (var i = 0; i < samples.length; i += 1) {
        ring[s.writeIndex] = samples[i];
        s.writeIndex = (s.writeIndex + 1) % ring.length;
    }
    s.filled = Math.min(ring.length, s.filled + samples.length);
}

function copyLatest(s, target) {
    var ring = s.ring;
    var start = (s.writeIndex - target.length + ring.length) % ring.length;
    for (var i = 0; i < target.length; i += 1) target[i] = ring[(start + i) % ring.length];
    return target;
}

// 10 ms RMS envelope over contiguous samples; returns completed windows.
function envelopeFrames(s, samples, startFrame) {
    var out = [];
    for (var i = 0; i < samples.length; i += 1) {
        var v = samples[i];
        if (s.envelopeCount === 0) s.envelopeStart = startFrame + i;
        s.envelopeSum += v * v;
        var mag = Math.abs(v);
        if (mag > s.envelopePeak) s.envelopePeak = mag;
        s.envelopeClipRun = mag >= 0.999 ? s.envelopeClipRun + 1 : 0;
        if (s.envelopeClipRun >= 3) s.envelopeClipped = true;
        s.envelopeCount += 1;
        if (s.envelopeCount === s.envelopeLength) {
            var power = s.envelopeSum / s.envelopeLength;
            out.push({
                startFrame: s.envelopeStart,
                endFrame: s.envelopeStart + s.envelopeLength,
                effectiveFrame2: 2 * s.envelopeStart + s.envelopeLength - 1,
                rmsDbfs: power > 0 ? Math.max(-160, 10 * Math.log10(power)) : -160,
                peak: s.envelopePeak,
                clipped: s.envelopeClipped,
            });
            s.envelopeSum = 0;
            s.envelopePeak = 0;
            s.envelopeCount = 0;
            s.envelopeClipRun = 0;
            s.envelopeClipped = false;
        }
    }
    return out;
}

function detectorFor(s, windowName) {
    return windowName === 'short'
        ? { detector: s.shortDetector, scratch: s.shortScratch }
        : { detector: s.longDetector, scratch: s.longScratch };
}

function buildFrame(s, result, endFrame, detector, windowName) {
    var pitchLib = self.PortalTunerLib.pitch;
    var startFrame = endFrame - detector.frameLength;
    var flags = result.flags || 0;
    if (s.transitionFrames > 0) flags |= pitchLib.FLAGS.profileTransition;
    return {
        // Legacy fields (display): time is the window end, as before.
        startFrame: startFrame,
        endFrame: endFrame,
        time: endFrame / s.sampleRate,
        frequency: result.valid ? result.frequency : 0,
        confidence: result.confidence,
        valid: result.valid,
        reason: result.reason,
        rmsDbfs: result.rmsDbfs,
        // Protocol 2 contract fields.
        captureEpoch: s.generation,
        analysisStartFrame: startFrame,
        analysisEndFrameExclusive: endFrame,
        effectiveFrame2: startFrame + endFrame - 1,
        effectiveTime: (startFrame + endFrame - 1) / 2 / s.sampleRate,
        frequencyHz: result.valid ? result.frequency : null,
        qualityFlags: flags,
        invalidReason: result.invalidReason || 0,
        octaveAmbiguous: Boolean(flags & pitchLib.FLAGS.octaveAmbiguous),
        clipped: Boolean(flags & pitchLib.FLAGS.clipped),
        window: windowName,
        windowSamples: detector.frameLength,
        profile: s.profileName,
        engineVersion: ENGINE_VERSION,
    };
}

// Octave quality check with the short FFT (never replaces the YIN value).
function checkOctave(s, frame) {
    if (!frame.valid || !(frame.frequency >= 200)) return;
    copyLatest(s, s.shortSpectrumScratch);
    s.shortSpectrum.analyze(s.shortSpectrumScratch);
    var evidence = s.shortSpectrum.subharmonicEvidence(frame.frequency);
    if (self.PortalTunerLib.spectrum.isOctaveAmbiguous(evidence)) {
        frame.qualityFlags |= self.PortalTunerLib.pitch.FLAGS.octaveAmbiguous;
        frame.octaveAmbiguous = true;
    }
}

function adaptWindow(s, frame) {
    if (!s.adaptive || s.range.window !== 'long' || s.profileName !== 'full') return;
    if (s.activeWindow === 'long') {
        if (frame.valid && frame.frequency >= ADAPTIVE.toShortHz) s.adaptiveCount += 1;
        else s.adaptiveCount = 0;
        if (s.adaptiveCount >= ADAPTIVE.toShortFrames) {
            s.activeWindow = 'short';
            s.adaptiveCount = 0;
            s.transitionFrames = 2;
        }
    } else {
        var low = frame.valid && frame.frequency < ADAPTIVE.toLongHz;
        if (low || !frame.valid) s.adaptiveCount += 1;
        else s.adaptiveCount = 0;
        if (s.adaptiveCount >= ADAPTIVE.toLongFrames) {
            s.activeWindow = 'long';
            s.adaptiveCount = 0;
            s.transitionFrames = 2;
        }
    }
}

function analysePitch(s, endFrame) {
    var chosen = detectorFor(s, s.activeWindow);
    if (s.filled < chosen.detector.frameLength) return false;
    var result = chosen.detector.detect(copyLatest(s, chosen.scratch));
    var frame = buildFrame(s, result, endFrame, chosen.detector, s.activeWindow);
    checkOctave(s, frame);
    if (s.transitionFrames > 0) s.transitionFrames -= 1;
    if (frame.valid) s.lastValidPitch = frame;
    adaptWindow(s, frame);
    post({ type: 'pitch', frame: frame });
    return true;
}

// While the short window is active, the long window is checked at 5 Hz so a
// jump to a low note is not followed as one of its harmonics.
function monitorLong(s, endFrame) {
    if (s.activeWindow !== 'short' || !s.adaptive) return;
    if (s.filled < s.longDetector.frameLength) return;
    var result = s.longDetector.detect(copyLatest(s, s.longScratch));
    if (result.valid && result.frequency < ADAPTIVE.toLongHz) {
        s.activeWindow = 'long';
        s.adaptiveCount = 0;
        s.transitionFrames = 2;
    }
}

function playbackLeak(s, analyzer, fundamental) {
    var pb = s.playback;
    if (!pb.active || !pb.frequencies.length) return null;
    var total = analyzer.totalPowerDb();
    var levels = analyzer.bandsDb(pb.frequencies);
    var worst = null;
    var overlapsHarmonic = false;
    pb.frequencies.forEach(function (f, i) {
        // A played component on one of the detected note's harmonics cannot
        // be told apart from the player (design: any harmonic, not only
        // unison/octave): reported, never used to clear the data.
        if (fundamental > 0) {
            var n = Math.round(f / fundamental);
            if (n >= 1 && Math.abs(1200 * Math.log2(f / (n * fundamental))) < 35) overlapsHarmonic = true;
        }
        if (levels[i] === null) return;
        var rel = levels[i] - total;
        if (worst === null || rel > worst) worst = rel;
    });
    return { leakDb: worst, overlapsHarmonic: overlapsHarmonic };
}

function analyseSpectrum(s, endFrame) {
    s.spectrum.analyze(copyLatest(s, s.spectrumScratch));
    var display = s.spectrum.reduceForDisplay(new Float32Array(s.axis.frequencies.length), s.axis.frequencies);
    var fundamental = 0;
    if (s.lastValidPitch && (endFrame - s.lastValidPitch.endFrame) / s.sampleRate <= FUNDAMENTAL_MAX_AGE_SECONDS) {
        fundamental = s.lastValidPitch.frequency;
    }
    var startFrame = endFrame - s.spectrum.fftSize;
    var frame = {
        startFrame: startFrame,
        endFrame: endFrame,
        time: endFrame / s.sampleRate,
        effectiveFrame2: startFrame + endFrame - 1,
        fundamental: fundamental,
        // Analysis harmonics up to Nyquist (not limited by the display axis).
        harmonics: fundamental ? s.spectrum.harmonics(fundamental) : [],
        harmonicsWindow: s.spectrum.fftSize,
        axisId: s.axis.axisId,
        display: display,
        playback: playbackLeak(s, s.spectrum, fundamental),
    };
    post({ type: 'spectrum', frame: frame }, [display.buffer]);
}

// Short-window harmonics (4,096 points) for the attack part of notes.
function analyseShortHarmonics(s, endFrame) {
    if (!s.lastValidPitch || (endFrame - s.lastValidPitch.endFrame) / s.sampleRate > 0.1) return;
    var fundamental = s.lastValidPitch.frequency;
    copyLatest(s, s.shortSpectrumScratch);
    s.shortSpectrum.analyze(s.shortSpectrumScratch);
    var startFrame = endFrame - SHORT_FFT_SIZE;
    post({
        type: 'harmonics',
        frame: {
            effectiveFrame2: startFrame + endFrame - 1,
            startFrame: startFrame,
            endFrame: endFrame,
            window: SHORT_FFT_SIZE,
            fundamental: fundamental,
            harmonics: s.shortSpectrum.harmonics(fundamental),
        },
    });
}

function dueAt(s, key, interval, endFrame) {
    if (s[key] === null) {
        s[key] = endFrame + interval;
        return true;
    }
    if (endFrame < s[key]) return false;
    s[key] += interval;
    if (s[key] <= endFrame) s[key] = endFrame + 1;
    return true;
}

function handleAudio(message) {
    var s = session;
    if (!s || !message || message.type !== 'audio') return;
    if (message.release !== TUNER_RELEASE_ID || message.protocol !== TUNER_PROTOCOL) {
        if (!s.versionReported) post({ type: 'version-mismatch', source: 'worklet' });
        s.versionReported = true;
        return;
    }
    if (message.generation !== s.generation || !(message.buffer instanceof ArrayBuffer)) return;
    var samples = new Float32Array(message.buffer);
    // Continuity is also checked from the timestamps and the sequence, so a
    // discontinuity is never stitched together even without the gap flag.
    var discontinuous = s.expectedStartFrame !== null && message.startFrame !== s.expectedStartFrame;
    var sequenceBroken = s.expectedSequence !== null && Number.isInteger(message.sequence) && message.sequence !== s.expectedSequence;
    if (message.gap || discontinuous || sequenceBroken) {
        // Audio was dropped (or this is the first chunk): never treat the
        // samples before and after as one continuous waveform.
        resetContinuity(s);
        var dropped = message.droppedFrames || (discontinuous ? Math.max(0, message.startFrame - s.expectedStartFrame) : 0);
        post({ type: 'gap', droppedFrames: dropped, startFrame: message.startFrame });
    }
    s.expectedStartFrame = message.startFrame + samples.length;
    if (Number.isInteger(message.sequence)) s.expectedSequence = message.sequence + 1;
    writeSamples(s, samples);
    var envelope = envelopeFrames(s, samples, message.startFrame);
    var endFrame = message.startFrame + samples.length;
    // Hand the buffer back to the worklet's fixed pool as soon as it is copied.
    try {
        s.port.postMessage({ type: 'return', buffer: message.buffer }, [message.buffer]);
    } catch (_) { /* port closed during shutdown */ }
    if (envelope.length) post({ type: 'envelope', frames: envelope });

    // Analysis runs on a schedule in audio-frame time (not per chunk). At
    // most one analysis of each kind runs per chunk; when behind, the
    // schedule restarts from now instead of queueing up catch-up work.
    if (dueAt(s, 'nextPitchAt', s.pitchInterval, endFrame)) {
        if (!analysePitch(s, endFrame)) post({ type: 'status', state: 'buffering' }); // keeps the main-thread watchdog fed
    }
    if (s.adaptive && dueAt(s, 'nextMonitorAt', s.monitorInterval, endFrame)) monitorLong(s, endFrame);
    if (s.filled >= SHORT_FFT_SIZE && dueAt(s, 'nextShortAt', s.shortInterval, endFrame)) analyseShortHarmonics(s, endFrame);
    if (s.filled >= s.spectrum.fftSize && dueAt(s, 'nextSpectrumAt', s.spectrumInterval, endFrame)) {
        analyseSpectrum(s, endFrame);
    }
}

function stopSession() {
    if (session && session.port) {
        try { session.port.onmessage = null; session.port.close(); } catch (_) { /* already closed */ }
    }
    session = null;
}

function applyConfig(s, config) {
    if (!config) return;
    var changed = false;
    if (PROFILES[config.profile] && config.profile !== s.profileName) { s.profileName = config.profile; changed = true; }
    if (typeof config.adaptive === 'boolean' && config.adaptive !== s.adaptive) { s.adaptive = config.adaptive; changed = true; }
    if (typeof config.silenceDbfs === 'number') {
        var next = Math.max(-90, Math.min(-20, config.silenceDbfs));
        if (next !== s.silenceDbfs) { s.silenceDbfs = next; changed = true; }
    }
    if (Number.isInteger(config.settingsRevision)) s.settingsRevision = config.settingsRevision;
    if (changed) {
        createDetectors(s);
        s.transitionFrames = 2;
    }
}

self.onmessage = function (event) {
    var message = event.data || {};
    if (message.type === 'init') {
        stopSession();
        if (!depsLoaded) {
            self.postMessage({ type: 'load-failed', release: TUNER_RELEASE_ID, protocol: TUNER_PROTOCOL, generation: message.generation });
            return;
        }
        if (message.release !== TUNER_RELEASE_ID || message.protocol !== TUNER_PROTOCOL || !dependencyReleasesMatch()) {
            self.postMessage({ type: 'version-mismatch', source: 'worker', release: TUNER_RELEASE_ID, protocol: TUNER_PROTOCOL, generation: message.generation });
            return;
        }
        if (!(message.sampleRate > 0) || !message.port) {
            self.postMessage({ type: 'error', release: TUNER_RELEASE_ID, protocol: TUNER_PROTOCOL, generation: message.generation });
            return;
        }
        session = createSession(message);
        session.port.onmessage = function (portEvent) { handleAudio(portEvent.data); };
        post({
            type: 'ready',
            session: {
                sampleRate: session.sampleRate,
                pitchFrameLength: session.longDetector.frameLength,
                pitchWindowLength: session.longDetector.windowLength,
                shortFrameLength: session.shortDetector.frameLength,
                fftSize: session.spectrum.fftSize,
                shortFftSize: SHORT_FFT_SIZE,
                window: session.spectrum.window,
                binHz: session.spectrum.binHz,
                nyquist: session.spectrum.nyquist,
                floorDb: session.spectrum.options.floorDb,
                ceilingDb: session.spectrum.options.ceilingDb,
                displayMinFrequency: session.axis.min,
                displayMaxFrequency: session.axis.max,
                profile: session.profileName,
                range: { minHz: session.range.minHz, maxHz: session.range.maxHz, rateHz: session.range.rateHz, window: session.range.window },
                envelopeWindowFrames: session.envelopeLength,
                engineVersion: ENGINE_VERSION,
            },
        });
        postAxis(session);
    } else if (message.type === 'display-range') {
        if (!session || message.generation !== session.generation) return;
        session.axis = buildAxis(message.range, session.axis);
        postAxis(session);
    } else if (message.type === 'configure') {
        if (!session || message.generation !== session.generation) return;
        applyConfig(session, message.config);
        post({ type: 'configured', profile: session.profileName, range: { minHz: session.range.minHz, maxHz: session.range.maxHz, rateHz: session.range.rateHz, window: session.range.window } });
    } else if (message.type === 'playback-state') {
        if (!session || message.generation !== session.generation) return;
        var freqs = Array.isArray(message.frequencies) ? message.frequencies.filter(function (f) { return typeof f === 'number' && f > 0 && Number.isFinite(f); }).slice(0, 8) : [];
        session.playback = { active: Boolean(message.active) && freqs.length > 0, frequencies: freqs };
    } else if (message.type === 'stop') {
        stopSession();
        self.close();
    }
};

