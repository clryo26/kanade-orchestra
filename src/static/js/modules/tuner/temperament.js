// Tuner: just-intonation thirds measured against a chosen root.
//
// The root's frequency comes from the current A4 reference in 12-tone equal
// temperament; the target is the third ABOVE that root by the pure ratio
// (minor 6/5, major 5/4). The target is always computed from the root, never
// as a fixed cent correction, and it never follows the detected note.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-b0635dde6c4d'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    var music = lib.music || (typeof require === 'function' ? require('./music.js') : null);
    if (!music) throw new Error('tuner temperament.js requires music.js to be loaded first');

    var MODES = {
        equal: { id: 'equal', label: '平均律' },
        'minor-third': { id: 'minor-third', label: '純正律・短3度', intervalLabel: '純正短3度', semitones: 3, numerator: 6, denominator: 5 },
        'major-third': { id: 'major-third', label: '純正律・長3度', intervalLabel: '純正長3度', semitones: 4, numerator: 5, denominator: 4 },
    };
    var DEFAULT_MODE = 'equal';
    var DEFAULT_ROOT_MIDI = 60; // C4
    // Roots C1..A♭7: the third above stays within the detection range C1-C8
    // for both modes (A♭7 + major third = C8).
    var ROOT_MIN_MIDI = 24;
    var ROOT_MAX_MIDI = 104;

    function isJustMode(mode) {
        return mode === 'minor-third' || mode === 'major-third';
    }

    function isValidRoot(midi) {
        return Number.isInteger(midi) && midi >= ROOT_MIN_MIDI && midi <= ROOT_MAX_MIDI;
    }

    function rootOptions() {
        var list = [];
        for (var midi = ROOT_MIN_MIDI; midi <= ROOT_MAX_MIDI; midi += 1) list.push(music.describeNote(midi));
        return list;
    }

    // Difference between the pure and the equal-tempered interval, in cents
    // (+15.6413 for the minor third, -13.6863 for the major third).
    function pureOffsetCents(mode) {
        var info = MODES[mode];
        if (!isJustMode(mode)) return 0;
        return 1200 * Math.log2(info.numerator / info.denominator) - 100 * info.semitones;
    }

    // Everything the judgment and the graph need for one setting.
    function justTarget(mode, rootMidi, referenceA4) {
        if (!isJustMode(mode) || !isValidRoot(rootMidi)) return null;
        var info = MODES[mode];
        var rootFrequency = music.noteFrequency(rootMidi, referenceA4);
        var targetMidi = rootMidi + info.semitones;
        return {
            mode: mode,
            intervalLabel: info.intervalLabel,
            root: music.describeNote(rootMidi),
            rootFrequency: rootFrequency,
            target: music.describeNote(targetMidi),
            // Exact value; rounding is a display concern only.
            targetFrequency: (rootFrequency * info.numerator) / info.denominator,
            equalTargetFrequency: music.noteFrequency(targetMidi, referenceA4),
            offsetCents: pureOffsetCents(mode),
        };
    }

    var api = {
        MODES: MODES,
        DEFAULT_MODE: DEFAULT_MODE,
        DEFAULT_ROOT_MIDI: DEFAULT_ROOT_MIDI,
        ROOT_MIN_MIDI: ROOT_MIN_MIDI,
        ROOT_MAX_MIDI: ROOT_MAX_MIDI,
        isJustMode: isJustMode,
        isValidRoot: isValidRoot,
        rootOptions: rootOptions,
        pureOffsetCents: pureOffsetCents,
        justTarget: justTarget,
    };

    lib.releases = lib.releases || {};
    lib.temperament = api;
    lib.releases.temperament = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
