// Tuner: common target model (Phase 1). One pure function decides the
// target frequency for every temperament so that the meter, the graph,
// playback ("set from target") and the analysis all use the same value.
//
// resolve(config, detectedHz?) -> { targetHz, equalHz, midi, spelling, role,
//   ratio, temperament, temperamentVersion, anchorHz } or null.
//
// Rules (docs/TUNER_ADVANCED_DESIGN.md, "temperament"):
// - Equal: f(n) = A4 * 2^((n - 69) / 12). Auto = nearest note (the display
//   filter adds hysteresis), fixed = the chosen note.
// - Just thirds (existing modes): equal-tempered root Hz * 6/5 or * 5/4.
// - Just triads / seventh chords: equal-tempered root Hz * role ratio * 2^k.
// - Pythagorean: equal-tempered anchor Hz * (3/2)^k folded into one octave,
//   k taken from a 12-fifth window [start, start + 11] (default -3..8 =
//   E-flat..G-sharp around C). The window start is the "break" of the cycle.
// - Custom: equal temperament of each note plus a per-pitch-class offset in
//   cents (-100..+100, 0.1 steps) relative to the anchor; the anchor is 0.
// Spelling only changes names, never the frequency.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-5c2ad5661ae9'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)
    var TEMPERAMENT_VERSION = 1;

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    var music = lib.music || (typeof require === 'function' ? require('./music.js') : null);
    if (!music) throw new Error('tuner target_model.js requires music.js to be loaded first');

    // Standard note range C1..C8 (design: 28-4,700 Hz covers C1@390 and C8@480).
    var MIN_MIDI = 24;
    var MAX_MIDI = 108;
    var MIN_HZ = 28;
    var MAX_HZ = 4700;

    var TEMPERAMENTS = {
        equal: { id: 'equal', label: '平均律' },
        'minor-third': { id: 'minor-third', label: '純正律・短3度' },
        'major-third': { id: 'major-third', label: '純正律・長3度' },
        'just-major': { id: 'just-major', label: '純正律・長三和音' },
        'just-minor': { id: 'just-minor', label: '純正律・短三和音' },
        pythagorean: { id: 'pythagorean', label: 'ピタゴラス音律' },
        custom: { id: 'custom', label: 'カスタム音律' },
    };

    // Seventh ratios (design: major 7 = 15/8, minor 7 default 9/5, 16/9 and 7/4 selectable).
    var SEVENTHS = {
        'major-15/8': { semitones: 11, numerator: 15, denominator: 8, label: '長7度（15/8）' },
        'minor-9/5': { semitones: 10, numerator: 9, denominator: 5, label: '短7度（9/5）' },
        'minor-16/9': { semitones: 10, numerator: 16, denominator: 9, label: '短7度（16/9）' },
        'minor-7/4': { semitones: 10, numerator: 7, denominator: 4, label: '短7度（7/4・自然7度）' },
    };

    var ROLES = {
        'just-major': {
            root: { semitones: 0, numerator: 1, denominator: 1, label: '根音' },
            third: { semitones: 4, numerator: 5, denominator: 4, label: '長3度' },
            fifth: { semitones: 7, numerator: 3, denominator: 2, label: '完全5度' },
            seventh: null, // ratio chosen by config.seventh
        },
        'just-minor': {
            root: { semitones: 0, numerator: 1, denominator: 1, label: '根音' },
            third: { semitones: 3, numerator: 6, denominator: 5, label: '短3度' },
            fifth: { semitones: 7, numerator: 3, denominator: 2, label: '完全5度' },
            seventh: null,
        },
    };
    var THIRD_MODES = {
        'minor-third': { semitones: 3, numerator: 6, denominator: 5, label: '純正短3度' },
        'major-third': { semitones: 4, numerator: 5, denominator: 4, label: '純正長3度' },
    };

    // Letters and their pitch class; used for spelling.
    var LETTERS = ['C', 'D', 'E', 'F', 'G', 'A', 'B'];
    var LETTER_PC = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };
    var SOLFEGE = { C: 'ド', D: 'レ', E: 'ミ', F: 'ファ', G: 'ソ', A: 'ラ', B: 'シ' };
    var SHARP_NAMES = ['C', 'C♯', 'D', 'D♯', 'E', 'F', 'F♯', 'G', 'G♯', 'A', 'A♯', 'B'];
    var FLAT_NAMES = ['C', 'D♭', 'D', 'E♭', 'E', 'F', 'G♭', 'G', 'A♭', 'A', 'B♭', 'B'];

    function mod(n, m) {
        return ((n % m) + m) % m;
    }

    function accidentalText(offset) {
        if (offset === 0) return '';
        if (offset > 0) return offset === 2 ? '𝄪' : (offset === 1 ? '♯' : '♯' + offset);
        return offset === -2 ? '𝄫' : (offset === -1 ? '♭' : '♭' + -offset);
    }

    // Spelling from a letter + accidental, with the octave of the letter
    // (B♯3 is the same key as C4; the octave follows the written letter).
    function spellWith(midi, letter, offset) {
        var octave = Math.floor((midi - LETTER_PC[letter] - offset) / 12) - 1;
        var acc = accidentalText(offset);
        return {
            midi: midi,
            letter: letter + acc,
            solfege: SOLFEGE[letter] + acc,
            octave: octave,
            label: letter + acc + octave,
        };
    }

    function parseName(name) {
        var letter = name.charAt(0);
        var rest = name.slice(1);
        var offset = rest === '♯' ? 1 : (rest === '♭' ? -1 : 0);
        return { letter: letter, offset: offset };
    }

    // preference: 'sharp' | 'flat' | 'default' (the current fixed table).
    function spell(midi, preference) {
        var pc = mod(midi, 12);
        var name;
        if (preference === 'sharp') name = SHARP_NAMES[pc];
        else if (preference === 'flat') name = FLAT_NAMES[pc];
        else name = music.NOTE_NAMES[pc].letter;
        var parsed = parseName(name);
        return spellWith(midi, parsed.letter, parsed.offset);
    }

    // Spelling along a chain of fifths from the anchor's spelling. k fifths
    // above the anchor move the letter by 4 * k steps (mod 7).
    function spellFifths(midi, anchorMidi, k, anchorPreference) {
        var anchor = parseName(spell(anchorMidi, anchorPreference).letter.replace(/[0-9]/g, ''));
        var letterIndex = LETTERS.indexOf(anchor.letter);
        var targetLetter = LETTERS[mod(letterIndex + 4 * k, 7)];
        var natural = LETTER_PC[targetLetter];
        // Accidental so that letter + accidental equals the pitch class.
        var offset = mod(mod(midi, 12) - natural + 6, 12) - 6;
        return spellWith(midi, targetLetter, offset);
    }

    function isValidMidi(midi) {
        return Number.isInteger(midi) && midi >= MIN_MIDI && midi <= MAX_MIDI;
    }

    function a4From(config) {
        if (config && Number.isInteger(config.a4Tenths)) return config.a4Tenths / 10;
        if (config && typeof config.a4Hz === 'number' && config.a4Hz > 0) return config.a4Hz;
        return 442;
    }

    function pythagoreanK(pcOffset, start) {
        var first = Number.isInteger(start) ? start : -3;
        for (var k = first; k < first + 12; k += 1) {
            if (mod(7 * k, 12) === pcOffset) return k;
        }
        return 0; // unreachable: 7 is invertible mod 12
    }

    function foldOctave(ratio) {
        var r = ratio;
        while (r >= 2) r /= 2;
        while (r < 1) r *= 2;
        return r;
    }

    // Target for one note number under a pitch-class based temperament.
    function pcTarget(config, midi, a4) {
        var anchorMidi = isValidMidi(config.rootMidi) ? config.rootMidi : 60;
        var anchorHz = music.noteFrequency(anchorMidi, a4);
        var diff = midi - anchorMidi;
        var pcOffset = mod(diff, 12);
        var octaves = Math.floor(diff / 12);
        if (config.temperament === 'pythagorean') {
            var k = pythagoreanK(pcOffset, config.pythagoreanStart);
            var ratio = foldOctave(Math.pow(1.5, k));
            return {
                targetHz: anchorHz * ratio * Math.pow(2, octaves),
                ratio: ratio * Math.pow(2, octaves),
                fifths: k,
                spelling: spellFifths(midi, anchorMidi, k, config.anchorSpelling),
                anchorHz: anchorHz,
            };
        }
        // custom
        var offsets = Array.isArray(config.customOffsets) ? config.customOffsets : [];
        var cents = pcOffset === 0 ? 0 : clampOffset(offsets[pcOffset]);
        return {
            targetHz: music.noteFrequency(midi, a4) * Math.pow(2, cents / 1200),
            ratio: null,
            offsetCents: cents,
            spelling: spell(midi, config.spelling === 'flat' ? 'flat' : (config.spelling === 'sharp' ? 'sharp' : 'default')),
            anchorHz: anchorHz,
        };
    }

    function clampOffset(value) {
        var v = Number(value);
        if (!Number.isFinite(v)) return 0;
        return Math.max(-100, Math.min(100, Math.round(v * 10) / 10));
    }

    function nearestMidi(detectedHz, a4) {
        if (!(detectedHz > 0)) return null;
        return music.nearestMidi(detectedHz, a4);
    }

    function spellingFor(config, midi) {
        var pref = config.spelling === 'flat' ? 'flat' : (config.spelling === 'sharp' ? 'sharp' : 'default');
        return spell(midi, pref);
    }

    function result(config, fields) {
        var out = {
            temperament: config.temperament,
            temperamentVersion: TEMPERAMENT_VERSION,
            targetHz: fields.targetHz,
            equalHz: music.noteFrequency(fields.midi, fields.a4),
            midi: fields.midi,
            spelling: fields.spelling,
            role: fields.role || null,
            roleLabel: fields.roleLabel || null,
            ratio: fields.ratio === undefined ? null : fields.ratio,
            anchorHz: fields.anchorHz || null,
            rootMidi: fields.rootMidi === undefined ? null : fields.rootMidi,
            fixed: Boolean(fields.fixed),
        };
        out.equalCentsOffset = 1200 * Math.log2(out.targetHz / out.equalHz);
        if (fields.fifths !== undefined) out.fifths = fields.fifths;
        if (fields.offsetCents !== undefined) out.offsetCents = fields.offsetCents;
        return out;
    }

    // config: { temperament, a4Tenths, rootMidi, role, seventh, octaveShift,
    //           fixedMidi, pythagoreanStart, customOffsets, spelling }
    function resolve(config, detectedHz) {
        var cfg = config || {};
        var temperament = TEMPERAMENTS[cfg.temperament] ? cfg.temperament : 'equal';
        var a4 = a4From(cfg);
        var c = Object.assign({}, cfg, { temperament: temperament });
        var fixed = isValidMidi(cfg.fixedMidi) ? cfg.fixedMidi : null;

        if (temperament === 'equal') {
            var midi = fixed !== null ? fixed : nearestMidi(detectedHz, a4);
            if (midi === null) return null;
            return result(c, { a4: a4, midi: midi, targetHz: music.noteFrequency(midi, a4), spelling: spellingFor(c, midi), ratio: null, fixed: fixed !== null });
        }

        if (THIRD_MODES[temperament]) {
            var info = THIRD_MODES[temperament];
            var root = isValidMidi(cfg.rootMidi) ? cfg.rootMidi : 60;
            var rootHz = music.noteFrequency(root, a4);
            var targetMidi = root + info.semitones;
            return result(c, {
                a4: a4, midi: targetMidi, rootMidi: root, anchorHz: rootHz,
                targetHz: (rootHz * info.numerator) / info.denominator,
                ratio: info.numerator / info.denominator,
                spelling: spellFifths(targetMidi, root, info.semitones === 4 ? 4 : -3, cfg.anchorSpelling),
                role: 'third', roleLabel: info.label, fixed: true,
            });
        }

        if (ROLES[temperament]) {
            var rootMidi = isValidMidi(cfg.rootMidi) ? cfg.rootMidi : 60;
            var role = cfg.role && Object.prototype.hasOwnProperty.call(ROLES[temperament], cfg.role) ? cfg.role : 'root';
            var def = ROLES[temperament][role];
            if (role === 'seventh') def = SEVENTHS[cfg.seventh] || SEVENTHS['minor-9/5'];
            var shift = Number.isInteger(cfg.octaveShift) ? cfg.octaveShift : 0;
            var baseHz = music.noteFrequency(rootMidi, a4);
            var roleMidi = rootMidi + def.semitones + 12 * shift;
            if (!isValidMidi(roleMidi)) return null; // outside the standard range: not selectable
            var ratio = (def.numerator / def.denominator) * Math.pow(2, shift);
            var fifthsForSpelling = { 0: 0, 3: -3, 4: 4, 7: 1, 10: -2, 11: 5 }[def.semitones] || 0;
            return result(c, {
                a4: a4, midi: roleMidi, rootMidi: rootMidi, anchorHz: baseHz,
                targetHz: baseHz * ratio, ratio: ratio,
                spelling: spellFifths(roleMidi, rootMidi, fifthsForSpelling, cfg.anchorSpelling),
                role: role, roleLabel: def.label, fixed: true,
            });
        }

        // Pythagorean / custom: fixed note or the candidate nearest to the input.
        var chosen = fixed;
        if (chosen === null) {
            var near = nearestMidi(detectedHz, a4);
            if (near === null) return null;
            // The temperament can move a note by up to ~24 cents (custom: 100),
            // so compare the neighbours by their own targets.
            var best = null;
            for (var m = near - 1; m <= near + 1; m += 1) {
                if (!isValidMidi(m)) continue;
                var t = pcTarget(c, m, a4);
                var distance = Math.abs(1200 * Math.log2(detectedHz / t.targetHz));
                if (!best || distance < best.distance) best = { midi: m, distance: distance };
            }
            if (!best) return null;
            chosen = best.midi;
        }
        var pc = pcTarget(c, chosen, a4);
        return result(c, {
            a4: a4, midi: chosen, rootMidi: isValidMidi(cfg.rootMidi) ? cfg.rootMidi : 60,
            targetHz: pc.targetHz, ratio: pc.ratio, spelling: pc.spelling, anchorHz: pc.anchorHz,
            fifths: pc.fifths, offsetCents: pc.offsetCents, fixed: fixed !== null,
        });
    }

    // Twelve-note table for the detail view and for playback presets.
    function table(config) {
        var cfg = Object.assign({}, config || {});
        var anchor = isValidMidi(cfg.rootMidi) ? cfg.rootMidi : 60;
        var rows = [];
        for (var i = 0; i < 12; i += 1) {
            var r = resolve(Object.assign({}, cfg, { fixedMidi: anchor + i, role: cfg.role }), null);
            if (r) rows.push(r);
        }
        return rows;
    }

    // Validation shared by settings and presets.
    function normalizeConfig(config) {
        var cfg = config || {};
        var out = {
            temperament: TEMPERAMENTS[cfg.temperament] ? cfg.temperament : 'equal',
            rootMidi: isValidMidi(cfg.rootMidi) ? cfg.rootMidi : 60,
            role: ['root', 'third', 'fifth', 'seventh'].indexOf(cfg.role) >= 0 ? cfg.role : 'root',
            seventh: SEVENTHS[cfg.seventh] ? cfg.seventh : 'minor-9/5',
            octaveShift: Number.isInteger(cfg.octaveShift) && Math.abs(cfg.octaveShift) <= 3 ? cfg.octaveShift : 0,
            fixedMidi: isValidMidi(cfg.fixedMidi) ? cfg.fixedMidi : null,
            pythagoreanStart: Number.isInteger(cfg.pythagoreanStart) && cfg.pythagoreanStart >= -11 && cfg.pythagoreanStart <= 0 ? cfg.pythagoreanStart : -3,
            customOffsets: [],
            spelling: ['default', 'sharp', 'flat'].indexOf(cfg.spelling) >= 0 ? cfg.spelling : 'default',
        };
        for (var i = 0; i < 12; i += 1) out.customOffsets.push(i === 0 ? 0 : clampOffset((cfg.customOffsets || [])[i]));
        return out;
    }

    function inStandardRange(hz) {
        return typeof hz === 'number' && Number.isFinite(hz) && hz >= MIN_HZ && hz <= MAX_HZ;
    }

    var api = {
        TEMPERAMENT_VERSION: TEMPERAMENT_VERSION,
        TEMPERAMENTS: TEMPERAMENTS,
        SEVENTHS: SEVENTHS,
        ROLES: ROLES,
        MIN_MIDI: MIN_MIDI,
        MAX_MIDI: MAX_MIDI,
        MIN_HZ: MIN_HZ,
        MAX_HZ: MAX_HZ,
        resolve: resolve,
        table: table,
        spell: spell,
        spellFifths: spellFifths,
        normalizeConfig: normalizeConfig,
        isValidMidi: isValidMidi,
        inStandardRange: inStandardRange,
        pythagoreanK: pythagoreanK,
    };

    lib.releases = lib.releases || {};
    lib.targetModel = api;
    lib.releases.target_model = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
