// Tuner: Canvas drawing of the frequency spectrum (not an oscilloscope).
// x: log frequency (25 Hz - 10 kHz by default), y: fixed -100..0 dBFS.
// Only drawing lives here; values arrive already reduced by the Worker.
// Display smoothing/decay is local to the graph and never feeds analysis.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-e945264406d5'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var FREQUENCY_TICKS = [
        [50, '50'], [100, '100'], [200, '200'], [500, '500'],
        [1000, '1k'], [2000, '2k'], [5000, '5k'], [10000, '10k'],
    ];
    var DB_TICKS = [-100, -80, -60, -40, -20, 0];
    // Shown levels fall at this rate when the input drops (dB per second).
    var DECAY_DB_PER_SECOND = 60;

    function createSpectrumGraph(canvas, options) {
        var opts = Object.assign({ height: 200 }, options || {});
        var ctx2d = canvas.getContext ? canvas.getContext('2d') : null;
        var session = null;
        var shown = null;
        var latest = null;
        var silent = true;
        var markers = { fundamental: 0, target: 0 };
        var lastDrawAt = 0;
        var cleared = true;

        function setSession(info) {
            session = info;
            shown = null;
            latest = null;
            cleared = true;
        }

        function setSpectrum(frame) {
            latest = frame ? frame.display : null;
        }

        function setSilent(value) {
            silent = Boolean(value);
        }

        function setMarkers(next) {
            markers = Object.assign({ fundamental: 0, target: 0 }, next || {});
        }

        function clear() {
            shown = null;
            latest = null;
            cleared = true;
            markers = { fundamental: 0, target: 0 };
            draw(0);
        }

        function color(name, fallback) {
            try {
                var value = getComputedStyle(canvas).getPropertyValue(name).trim();
                return value || fallback;
            } catch (_) {
                return fallback;
            }
        }

        function resize() {
            var ratio = globalObj.devicePixelRatio || 1;
            var width = Math.max(1, Math.round(canvas.clientWidth || 320));
            var height = Math.max(1, Math.round(canvas.clientHeight || opts.height));
            if (canvas.width !== Math.round(width * ratio) || canvas.height !== Math.round(height * ratio)) {
                canvas.width = Math.round(width * ratio);
                canvas.height = Math.round(height * ratio);
            }
            return { width: width, height: height, ratio: ratio };
        }

        // Rising levels show at once; falling levels decay so short gaps do
        // not flicker. With silence the target is the floor, so the trace
        // sinks and is then cleared entirely.
        function advance(now) {
            if (!session) return;
            var points = session.displayFrequencies.length;
            var floor = session.floorDb;
            var dt = lastDrawAt ? Math.max(0, Math.min(0.25, (now - lastDrawAt) / 1000)) : 0;
            lastDrawAt = now;
            if (!shown || shown.length !== points) {
                shown = new Float32Array(points);
                shown.fill(floor);
            }
            var decay = DECAY_DB_PER_SECOND * dt;
            var anyAbove = false;
            for (var i = 0; i < points; i += 1) {
                var target = !silent && latest && Number.isFinite(latest[i]) ? latest[i] : floor;
                var previous = shown[i];
                var next = target >= previous ? target : Math.max(target, previous - decay);
                shown[i] = next;
                if (next > floor + 0.5) anyAbove = true;
            }
            cleared = !anyAbove;
        }

        function draw(now) {
            if (!ctx2d) return;
            if (now) advance(now);
            var size = resize();
            var w = size.width;
            var h = size.height;
            ctx2d.setTransform(size.ratio, 0, 0, size.ratio, 0, 0);
            ctx2d.clearRect(0, 0, w, h);
            var left = 34;
            var right = w - 6;
            var top = 18;
            var bottom = h - 20;
            var minF = session ? session.displayMinFrequency : 25;
            var maxF = session ? session.displayMaxFrequency : 10000;
            var floor = session ? session.floorDb : -100;
            var ceiling = session ? session.ceilingDb : 0;
            var nyquist = session ? session.nyquist : Infinity;
            var logSpan = Math.log(maxF / minF);
            function x(f) { return left + ((right - left) * Math.log(f / minF)) / logSpan; }
            function y(db) { return bottom - ((bottom - top) * (Math.max(floor, Math.min(ceiling, db)) - floor)) / (ceiling - floor); }

            var gridColor = color('--tuner-graph-grid', 'rgba(127,127,127,0.25)');
            var textColor = color('--tuner-graph-text', '#666');
            ctx2d.font = '10px system-ui, sans-serif';
            ctx2d.lineWidth = 1;
            ctx2d.strokeStyle = gridColor;
            ctx2d.fillStyle = textColor;
            ctx2d.textAlign = 'center';
            ctx2d.textBaseline = 'top';
            FREQUENCY_TICKS.forEach(function (tick) {
                if (tick[0] < minF || tick[0] > maxF) return;
                var px = x(tick[0]);
                ctx2d.beginPath();
                ctx2d.moveTo(px, top);
                ctx2d.lineTo(px, bottom);
                ctx2d.stroke();
                ctx2d.fillText(tick[1], px, bottom + 4);
            });
            ctx2d.textAlign = 'right';
            ctx2d.textBaseline = 'middle';
            DB_TICKS.forEach(function (db) {
                var py = y(db);
                ctx2d.beginPath();
                ctx2d.moveTo(left, py);
                ctx2d.lineTo(right, py);
                ctx2d.stroke();
                ctx2d.fillText(String(db), left - 4, py);
            });

            // Above Nyquist nothing can be measured: shade, never draw data.
            if (nyquist < maxF) {
                ctx2d.fillStyle = color('--tuner-graph-unavailable', 'rgba(127,127,127,0.15)');
                ctx2d.fillRect(x(nyquist), top, right - x(nyquist), bottom - top);
            }

            if (session && shown && !cleared) {
                var freqs = session.displayFrequencies;
                ctx2d.beginPath();
                var started = false;
                for (var i = 0; i < freqs.length; i += 1) {
                    if (freqs[i] >= nyquist) break;
                    var px = x(freqs[i]);
                    var py = y(shown[i]);
                    if (!started) {
                        ctx2d.moveTo(px, bottom);
                        ctx2d.lineTo(px, py);
                        started = true;
                    } else {
                        ctx2d.lineTo(px, py);
                    }
                }
                if (started) {
                    ctx2d.lineTo(px, bottom);
                    ctx2d.closePath();
                    ctx2d.fillStyle = color('--tuner-graph-fill', 'rgba(13,110,253,0.18)');
                    ctx2d.fill();
                    ctx2d.strokeStyle = color('--tuner-graph-line', '#0d6efd');
                    ctx2d.lineWidth = 1.5;
                    ctx2d.stroke();
                }
            }

            var fundamental = markers.fundamental;
            var limit = Math.min(maxF, nyquist);
            if (fundamental > 0 && fundamental >= minF && fundamental <= limit) {
                // Harmonic markers (triangles) at integer multiples, up to the axis
                // limit, skipped where they would crowd into each other.
                ctx2d.fillStyle = color('--tuner-graph-harmonic', '#6c757d');
                ctx2d.textAlign = 'center';
                ctx2d.textBaseline = 'top';
                var previousX = x(fundamental);
                for (var n = 2; fundamental * n <= limit; n += 1) {
                    var hx = x(fundamental * n);
                    if (hx - previousX < 4) break;
                    ctx2d.beginPath();
                    ctx2d.moveTo(hx - 4, top - 8);
                    ctx2d.lineTo(hx + 4, top - 8);
                    ctx2d.lineTo(hx, top - 1);
                    ctx2d.closePath();
                    ctx2d.fill();
                    previousX = hx;
                }
                var fx = x(fundamental);
                ctx2d.strokeStyle = color('--tuner-graph-fundamental', '#d63384');
                ctx2d.lineWidth = 2;
                ctx2d.setLineDash([]);
                ctx2d.beginPath();
                ctx2d.moveTo(fx, top);
                ctx2d.lineTo(fx, bottom);
                ctx2d.stroke();
                ctx2d.fillStyle = color('--tuner-graph-fundamental', '#d63384');
                ctx2d.textAlign = fx > (left + right) / 2 ? 'right' : 'left';
                ctx2d.textBaseline = 'top';
                ctx2d.font = 'bold 11px system-ui, sans-serif';
                ctx2d.fillText(fundamental.toFixed(1) + ' Hz', fx + (ctx2d.textAlign === 'left' ? 4 : -4), top + 2);
            }
            var target = markers.target;
            if (target > 0 && target >= minF && target <= limit) {
                var tx = x(target);
                ctx2d.strokeStyle = color('--tuner-graph-target', '#198754');
                ctx2d.lineWidth = 1.5;
                ctx2d.setLineDash([5, 4]);
                ctx2d.beginPath();
                ctx2d.moveTo(tx, top);
                ctx2d.lineTo(tx, bottom);
                ctx2d.stroke();
                ctx2d.setLineDash([]);
            }
        }

        return {
            setSession: setSession,
            setSpectrum: setSpectrum,
            setSilent: setSilent,
            setMarkers: setMarkers,
            draw: draw,
            clear: clear,
            isCleared: function () { return cleared; },
        };
    }

    var api = { createSpectrumGraph: createSpectrumGraph, DECAY_DB_PER_SECOND: DECAY_DB_PER_SECOND };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.graph = api;
    lib.releases.graph = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
