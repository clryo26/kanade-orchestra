// Tuner: Canvas drawing of the frequency spectrum (not an oscilloscope).
// x: log frequency over the selected display range, y: fixed -100..0 dBFS
// (never auto-scaled, never auto-zoomed). Only drawing lives here; values
// arrive already reduced by the Worker for the matching display axis.
// Display smoothing/decay is local to the graph and never feeds analysis.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-b0635dde6c4d'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    // Display ranges (display only; analysis ranges live in the worker).
    var DISPLAY_RANGES = {
        harmonics: { id: 'harmonics', label: '倍音重視', detail: '500 Hz～16 kHz', min: 500, max: 16000 },
        full: { id: 'full', label: '全音域', detail: '25 Hz～16 kHz', min: 25, max: 16000 },
    };
    var DEFAULT_DISPLAY_RANGE = 'harmonics';

    var FREQUENCY_TICKS = [
        [25, '25'], [50, '50'], [100, '100'], [200, '200'], [500, '500'],
        [1000, '1k'], [2000, '2k'], [5000, '5k'], [10000, '10k'], [16000, '16k'],
    ];
    var DB_TICKS = [-100, -80, -60, -40, -20, 0];
    // Labels closer than this (CSS px) are skipped so narrow phones stay legible.
    var MIN_TICK_LABEL_SPACING = 28;
    var MIN_HARMONIC_SPACING = 6;
    // Shown levels fall at this rate when the input drops (dB per second).
    var DECAY_DB_PER_SECOND = 60;

    function resolveRange(id) {
        return DISPLAY_RANGES[id] || DISPLAY_RANGES[DEFAULT_DISPLAY_RANGE];
    }

    // Upper end where data can exist: the display max or Nyquist, whichever is lower.
    function measurableLimit(range, nyquist) {
        return Math.min(range.max, nyquist > 0 ? nyquist : Infinity);
    }

    // Tick positions inside the range; labels thinned left to right.
    function visibleTicks(range, xOf) {
        var result = [];
        var lastLabelX = -Infinity;
        FREQUENCY_TICKS.forEach(function (tick) {
            if (tick[0] < range.min || tick[0] > range.max) return;
            var px = xOf(tick[0]);
            var labelled = px - lastLabelX >= MIN_TICK_LABEL_SPACING;
            if (labelled) lastLabelX = px;
            result.push({ frequency: tick[0], x: px, label: labelled ? tick[1] : '' });
        });
        return result;
    }

    // Harmonic numbers whose frequency lies inside [range.min, limit],
    // including harmonics of a fundamental below the range (high partials of
    // low notes), stopping once neighbours would be closer than minSpacing px.
    function harmonicMarkers(fundamental, range, limit, xOf, minSpacing) {
        var list = [];
        if (!(fundamental > 0)) return list;
        var spacing = minSpacing || MIN_HARMONIC_SPACING;
        var first = Math.max(2, Math.ceil(range.min / fundamental));
        var previousX = null;
        for (var n = first; fundamental * n <= limit; n += 1) {
            var px = xOf(fundamental * n);
            if (previousX !== null && px - previousX < spacing) break;
            list.push({ number: n, frequency: fundamental * n, x: px });
            previousX = px;
        }
        return list;
    }

    function createSpectrumGraph(canvas, options) {
        var opts = Object.assign({ height: 200 }, options || {});
        var ctx2d = canvas.getContext ? canvas.getContext('2d') : null;
        var levels = { floorDb: -100, ceilingDb: 0, nyquist: Infinity };
        var range = resolveRange(DEFAULT_DISPLAY_RANGE);
        var axisId = 0;
        var axis = null; // { axisId, frequencies } matching `range`
        var shown = null;
        var latest = null;
        var silent = true;
        var markers = { fundamental: 0, target: 0, equalTarget: 0 };
        var lastDrawAt = 0;
        var cleared = true;

        function setSession(info) {
            if (info) {
                levels = {
                    floorDb: typeof info.floorDb === 'number' ? info.floorDb : -100,
                    ceilingDb: typeof info.ceilingDb === 'number' ? info.ceilingDb : 0,
                    nyquist: info.nyquist > 0 ? info.nyquist : Infinity,
                };
            }
            shown = null;
            latest = null;
            cleared = true;
        }

        // Switching range takes effect at once for ticks/markers; data waits for
        // the worker's axis with the same id, so old-axis frames are never drawn.
        function setRange(id, nextAxisId) {
            range = resolveRange(id);
            axisId = nextAxisId;
            axis = null;
            shown = null;
            latest = null;
            cleared = true;
        }

        function setAxis(next) {
            if (!next || next.axisId !== axisId) return false;
            axis = { axisId: next.axisId, frequencies: next.frequencies };
            if (next.nyquist > 0) levels.nyquist = next.nyquist;
            shown = null;
            latest = null;
            return true;
        }

        function setSpectrum(frame) {
            if (!frame || !axis || frame.axisId !== axis.axisId || !frame.display || frame.display.length !== axis.frequencies.length) {
                return false;
            }
            latest = frame.display;
            return true;
        }

        function setSilent(value) {
            silent = Boolean(value);
        }

        function setMarkers(next) {
            markers = Object.assign({ fundamental: 0, target: 0, equalTarget: 0 }, next || {});
        }

        function clear() {
            shown = null;
            latest = null;
            cleared = true;
            markers = { fundamental: 0, target: 0, equalTarget: 0 };
            draw(0);
        }

        function color(name, fallback) {
            try {
                var value = getComputedStyle(canvas).getPropertyValue(name).trim();
                return value || fallback;
            } catch (_) {
                return fallback;
            }
        }

        function resize() {
            var ratio = globalObj.devicePixelRatio || 1;
            var width = Math.max(1, Math.round(canvas.clientWidth || 320));
            var height = Math.max(1, Math.round(canvas.clientHeight || opts.height));
            if (canvas.width !== Math.round(width * ratio) || canvas.height !== Math.round(height * ratio)) {
                canvas.width = Math.round(width * ratio);
                canvas.height = Math.round(height * ratio);
            }
            return { width: width, height: height, ratio: ratio };
        }

        // Rising levels show at once; falling levels decay so short gaps do
        // not flicker. With silence the target is the floor, so the trace
        // sinks and is then cleared entirely.
        function advance(now) {
            if (!axis) return;
            var points = axis.frequencies.length;
            var floor = levels.floorDb;
            var dt = lastDrawAt ? Math.max(0, Math.min(0.25, (now - lastDrawAt) / 1000)) : 0;
            lastDrawAt = now;
            if (!shown || shown.length !== points) {
                shown = new Float32Array(points);
                shown.fill(floor);
            }
            var decay = DECAY_DB_PER_SECOND * dt;
            var anyAbove = false;
            for (var i = 0; i < points; i += 1) {
                var target = !silent && latest && Number.isFinite(latest[i]) ? latest[i] : floor;
                var previous = shown[i];
                var next = target >= previous ? target : Math.max(target, previous - decay);
                shown[i] = next;
                if (next > floor + 0.5) anyAbove = true;
            }
            cleared = !anyAbove;
        }

        function verticalLine(px, top, bottom, strokeColor, width, dash) {
            ctx2d.strokeStyle = strokeColor;
            ctx2d.lineWidth = width;
            ctx2d.setLineDash(dash);
            ctx2d.beginPath();
            ctx2d.moveTo(px, top);
            ctx2d.lineTo(px, bottom);
            ctx2d.stroke();
            ctx2d.setLineDash([]);
        }

        function draw(now) {
            if (!ctx2d) return;
            if (now) advance(now);
            var size = resize();
            var w = size.width;
            var h = size.height;
            ctx2d.setTransform(size.ratio, 0, 0, size.ratio, 0, 0);
            ctx2d.clearRect(0, 0, w, h);
            var left = 34;
            var right = w - 8;
            var top = 18;
            var bottom = h - 20;
            var minF = range.min;
            var maxF = range.max;
            var floor = levels.floorDb;
            var ceiling = levels.ceilingDb;
            var limit = measurableLimit(range, levels.nyquist);
            var logSpan = Math.log(maxF / minF);
            function x(f) { return left + ((right - left) * Math.log(f / minF)) / logSpan; }
            function y(db) { return bottom - ((bottom - top) * (Math.max(floor, Math.min(ceiling, db)) - floor)) / (ceiling - floor); }

            var gridColor = color('--tuner-graph-grid', 'rgba(127,127,127,0.25)');
            var textColor = color('--tuner-graph-text', '#666');
            ctx2d.font = '10px system-ui, sans-serif';
            ctx2d.lineWidth = 1;
            ctx2d.strokeStyle = gridColor;
            ctx2d.fillStyle = textColor;
            ctx2d.textBaseline = 'top';
            visibleTicks(range, x).forEach(function (tick) {
                ctx2d.beginPath();
                ctx2d.moveTo(tick.x, top);
                ctx2d.lineTo(tick.x, bottom);
                ctx2d.stroke();
                if (!tick.label) return;
                // Keep the end labels inside the canvas.
                ctx2d.textAlign = tick.x > right - 12 ? 'right' : (tick.x < left + 12 ? 'left' : 'center');
                ctx2d.fillText(tick.label, tick.x, bottom + 4);
            });
            ctx2d.textAlign = 'right';
            ctx2d.textBaseline = 'middle';
            DB_TICKS.forEach(function (db) {
                var py = y(db);
                ctx2d.beginPath();
                ctx2d.moveTo(left, py);
                ctx2d.lineTo(right, py);
                ctx2d.stroke();
                ctx2d.fillText(String(db), left - 4, py);
            });

            // Above Nyquist nothing can be measured: shade, never draw data.
            if (limit < maxF) {
                ctx2d.fillStyle = color('--tuner-graph-unavailable', 'rgba(127,127,127,0.15)');
                ctx2d.fillRect(x(limit), top, right - x(limit), bottom - top);
            }

            if (axis && shown && !cleared) {
                var freqs = axis.frequencies;
                ctx2d.beginPath();
                var started = false;
                var px = left;
                for (var i = 0; i < freqs.length; i += 1) {
                    if (freqs[i] >= limit || !Number.isFinite(shown[i])) break;
                    px = x(freqs[i]);
                    var py = y(shown[i]);
                    if (!started) {
                        ctx2d.moveTo(px, bottom);
                        ctx2d.lineTo(px, py);
                        started = true;
                    } else {
                        ctx2d.lineTo(px, py);
                    }
                }
                if (started) {
                    ctx2d.lineTo(px, bottom);
                    ctx2d.closePath();
                    ctx2d.fillStyle = color('--tuner-graph-fill', 'rgba(13,110,253,0.18)');
                    ctx2d.fill();
                    ctx2d.strokeStyle = color('--tuner-graph-line', '#0d6efd');
                    ctx2d.lineWidth = 1.5;
                    ctx2d.stroke();
                }
            }

            var fundamental = markers.fundamental;
            function inRange(f) { return f > 0 && f >= minF && f <= limit; }
            if (fundamental > 0) {
                // Harmonic markers (triangles) for every multiple inside the range,
                // also when the fundamental itself is below the range.
                ctx2d.fillStyle = color('--tuner-graph-harmonic', '#6c757d');
                harmonicMarkers(fundamental, range, limit, x).forEach(function (marker) {
                    ctx2d.beginPath();
                    ctx2d.moveTo(marker.x - 4, top - 8);
                    ctx2d.lineTo(marker.x + 4, top - 8);
                    ctx2d.lineTo(marker.x, top - 1);
                    ctx2d.closePath();
                    ctx2d.fill();
                });
            }
            // Equal-tempered auxiliary line (just-intonation modes): dotted grey.
            if (inRange(markers.equalTarget)) {
                verticalLine(x(markers.equalTarget), top, bottom, color('--tuner-graph-equal', '#6b7280'), 1.5, [2, 3]);
            }
            // Main judgment target: dashed green.
            if (inRange(markers.target)) {
                verticalLine(x(markers.target), top, bottom, color('--tuner-graph-target', '#198754'), 1.5, [5, 4]);
            }
            var fundamentalColor = color('--tuner-graph-fundamental', '#d63384');
            ctx2d.font = 'bold 11px system-ui, sans-serif';
            ctx2d.textBaseline = 'top';
            ctx2d.fillStyle = fundamentalColor;
            if (inRange(fundamental)) {
                var fx = x(fundamental);
                verticalLine(fx, top, bottom, fundamentalColor, 2, []);
                ctx2d.fillStyle = fundamentalColor;
                ctx2d.textAlign = fx > (left + right) / 2 ? 'right' : 'left';
                ctx2d.fillText(fundamental.toFixed(1) + ' Hz', fx + (ctx2d.textAlign === 'left' ? 4 : -4), top + 2);
            } else if (fundamental > 0) {
                // Outside the display range: say where it is instead of drawing it.
                var below = fundamental < minF;
                ctx2d.textAlign = below ? 'left' : 'right';
                ctx2d.fillText((below ? '◀ 基音 ' : '基音 ') + fundamental.toFixed(1) + ' Hz' + (below ? '' : ' ▶'), below ? left + 4 : right - 4, top + 2);
            }
        }

        return {
            setSession: setSession,
            setRange: setRange,
            setAxis: setAxis,
            setSpectrum: setSpectrum,
            setSilent: setSilent,
            setMarkers: setMarkers,
            draw: draw,
            clear: clear,
            getRange: function () { return range; },
            isCleared: function () { return cleared; },
        };
    }

    var api = {
        DISPLAY_RANGES: DISPLAY_RANGES,
        DEFAULT_DISPLAY_RANGE: DEFAULT_DISPLAY_RANGE,
        MIN_TICK_LABEL_SPACING: MIN_TICK_LABEL_SPACING,
        DECAY_DB_PER_SECOND: DECAY_DB_PER_SECOND,
        resolveRange: resolveRange,
        measurableLimit: measurableLimit,
        visibleTicks: visibleTicks,
        harmonicMarkers: harmonicMarkers,
        createSpectrumGraph: createSpectrumGraph,
    };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.graph = api;
    lib.releases.graph = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
