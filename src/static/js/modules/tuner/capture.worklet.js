// Tuner: AudioWorklet that only captures microphone samples and forwards
// them to the analysis Worker through a MessagePort handed over by the main
// thread. Everything heavy happens in the Worker so this audio thread stays
// cheap. Self-contained on purpose: audioWorklet.addModule() loads it as a
// module, but it must not depend on import/export.
//
// Memory/latency bound: a small pool of chunk buffers is transferred to the
// Worker and returned after use. When the pool is empty (Worker stalled) the
// samples are dropped and the next chunk is flagged as a gap, so the Worker
// never stitches non-contiguous audio together and no queue grows unbounded.

const TUNER_RELEASE_ID = 't-5c2ad5661ae9'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)
const TUNER_PROTOCOL = 2;

class PortalTunerCaptureProcessor extends AudioWorkletProcessor {
    constructor(options) {
        super();
        const opts = (options && options.processorOptions) || {};
        this.generation = opts.generation;
        this.chunkSize = Math.max(256, Math.min(16384, Number(opts.chunkSize) || 2048));
        this.pool = [];
        const poolSize = Math.max(2, Math.min(32, Number(opts.poolSize) || 8));
        for (let i = 0; i < poolSize; i += 1) this.pool.push(new Float32Array(this.chunkSize));
        this.current = null;
        this.fill = 0;
        this.chunkStartFrame = 0;
        this.sequence = 0;
        this.pendingGap = true;
        this.droppedFrames = 0;
        this.out = null;
        this.alive = true;
        this.port.onmessage = (event) => this.handleControl(event.data);
        const versionOk = opts.release === TUNER_RELEASE_ID && opts.protocol === TUNER_PROTOCOL;
        this.port.postMessage({
            type: versionOk ? 'ready' : 'version-mismatch',
            release: TUNER_RELEASE_ID,
            protocol: TUNER_PROTOCOL,
            generation: this.generation,
            sampleRate: sampleRate,
        });
        if (!versionOk) this.alive = false;
    }

    handleControl(message) {
        if (!message || typeof message !== 'object') return;
        if (message.type === 'connect' && message.port) {
            this.out = message.port;
            this.out.onmessage = (event) => this.handleReturn(event.data);
        } else if (message.type === 'stop') {
            this.alive = false;
            this.releaseBuffers();
        }
    }

    handleReturn(message) {
        if (!message || message.type !== 'return' || !(message.buffer instanceof ArrayBuffer)) return;
        if (!this.alive || message.buffer.byteLength !== this.chunkSize * 4) return;
        if (this.pool.length < 32) this.pool.push(new Float32Array(message.buffer));
    }

    releaseBuffers() {
        this.pool = [];
        this.current = null;
        if (this.out) {
            try { this.out.close(); } catch (_) { /* already closed */ }
            this.out = null;
        }
    }

    process(inputs, outputs) {
        // The node is wired to a zero-gain node so it is pulled by the graph;
        // the output itself is also silent so nothing can reach the speakers.
        const output = outputs[0];
        if (output) for (let c = 0; c < output.length; c += 1) output[c].fill(0);
        if (!this.alive) return false;
        if (!this.out) return true;
        const input = inputs[0] && inputs[0][0];
        if (!input || input.length === 0) {
            // No input this block (source disconnected/muted by the browser):
            // the partial chunk would otherwise be continued later by audio
            // that is not contiguous with it, so discard it and flag a gap.
            const blockLength = output && output[0] ? output[0].length : 128;
            this.droppedFrames += this.fill + blockLength;
            this.fill = 0;
            this.pendingGap = true;
            return true;
        }
        // Block length is read every call; 128 frames is common but not guaranteed.
        const length = input.length;
        let index = 0;
        while (index < length) {
            if (!this.current) {
                this.current = this.pool.pop() || null;
                this.fill = 0;
                if (!this.current) {
                    this.droppedFrames += length - index;
                    this.pendingGap = true;
                    return true;
                }
            }
            if (this.fill === 0) this.chunkStartFrame = currentFrame + index;
            const take = Math.min(length - index, this.chunkSize - this.fill);
            this.current.set(input.subarray(index, index + take), this.fill);
            this.fill += take;
            index += take;
            if (this.fill === this.chunkSize) this.flush();
        }
        return true;
    }

    flush() {
        const buffer = this.current.buffer;
        this.sequence += 1;
        this.out.postMessage({
            type: 'audio',
            release: TUNER_RELEASE_ID,
            protocol: TUNER_PROTOCOL,
            generation: this.generation,
            sequence: this.sequence,
            startFrame: this.chunkStartFrame,
            gap: this.pendingGap,
            droppedFrames: this.droppedFrames,
            buffer: buffer,
        }, [buffer]);
        this.pendingGap = false;
        this.droppedFrames = 0;
        this.current = null;
        this.fill = 0;
    }
}

registerProcessor('portal-tuner-capture', PortalTunerCaptureProcessor);
