// Tuner: time-series graph (cent / Hz / dBFS over time) on a canvas.
// - Data are reduced to per-pixel min/max columns so peaks survive at any
//   zoom; gaps (missing frames, invalid values, epoch boundaries) are never
//   connected and never interpolated.
// - Time axis: zoom 10 s .. whole session, horizontal scroll, "follow"
//   returns to the newest data. A selection is kept in absolute seconds, so
//   zooming never changes what is selected.
// - Lines are distinguished by style and labels, not only by colour.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-5c2ad5661ae9'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var MODES = {
        cents: { label: 'cent', unit: 'cent', min: -50, max: 50 },
        hz: { label: 'Hz', unit: 'Hz', min: null, max: null },
        dbfs: { label: '入力の大きさ', unit: 'dBFS', min: -90, max: 0 },
    };

    // times (seconds, sorted), values (NaN = missing), visible [t0, t1],
    // width px, maxGapSeconds: neighbours further apart are not joined.
    function decimate(times, values, t0, t1, width, maxGapSeconds) {
        var cols = new Array(width);
        for (var c = 0; c < width; c += 1) cols[c] = null;
        var span = t1 - t0;
        if (!(span > 0) || width <= 0) return cols;
        var prevT = null;
        var prevCol = null;
        for (var i = 0; i < times.length; i += 1) {
            var t = times[i];
            var v = values[i];
            if (t < t0 || t > t1) { prevT = Number.isFinite(v) ? t : null; continue; }
            var col = Math.min(width - 1, Math.max(0, Math.floor(((t - t0) / span) * width)));
            if (!Number.isFinite(v)) { prevT = null; prevCol = null; continue; }
            var cell = cols[col] || (cols[col] = { min: v, max: v, first: v, last: v, joinLeft: false });
            if (v < cell.min) cell.min = v;
            if (v > cell.max) cell.max = v;
            cell.last = v;
            // Joined to the previous column only when the time step is small.
            if (prevT !== null && prevCol !== null && prevCol !== col && t - prevT <= maxGapSeconds) cell.joinLeft = true;
            prevT = t;
            prevCol = col;
        }
        return cols;
    }

    function createHistoryGraph(canvas, options) {
        var opts = Object.assign({ height: 180 }, options || {});
        var ctx2d = canvas.getContext ? canvas.getContext('2d') : null;
        var view = { mode: 'cents', windowSeconds: 30, follow: true, end: 0, yMin: null, yMax: null };
        var data = null; // { times, cents, hz, dbfs, maxGap, now }
        var selection = null; // { from, to } seconds

        function color(name, fallback) {
            try {
                var value = getComputedStyle(canvas).getPropertyValue(name).trim();
                return value || fallback;
            } catch (_) {
                return fallback;
            }
        }

        function resize() {
            var ratio = globalObj.devicePixelRatio || 1;
            var w = Math.max(1, Math.round(canvas.clientWidth || 320));
            var h = Math.max(1, Math.round(canvas.clientHeight || opts.height));
            if (canvas.width !== Math.round(w * ratio) || canvas.height !== Math.round(h * ratio)) {
                canvas.width = Math.round(w * ratio);
                canvas.height = Math.round(h * ratio);
            }
            return { w: w, h: h, ratio: ratio };
        }

        function visibleRange() {
            if (!data) return [0, view.windowSeconds];
            var end = view.follow ? data.now : view.end;
            return [end - view.windowSeconds, end];
        }

        function draw() {
            if (!ctx2d) return;
            var size = resize();
            var w = size.w;
            var h = size.h;
            ctx2d.setTransform(size.ratio, 0, 0, size.ratio, 0, 0);
            ctx2d.clearRect(0, 0, w, h);
            var left = 40;
            var right = w - 8;
            var top = 10;
            var bottom = h - 22;
            var range = visibleRange();
            var mode = MODES[view.mode];
            var values = data ? data[view.mode] : null;
            var yMin = view.yMin !== null ? view.yMin : mode.min;
            var yMax = view.yMax !== null ? view.yMax : mode.max;
            if ((yMin === null || yMax === null) && values) {
                var lo = Infinity;
                var hi = -Infinity;
                for (var i = 0; i < values.length; i += 1) {
                    if (data.times[i] < range[0] || data.times[i] > range[1] || !Number.isFinite(values[i])) continue;
                    lo = Math.min(lo, values[i]);
                    hi = Math.max(hi, values[i]);
                }
                if (!Number.isFinite(lo)) { lo = 0; hi = 1; }
                var pad = Math.max(1, (hi - lo) * 0.1);
                yMin = yMin === null ? lo - pad : yMin;
                yMax = yMax === null ? hi + pad : yMax;
            }
            function y(v) { return bottom - ((bottom - top) * (Math.max(yMin, Math.min(yMax, v)) - yMin)) / (yMax - yMin); }
            function x(t) { return left + ((right - left) * (t - range[0])) / (range[1] - range[0]); }
            ctx2d.strokeStyle = color('--tuner-graph-grid', 'rgba(127,127,127,0.25)');
            ctx2d.fillStyle = color('--tuner-graph-text', '#666');
            ctx2d.font = '10px system-ui, sans-serif';
            ctx2d.lineWidth = 1;
            ctx2d.textAlign = 'right';
            ctx2d.textBaseline = 'middle';
            for (var k = 0; k <= 4; k += 1) {
                var v = yMin + ((yMax - yMin) * k) / 4;
                var py = y(v);
                ctx2d.beginPath();
                ctx2d.moveTo(left, py);
                ctx2d.lineTo(right, py);
                ctx2d.stroke();
                ctx2d.fillText(v.toFixed(Math.abs(yMax - yMin) < 20 ? 1 : 0), left - 4, py);
            }
            ctx2d.textAlign = 'center';
            ctx2d.textBaseline = 'top';
            ctx2d.fillText(range[0].toFixed(1) + ' s', left + 20, bottom + 4);
            ctx2d.fillText(range[1].toFixed(1) + ' s', right - 20, bottom + 4);
            if (view.mode === 'cents') {
                ctx2d.strokeStyle = color('--tuner-graph-target', '#198754');
                ctx2d.setLineDash([5, 4]);
                ctx2d.beginPath();
                ctx2d.moveTo(left, y(0));
                ctx2d.lineTo(right, y(0));
                ctx2d.stroke();
                ctx2d.setLineDash([]);
            }
            if (selection) {
                ctx2d.fillStyle = color('--tuner-graph-fill', 'rgba(13,110,253,0.15)');
                var sx0 = Math.max(left, x(selection.from));
                var sx1 = Math.min(right, x(selection.to));
                if (sx1 > sx0) ctx2d.fillRect(sx0, top, sx1 - sx0, bottom - top);
            }
            if (!values) return;
            var width = Math.max(1, Math.round(right - left));
            var cols = decimate(data.times, values, range[0], range[1], width, data.maxGap);
            ctx2d.strokeStyle = color('--tuner-graph-line', '#0d6efd');
            ctx2d.lineWidth = 1.5;
            ctx2d.beginPath();
            var penDown = false;
            for (var c = 0; c < cols.length; c += 1) {
                var cell = cols[c];
                var px = left + c + 0.5;
                if (!cell) { penDown = false; continue; }
                if (!penDown || !cell.joinLeft) ctx2d.moveTo(px, y(cell.first));
                else ctx2d.lineTo(px, y(cell.first));
                ctx2d.lineTo(px, y(cell.min));
                ctx2d.lineTo(px, y(cell.max));
                ctx2d.lineTo(px, y(cell.last));
                penDown = true;
            }
            ctx2d.stroke();
        }

        return {
            setData: function (next) { data = next; },
            setMode: function (mode) { if (MODES[mode]) { view.mode = mode; view.yMin = null; view.yMax = null; } },
            setYRange: function (min, max) {
                view.yMin = Number.isFinite(min) ? min : null;
                view.yMax = Number.isFinite(max) && (!Number.isFinite(min) || max > min) ? max : null;
            },
            setWindow: function (seconds) { view.windowSeconds = Math.max(1, Math.min(7200, seconds)); },
            zoom: function (factor) { view.windowSeconds = Math.max(1, Math.min(7200, view.windowSeconds * factor)); },
            scroll: function (seconds) {
                var current = view.follow && data ? data.now : view.end;
                view.follow = false;
                view.end = Math.min(data ? data.now : current, Math.max(view.windowSeconds, current + seconds));
            },
            follow: function () { view.follow = true; },
            isFollowing: function () { return view.follow; },
            setSelection: function (from, to) {
                if (!(Number.isFinite(from) && Number.isFinite(to)) || to <= from) { selection = null; return null; }
                selection = { from: from, to: to };
                return selection;
            },
            getSelection: function () { return selection ? Object.assign({}, selection) : null; },
            visibleRange: visibleRange,
            // Seconds at a canvas x position (for selection handles).
            timeAt: function (clientX) {
                var rect = canvas.getBoundingClientRect ? canvas.getBoundingClientRect() : { left: 0, width: canvas.clientWidth || 320 };
                var range = visibleRange();
                var left = 40;
                var right = (rect.width || 320) - 8;
                var px = clientX - rect.left;
                return range[0] + ((range[1] - range[0]) * (px - left)) / Math.max(1, right - left);
            },
            draw: draw,
            getView: function () { return Object.assign({}, view); },
        };
    }

    var api = { MODES: MODES, decimate: decimate, createHistoryGraph: createHistoryGraph };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.historyGraph = api;
    lib.releases.history_graph = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
