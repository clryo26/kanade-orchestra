// Tuner: personal intonation diagnosis (Phase 4). Pure functions over saved
// note-event summaries; no audio, no network.
//
// Statistical rules (design 10, data design 6):
// - Units: frame (inside an event only) -> note event -> session. A long
//   note or a long session never counts as many performances: events give
//   one value each, sessions are weighted equally.
// - Mean (I-001) and median are both reported; spreads are separated into
//   within-event, between-event and between-session.
// - 95 % intervals resample sessions as clusters (never frames).
// - Diagnosis starts only with >= 5 eligible events in >= 3 sessions
//   (tuning values) and a narrow enough interval; otherwise "insufficient"
//   or "reference". Missing data is never counted as 0 cent.
// - Records with different conditions (A4, temperament and targets,
//   instrument/setting, exercise, direction, dynamics, engine/stats version,
//   capture calibration) are never mixed: conditionsKey separates them.
// - Suggestions are rule based, with reasons and counts; they never claim
//   instrument faults, technique causes or a musical quality judgement.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-5c2ad5661ae9'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)
    var DIAGNOSIS_VERSION = 1;

    var DEFAULTS = {
        minEvents: 5,
        minSessions: 3,
        minEventSeconds: 0.15,
        minObservations: 3,
        minCoverage: 0.8,
        maxIntervalWidthCents: 10,
        bootstrapSamples: 400,
        seed: 12345,
    };

    // Stable JSON (sorted keys) of a value.
    function stableStringify(value) {
        if (value === null || typeof value !== 'object') return JSON.stringify(value === undefined ? null : value);
        if (Array.isArray(value)) return '[' + value.map(stableStringify).join(',') + ']';
        return '{' + Object.keys(value).sort().filter(function (k) { return value[k] !== undefined; }).map(function (k) {
            return JSON.stringify(k) + ':' + stableStringify(value[k]);
        }).join(',') + '}';
    }

    // FNV-1a (two 32-bit lanes) -> 16 hex chars. Not a security hash.
    function hash(text) {
        var h1 = 0x811c9dc5;
        var h2 = 0x01000193 ^ 0x5bd1e995;
        for (var i = 0; i < text.length; i += 1) {
            var c = text.charCodeAt(i);
            h1 ^= c; h1 = Math.imul(h1, 0x01000193) >>> 0;
            h2 ^= c; h2 = Math.imul(h2, 0x01000197) >>> 0;
        }
        return ('00000000' + h1.toString(16)).slice(-8) + ('00000000' + h2.toString(16)).slice(-8);
    }

    // Statistics conditions only (display colours, smoothing and axes excluded).
    var CONDITION_FIELDS = ['a4Tenths', 'temperament', 'targetDefinition', 'instrumentId', 'instrumentRevision', 'settingRevision',
        'exerciseKind', 'exerciseVersion', 'tempo', 'direction', 'dynamicMarking', 'inputProcessing', 'analysisProfile',
        'engineVersion', 'statsVersion', 'calibrationId'];

    function conditionsKey(conditions) {
        var c = conditions || {};
        var picked = {};
        CONDITION_FIELDS.forEach(function (f) {
            var v = c[f];
            picked[f] = v === undefined || v === null || v === '' ? 'unknown' : v;
        });
        return hash(stableStringify(picked));
    }

    // E-003: optional playing environment of a session (record only). It is
    // not part of the condition key and never used to estimate causes.
    // temperature -10..50 C (0.1), humidity 0..100 % (1), warm-up: not
    // entered / done / minutes (0..240). Out-of-range values are not stored.
    function normalizeEnvironment(input) {
        var v = input || {};
        var num = function (x) { return x === '' || x === null || x === undefined ? NaN : Number(x); };
        var t = num(v.temperatureC);
        var hum = num(v.humidityPct);
        var out = {
            temperatureC: Number.isFinite(t) && t >= -10 && t <= 50 ? Math.round(t * 10) / 10 : null,
            humidityPct: Number.isFinite(hum) && hum >= 0 && hum <= 100 ? Math.round(hum) : null,
            warmup: 'unknown',
            warmupMinutes: null,
        };
        var minutes = num(v.warmupMinutes);
        if (v.warmup === 'minutes' && Number.isFinite(minutes) && minutes >= 0 && minutes <= 240) {
            out.warmup = 'minutes';
            out.warmupMinutes = Math.round(minutes);
        } else if (v.warmup === 'done') {
            out.warmup = 'done';
        }
        return out;
    }

    function describeEnvironment(env) {
        if (!env) return '未記入';
        var e = normalizeEnvironment(env);
        var parts = [];
        if (e.temperatureC !== null) parts.push('気温 ' + e.temperatureC.toFixed(1) + '℃');
        if (e.humidityPct !== null) parts.push('湿度 ' + e.humidityPct + '%');
        if (e.warmup === 'done') parts.push('ウォームアップ済み');
        if (e.warmup === 'minutes') parts.push('ウォームアップ ' + e.warmupMinutes + '分');
        return parts.length ? parts.join('・') : '未記入';
    }

    // Which fields differ between two condition snapshots (for comparisons).
    function conditionDifferences(a, b) {
        return CONDITION_FIELDS.filter(function (f) {
            return stableStringify((a || {})[f] === undefined ? null : (a || {})[f]) !== stableStringify((b || {})[f] === undefined ? null : (b || {})[f]);
        });
    }

    function eligibility(event, options) {
        var o = Object.assign({}, DEFAULTS, options || {});
        if (!event) return { ok: false, reason: 'missing' };
        if (event.simultaneousPlayback || event.playbackOverlap) return { ok: false, reason: 'playback' };
        if (event.boundaryType === 'targetChange' && event.countsAsAttempt === false) return { ok: false, reason: 'target-change' };
        if (!(event.durationSeconds >= o.minEventSeconds)) return { ok: false, reason: 'short' };
        if (!(event.observationCount >= o.minObservations)) return { ok: false, reason: 'few-observations' };
        if (!(event.coverage >= o.minCoverage)) return { ok: false, reason: 'low-coverage' };
        if (typeof event.meanCents !== 'number' || !Number.isFinite(event.meanCents) || typeof event.medianCents !== 'number') return { ok: false, reason: 'no-value' };
        if (event.unknownFlags) return { ok: false, reason: 'unknown-flags' };
        return { ok: true, reason: null };
    }

    function mean(values) {
        if (!values.length) return null;
        return values.reduce(function (s, v) { return s + v; }, 0) / values.length;
    }

    function median(values) {
        var v = values.slice().sort(function (a, b) { return a - b; });
        if (!v.length) return null;
        var mid = Math.floor(v.length / 2);
        return v.length % 2 ? v[mid] : (v[mid - 1] + v[mid]) / 2;
    }

    function sd(values) {
        if (values.length < 2) return null;
        var m = mean(values);
        return Math.sqrt(values.reduce(function (s, v) { return s + (v - m) * (v - m); }, 0) / (values.length - 1));
    }

    function rng(seed) {
        var a = seed >>> 0;
        return function () {
            a = (a + 0x6D2B79F5) >>> 0;
            var t = a;
            t = Math.imul(t ^ (t >>> 15), t | 1);
            t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
            return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
        };
    }

    // Session-cluster bootstrap of the mean of session representatives.
    function clusterInterval(sessionValues, options) {
        var o = Object.assign({}, DEFAULTS, options || {});
        var n = sessionValues.length;
        if (n < 2) return null;
        var rand = rng(o.seed);
        var means = [];
        for (var b = 0; b < o.bootstrapSamples; b += 1) {
            var s = 0;
            for (var i = 0; i < n; i += 1) s += sessionValues[Math.floor(rand() * n)];
            means.push(s / n);
        }
        means.sort(function (x, y) { return x - y; });
        return [means[Math.floor(0.025 * (means.length - 1))], means[Math.ceil(0.975 * (means.length - 1))]];
    }

    // Aggregates eligible events of ONE condition group.
    function summarize(events, options) {
        var o = Object.assign({}, DEFAULTS, options || {});
        var excluded = {};
        var eligible = [];
        (events || []).forEach(function (ev) {
            var e = eligibility(ev, o);
            if (e.ok) eligible.push(ev);
            else excluded[e.reason] = (excluded[e.reason] || 0) + 1;
        });
        var bySession = {};
        eligible.forEach(function (ev) { (bySession[ev.sessionId] = bySession[ev.sessionId] || []).push(ev); });
        var sessionIds = Object.keys(bySession);
        var sessionMeans = sessionIds.map(function (id) { return mean(bySession[id].map(function (ev) { return ev.medianCents; })); });
        var sessionMedians = sessionIds.map(function (id) { return median(bySession[id].map(function (ev) { return ev.medianCents; })); });
        var eventMedians = eligible.map(function (ev) { return ev.medianCents; });
        var eventMeans = eligible.map(function (ev) { return ev.meanCents; });
        var withinSd = eligible.map(function (ev) { return ev.sdCents; }).filter(function (v) { return typeof v === 'number'; });
        var interval = clusterInterval(sessionMeans, o);
        var nEvents = eligible.length;
        var nSessions = sessionIds.length;
        var status;
        if (nEvents < o.minEvents || nSessions < o.minSessions) status = 'insufficient';
        else if (!interval || interval[1] - interval[0] > o.maxIntervalWidthCents) status = 'reference';
        else status = 'ok';
        var tendency = 'undetermined';
        if (status === 'ok') tendency = interval[0] > 0 ? 'high' : (interval[1] < 0 ? 'low' : 'none');
        return {
            diagnosisVersion: DIAGNOSIS_VERSION,
            status: status,
            nEvents: nEvents,
            nSessions: nSessions,
            excludedByReason: excluded,
            // I-001: mean of the session representatives (sessions equally weighted).
            meanCents: mean(sessionMeans),
            medianCents: median(sessionMedians),
            eventMeanCents: mean(eventMeans),
            eventMedianCents: median(eventMedians),
            sdWithinEventCents: median(withinSd),
            sdBetweenEventsCents: sd(eventMedians),
            sdBetweenSessionsCents: sd(sessionMeans),
            interval95: interval,
            tendency: tendency,
            meanAbsCents: mean(sessionIds.map(function (id) { return mean(bySession[id].map(function (ev) { return Math.abs(ev.medianCents); })); })),
            firstAt: eligible.length ? Math.min.apply(null, eligible.map(function (ev) { return ev.startedAt || 0; })) : null,
            lastAt: eligible.length ? Math.max.apply(null, eligible.map(function (ev) { return ev.startedAt || 0; })) : null,
        };
    }

    // groupBy: function(event) -> key (null = skip). Every group is computed
    // only within one conditionsKey (callers include it in the key).
    function groupSummaries(events, groupBy, options) {
        var groups = {};
        (events || []).forEach(function (ev) {
            var key = groupBy(ev);
            if (key === null || key === undefined) return;
            (groups[key] = groups[key] || []).push(ev);
        });
        var out = {};
        Object.keys(groups).forEach(function (key) { out[key] = summarize(groups[key], options); });
        return out;
    }

    // Per note (MIDI) map for one condition key (I-001, I-002, I-005, I-014).
    function noteMap(events, conditionKey, options) {
        return groupSummaries(events, function (ev) { return ev.conditionsKey === conditionKey ? String(ev.midi) : null; }, options);
    }

    function registerOf(midi, boundaries) {
        var b = boundaries || { lowMax: 59, midMax: 76 };
        if (midi <= b.lowMax) return 'low';
        if (midi <= b.midMax) return 'mid';
        return 'high';
    }

    // I-003 / I-006 / I-007 / I-008 categories.
    function categoryMap(events, conditionKey, category, options) {
        var o = options || {};
        return groupSummaries(events, function (ev) {
            if (ev.conditionsKey !== conditionKey) return null;
            if (category === 'register') return registerOf(ev.midi, o.registerBoundaries);
            if (category === 'direction') return ev.direction || null;
            if (category === 'dynamics') return ev.dynamicMarking || ev.relativeLevel || null;
            if (category === 'instrument') return ev.instrumentId || null;
            return null;
        }, o);
    }

    // I-010 / H-004 / H-005: day / week / month keys in Japan time (UTC+9).
    function periodKey(utcMs, period) {
        var d = new Date(utcMs + 9 * 3600 * 1000);
        var y = d.getUTCFullYear();
        var m = d.getUTCMonth() + 1;
        var day = d.getUTCDate();
        var pad = function (n) { return (n < 10 ? '0' : '') + n; };
        if (period === 'month') return y + '-' + pad(m);
        if (period === 'week') {
            // ISO week number.
            var date = new Date(Date.UTC(y, m - 1, day));
            var dow = date.getUTCDay() || 7;
            date.setUTCDate(date.getUTCDate() + 4 - dow);
            var yearStart = Date.UTC(date.getUTCFullYear(), 0, 1);
            var week = Math.ceil(((date - yearStart) / 86400000 + 1) / 7);
            return date.getUTCFullYear() + '-W' + pad(week);
        }
        return y + '-' + pad(m) + '-' + pad(day);
    }

    function periodMap(events, conditionKey, period, options) {
        return groupSummaries(events, function (ev) {
            return ev.conditionsKey === conditionKey && typeof ev.startedAt === 'number' ? periodKey(ev.startedAt, period) : null;
        }, options);
    }

    // I-012 / H-006: recent group vs earlier group of the same condition and
    // engine/stats version. Usage count alone is never "improvement".
    function improvement(recentEvents, pastEvents, options) {
        var o = Object.assign({}, DEFAULTS, options || {});
        var recent = summarize(recentEvents, o);
        var past = summarize(pastEvents, o);
        var versions = function (list) {
            var set = {};
            list.forEach(function (ev) { set[(ev.engineVersion || 'unknown') + '/' + (ev.statsVersion || 'unknown')] = true; });
            return Object.keys(set);
        };
        var rv = versions(recentEvents || []);
        var pv = versions(pastEvents || []);
        if (rv.length !== 1 || pv.length !== 1 || rv[0] !== pv[0]) {
            return { status: 'not-comparable', reason: 'different-engine-or-stats-version', recent: recent, past: past };
        }
        if (recent.status === 'insufficient' || past.status === 'insufficient') {
            return { status: 'insufficient', recent: recent, past: past };
        }
        // Difference of mean absolute deviation (positive = closer to target now).
        var sessionsAbs = function (list) {
            var by = {};
            list.forEach(function (ev) { if (eligibility(ev, o).ok) (by[ev.sessionId] = by[ev.sessionId] || []).push(Math.abs(ev.medianCents)); });
            return Object.keys(by).map(function (k) { return mean(by[k]); });
        };
        var r = sessionsAbs(recentEvents);
        var p = sessionsAbs(pastEvents);
        var rand = rng(o.seed);
        var diffs = [];
        for (var b = 0; b < o.bootstrapSamples; b += 1) {
            var rs = 0;
            var ps = 0;
            for (var i = 0; i < r.length; i += 1) rs += r[Math.floor(rand() * r.length)];
            for (var j = 0; j < p.length; j += 1) ps += p[Math.floor(rand() * p.length)];
            diffs.push(ps / p.length - rs / r.length);
        }
        diffs.sort(function (x, y) { return x - y; });
        var ci = [diffs[Math.floor(0.025 * (diffs.length - 1))], diffs[Math.ceil(0.975 * (diffs.length - 1))]];
        var change = mean(p) - mean(r);
        var status = ci[0] > 0 ? 'closer' : (ci[1] < 0 ? 'further' : 'no-clear-change');
        return { status: status, changeCents: change, interval95: ci, recent: recent, past: past };
    }

    // I-011 / H-008: weak notes, two separate rankings, only diagnosable notes.
    function weakRanking(noteSummaries, limit) {
        var rows = Object.keys(noteSummaries || {}).map(function (k) { return Object.assign({ key: k }, noteSummaries[k]); }).filter(function (r) { return r.status === 'ok'; });
        var byDeviation = rows.slice().sort(function (a, b) { return Math.abs(b.medianCents) - Math.abs(a.medianCents); }).slice(0, limit || 5);
        var bySpread = rows.filter(function (r) { return typeof r.sdBetweenSessionsCents === 'number'; }).sort(function (a, b) { return b.sdBetweenSessionsCents - a.sdBetweenSessionsCents; }).slice(0, limit || 5);
        return { byDeviation: byDeviation, bySpread: bySpread };
    }

    // I-013: rule-based practice suggestions with reasons and counts.
    function suggestions(noteSummaries, categories, describe) {
        var name = typeof describe === 'function' ? describe : function (midi) { return 'MIDI ' + midi; };
        var list = [];
        Object.keys(noteSummaries || {}).forEach(function (k) {
            var s = noteSummaries[k];
            if (s.status !== 'ok' || (s.tendency !== 'high' && s.tendency !== 'low')) return;
            list.push({
                kind: 'longtone',
                midi: Number(k),
                text: name(Number(k)) + 'が' + (s.tendency === 'high' ? '高め' : '低め') + 'に出る傾向があります。' + name(Number(k)) + 'のロングトーンで、目標に合わせる練習を提案します。',
                reason: { meanCents: s.meanCents, interval95: s.interval95, nEvents: s.nEvents, nSessions: s.nSessions },
            });
        });
        var dir = categories && categories.direction;
        if (dir && dir.up && dir.down && dir.up.status === 'ok' && dir.down.status === 'ok' &&
            typeof dir.up.sdBetweenEventsCents === 'number' && typeof dir.down.sdBetweenEventsCents === 'number') {
            var diff = dir.up.sdBetweenEventsCents - dir.down.sdBetweenEventsCents;
            if (Math.abs(diff) >= 3) {
                list.push({
                    kind: diff > 0 ? 'scale-up' : 'scale-down',
                    text: (diff > 0 ? '上行' : '下行') + 'で音程のばらつきが大きめです。' + (diff > 0 ? '上行' : '下行') + 'の音階練習を提案します。',
                    reason: { upSd: dir.up.sdBetweenEventsCents, downSd: dir.down.sdBetweenEventsCents, upEvents: dir.up.nEvents, downEvents: dir.down.nEvents },
                });
            }
        }
        var leap = categories && categories.direction && categories.direction.leap;
        if (leap && leap.status === 'ok' && typeof leap.meanAbsCents === 'number' && leap.meanAbsCents >= 10) {
            list.push({ kind: 'leap', text: '跳躍の直後に目標から離れやすい傾向があります。音程跳躍の練習を提案します。', reason: { meanAbsCents: leap.meanAbsCents, nEvents: leap.nEvents, nSessions: leap.nSessions } });
        }
        return list;
    }

    var api = {
        DIAGNOSIS_VERSION: DIAGNOSIS_VERSION,
        DEFAULTS: DEFAULTS,
        CONDITION_FIELDS: CONDITION_FIELDS,
        stableStringify: stableStringify,
        hash: hash,
        conditionsKey: conditionsKey,
        conditionDifferences: conditionDifferences,
        normalizeEnvironment: normalizeEnvironment,
        describeEnvironment: describeEnvironment,
        eligibility: eligibility,
        summarize: summarize,
        groupSummaries: groupSummaries,
        noteMap: noteMap,
        categoryMap: categoryMap,
        registerOf: registerOf,
        periodKey: periodKey,
        periodMap: periodMap,
        improvement: improvement,
        weakRanking: weakRanking,
        suggestions: suggestions,
        clusterInterval: clusterInterval,
    };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.intonationProfile = api;
    lib.releases.intonation_profile = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
