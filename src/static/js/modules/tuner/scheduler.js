// Tuner: look-ahead scheduler for playback patterns (hold, timed, repeat,
// alternate, metronome). Events are placed on the AudioContext clock; the JS
// timer only refills the look-ahead window (design 7: look-ahead 100 ms,
// timer 25 ms, both tuning values). Stopping invalidates everything that was
// planned through a generation number, so a late timer can never start a
// sound again. The scheduler itself never touches audio nodes: it calls
// handlers with { time, type, group, index }.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-5c2ad5661ae9'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var DEFAULTS = { lookaheadSeconds: 0.1, timerMs: 25, startDelaySeconds: 0.03 };
    var LIMITS = { minSeconds: 0.1, maxSeconds: 600, maxRepeats: 100, minBpm: 30, maxBpm: 240 };

    function clamp(value, lo, hi) {
        return Math.max(lo, Math.min(hi, value));
    }

    // pattern: { kind: 'hold' | 'timed' | 'repeat' | 'alternate' | 'metronome',
    //   seconds (timed / note length), gapSeconds, repeats (null = until stop),
    //   bpm, beatsPerBar, groups (alternate: number of groups) }
    function normalizePattern(pattern) {
        var p = pattern || {};
        var kind = ['hold', 'timed', 'repeat', 'alternate', 'metronome'].indexOf(p.kind) >= 0 ? p.kind : 'hold';
        var seconds = clamp(Number(p.seconds) || 2, LIMITS.minSeconds, LIMITS.maxSeconds);
        var gap = clamp(Number(p.gapSeconds) >= 0 ? Number(p.gapSeconds) : 0.5, 0, LIMITS.maxSeconds);
        var repeats = p.repeats === null || p.repeats === undefined ? null : clamp(Math.round(Number(p.repeats)) || 1, 1, LIMITS.maxRepeats);
        var bpm = clamp(Number(p.bpm) || 60, LIMITS.minBpm, LIMITS.maxBpm);
        var beatsPerBar = clamp(Math.round(Number(p.beatsPerBar)) || 4, 1, 12);
        return { kind: kind, seconds: seconds, gapSeconds: gap, repeats: repeats, bpm: bpm, beatsPerBar: beatsPerBar, groups: kind === 'alternate' ? 2 : 1 };
    }

    // Pure: the k-th event of a pattern starting at t0 (null = no more).
    function eventAt(pattern, t0, k) {
        var p = pattern;
        if (p.kind === 'hold') return k === 0 ? { time: t0, type: 'on', group: 0, index: 0 } : null;
        if (p.kind === 'timed') {
            if (k === 0) return { time: t0, type: 'on', group: 0, index: 0 };
            if (k === 1) return { time: t0 + p.seconds, type: 'off', group: 0, index: 0, last: true };
            return null;
        }
        if (p.kind === 'metronome') {
            if (p.repeats !== null && k >= p.repeats) return null;
            var beat = 60 / p.bpm;
            return { time: t0 + k * beat, type: 'click', group: 0, index: k, accent: k % p.beatsPerBar === 0, last: p.repeats !== null && k === p.repeats - 1 };
        }
        // repeat / alternate: on/off pairs
        var note = Math.floor(k / 2);
        if (p.repeats !== null && note >= p.repeats * (p.kind === 'alternate' ? 2 : 1)) return null;
        var period = p.seconds + p.gapSeconds;
        var start = t0 + note * period;
        var group = p.kind === 'alternate' ? note % 2 : 0;
        var total = p.repeats === null ? null : p.repeats * (p.kind === 'alternate' ? 2 : 1);
        if (k % 2 === 0) return { time: start, type: 'on', group: group, index: note };
        return { time: start + p.seconds, type: 'off', group: group, index: note, last: total !== null && note === total - 1 };
    }

    // env: { now() (AudioContext seconds), setTimeout, clearTimeout }
    function createScheduler(env, options) {
        var opts = Object.assign({}, DEFAULTS, options || {});
        var generation = 0;
        var timer = null;
        var job = null;

        function clearTimer() {
            if (timer !== null) env.clearTimeout(timer);
            timer = null;
        }

        function fill(gen) {
            timer = null;
            if (!job || gen !== generation) return;
            var horizon = env.now() + opts.lookaheadSeconds;
            while (true) {
                var ev = eventAt(job.pattern, job.t0, job.next);
                if (!ev) {
                    job.done = true;
                    break;
                }
                if (ev.time > horizon) break;
                job.next += 1;
                try { job.handler(ev, gen); } catch (_) { /* a failing handler must not stop the stop path */ }
                if (gen !== generation) return; // handler stopped us
                if (ev.last) {
                    job.done = true;
                    if (job.onDone) job.onDone(ev, gen);
                    return;
                }
            }
            if (!job.done) timer = env.setTimeout(function () { fill(gen); }, opts.timerMs);
        }

        // Starts a pattern; returns its generation. handler(ev, generation).
        function start(pattern, handler, onDone) {
            stop();
            generation += 1;
            var gen = generation;
            job = { pattern: normalizePattern(pattern), t0: env.now() + opts.startDelaySeconds, next: 0, handler: handler, onDone: onDone, done: false };
            fill(gen);
            return gen;
        }

        // Invalidates every planned event and timer (idempotent).
        function stop() {
            generation += 1;
            clearTimer();
            job = null;
        }

        return {
            start: start,
            stop: stop,
            isRunning: function () { return Boolean(job) && !job.done; },
            generation: function () { return generation; },
            current: function () { return job ? { pattern: job.pattern, t0: job.t0 } : null; },
        };
    }

    var api = { DEFAULTS: DEFAULTS, LIMITS: LIMITS, normalizePattern: normalizePattern, eventAt: eventAt, createScheduler: createScheduler };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.scheduler = api;
    lib.releases.scheduler = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
