// Tuner: fundamental-frequency estimation with the YIN method.
// The difference function is computed from an FFT cross-correlation plus
// cumulative sums of squares instead of an O(W * tauMax) brute-force loop,
// because C1 needs a ~1,500-sample lag range and the worker runs this up to
// 20 times per second on phones.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-e8d471ab55a0'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    var fft = lib.fft || (typeof require === 'function' ? require('./fft.js') : null);
    if (!fft) throw new Error('tuner pitch.js requires fft.js to be loaded first');

    var DEFAULTS = {
        // Search range has headroom beyond C1-C8 so that 430-450 Hz references still fit.
        minFrequency: 31,
        maxFrequency: 4400,
        // YIN absolute threshold for the first dip of the normalised difference.
        threshold: 0.15,
        // A dip deeper than this (confidence >= 0.8) is treated as a usable pitch.
        validityThreshold: 0.2,
        // Frames quieter than this RMS level (dBFS, see rmsDbfs below) are silence.
        silenceDbfs: -60,
        // Max energy ratio between the frame halves (4 = 6 dB). A frame that
        // contains an attack or a sudden stop biases the period estimate (seen
        // as -20..-45 cent readings right after start-up), so it is unstable.
        maxHalfEnergyRatio: 4,
        // A run of this many exactly-zero samples inside an audible frame is
        // an audio dropout (buffer underrun), not sound: real microphone noise
        // never holds exactly 0. Such frames gave -20..-45 cent readings.
        dropoutZeroRun: 16,
    };

    function frameGeometry(sampleRate, minFrequency, maxFrequency) {
        var tauMin = Math.max(2, Math.floor(sampleRate / maxFrequency));
        var tauMax = Math.ceil(sampleRate / minFrequency);
        // Integration window of 1.5 longest periods keeps C1 stable without
        // making every update wait for a much longer block of audio.
        var windowLength = Math.ceil(tauMax * 1.5);
        return {
            tauMin: tauMin,
            tauMax: tauMax,
            windowLength: windowLength,
            frameLength: windowLength + tauMax + 1,
        };
    }

    // Reference O(W * tauMax) difference function, used only by tests to
    // prove that the FFT version computes the same values.
    function differenceDirect(x, windowLength, tauMax) {
        var d = new Float64Array(tauMax + 1);
        for (var tau = 0; tau <= tauMax; tau += 1) {
            var sum = 0;
            for (var j = 0; j < windowLength; j += 1) {
                var diff = x[j] - x[j + tau];
                sum += diff * diff;
            }
            d[tau] = sum;
        }
        return d;
    }

    // d(tau) = sum(x[j]^2) + sum(x[j+tau]^2) - 2 * sum(x[j] * x[j+tau]), j < W.
    // The cross term comes from one zero-padded FFT correlation. Padding to at
    // least frameLength + W - 1 prevents circular wrap-around from leaking
    // the end of the frame into small lags.
    function createDifferenceWorkspace(frameLength, windowLength) {
        var size = fft.nextPowerOfTwo(frameLength + windowLength);
        return {
            size: size,
            aRe: new Float64Array(size),
            aIm: new Float64Array(size),
            bRe: new Float64Array(size),
            bIm: new Float64Array(size),
            prefix: new Float64Array(frameLength + 1),
        };
    }

    function differenceFFT(x, windowLength, tauMax, workspace, out) {
        var frameLength = windowLength + tauMax;
        var ws = workspace || createDifferenceWorkspace(frameLength + 1, windowLength);
        var d = out || new Float64Array(tauMax + 1);
        var size = ws.size;
        var i;
        for (i = 0; i < size; i += 1) {
            ws.aRe[i] = i < windowLength ? x[i] : 0;
            ws.aIm[i] = 0;
            ws.bRe[i] = i < frameLength ? x[i] : 0;
            ws.bIm[i] = 0;
        }
        fft.transform(ws.aRe, ws.aIm, false);
        fft.transform(ws.bRe, ws.bIm, false);
        // conj(A) * B gives sum_j a[j] * b[j + tau] after the inverse transform.
        for (i = 0; i < size; i += 1) {
            var ar = ws.aRe[i];
            var ai = -ws.aIm[i];
            var br = ws.bRe[i];
            var bi = ws.bIm[i];
            ws.aRe[i] = ar * br - ai * bi;
            ws.aIm[i] = ar * bi + ai * br;
        }
        fft.transform(ws.aRe, ws.aIm, true);
        var prefix = ws.prefix;
        prefix[0] = 0;
        for (i = 0; i < frameLength; i += 1) prefix[i + 1] = prefix[i] + x[i] * x[i];
        var energy0 = prefix[windowLength];
        for (var tau = 0; tau <= tauMax; tau += 1) {
            var energyTau = prefix[tau + windowLength] - prefix[tau];
            var cross = ws.aRe[tau] / size;
            var value = energy0 + energyTau - 2 * cross;
            // Rounding can make perfectly periodic input slightly negative.
            d[tau] = value > 0 ? value : 0;
        }
        return d;
    }

    function cumulativeMeanNormalized(d, out) {
        var cmnd = out || new Float64Array(d.length);
        cmnd[0] = 1;
        var running = 0;
        for (var tau = 1; tau < d.length; tau += 1) {
            running += d[tau];
            cmnd[tau] = running > 0 ? (d[tau] * tau) / running : 1;
        }
        return cmnd;
    }

    function localMinimumNear(values, center, radius, lo, hi) {
        var best = -1;
        for (var t = Math.max(lo, center - radius); t <= Math.min(hi, center + radius); t += 1) {
            if (best < 0 || values[t] < values[best]) best = t;
        }
        return best;
    }

    function parabolicOffset(values, tau) {
        if (tau <= 0 || tau >= values.length - 1) return 0;
        var left = values[tau - 1];
        var mid = values[tau];
        var right = values[tau + 1];
        var denom = left - 2 * mid + right;
        if (!(denom > 0)) return 0;
        var offset = (left - right) / (2 * denom);
        return Math.max(-1, Math.min(1, offset));
    }

    // Depth of a dip between integer lags. High notes have periods of only
    // ~11 samples, so the true dip usually falls between samples and the
    // integer value alone would hide it (causing octave errors).
    function interpolatedMinimum(values, tau) {
        if (tau <= 0 || tau >= values.length - 1) return values[tau];
        var left = values[tau - 1];
        var mid = values[tau];
        var right = values[tau + 1];
        var denom = left - 2 * mid + right;
        if (!(denom > 0)) return mid;
        var value = mid - ((left - right) * (left - right)) / (8 * denom);
        return Math.max(0, Math.min(mid, value));
    }

    function isLocalMinimum(values, t) {
        return values[t] <= values[t - 1] && values[t] <= values[t + 1];
    }

    // Multi-period refinement: a periodic signal also dips at K * period.
    // Interpolating that later dip and dividing by K shrinks the sub-sample
    // interpolation error by ~K, which is what makes C7-C8 usable. K grows
    // step by step so the predicted lag never lands on a neighbouring dip.
    function refinePeriod(d, tauEstimate, tauMax) {
        var estimate = tauEstimate;
        var uncertainty = 0.5;
        for (var step = 0; step < 4; step += 1) {
            var multiple = Math.floor(Math.min((estimate * 0.25) / uncertainty, (tauMax - 1) / estimate));
            if (multiple < 2) break;
            var predicted = Math.round(estimate * multiple);
            var radius = Math.max(1, Math.floor(estimate * 0.25));
            var lag = -1;
            for (var t = Math.max(1, predicted - radius); t <= Math.min(tauMax - 1, predicted + radius); t += 1) {
                if (lag < 0 || d[t] < d[lag]) lag = t;
            }
            if (lag < 0) break;
            estimate = (lag + parabolicOffset(d, lag)) / multiple;
            uncertainty = Math.max(0.5 / multiple, 1e-4);
        }
        return estimate;
    }

    function createPitchDetector(options) {
        var opts = Object.assign({}, DEFAULTS, options || {});
        var sampleRate = Number(opts.sampleRate);
        if (!(sampleRate > 0)) throw new Error('sampleRate is required');
        var geometry = frameGeometry(sampleRate, opts.minFrequency, opts.maxFrequency);
        var workspace = createDifferenceWorkspace(geometry.frameLength, geometry.windowLength);
        var centered = new Float64Array(geometry.frameLength);
        var d = new Float64Array(geometry.tauMax + 1);
        var cmnd = new Float64Array(geometry.tauMax + 1);

        function detect(frame) {
            if (!frame || frame.length < geometry.frameLength) {
                throw new Error('frame must contain at least ' + geometry.frameLength + ' samples');
            }
            var n = geometry.frameLength;
            var offset = frame.length - n;
            var mean = 0;
            var i;
            var zeroRun = 0;
            var longestZeroRun = 0;
            for (i = 0; i < n; i += 1) {
                var sample = frame[offset + i];
                mean += sample;
                zeroRun = sample === 0 ? zeroRun + 1 : 0;
                if (zeroRun > longestZeroRun) longestZeroRun = zeroRun;
            }
            mean /= n;
            var power = 0;
            var firstHalf = 0;
            var half = Math.floor(n / 2);
            for (i = 0; i < n; i += 1) {
                var v = frame[offset + i] - mean;
                centered[i] = v;
                power += v * v;
                if (i < half) firstHalf += v * v;
            }
            var secondHalf = power - firstHalf;
            power /= n;
            // RMS level in dBFS where an RMS of 1.0 is 0 dBFS (a full-scale sine is -3.01 dBFS).
            var rmsDbfs = power > 0 ? Math.max(-160, 10 * Math.log10(power)) : -160;
            var result = {
                frequency: 0,
                confidence: 0,
                rmsDbfs: rmsDbfs,
                valid: false,
                reason: 'silent',
                periodSamples: 0,
            };
            if (rmsDbfs < opts.silenceDbfs) return result;
            if (longestZeroRun >= opts.dropoutZeroRun) {
                result.reason = 'dropout';
                return result;
            }

            differenceFFT(centered, geometry.windowLength, geometry.tauMax, workspace, d);
            cumulativeMeanNormalized(d, cmnd);

            // YIN step 4 with sub-sample depth: take the first dip whose
            // interpolated depth is under the threshold, then the deepest point
            // of that dip (noise can put small wiggles inside a broad low-note dip).
            var tau = -1;
            var lastLag = geometry.tauMax - 1;
            for (var t = Math.max(1, geometry.tauMin); t <= lastLag; t += 1) {
                if (!isLocalMinimum(cmnd, t) || interpolatedMinimum(cmnd, t) >= opts.threshold) continue;
                tau = t;
                for (var u = t + 1; u <= lastLag && interpolatedMinimum(cmnd, u) < opts.threshold; u += 1) {
                    if (cmnd[u] < cmnd[tau]) tau = u;
                }
                break;
            }
            if (tau < 0) {
                tau = Math.max(1, geometry.tauMin);
                for (var s = tau + 1; s <= lastLag; s += 1) {
                    if (cmnd[s] < cmnd[tau]) tau = s;
                }
            }
            var depth = interpolatedMinimum(cmnd, tau);
            // The first-dip rule already prefers the shortest (higher octave)
            // candidate. Guard against the opposite error: a weak fundamental
            // with a strong 2nd harmonic leaves a shallow dip at half the true
            // period while the true period is far deeper.
            var doubled = tau * 2;
            if (doubled <= lastLag && depth > 0.05) {
                var candidate = localMinimumNear(cmnd, doubled, 2, Math.max(1, geometry.tauMin), lastLag);
                // If the signal really repeats every tau it also dips at 3 * tau;
                // a true period of 2 * tau would be half a cycle off there.
                var tripled = tau * 3;
                var tripledDip = tripled <= lastLag
                    ? interpolatedMinimum(cmnd, localMinimumNear(cmnd, tripled, 2, Math.max(1, geometry.tauMin), lastLag))
                    : Infinity;
                var periodicAtTau = tripledDip < Math.max(opts.threshold, depth);
                if (candidate > 0 && !periodicAtTau && interpolatedMinimum(cmnd, candidate) < depth * 0.3) {
                    tau = candidate;
                    depth = interpolatedMinimum(cmnd, candidate);
                }
            }
            var refined = refinePeriod(d, tau + parabolicOffset(d, tau), geometry.tauMax);
            var frequency = sampleRate / refined;
            var confidence = Math.max(0, Math.min(1, 1 - depth));
            result.frequency = frequency;
            result.confidence = confidence;
            result.periodSamples = refined;
            var halves = Math.max(firstHalf, secondHalf) / Math.max(Math.min(firstHalf, secondHalf), 1e-12);
            result.levelChange = halves;
            if (depth > opts.validityThreshold || halves > opts.maxHalfEnergyRatio) {
                result.reason = 'unstable';
            } else if (frequency < opts.minFrequency || frequency > opts.maxFrequency) {
                result.reason = 'out-of-range';
            } else {
                result.valid = true;
                result.reason = 'ok';
            }
            return result;
        }

        return {
            sampleRate: sampleRate,
            frameLength: geometry.frameLength,
            windowLength: geometry.windowLength,
            tauMin: geometry.tauMin,
            tauMax: geometry.tauMax,
            options: opts,
            detect: detect,
        };
    }

    var api = {
        DEFAULTS: DEFAULTS,
        frameGeometry: frameGeometry,
        differenceDirect: differenceDirect,
        differenceFFT: differenceFFT,
        createDifferenceWorkspace: createDifferenceWorkspace,
        cumulativeMeanNormalized: cumulativeMeanNormalized,
        createPitchDetector: createPitchDetector,
    };

    lib.releases = lib.releases || {};
    lib.pitch = api;
    lib.releases.pitch = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
