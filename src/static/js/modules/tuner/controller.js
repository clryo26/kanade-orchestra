// Tuner: measurement lifecycle and race control.
//
// States: hidden -> starting -> measuring | resume-required | unavailable.
// "Waiting for permission" is deliberately part of `starting`: a pending
// getUserMedia() cannot tell a visible prompt from a slow device.
//
// Every start belongs to a generation number issued by the launcher. After
// each await the controller re-checks that its run is still current and that
// the external guard (screen visible, signed in, admin) still holds; a run
// that lost the race releases whatever it acquired (e.g. a microphone granted
// after the user already left). Teardown never waits for pending promises and
// is safe to call any number of times. Explicit track.stop() does not fire
// `ended`, so teardown does all cleanup itself instead of relying on events.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-5c2ad5661ae9'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)
    var TUNER_PROTOCOL = 2;

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    var audio = lib.audio || (typeof require === 'function' ? require('./audio.js') : null);
    var errors = lib.errors || (typeof require === 'function' ? require('./errors.js') : null);
    if (!audio || !errors) throw new Error('tuner controller.js requires audio.js and errors.js');

    var TIMING = {
        workletReadyMs: 4000,
        workerReadyMs: 6000,
        resumeWaitMs: 1000,
        watchdogIntervalMs: 500,
        // No result from the worker for this long while measuring = audio stalled.
        stallMs: 3000,
    };

    function createTunerController(deps) {
        var env = deps.env;
        var timing = Object.assign({}, TIMING, deps.timing || {});
        var state = 'hidden';
        var stateCode = null;
        var current = null;
        var lastSession = null;

        function emit(next, code) {
            state = next;
            stateCode = code || null;
            if (deps.onState) deps.onState({ state: next, code: stateCode, generation: current ? current.generation : null });
        }

        function isCurrent(run) {
            return Boolean(run) && current === run && !run.stopped;
        }

        // Re-checks run identity and the external guard; a failed guard asks
        // the launcher to leave, which ends in stop() for every resource.
        function checkAlive(run) {
            if (!isCurrent(run)) return false;
            if (!deps.guard(run.generation)) {
                if (deps.requestLeave) deps.requestLeave('guard');
                return false;
            }
            return true;
        }

        function teardown(run) {
            if (!run || run.stopped) return;
            run.stopped = true;
            if (run.watchdog) env.clearInterval(run.watchdog);
            run.watchdog = null;
            (run.timeouts || []).forEach(function (id) { env.clearTimeout(id); });
            run.timeouts = [];
            audio.stopStream(run.stream);
            run.stream = null;
            if (run.graph) run.graph.disconnect();
            run.graph = null;
            if (run.channel) {
                [run.channel.port1, run.channel.port2].forEach(function (port) {
                    try { port.close(); } catch (_) { /* already transferred/closed */ }
                });
            }
            run.channel = null;
            if (run.worker) {
                try { run.worker.onmessage = null; run.worker.onerror = null; } catch (_) { /* ignore */ }
                try { run.worker.postMessage({ type: 'stop' }); } catch (_) { /* already terminated */ }
                try { run.worker.terminate(); } catch (_) { /* already terminated */ }
            }
            run.worker = null;
            audio.closeContext(run.ctx);
            run.ctx = null;
            if (run.wakeLock) {
                var lock = run.wakeLock;
                run.wakeLock = null;
                try {
                    var released = lock.release();
                    if (released && typeof released.catch === 'function') released.catch(function () {});
                } catch (_) { /* already released */ }
            }
            (run.waiters || []).forEach(function (reject) { reject(errors.makeError('cancelled')); });
            run.waiters = [];
            if (current === run) current = null;
        }

        function fail(run, code) {
            if (!isCurrent(run)) return;
            teardown(run);
            emit(code === 'resume-required' ? 'resume-required' : 'unavailable', code);
        }

        function later(run, ms, fn) {
            var id = env.setTimeout(fn, ms);
            run.timeouts.push(id);
            return id;
        }

        // Promise settled by a message handler, with a timeout; rejected with
        // "cancelled" if the run is torn down while waiting.
        function waitFor(run, key, ms, timeoutCode) {
            return new Promise(function (resolve, reject) {
                run.resolvers[key] = resolve;
                run.waiters.push(reject);
                later(run, ms, function () { reject(errors.makeError(timeoutCode)); });
            });
        }

        function environmentSnapshot() {
            return {
                isSecureContext: env.isSecureContext !== false,
                hasGetUserMedia: Boolean(env.mediaDevices && typeof env.mediaDevices.getUserMedia === 'function'),
                hasAudioContext: typeof env.AudioContext === 'function',
                hasAudioWorklet: typeof env.AudioWorkletNode === 'function',
                hasWorker: typeof env.Worker === 'function',
                hasMessageChannel: typeof env.MessageChannel === 'function',
            };
        }

        function handleWorkerMessage(run, message) {
            if (!isCurrent(run) || !message) return;
            if (message.type === 'version-mismatch' || message.release !== deps.release || message.protocol !== TUNER_PROTOCOL) {
                fail(run, 'version-mismatch');
                return;
            }
            if (message.generation !== run.generation) return; // stale result from an older run
            run.lastMessageAt = env.now();
            if (!checkAlive(run)) return;
            switch (message.type) {
            case 'ready':
                if (run.resolvers.worker) run.resolvers.worker(message.session);
                break;
            case 'pitch':
                if (state === 'measuring' && deps.onPitch) deps.onPitch(message.frame);
                break;
            case 'spectrum':
                if (state === 'measuring' && deps.onSpectrum) deps.onSpectrum(message.frame);
                break;
            case 'display-axis':
                if (deps.onDisplayAxis) deps.onDisplayAxis(message.axis);
                break;
            case 'envelope':
                if (state === 'measuring' && deps.onEnvelope) deps.onEnvelope(message.frames || [], message.captureEpoch);
                break;
            case 'harmonics':
                if (state === 'measuring' && deps.onHarmonics) deps.onHarmonics(message.frame);
                break;
            case 'configured':
                if (deps.onConfigured) deps.onConfigured(message);
                break;
            case 'gap':
                if (deps.onGap) deps.onGap(message.droppedFrames || 0, message.startFrame);
                break;
            case 'load-failed':
                fail(run, 'load-failed');
                break;
            case 'error':
                fail(run, 'unreadable');
                break;
            default:
                break; // 'status' heartbeats only refresh lastMessageAt
            }
        }

        function handleWorkletMessage(run, message) {
            if (!isCurrent(run) || !message) return;
            if (message.type === 'version-mismatch' || message.release !== deps.release || message.protocol !== TUNER_PROTOCOL) {
                fail(run, 'version-mismatch');
                return;
            }
            if (message.generation !== run.generation) return;
            if (message.type === 'ready' && run.resolvers.worklet) run.resolvers.worklet(message);
        }

        // Interruptions (track ended/muted, context interrupted) end the run
        // and wait for a tap. There is no automatic re-acquisition loop.
        function interrupted(run) {
            if (!isCurrent(run) || state !== 'measuring') return;
            fail(run, 'resume-required');
        }

        // Clock correspondence of this capture epoch: audio frames are the
        // analysis clock; performance time and UTC are only mapped to it.
        // getOutputTimestamp() (when present) relates the context clock to
        // performance.now(); it is not a calibration of the microphone delay.
        function sampleClock(run) {
            if (!run.ctx || !deps.onClock) return;
            var point = null;
            try {
                if (typeof run.ctx.getOutputTimestamp === 'function') {
                    var ts = run.ctx.getOutputTimestamp();
                    if (ts && typeof ts.contextTime === 'number' && typeof ts.performanceTime === 'number' && ts.performanceTime > 0) {
                        point = { contextTime: ts.contextTime, performanceTime: ts.performanceTime, source: 'output-timestamp' };
                    }
                }
            } catch (_) { point = null; }
            if (!point) point = { contextTime: run.ctx.currentTime, performanceTime: env.now(), source: 'current-time' };
            point.captureEpoch = run.generation;
            point.sampleRate = run.ctx.sampleRate;
            point.utcMs = typeof env.utcNow === 'function' ? env.utcNow() : null;
            deps.onClock(point);
        }

        function startWatchdog(run) {
            run.lastMessageAt = env.now();
            sampleClock(run);
            run.watchdog = env.setInterval(function () {
                if (!checkAlive(run)) return;
                if (state === 'measuring' && env.now() - run.lastMessageAt > timing.stallMs) interrupted(run);
                if (state === 'measuring') sampleClock(run);
            }, timing.watchdogIntervalMs);
        }

        function requestWakeLock(run) {
            var wakeLock = env.wakeLock;
            if (!wakeLock || typeof wakeLock.request !== 'function') return;
            var pending;
            try {
                pending = wakeLock.request('screen');
            } catch (_) {
                return;
            }
            if (!pending || typeof pending.then !== 'function') return;
            pending.then(function (lock) {
                if (!isCurrent(run)) {
                    try { lock.release(); } catch (_) { /* ignore */ }
                    return;
                }
                run.wakeLock = lock;
            }, function () { /* Wake Lock is optional; measurement continues */ });
        }

        async function start(options) {
            var generation = options.generation;
            if (current && current.generation === generation && !current.stopped) return; // duplicate start
            teardown(current);
            var run = {
                generation: generation,
                stopped: false,
                ctx: null,
                stream: null,
                graph: null,
                worker: null,
                channel: null,
                wakeLock: null,
                watchdog: null,
                timeouts: [],
                waiters: [],
                resolvers: {},
                lastMessageAt: 0,
            };
            current = run;
            emit('starting');
            // Guard first: a hidden screen must never create audio or ask for the mic.
            if (!checkAlive(run)) {
                audio.closeContext(options.audioContext);
                return;
            }

            var snapshot = environmentSnapshot();
            var envCode = errors.checkEnvironment(snapshot);
            if (envCode) {
                audio.closeContext(options.audioContext);
                fail(run, envCode);
                return;
            }
            try {
                run.ctx = options.audioContext || new env.AudioContext({ latencyHint: 'interactive' });
                // Not awaited: a pending resume() must not hold up loading or the microphone.
                audio.resumeQuietly(run.ctx);
                run.ctx.onstatechange = function () {
                    if (!isCurrent(run) || !run.ctx) return;
                    var ctxState = run.ctx.state;
                    if (state === 'measuring' && (ctxState === 'suspended' || ctxState === 'interrupted' || ctxState === 'closed')) {
                        interrupted(run);
                    }
                };

                if (!checkAlive(run)) return;
                var microphone = env.mediaDevices.getUserMedia(audio.microphoneConstraints()).then(function (stream) {
                    if (!isCurrent(run)) {
                        audio.stopStream(stream); // granted after the user left
                        throw errors.makeError('cancelled');
                    }
                    run.stream = stream;
                    return stream;
                });
                var worklet = Promise.resolve()
                    .then(function () { return run.ctx.audioWorklet.addModule(deps.urls.worklet); })
                    .catch(function (error) { throw errors.makeError('load-failed', error); });
                run.worker = new env.Worker(deps.urls.worker);
                run.worker.onmessage = function (event) { handleWorkerMessage(run, event.data); };
                run.worker.onerror = function () { fail(run, 'load-failed'); };
                // Keep later rejections from surfacing as unhandled once another step failed first.
                microphone.catch(function () {});
                worklet.catch(function () {});

                var results = await Promise.all([microphone, worklet]);
                if (!checkAlive(run)) return;
                var stream = results[0];
                var track = stream.getAudioTracks ? stream.getAudioTracks()[0] : null;
                var micSettings = audio.confirmedMicrophoneSettings(track);

                var workletReady = waitFor(run, 'worklet', timing.workletReadyMs, 'load-failed');
                run.graph = audio.createCaptureGraph({
                    audioContext: run.ctx,
                    AudioWorkletNode: env.AudioWorkletNode,
                    stream: stream,
                    release: deps.release,
                    protocol: TUNER_PROTOCOL,
                    generation: generation,
                });
                run.graph.node.port.onmessage = function (event) { handleWorkletMessage(run, event.data); };
                await workletReady;
                if (!checkAlive(run)) return;

                // Audio goes worklet -> worker directly; the main thread never relays samples.
                run.channel = new env.MessageChannel();
                var workerReady = waitFor(run, 'worker', timing.workerReadyMs, 'load-failed');
                run.graph.node.port.postMessage({ type: 'connect', port: run.channel.port1 }, [run.channel.port1]);
                run.worker.postMessage({
                    type: 'init',
                    release: deps.release,
                    protocol: TUNER_PROTOCOL,
                    generation: generation,
                    sampleRate: run.ctx.sampleRate,
                    // Display axis; the analysis profile/threshold come with config.
                    displayRange: deps.getDisplayRange ? deps.getDisplayRange() : null,
                    config: deps.getAnalysisConfig ? deps.getAnalysisConfig() : null,
                    port: run.channel.port2,
                }, [run.channel.port2]);
                var workerSession = await workerReady;
                if (!checkAlive(run)) return;

                if (run.ctx.state !== 'running') {
                    var resumed = audio.resumeQuietly(run.ctx) || Promise.resolve();
                    await Promise.race([
                        resumed,
                        new Promise(function (resolve) { later(run, timing.resumeWaitMs, resolve); }),
                    ]);
                    if (!checkAlive(run)) return;
                    if (run.ctx.state !== 'running') {
                        // Autoplay policy: needs a tap. Not an error.
                        fail(run, 'resume-required');
                        return;
                    }
                }

                if (track) {
                    track.onended = function () { interrupted(run); };
                    track.onmute = function () { interrupted(run); };
                }
                lastSession = Object.assign({}, workerSession, {
                    requestedConstraints: audio.microphoneConstraints().audio,
                    microphone: micSettings,
                    chunkSize: audio.CHUNK_SIZE,
                });
                if (deps.onSession) deps.onSession(lastSession);
                emit('measuring');
                startWatchdog(run);
                requestWakeLock(run);
            } catch (error) {
                if (!isCurrent(run)) return; // superseded or stopped: nothing to report
                if (error && error.tunerCode === 'cancelled') return;
                // Logged for maintenance; the screen shows only the classified guidance.
                if (globalObj.console) globalObj.console.warn('[チューナー] 測定を開始できませんでした', error);
                fail(run, errors.classifyStartError(error, snapshot));
            }
        }

        // Display range switch while running: the worker answers with a new
        // 'display-axis'; frames for the old axis are dropped by the graph.
        function setDisplayRange(range) {
            var run = current;
            if (!run || run.stopped || !run.worker) return false;
            try {
                run.worker.postMessage({ type: 'display-range', generation: run.generation, range: range });
                return true;
            } catch (_) {
                return false;
            }
        }

        // Analysis profile / input threshold change while running. The worker
        // answers with 'configured' and tags frames with the revision.
        function configure(config) {
            var run = current;
            if (!run || run.stopped || !run.worker) return false;
            try {
                run.worker.postMessage({ type: 'configure', generation: run.generation, config: config });
                return true;
            } catch (_) {
                return false;
            }
        }

        // Frequencies that our own output plays (simultaneous mode warning).
        function setPlaybackState(playback) {
            var run = current;
            if (!run || run.stopped || !run.worker) return false;
            try {
                run.worker.postMessage({
                    type: 'playback-state',
                    generation: run.generation,
                    active: Boolean(playback && playback.active),
                    frequencies: playback && Array.isArray(playback.frequencies) ? playback.frequencies.slice(0, 8) : [],
                });
                return true;
            } catch (_) {
                return false;
            }
        }

        function stop() {
            var wasActive = current !== null || state !== 'hidden';
            teardown(current);
            current = null;
            if (wasActive) emit('hidden');
        }

        // Ends the current run but shows a state (used for background/page hide).
        function suspend(nextState) {
            teardown(current);
            current = null;
            emit(nextState || 'hidden');
        }

        return {
            start: start,
            stop: stop,
            suspend: suspend,
            setDisplayRange: setDisplayRange,
            configure: configure,
            setPlaybackState: setPlaybackState,
            getContextTime: function () { return current && current.ctx ? current.ctx.currentTime : null; },
            getState: function () { return state; },
            getStateCode: function () { return stateCode; },
            getSession: function () { return lastSession ? Object.assign({}, lastSession) : null; },
            getGeneration: function () { return current ? current.generation : null; },
        };
    }

    var api = { TIMING: TIMING, PROTOCOL: TUNER_PROTOCOL, createTunerController: createTunerController };

    lib.releases = lib.releases || {};
    lib.controller = api;
    lib.releases.controller = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
