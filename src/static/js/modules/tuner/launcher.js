// Tuner launcher: the only tuner code loaded with the page (index.html).
//
// Why it exists: iOS Safari only lets an AudioContext start inside a user
// gesture. Creating it after an awaited dynamic script load would lose the
// gesture, so the tap handler calls prime() synchronously, which creates and
// resumes the AudioContext before anything is awaited, and enter() then hands
// that context plus its generation number to the lazily loaded tuner body.
//
// It also owns the generation counter: every enter/leave bumps it, so work
// that finishes after the user left (late microphone grant, slow load) is
// recognised as stale and released. leave() is synchronous, idempotent and
// never waits for pending start-up work.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-b0635dde6c4d'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)
    // Shared output manager (also used by the metronome; release id "a-…").
    var TUNER_AUDIO_RELEASE_ID = 'a-bab6e0cd35e7'; // tuner-audio-release-id (generated by scripts/generate_tuner_release.mjs)
    var AUDIO_URL = '/static/js/modules/audio/output_manager.js';
    var TUNER_BASE_URL = '/static/js/modules/tuner/';
    var TUNER_CSS_URL = '/static/css/tuner.css';
    // Ordered: later files depend on earlier ones. Names double as release keys.
    var MAIN_SCRIPTS = ['music', 'temperament', 'target_model', 'display_filter', 'settings', 'errors', 'audio', 'scheduler', 'playback', 'graph', 'view', 'controller', 'onset', 'note_events', 'analysis_stats', 'measurement_store', 'session_coordinator', 'view_tabs', 'workspace', 'index'];
    var SYSTEM_ADMIN_PERMISSION = 'システム管理者';

    function closeContext(ctx) {
        if (!ctx) return;
        try {
            ctx.onstatechange = null;
            if (ctx.state !== 'closed') {
                var result = ctx.close();
                if (result && typeof result.catch === 'function') result.catch(function () {});
            }
        } catch (_) { /* best effort */ }
    }

    function resumeQuietly(ctx) {
        if (!ctx || typeof ctx.resume !== 'function') return;
        try {
            var result = ctx.resume();
            if (result && typeof result.catch === 'function') result.catch(function () {});
        } catch (_) { /* resume may throw outside a gesture; start-up handles it */ }
    }

    // env: { release, isAllowed(), AudioContext, getBody(), loadAssets(release, names?), setTimeout, clearTimeout,
    //        hostVisible(host), isDocumentVisible(), renderFallback(host, kind, onRetry) }
    function createTunerLauncher(env) {
        var release = env.release || TUNER_RELEASE_ID;
        var generation = 0;
        var primed = null;
        var activeHost = null;
        var activeGeneration = null;
        var wantActive = false;
        var entering = false;
        var resumeOnVisible = false;
        var loadPromise = null;
        // The context of a start that is still loading the body. Kept here (not
        // only in enter()'s local scope) so leave() can close it immediately,
        // even if the body download never finishes.
        var starting = null;
        // Pending "restart measurement after playback" (see resumeMeasurementFromGesture).
        var resumeTimer = null;

        function bodyIsBusy(body) {
            if (!body || typeof body.getState !== 'function') return false;
            var state = body.getState();
            // 'playing': the reference tone sounds and measurement is paused on purpose.
            return state === 'starting' || state === 'measuring' || state === 'playing';
        }

        function alreadyActive(host) {
            return wantActive && activeGeneration === generation &&
                (!host || activeHost === host) && (entering || bodyIsBusy(env.getBody()));
        }

        // Synchronous: must be called directly inside the tap handler.
        function prime() {
            if (!env.isAllowed()) return null;
            if (alreadyActive(null)) return generation; // repeated tap while starting/measuring
            if (primed) {
                resumeQuietly(primed.ctx);
                return primed.generation;
            }
            generation += 1;
            var ctx = null;
            if (typeof env.AudioContext === 'function') {
                try {
                    ctx = new env.AudioContext({ latencyHint: 'interactive' });
                } catch (_) {
                    ctx = null; // the body reports "unsupported" with guidance
                }
            }
            resumeQuietly(ctx);
            primed = { ctx: ctx, generation: generation };
            return generation;
        }

        // Takes over an AudioContext that the laboratory created and resumed
        // inside the tap before this launcher had loaded (see
        // improvement_suggestions.js). Same role as prime(), minus creation.
        function adoptPrimed(ctx) {
            if (!ctx) return prime();
            if (!env.isAllowed()) {
                closeContext(ctx);
                return null;
            }
            if (alreadyActive(null)) {
                closeContext(ctx);
                return generation;
            }
            if (primed && primed.ctx !== ctx) closeContext(primed.ctx);
            generation += 1;
            resumeQuietly(ctx);
            primed = { ctx: ctx, generation: generation };
            return generation;
        }

        function releaseStarting(runGeneration) {
            if (starting && (runGeneration === undefined || starting.generation === runGeneration)) {
                closeContext(starting.ctx);
                starting = null;
            }
        }

        function screenIsShowing(host) {
            return env.isAllowed() && env.isDocumentVisible() && env.hostVisible(host);
        }

        function loadBody() {
            var body = env.getBody();
            if (body) return Promise.resolve(body);
            if (!loadPromise) {
                var started;
                try {
                    started = Promise.resolve(env.loadAssets(release));
                } catch (error) {
                    started = Promise.reject(error);
                }
                loadPromise = started
                    .then(function () {
                        var loaded = env.getBody();
                        if (!loaded) throw new Error('tuner body did not register');
                        return loaded;
                    })
                    .catch(function (error) {
                        loadPromise = null; // allow a clean retry
                        throw error;
                    });
            }
            return loadPromise;
        }

        // Preload only fetches code: no AudioContext, no microphone.
        function preload() {
            return loadBody().then(function () { return true; }, function () { return false; });
        }

        function guard(runGeneration) {
            return runGeneration === generation && wantActive && env.isAllowed() &&
                env.isDocumentVisible() && env.hostVisible(activeHost);
        }

        function leave(reason) {
            generation += 1;
            wantActive = false;
            entering = false;
            resumeOnVisible = false;
            activeGeneration = null;
            if (primed) {
                closeContext(primed.ctx);
                primed = null;
            }
            releaseStarting();
            cancelResumeTimer();
            var body = env.getBody();
            if (body) body.stop(typeof reason === 'string' ? reason : 'leave');
        }

        // Tab scripts (analysis, practice, history) are loaded on the first
        // visit of their tab; a failed load can be retried.
        var groupPromises = {};
        function ensureGroup(names) {
            var list = Array.isArray(names) ? names.slice() : [];
            var key = list.join(',');
            if (!list.length) return Promise.resolve(true);
            if (!groupPromises[key]) {
                var started;
                try {
                    started = Promise.resolve(env.loadAssets(release, list));
                } catch (error) {
                    started = Promise.reject(error);
                }
                groupPromises[key] = started.then(function () { return true; }, function (error) {
                    delete groupPromises[key];
                    throw error;
                });
            }
            return groupPromises[key];
        }

        function cancelResumeTimer() {
            if (resumeTimer !== null && env.clearTimeout) env.clearTimeout(resumeTimer);
            resumeTimer = null;
        }

        // Called synchronously from the playback "停止" tap: the measurement
        // AudioContext is primed inside that tap (iOS), then the microphone
        // restarts after delayMs so the fading tone/reverb is not measured.
        // A leave() in between closes the primed context and cancels the timer;
        // a stale timer from an older generation never enters.
        // Called when playback starts again before the delayed restart ran:
        // drop the timer and close the context primed by the stop tap.
        function cancelMeasurementResume() {
            cancelResumeTimer();
            if (primed) {
                closeContext(primed.ctx);
                primed = null;
            }
        }

        function resumeMeasurementFromGesture(delayMs) {
            if (!activeHost || !wantActive) return;
            var host = activeHost;
            cancelResumeTimer();
            var primedGeneration = prime();
            if (primedGeneration === null) return;
            var enterNow = function () {
                resumeTimer = null;
                if (!primed || primed.generation !== primedGeneration || primedGeneration !== generation) return;
                void enter(host);
            };
            if (delayMs > 0 && env.setTimeout) resumeTimer = env.setTimeout(enterNow, delayMs);
            else enterNow();
        }

        async function enter(host) {
            if (!host) return;
            // Checked before any AudioContext or microphone work: the tab may
            // be "shown" while a parent panel is hidden, or permission is gone.
            if (!screenIsShowing(host)) {
                leave();
                return;
            }
            var ctx = null;
            var runGeneration;
            if (primed) {
                runGeneration = primed.generation;
                ctx = primed.ctx;
                primed = null;
            } else {
                if (alreadyActive(host)) return;
                generation += 1;
                runGeneration = generation;
            }
            if (runGeneration !== generation) {
                closeContext(ctx);
                return;
            }
            wantActive = true;
            activeHost = host;
            activeGeneration = runGeneration;
            entering = true;
            starting = { ctx: ctx, generation: runGeneration };
            var body;
            try {
                if (!env.getBody()) env.renderFallback(host, 'loading', null);
                body = await loadBody();
            } catch (_) {
                if (runGeneration === generation) {
                    entering = false;
                    env.renderFallback(host, 'load-failed', restartFromGesture);
                }
                releaseStarting(runGeneration);
                return;
            }
            if (runGeneration !== generation || !wantActive) {
                releaseStarting(runGeneration); // leave() normally closed it already
                return;
            }
            entering = false;
            var check = body.verifyRelease(release);
            if (!check.ok) {
                releaseStarting(runGeneration);
                body.showError(host, 'version-mismatch');
                return;
            }
            if (!screenIsShowing(host)) {
                leave(); // hidden (e.g. parent panel) while loading: never reach getUserMedia
                return;
            }
            // From here the body owns the context and closes it on stop.
            starting = null;
            await body.start({
                host: host,
                generation: runGeneration,
                audioContext: ctx,
                guard: guard,
                requestLeave: leave,
                onUserRestart: restartFromGesture,
                onMeasurementResume: resumeMeasurementFromGesture,
                cancelMeasurementResume: cancelMeasurementResume,
                isScreenActive: function () { return wantActive && screenIsShowing(host); },
            });
        }

        // Retry/resume buttons: prime inside the click, then enter.
        function restartFromGesture() {
            if (!activeHost) return;
            var host = activeHost;
            cancelResumeTimer(); // a pending post-playback restart is superseded by this tap
            var body = env.getBody();
            if (body) body.stop();
            wantActive = false;
            activeGeneration = null;
            if (prime() === null) return;
            void enter(host);
        }

        // Background: release everything but remember to try again on return.
        function suspendForBackground() {
            if (!wantActive) return;
            var host = activeHost;
            leave('background');
            activeHost = host;
            resumeOnVisible = true;
        }

        // Automatic resume is attempted once per return; if the browser needs
        // a tap, the body ends in "resume-required" and shows the button.
        function resumeAfterVisible() {
            if (!resumeOnVisible) return;
            resumeOnVisible = false;
            if (activeHost && env.hostVisible(activeHost) && env.isAllowed()) void enter(activeHost);
        }

        return {
            release: release,
            prime: prime,
            adoptPrimed: adoptPrimed,
            resumeMeasurementFromGesture: resumeMeasurementFromGesture,
            cancelMeasurementResume: cancelMeasurementResume,
            enter: enter,
            leave: leave,
            ensureGroup: ensureGroup,
            preload: preload,
            restartFromGesture: restartFromGesture,
            suspendForBackground: suspendForBackground,
            resumeAfterVisible: resumeAfterVisible,
            isActive: function () { return wantActive; },
            getGeneration: function () { return generation; },
        };
    }

    // ----- Browser wiring -------------------------------------------------

    function browserIsAllowed() {
        var context = globalObj.portalRuntimeContext;
        var appState = context && context.appState;
        return Boolean(appState) && appState.portalAuthVerified === true &&
            appState.currentUserPermission === SYSTEM_ADMIN_PERMISSION;
    }

    function browserHostVisible(host) {
        if (!host || !host.isConnected) return false;
        if (host.closest('[hidden]')) return false;
        return host.getClientRects().length > 0;
    }

    function tunerLib() {
        return globalObj.PortalTunerLib || {};
    }

    // Ordered classic-script loading (async=false keeps execution order while
    // downloading in parallel). Files already registered for this release are
    // skipped so a retry only re-requests what failed.
    // The shared output manager is loaded once per page with its own id; a
    // copy of another release (mixed cache) stops the start (MT-19).
    function loadSharedAudio() {
        var doc = globalObj.document;
        var lib = globalObj.PortalAudioLib;
        var have = lib && lib.releases ? lib.releases.output_manager : null;
        if (have === TUNER_AUDIO_RELEASE_ID) return Promise.resolve();
        if (have) return Promise.reject(new Error('tuner shared audio release mismatch: ' + have));
        return new Promise(function (resolve, reject) {
            var script = doc.createElement('script');
            script.src = AUDIO_URL + '?rev=' + encodeURIComponent(TUNER_AUDIO_RELEASE_ID);
            script.async = false;
            script.setAttribute('data-tuner-script', 'output_manager');
            script.addEventListener('load', function () { resolve(); }, { once: true });
            script.addEventListener('error', function () { script.remove(); reject(new Error('tuner shared audio failed to load')); }, { once: true });
            doc.head.appendChild(script);
        }).then(function () {
            var after = globalObj.PortalAudioLib && globalObj.PortalAudioLib.releases;
            if (!after || after.output_manager !== TUNER_AUDIO_RELEASE_ID) throw new Error('tuner shared audio release mismatch');
        });
    }

    function browserLoadAssets(release, names) {
        if (!Array.isArray(names) || !names.length) {
            return loadSharedAudio().then(function () { return loadTunerAssets(release, names); });
        }
        return loadTunerAssets(release, names);
    }

    function loadTunerAssets(release, names) {
        var doc = globalObj.document;
        var query = '?rev=' + encodeURIComponent(release);
        if (!doc.querySelector('link[data-tuner-style]')) {
            var link = doc.createElement('link');
            link.rel = 'stylesheet';
            link.href = TUNER_CSS_URL + query;
            link.setAttribute('data-tuner-style', 'true');
            link.addEventListener('error', function () { link.remove(); }, { once: true });
            doc.head.appendChild(link);
        }
        var wanted = Array.isArray(names) && names.length ? names : MAIN_SCRIPTS;
        var releases = tunerLib().releases || {};
        var pending = wanted.filter(function (name) { return releases[name] !== release; });
        return Promise.all(pending.map(function (name) {
            return new Promise(function (resolve, reject) {
                var script = doc.createElement('script');
                script.src = TUNER_BASE_URL + name + '.js' + query;
                script.async = false;
                script.setAttribute('data-tuner-script', name);
                script.addEventListener('load', function () { resolve(); }, { once: true });
                script.addEventListener('error', function () {
                    script.remove();
                    reject(new Error('tuner script failed to load: ' + name));
                }, { once: true });
                doc.head.appendChild(script);
            });
        })).then(function () {
            var after = tunerLib().releases || {};
            var missing = wanted.filter(function (name) { return after[name] !== release; });
            if (missing.length) throw new Error('tuner scripts did not register: ' + missing.join(', '));
        });
    }

    // Minimal markup used before the body (and its view) is available.
    function browserRenderFallback(host, kind, onRetry) {
        if (!host) return;
        var doc = globalObj.document;
        var box = doc.createElement('div');
        box.className = 'tuner-fallback';
        box.setAttribute('role', 'status');
        var title = doc.createElement('p');
        title.className = 'tuner-status-title';
        if (kind === 'load-failed') {
            title.textContent = 'チューナーを読み込めませんでした';
            var detail = doc.createElement('p');
            detail.textContent = '通信状態を確認してから、もう一度お試しください。';
            var button = doc.createElement('button');
            button.type = 'button';
            button.className = 'btn btn-primary tuner-action';
            button.textContent = 'もう一度試す';
            button.addEventListener('click', function () { if (onRetry) onRetry(); });
            box.appendChild(title);
            box.appendChild(detail);
            box.appendChild(button);
        } else {
            title.textContent = 'マイクを準備しています。許可を求められたら『許可』を選んでください';
            box.appendChild(title);
        }
        host.replaceChildren(box);
    }

    var api = {
        TUNER_RELEASE_ID: TUNER_RELEASE_ID,
        TUNER_AUDIO_RELEASE_ID: TUNER_AUDIO_RELEASE_ID,
        MAIN_SCRIPTS: MAIN_SCRIPTS,
        createTunerLauncher: createTunerLauncher,
    };

    if (typeof module !== 'undefined' && module.exports) module.exports = api;

    if (typeof globalObj.document !== 'undefined' && globalObj.document && !globalObj.PortalTunerLauncher) {
        var launcher = createTunerLauncher({
            release: TUNER_RELEASE_ID,
            isAllowed: browserIsAllowed,
            AudioContext: globalObj.AudioContext || globalObj.webkitAudioContext,
            getBody: function () { return globalObj.PortalTunerBody || null; },
            loadAssets: browserLoadAssets,
            hostVisible: browserHostVisible,
            isDocumentVisible: function () { return globalObj.document.visibilityState === 'visible'; },
            renderFallback: browserRenderFallback,
            setTimeout: function (fn, ms) { return globalObj.setTimeout(fn, ms); },
            clearTimeout: function (id) { globalObj.clearTimeout(id); },
        });
        globalObj.PortalTunerLauncher = launcher;
        globalObj.document.addEventListener('visibilitychange', function () {
            if (globalObj.document.visibilityState === 'hidden') launcher.suspendForBackground();
            else launcher.resumeAfterVisible();
        });
        // pagehide covers navigation away and iOS app switching; a page
        // restored from the back/forward cache starts again only if the tuner
        // screen is what is shown.
        globalObj.addEventListener('pagehide', function () { launcher.suspendForBackground(); });
        globalObj.addEventListener('pageshow', function (event) {
            if (event.persisted) launcher.resumeAfterVisible();
        });
    }
})(typeof window !== 'undefined' ? window : globalThis);
