// Tuner: microphone constraints and the audio node graph.
//
// Graph: mic -> AudioWorkletNode(capture) -> GainNode(gain 0) -> destination.
// Safari may not pull nodes that are not connected to the destination, and
// support for numberOfOutputs: 0 differs between browsers, so the capture
// node keeps one (silent) output routed through a gain that is already 0
// before it is connected. Nothing from the microphone can reach the speakers.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-e945264406d5'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var PROCESSOR_NAME = 'portal-tuner-capture';
    var CHUNK_SIZE = 2048;
    var POOL_SIZE = 8;

    // Browser voice processing would treat sustained tones as noise and change
    // levels, so ask for it to be off. These are requests, not guarantees.
    function microphoneConstraints() {
        return {
            audio: {
                echoCancellation: false,
                noiseSuppression: false,
                autoGainControl: false,
                channelCount: { ideal: 1 },
            },
            video: false,
        };
    }

    // Report only what the browser confirms. Anything the browser does not
    // report stays "unconfirmed" and must not be treated as disabled.
    function confirmedMicrophoneSettings(track) {
        var settings = {};
        try {
            settings = track && typeof track.getSettings === 'function' ? track.getSettings() || {} : {};
        } catch (_) {
            settings = {};
        }
        function state(value) {
            if (value === false) return 'disabled';
            if (value === true) return 'enabled';
            return 'unconfirmed';
        }
        return {
            echoCancellation: state(settings.echoCancellation),
            noiseSuppression: state(settings.noiseSuppression),
            autoGainControl: state(settings.autoGainControl),
            sampleRate: typeof settings.sampleRate === 'number' ? settings.sampleRate : null,
            channelCount: typeof settings.channelCount === 'number' ? settings.channelCount : null,
        };
    }

    function createCaptureGraph(options) {
        var ctx = options.audioContext;
        var NodeCtor = options.AudioWorkletNode;
        var gain = ctx.createGain();
        gain.gain.value = 0; // silenced before anything is connected
        var source = ctx.createMediaStreamSource(options.stream);
        var node = new NodeCtor(ctx, PROCESSOR_NAME, {
            numberOfInputs: 1,
            numberOfOutputs: 1,
            outputChannelCount: [1],
            channelCount: 1,
            channelCountMode: 'explicit',
            channelInterpretation: 'speakers',
            processorOptions: {
                release: options.release,
                protocol: options.protocol,
                generation: options.generation,
                chunkSize: CHUNK_SIZE,
                poolSize: POOL_SIZE,
            },
        });
        source.connect(node);
        node.connect(gain);
        gain.connect(ctx.destination);
        var disconnected = false;
        return {
            source: source,
            node: node,
            gain: gain,
            disconnect: function () {
                if (disconnected) return;
                disconnected = true;
                [source, node, gain].forEach(function (item) {
                    try { item.disconnect(); } catch (_) { /* already disconnected */ }
                });
                try { node.port.postMessage({ type: 'stop' }); } catch (_) { /* port closed */ }
                try { node.port.onmessage = null; node.port.close(); } catch (_) { /* port closed */ }
            },
        };
    }

    function stopStream(stream) {
        if (!stream || typeof stream.getTracks !== 'function') return;
        stream.getTracks().forEach(function (track) {
            track.onended = null;
            track.onmute = null;
            track.onunmute = null;
            try { track.stop(); } catch (_) { /* already stopped */ }
        });
    }

    function closeContext(ctx) {
        if (!ctx) return;
        ctx.onstatechange = null;
        if (ctx.state === 'closed') return;
        try {
            var result = ctx.close();
            if (result && typeof result.catch === 'function') result.catch(function () {});
        } catch (_) { /* close is best effort */ }
    }

    function resumeQuietly(ctx) {
        if (!ctx || typeof ctx.resume !== 'function') return null;
        try {
            var result = ctx.resume();
            if (result && typeof result.catch === 'function') result.catch(function () {});
            return result;
        } catch (_) {
            return null;
        }
    }

    var api = {
        PROCESSOR_NAME: PROCESSOR_NAME,
        CHUNK_SIZE: CHUNK_SIZE,
        POOL_SIZE: POOL_SIZE,
        microphoneConstraints: microphoneConstraints,
        confirmedMicrophoneSettings: confirmedMicrophoneSettings,
        createCaptureGraph: createCaptureGraph,
        stopStream: stopStream,
        closeContext: closeContext,
        resumeQuietly: resumeQuietly,
    };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.audio = api;
    lib.releases.audio = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
