// Tuner body: wires settings, judgment, playback, controller, display filter,
// view and graph. Loaded on demand by launcher.js (classic scripts, ordered).
// Exposes a small API (window.PortalTunerBody) so the laboratory screen never
// touches the tuner's DOM or audio objects directly.
//
// Resource ownership:
// - controller: microphone, capture AudioContext, worklet, worker, its wake lock.
// - playback engine: its own AudioContext, oscillator, gain and timers.
// - this body: which of the two is active, the playback watchdog/wake lock,
//   rendering and the in-memory settings (judgment, display range, playback).
// Playback and measurement never run together: starting playback stops the
// measurement (microphone released), stopping playback asks the launcher to
// restart measurement with a context primed inside the stop tap.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-e8d471ab55a0'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)
    var BASE_URL = '/static/js/modules/tuner/';
    // Every main-thread file the launcher loads; each registers its release id.
    var MAIN_MODULES = ['music', 'temperament', 'display_filter', 'settings', 'errors', 'audio', 'playback', 'graph', 'view', 'controller', 'index'];
    var RENDER_INTERVAL_MS = 1000 / 30;
    // Wait after the playback fade-out before the microphone restarts, so the
    // tail of the tone and the room's reverberation are not measured. The
    // fade itself is 30 ms; 250 ms covers a typical small-room decay to well
    // below the speaking level. Frames with large level changes are also
    // rejected by the pitch detector. To be confirmed on a real iPhone.
    var POST_PLAYBACK_DELAY_MS = 250;
    var PLAYBACK_WATCHDOG_MS = 500;

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.releases.index = TUNER_RELEASE_ID;

    function formatHzText(value) {
        return value.toFixed(1);
    }

    // deps: { lib, createController(callbacks), createView(host, handlers),
    //         createPlaybackEngine(env), storage, now(), requestAnimationFrame,
    //         cancelAnimationFrame, setTimeout, clearTimeout, setInterval,
    //         clearInterval, wakeLock, isDocumentHidden(), reload() }
    function createTunerBody(deps) {
        var L = deps.lib;
        var music = L.music;
        var temperament = L.temperament;
        var playbackLib = L.playback;
        var graphLib = L.graph;

        var settingsStore = L.settings.createSettingsStore(deps.storage);
        var filter = L.displayFilter.createDisplayFilter();
        var announcer = L.displayFilter.createAnnouncer();
        var view = null;
        var viewHost = null;
        var startOptions = null;
        var snapshot = null;
        var latestPitch = null;
        var renderHandle = null;
        var lastRenderAt = 0;

        // In-memory settings for this page (not persisted), except A4 above.
        var judgment = { mode: temperament.DEFAULT_MODE, rootMidi: temperament.DEFAULT_ROOT_MIDI };
        var rangeId = graphLib.DEFAULT_DISPLAY_RANGE;
        var axisCounter = 1;
        var playbackSettings = {
            source: 'note',
            midi: playbackLib.DEFAULT_MIDI,
            hz: null, // exact value (just-intonation values are not rounded)
            hzText: '',
            hzError: null,
            origin: 'input', // 'input' | 'root' | 'target'
            originLabel: '',
            volume: playbackLib.DEFAULT_VOLUME_PERCENT,
        };
        var playbackMessage = null;
        var playbackWatchdog = null;
        var playbackWakeLock = null;
        // Advances on every playback start and end, so a wake-lock request that
        // resolves after its playback ended (or after a newer one started) is
        // recognised as stale and released at once.
        var playbackSession = 0;

        var engine = deps.createPlaybackEngine({
            onInterrupted: function () {
                // A call / Siri stopped the tone: measurement needs a tap again.
                endPlaybackSideEffects();
                if (view) view.setStatus({ state: 'resume-required' });
                refreshPlayback();
            },
        });

        function referenceA4() {
            return settingsStore.get();
        }

        function currentJust() {
            return temperament.justTarget(judgment.mode, judgment.rootMidi, referenceA4());
        }

        function currentRangeRequest() {
            var range = graphLib.resolveRange(rangeId);
            return { axisId: axisCounter, min: range.min, max: range.max };
        }

        var controller = deps.createController({
            guard: function (generation) {
                return Boolean(startOptions) && startOptions.guard(generation);
            },
            requestLeave: function (reason) {
                if (startOptions) startOptions.requestLeave(reason);
            },
            getDisplayRange: currentRangeRequest,
            onState: function (info) {
                if (view) view.setStatus(info);
                if (info.state === 'measuring') {
                    startRender();
                } else {
                    stopRender();
                    resetReadings();
                }
            },
            onSession: function (session) {
                if (view) view.graph.setSession(session);
            },
            onDisplayAxis: function (axis) {
                if (view) view.graph.setAxis(axis);
            },
            onPitch: function (frame) {
                latestPitch = frame;
                snapshot = filter.push(frame, deps.now(), referenceA4());
            },
            onSpectrum: function (frame) {
                if (view) view.graph.setSpectrum(frame);
            },
            onGap: function () {
                // Dropped audio: restart smoothing instead of bridging the gap.
                filter.reset();
                snapshot = { state: 'none' };
            },
        });

        // ----- playback settings ----------------------------------------

        function resolvedPlayback() {
            return playbackLib.resolveFrequency({
                source: playbackSettings.source,
                midi: playbackSettings.midi,
                hz: playbackSettings.hz,
                error: playbackSettings.hzError,
            }, referenceA4());
        }

        function playbackSummary(resolved) {
            if (!resolved.ok) return '再生する音：' + (playbackSettings.source === 'note' ? '音名で指定' : '周波数で指定') + '（未設定）';
            if (playbackSettings.source === 'note') {
                return '再生する音：' + resolved.note.label + ' = ' + resolved.frequency.toFixed(1) + ' Hz（音名で指定・A4基準 ' + referenceA4() + ' Hz）';
            }
            var detail = playbackSettings.origin === 'input' ? '周波数で指定' : playbackSettings.originLabel;
            // The exact value is shown with more digits so the unrounded pure value is visible.
            return '再生する音：' + resolved.frequency.toFixed(3) + ' Hz（' + detail + '）';
        }

        function refreshPlayback(hzTextOverride) {
            if (!view) return;
            var resolved = resolvedPlayback();
            view.setPlayback({
                source: playbackSettings.source,
                midi: playbackSettings.midi,
                hzText: hzTextOverride === undefined ? playbackSettings.hzText : hzTextOverride,
                noteOptions: playbackLib.noteOptions(referenceA4()),
                summary: playbackSummary(resolved),
                error: playbackMessage || (resolved.ok ? null : resolved.message),
                volume: playbackSettings.volume,
                playing: engine.isPlaying(),
            });
        }

        // While playing, valid changes glide to the new frequency at once.
        function applyPlaybackChange() {
            playbackMessage = null;
            var resolved = resolvedPlayback();
            if (resolved.ok && engine.isPlaying()) engine.setFrequency(resolved.frequency);
        }

        function setPlaybackFromValue(frequency, origin, label) {
            if (!playbackLib.isPlayableFrequency(frequency)) {
                playbackMessage = label + 'は再生範囲（32.0～4,400.0 Hz）外のため設定できません。';
                refreshPlayback();
                return false;
            }
            // Snapshot of the value now: later root/mode changes do not follow it.
            playbackSettings.source = 'hz';
            playbackSettings.hz = frequency;
            playbackSettings.hzText = formatHzText(frequency);
            playbackSettings.hzError = null;
            playbackSettings.origin = origin;
            playbackSettings.originLabel = label;
            applyPlaybackChange();
            refreshPlayback();
            return true;
        }

        // ----- judgment / display ----------------------------------------

        function refreshReference() {
            if (!view) return;
            view.setReference(settingsStore.get(), settingsStore.canDecrease(), settingsStore.canIncrease(), settingsStore.lastSaveFailed());
        }

        function refreshJudgment() {
            if (!view) return;
            view.setJudgment({ mode: judgment.mode, rootMidi: judgment.rootMidi, just: currentJust() });
        }

        function changeJudgment(next) {
            judgment = next;
            // Recalculate from the latest measured Hz at once; the old target's
            // in-tune state is not carried over.
            snapshot = filter.setJudgment(judgment, deps.now(), referenceA4());
            refreshJudgment();
            renderNow();
        }

        function resetReadings() {
            filter.reset();
            announcer.reset();
            snapshot = null;
            latestPitch = null;
            if (view) {
                view.showReading(null);
                view.graph.clear();
            }
        }

        function renderNow() {
            if (!view) return;
            var shown = snapshot && snapshot.state !== 'none' ? snapshot : null;
            view.showReading(shown);
            view.graph.setSilent(!latestPitch || latestPitch.reason === 'silent');
            view.graph.setMarkers({
                fundamental: shown ? shown.frequency : 0,
                target: shown ? shown.targetFrequency : 0,
                equalTarget: shown && shown.just ? shown.equalTargetFrequency : 0,
            });
            view.graph.draw(deps.now());
            var spoken = announcer.update(shown && shown.state === 'active' ? shown.note.label + ' ' + shown.note.solfege : null, deps.now());
            if (spoken) view.announce(spoken);
        }

        // Drawing runs only while measuring and visible, at most 30 times a second.
        function frame(timestamp) {
            renderHandle = null;
            if (controller.getState() !== 'measuring' || deps.isDocumentHidden()) return;
            if (timestamp - lastRenderAt >= RENDER_INTERVAL_MS - 1) {
                lastRenderAt = timestamp;
                renderNow();
            }
            renderHandle = deps.requestAnimationFrame(frame);
        }

        function startRender() {
            if (renderHandle === null && typeof deps.requestAnimationFrame === 'function') {
                renderHandle = deps.requestAnimationFrame(frame);
            }
        }

        function stopRender() {
            if (renderHandle !== null) deps.cancelAnimationFrame(renderHandle);
            renderHandle = null;
        }

        // ----- playback session side effects ------------------------------

        function releaseLock(lock) {
            if (!lock) return;
            try {
                var released = lock.release();
                if (released && typeof released.catch === 'function') released.catch(function () {});
            } catch (_) { /* already released */ }
        }

        function requestPlaybackWakeLock(session) {
            var wakeLock = deps.wakeLock;
            if (!wakeLock || typeof wakeLock.request !== 'function' || deps.isDocumentHidden()) return;
            var pending;
            try { pending = wakeLock.request('screen'); } catch (_) { return; }
            if (!pending || typeof pending.then !== 'function') return;
            pending.then(function (lock) {
                if (session !== playbackSession || !engine.isPlaying()) {
                    releaseLock(lock); // its playback is over
                    return;
                }
                if (playbackWakeLock && playbackWakeLock !== lock) releaseLock(playbackWakeLock);
                playbackWakeLock = lock;
            }, function () { /* optional: playback continues */ });
        }

        // Idempotent: watchdog, wake lock.
        function endPlaybackSideEffects() {
            playbackSession += 1; // pending wake-lock answers become stale
            if (playbackWatchdog !== null) deps.clearInterval(playbackWatchdog);
            playbackWatchdog = null;
            var lock = playbackWakeLock;
            playbackWakeLock = null;
            releaseLock(lock);
        }

        // Safety net while playing (no worker messages then): leave if the
        // screen stopped showing without an explicit leave.
        function startPlaybackWatchdog() {
            playbackWatchdog = deps.setInterval(function () {
                if (!engine.isPlaying()) return;
                if (!startOptions || !startOptions.isScreenActive()) {
                    if (startOptions) startOptions.requestLeave('guard');
                    else stop();
                }
            }, PLAYBACK_WATCHDOG_MS);
        }

        // ----- handlers ----------------------------------------------------

        var handlers = {
            onStep: function (delta) {
                var result = settingsStore.step(delta);
                refreshReference();
                if (!result.changed) return;
                // Recalculate note/cent/target lines from the latest shown pitch now.
                snapshot = filter.recompute(deps.now(), referenceA4());
                refreshJudgment();
                // Note-name playback follows A4; Hz playback keeps its value.
                if (playbackSettings.source === 'note') applyPlaybackChange();
                refreshPlayback();
                renderNow();
                if (view) view.announce('基準周波数 A4 = ' + result.value + ' Hz');
            },
            onMode: function (mode) {
                if (!temperament.MODES[mode] || mode === judgment.mode) return;
                changeJudgment({ mode: mode, rootMidi: judgment.rootMidi });
                if (view) view.announce('判定方式：' + temperament.MODES[mode].label);
            },
            onRoot: function (midi) {
                if (!temperament.isValidRoot(midi) || midi === judgment.rootMidi) return;
                changeJudgment({ mode: judgment.mode, rootMidi: midi });
            },
            onRange: function (id) {
                if (!graphLib.DISPLAY_RANGES[id] || id === rangeId) return;
                rangeId = id;
                axisCounter += 1;
                if (view) {
                    view.setRange(id);
                    view.graph.setRange(id, axisCounter);
                    view.graph.draw(deps.now());
                    view.announce('グラフの表示範囲：' + graphLib.DISPLAY_RANGES[id].label);
                }
                controller.setDisplayRange(currentRangeRequest());
            },
            onPlaybackSource: function (source) {
                if ((source !== 'note' && source !== 'hz') || source === playbackSettings.source) return;
                playbackSettings.source = source;
                if (source === 'hz' && playbackSettings.hz === null && !playbackSettings.hzError) {
                    // Start the Hz field from the note currently selected.
                    var fromNote = music.noteFrequency(playbackSettings.midi, referenceA4());
                    var parsed = playbackLib.parseHzInput(formatHzText(fromNote));
                    if (parsed.ok) {
                        playbackSettings.hz = parsed.value;
                        playbackSettings.hzText = formatHzText(parsed.value);
                    }
                }
                applyPlaybackChange();
                refreshPlayback();
                if (view) view.announce(source === 'note' ? '音名で指定します' : '周波数で指定します');
            },
            onPlaybackNote: function (midi) {
                if (!Number.isInteger(midi)) return;
                playbackSettings.midi = midi;
                applyPlaybackChange();
                refreshPlayback();
            },
            onPlaybackHzInput: function (text) {
                var parsed = playbackLib.parseHzInput(text);
                playbackSettings.hzText = String(text);
                playbackSettings.origin = 'input';
                playbackSettings.originLabel = '';
                if (parsed.ok) {
                    playbackSettings.hz = parsed.value;
                    playbackSettings.hzError = null;
                    applyPlaybackChange();
                } else {
                    // Invalid input never reaches the oscillator; a playing tone keeps its last valid value.
                    playbackSettings.hzError = { reason: parsed.reason, message: parsed.message };
                }
                refreshPlayback(null);
            },
            onSetPlaybackFromRoot: function () {
                var just = currentJust();
                if (!just) return;
                if (setPlaybackFromValue(just.rootFrequency, 'root', '根音 ' + just.root.label)) {
                    if (view) view.announce('根音 ' + just.root.label + ' を再生欄に設定しました');
                }
            },
            onSetPlaybackFromTarget: function () {
                var just = currentJust();
                if (!just) return;
                // The pure value itself, not rounded to equal temperament or 0.1 Hz.
                var label = just.intervalLabel + ' ' + just.target.label + '（根音 ' + just.root.label + '）';
                if (setPlaybackFromValue(just.targetFrequency, 'target', label)) {
                    if (view) view.announce(just.intervalLabel + ' ' + just.target.label + ' を再生欄に設定しました');
                }
            },
            onVolume: function (percent) {
                playbackSettings.volume = Math.max(0, Math.min(100, Math.round(Number(percent) || 0)));
                if (engine.isPlaying()) engine.setGain(playbackLib.volumeToGain(playbackSettings.volume));
                refreshPlayback();
            },
            // Synchronous: the playback AudioContext is created inside this tap.
            onPlay: function () {
                if (!startOptions || !startOptions.isScreenActive()) return;
                var resolved = resolvedPlayback();
                if (!resolved.ok) {
                    playbackMessage = resolved.message;
                    refreshPlayback();
                    if (view) view.announce(resolved.message);
                    return;
                }
                // A restart scheduled by an earlier "停止" must not start the
                // microphone while this tone plays: cancel it and release its context.
                if (typeof startOptions.cancelMeasurementResume === 'function') startOptions.cancelMeasurementResume();
                var result = engine.start(resolved.frequency, playbackLib.volumeToGain(playbackSettings.volume));
                if (!result.started) {
                    refreshPlayback();
                    return;
                }
                // Measurement pauses: microphone and analysis are released so the
                // tone is never measured; old readings and the graph are cleared.
                controller.stop();
                stopRender();
                resetReadings();
                if (view) {
                    view.setStatus({ state: 'playing' });
                    view.showReading(null); // now shows "基準音を再生中" instead of old values
                }
                playbackSession += 1;
                startPlaybackWatchdog();
                requestPlaybackWakeLock(playbackSession);
                playbackMessage = null;
                refreshPlayback();
                if (view) view.announce('基準音を再生しています');
            },
            // Synchronous: the launcher primes the measurement context in this tap.
            onStop: function () {
                if (!engine.isPlaying()) return;
                engine.stop();
                endPlaybackSideEffects();
                refreshPlayback();
                if (view) {
                    view.setStatus({ state: 'starting' });
                    view.announce('基準音を停止しました。測定を再開します');
                }
                if (startOptions && typeof startOptions.onMeasurementResume === 'function') {
                    startOptions.onMeasurementResume(POST_PLAYBACK_DELAY_MS);
                }
            },
            onRestart: function () {
                if (startOptions && typeof startOptions.onUserRestart === 'function') startOptions.onUserRestart();
            },
            onReload: function () {
                deps.reload();
            },
        };

        function ensureView(host) {
            if (!view || viewHost !== host || !host.contains(view.root)) {
                view = deps.createView(host, handlers);
                viewHost = host;
                view.setRootOptions(temperament.rootOptions());
                view.graph.setRange(rangeId, axisCounter);
            }
            view.bind(handlers);
            view.setRange(rangeId);
            refreshJudgment();
            refreshPlayback();
            return view;
        }

        function verifyRelease(expected) {
            var mismatched = MAIN_MODULES.filter(function (name) { return L.releases[name] !== expected; });
            return { ok: mismatched.length === 0 && TUNER_RELEASE_ID === expected, mismatched: mismatched, release: TUNER_RELEASE_ID };
        }

        // options: { host, generation, audioContext, guard(gen), requestLeave(reason),
        //            onUserRestart(), onMeasurementResume(delayMs),
        //            cancelMeasurementResume(), isScreenActive() }
        function start(options) {
            startOptions = options;
            settingsStore.load();
            ensureView(options.host);
            refreshReference();
            if (engine.isPlaying()) {
                // Defence in depth: measurement never runs while the tone plays.
                // The context handed over for measurement is not needed.
                if (options.audioContext && typeof options.audioContext.close === 'function') {
                    try {
                        var closing = options.audioContext.close();
                        if (closing && typeof closing.catch === 'function') closing.catch(function () {});
                    } catch (_) { /* already closed */ }
                }
                if (view) view.setStatus({ state: 'playing' });
                return Promise.resolve();
            }
            filter.setJudgment(judgment, deps.now(), referenceA4());
            resetReadings();
            return controller.start({ generation: options.generation, audioContext: options.audioContext || null });
        }

        // Full stop (leave, background, logout, permission loss): tone and
        // measurement both end. Idempotent.
        function stop() {
            engine.dispose();
            endPlaybackSideEffects();
            controller.stop();
            stopRender();
            refreshPlayback();
        }

        function showError(host, code) {
            ensureView(host);
            refreshReference();
            view.setStatus({ state: 'unavailable', code: code });
        }

        return {
            release: TUNER_RELEASE_ID,
            protocol: L.controller.PROTOCOL,
            start: start,
            stop: stop,
            showError: showError,
            verifyRelease: verifyRelease,
            // 'playing' while the reference tone sounds (measurement paused).
            getState: function () { return engine.isPlaying() ? 'playing' : controller.getState(); },
            getStateCode: function () { return controller.getStateCode(); },
            getSession: function () { return controller.getSession(); },
            handlers: handlers,
        };
    }

    // ----- Browser wiring -------------------------------------------------

    function assetUrl(name) {
        return BASE_URL + name + '?rev=' + encodeURIComponent(TUNER_RELEASE_ID);
    }

    function safeLocalStorage() {
        try {
            return globalObj.localStorage || null;
        } catch (_) {
            return null; // access itself can throw when site data is blocked
        }
    }

    function now() {
        return globalObj.performance && typeof globalObj.performance.now === 'function'
            ? globalObj.performance.now()
            : Date.now();
    }

    function timers() {
        return {
            setTimeout: function (fn, ms) { return globalObj.setTimeout(fn, ms); },
            clearTimeout: function (id) { globalObj.clearTimeout(id); },
            setInterval: function (fn, ms) { return globalObj.setInterval(fn, ms); },
            clearInterval: function (id) { globalObj.clearInterval(id); },
        };
    }

    function browserBody() {
        var nav = globalObj.navigator || {};
        var AudioContextCtor = globalObj.AudioContext || globalObj.webkitAudioContext;
        var t = timers();
        return createTunerBody(Object.assign({
            lib: lib,
            storage: safeLocalStorage(),
            now: now,
            wakeLock: nav.wakeLock,
            requestAnimationFrame: function (fn) { return globalObj.requestAnimationFrame(fn); },
            cancelAnimationFrame: function (id) { globalObj.cancelAnimationFrame(id); },
            isDocumentHidden: function () { return Boolean(globalObj.document && globalObj.document.hidden); },
            reload: function () { globalObj.location.reload(); },
            createView: function (host, handlers) { return lib.view.createTunerView(host, handlers); },
            createPlaybackEngine: function (callbacks) {
                return lib.playback.createPlaybackEngine(Object.assign({
                    // Separate from the capture context on purpose (see playback.js).
                    createContext: function () { return new AudioContextCtor({ latencyHint: 'interactive' }); },
                }, t, callbacks));
            },
            createController: function (callbacks) {
                return lib.controller.createTunerController(Object.assign({
                    env: Object.assign({
                        isSecureContext: globalObj.isSecureContext !== false,
                        mediaDevices: nav.mediaDevices,
                        AudioContext: AudioContextCtor,
                        AudioWorkletNode: globalObj.AudioWorkletNode,
                        Worker: globalObj.Worker,
                        MessageChannel: globalObj.MessageChannel,
                        wakeLock: nav.wakeLock,
                        now: now,
                    }, t),
                    release: TUNER_RELEASE_ID,
                    urls: { worklet: assetUrl('capture.worklet.js'), worker: assetUrl('analysis.worker.js') },
                }, callbacks));
            },
        }, t));
    }

    var api = {
        MAIN_MODULES: MAIN_MODULES,
        POST_PLAYBACK_DELAY_MS: POST_PLAYBACK_DELAY_MS,
        createTunerBody: createTunerBody,
    };
    if (typeof module !== 'undefined' && module.exports) module.exports = api;

    if (typeof globalObj.document !== 'undefined' && globalObj.document && lib.view) {
        globalObj.PortalTunerBody = browserBody();
    }
})(typeof window !== 'undefined' ? window : globalThis);
