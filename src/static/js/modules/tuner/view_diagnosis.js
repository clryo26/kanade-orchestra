// Tuner: diagnosis tab (Phase 4). Works on saved note-event summaries of the
// signed-in owner (this device; account summaries when enabled). Every value
// shows its counts (events and sessions — never frames as performances), the
// direction by sign and text (colour is only an aid), and "データ不足" /
// "参考値" when the rules do not allow a diagnosis. Conditions are never
// mixed: one condition key at a time.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-b0635dde6c4d'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    var MINUS = '−';

    function h(tag, attrs, children) {
        var el = globalObj.document.createElement(tag);
        Object.keys(attrs || {}).forEach(function (k) {
            if (k === 'text') el.textContent = attrs[k];
            else if (k === 'className') el.className = attrs[k];
            else if (k.indexOf('data-') === 0 || k.indexOf('aria-') === 0 || k === 'for' || k === 'role') el.setAttribute(k, attrs[k]);
            else el[k] = attrs[k];
        });
        (children || []).forEach(function (c) { if (c) el.appendChild(typeof c === 'string' ? globalObj.document.createTextNode(c) : c); });
        return el;
    }

    function signed(v) {
        if (typeof v !== 'number' || !Number.isFinite(v)) return '—';
        var r = Math.round(v * 10) / 10;
        return (r > 0 ? '+' : (r < 0 ? MINUS : '')) + Math.abs(r).toFixed(1);
    }

    var STATUS_TEXT = { ok: '', reference: '参考値（ばらつきが大きい）', insufficient: 'データ不足' };
    var TENDENCY_TEXT = { high: '高めの傾向', low: '低めの傾向', none: 'はっきりした傾向なし', undetermined: '判定保留' };

    // Saved session + events -> intonation_profile event records (pure).
    function toProfileEvents(details) {
        var out = [];
        (details || []).forEach(function (d) {
            if (!d || !d.session) return;
            var s = d.session;
            (d.events || []).forEach(function (ev) {
                var st = ev.stats || {};
                var q = ev.quality || {};
                if (!ev.target || !Number.isInteger(ev.target.midi)) return;
                out.push({
                    sessionId: s.sessionId,
                    eventId: ev.eventId,
                    midi: ev.target.midi,
                    // An event judged after a change of A4 / target within the
                    // session carries its own key and is never mixed with the rest.
                    conditionsKey: ev.target.conditionKey || s.conditionKey,
                    startedAt: s.startedAt,
                    durationSeconds: st.durationSeconds,
                    observationCount: st.observationCount,
                    coverage: st.coverage,
                    meanCents: st.meanCents,
                    medianCents: st.medianCents,
                    sdCents: st.sdCents,
                    simultaneousPlayback: Boolean(q.simultaneousPlayback),
                    boundaryType: q.boundaryType,
                    countsAsAttempt: q.countsAsAttempt,
                    direction: q.direction || null,
                    dynamicMarking: s.conditions ? s.conditions.dynamicMarking : null,
                    instrumentId: s.instrumentId || null,
                    engineVersion: s.versions ? s.versions.engineVersion : null,
                    statsVersion: s.versions ? s.versions.statsVersion : null,
                });
            });
        });
        return out;
    }

    function describeConditions(conditions) {
        var c = conditions || {};
        var parts = [];
        if (Number.isInteger(c.a4Tenths)) parts.push('A4=' + (c.a4Tenths / 10).toFixed(1) + ' Hz');
        if (c.temperament) parts.push((lib.targetModel && lib.targetModel.TEMPERAMENTS[c.temperament] ? lib.targetModel.TEMPERAMENTS[c.temperament].label : c.temperament));
        if (c.exerciseKind) parts.push(lib.trainer && lib.trainer.KINDS[c.exerciseKind] ? lib.trainer.KINDS[c.exerciseKind] : (c.exerciseKind === 'free' ? '自由な測定' : c.exerciseKind));
        if (c.instrumentId) parts.push('楽器あり');
        parts.push('解析 ' + (c.engineVersion || '不明') + '／統計 v' + (c.statsVersion || '?'));
        return parts.join('・');
    }

    function createDiagnosisView(panel, ctx) {
        var L = ctx.lib;
        var details = [];
        var events = [];
        var current = null;

        var root = h('div', { className: 'tuner-diagnosis', 'data-tuner-diagnosis': 'true' });
        var status = h('p', { className: 'tuner-section-label', 'aria-live': 'polite', 'data-tuner-diagnosis-status': 'true' });
        var condition = h('select', { className: 'form-select tuner-select', id: 'tunerDiagCondition', 'data-tuner-diagnosis-condition': 'true' });
        var period = h('select', { className: 'form-select tuner-select', id: 'tunerDiagPeriod', 'data-tuner-diagnosis-period': 'true' });
        [['', 'まとめて'], ['day', '日ごと'], ['week', '週ごと'], ['month', '月ごと']].forEach(function (p) { period.appendChild(h('option', { value: p[0], text: p[1] })); });
        var reload = h('button', { type: 'button', className: 'btn btn-outline-primary tuner-wide-button', text: '保存した記録から診断する', 'data-tuner-diagnosis-run': 'true' });
        var account = h('button', { type: 'button', className: 'btn btn-outline-secondary tuner-wide-button', text: 'アカウントの記録で集計する', 'data-tuner-diagnosis-account': 'true', hidden: true });
        var map = h('div', { className: 'tuner-map', role: 'list', 'data-tuner-map': 'true' });
        var noteDetail = h('div', { className: 'tuner-event-detail', 'aria-live': 'polite', 'data-tuner-map-detail': 'true' });
        var categories = h('div', { className: 'tuner-categories', 'data-tuner-categories': 'true' });
        var periods = h('div', { className: 'tuner-periods', 'data-tuner-periods': 'true' });
        var improvement = h('div', { className: 'tuner-improvement', 'data-tuner-improvement': 'true' });
        var weak = h('div', { className: 'tuner-weak', 'data-tuner-weak': 'true' });
        var suggestions = h('div', { className: 'tuner-suggestions', 'data-tuner-suggestions': 'true' });

        root.appendChild(h('p', { className: 'tuner-detail-line', text: '保存した練習の要約から、音ごとの傾向を集計します。数値は測定結果の傾向で、楽器の不具合や奏法の原因を判定するものではありません。' }));
        root.appendChild(reload);
        root.appendChild(account);
        root.appendChild(h('div', { className: 'tuner-field' }, [h('label', { for: 'tunerDiagCondition', text: '比較する条件（条件の違う記録は混ぜません）' }), condition]));
        root.appendChild(h('div', { className: 'tuner-field' }, [h('label', { for: 'tunerDiagPeriod', text: '期間の区切り' }), period]));
        root.appendChild(status);
        root.appendChild(h('h3', { className: 'tuner-section-title', text: '音程傾向マップ' }));
        root.appendChild(map);
        root.appendChild(noteDetail);
        root.appendChild(h('h3', { className: 'tuner-section-title', text: '音域・方向・強弱・楽器ごと' }));
        root.appendChild(categories);
        root.appendChild(h('h3', { className: 'tuner-section-title', text: '期間ごと' }));
        root.appendChild(periods);
        root.appendChild(h('h3', { className: 'tuner-section-title', text: '変化（直近30日と、それより前）' }));
        root.appendChild(improvement);
        root.appendChild(h('h3', { className: 'tuner-section-title', text: '注意したい音' }));
        root.appendChild(weak);
        root.appendChild(h('h3', { className: 'tuner-section-title', text: '練習の提案' }));
        root.appendChild(suggestions);
        panel.appendChild(root);

        function label(midi) { return L.music.describeNote(Number(midi)).label; }

        function loadDetails() {
            status.textContent = '読み込み中…';
            return ctx.getOwner().then(function (owner) {
                if (!owner) { status.textContent = '本人の確認ができないため、保存した記録を開けません。'; return null; }
                return ctx.local().then(function (store) {
                    return store.listSessions(owner, {}).then(function (rows) {
                        return Promise.all(rows.map(function (r) { return store.getSession(owner, r.sessionId); }));
                    });
                });
            }).then(function (list) {
                if (!list) return;
                details = list.filter(Boolean).map(function (d) { return { session: d.session, events: d.events }; });
                events = toProfileEvents(details);
                fillConditions();
                status.textContent = details.length ? '保存したセッション ' + details.length + ' 件（音符 ' + events.length + ' 個）' : '保存した記録がありません。「履歴・楽器・設定」で保存方法を選ぶと、練習の要約が保存されます。';
                account.hidden = !ctx.identity().accountStorageAvailable;
                if (events.length) run();
            });
        }

        function fillConditions() {
            var keys = {};
            details.forEach(function (d) {
                var seen = {};
                var add = function (k, conditions) {
                    if (!k || seen[k]) return;
                    seen[k] = true;
                    keys[k] = keys[k] || { count: 0, conditions: conditions };
                    keys[k].count += 1;
                };
                add(d.session.conditionKey, d.session.conditions);
                (d.events || []).forEach(function (ev) {
                    var t = ev.target || {};
                    if (t.conditionKey && t.conditionKey !== d.session.conditionKey) {
                        add(t.conditionKey, Object.assign({}, d.session.conditions, { a4Tenths: t.a4Tenths || (d.session.conditions || {}).a4Tenths, temperament: t.definition ? t.definition.temperament : t.temperament }));
                    }
                });
            });
            condition.replaceChildren();
            Object.keys(keys).sort(function (a, b) { return keys[b].count - keys[a].count; }).forEach(function (k) {
                condition.appendChild(h('option', { value: k, text: describeConditions(keys[k].conditions) + '（' + keys[k].count + ' 件）' }));
            });
        }

        function run() {
            var key = condition.value;
            if (!key) return;
            ctx.stats.request('diagnose', { events: events, conditionKey: key, period: period.value || null, options: {} }).then(function (res) {
                if (!res || res.superseded || res.error) return;
                current = res;
                renderMap(res.notes);
                renderCategories(res.categories);
                renderPeriods(res.periods);
                renderWeak(res.weak);
                renderSuggestions(res.suggestions);
                renderImprovement(key);
            });
        }

        function cell(midi, s) {
            var cls = 'tuner-map-cell tuner-map-' + (s.status !== 'ok' ? 'insufficient' : s.tendency);
            var magnitude = typeof s.meanCents === 'number' ? Math.min(3, Math.floor(Math.abs(s.meanCents) / 5)) : 0;
            var el = h('button', { type: 'button', className: cls + ' tuner-map-m' + magnitude, role: 'listitem', 'data-tuner-map-note': String(midi) }, [
                h('span', { className: 'tuner-map-note', text: label(midi) }),
                h('span', { className: 'tuner-map-value', text: signed(s.meanCents) + ' cent' }),
                h('span', { className: 'tuner-map-n', text: s.nEvents + '音・' + s.nSessions + '回' }),
                h('span', { className: 'tuner-map-status', text: STATUS_TEXT[s.status] || TENDENCY_TEXT[s.tendency] }),
            ]);
            el.setAttribute('aria-label', label(midi) + ' 平均 ' + signed(s.meanCents) + ' cent、' + s.nEvents + ' 音、' + s.nSessions + ' セッション、' + (STATUS_TEXT[s.status] || TENDENCY_TEXT[s.tendency]));
            return el;
        }

        function renderMap(notes) {
            map.replaceChildren();
            var keys = Object.keys(notes || {}).map(Number).sort(function (a, b) { return a - b; });
            if (!keys.length) { map.appendChild(h('p', { className: 'tuner-section-label', text: 'この条件の記録はありません。' })); return; }
            keys.forEach(function (midi) { map.appendChild(cell(midi, notes[midi])); });
            map.appendChild(h('p', { className: 'tuner-graph-legend', text: '値は同じ音の各セッションの代表値を平均したもの（I-001）。＋は高め、−は低め。色は補助で、数値と文字で判断してください。' }));
        }

        map.addEventListener('click', function (e) {
            var b = e.target.closest('[data-tuner-map-note]');
            if (!b || !current) return;
            var midi = Number(b.getAttribute('data-tuner-map-note'));
            var s = current.notes[midi];
            var mine = events.filter(function (ev) { return ev.conditionsKey === condition.value && ev.midi === midi; });
            var medians = mine.map(function (ev) { return ev.medianCents; }).filter(function (v) { return typeof v === 'number'; }).sort(function (a, b2) { return a - b2; });
            var q = function (p) { return medians.length ? medians[Math.min(medians.length - 1, Math.floor(p * (medians.length - 1)))] : null; };
            var bySession = {};
            mine.forEach(function (ev) { (bySession[ev.sessionId] = bySession[ev.sessionId] || { at: ev.startedAt, values: [] }).values.push(ev.medianCents); });
            var trend = Object.keys(bySession).map(function (k) { return bySession[k]; }).sort(function (a, b2) { return a.at - b2.at; });
            var dl = h('dl', { className: 'tuner-dl' });
            [
                ['平均（セッション平均の平均）', signed(s.meanCents) + ' cent'],
                ['中央値', signed(s.medianCents) + ' cent'],
                ['95%区間（セッション単位で推定）', s.interval95 ? signed(s.interval95[0]) + '～' + signed(s.interval95[1]) + ' cent' : '—'],
                ['ばらつき（音符の中／音符の間／セッションの間）', [s.sdWithinEventCents, s.sdBetweenEventsCents, s.sdBetweenSessionsCents].map(function (v) { return typeof v === 'number' ? v.toFixed(1) : '—'; }).join(' ／ ') + ' cent'],
                ['分布（最小・25%・中央・75%・最大）', [q(0), q(0.25), q(0.5), q(0.75), q(1)].map(signed).join(' ／ ')],
                ['件数', s.nEvents + ' 音・' + s.nSessions + ' セッション（フレーム数ではありません）'],
                ['除外', Object.keys(s.excludedByReason || {}).map(function (k) { return k + ' ' + s.excludedByReason[k]; }).join('、') || 'なし'],
                ['判定', STATUS_TEXT[s.status] || TENDENCY_TEXT[s.tendency]],
            ].forEach(function (pair) { dl.appendChild(h('dt', { text: pair[0] })); dl.appendChild(h('dd', { text: pair[1] })); });
            var list = h('ol', { className: 'tuner-trend' });
            trend.forEach(function (t) {
                var m = t.values.reduce(function (a, v) { return a + v; }, 0) / t.values.length;
                list.appendChild(h('li', { text: new Date(t.at).toLocaleDateString('ja-JP') + '：' + signed(m) + ' cent（' + t.values.length + ' 音）' }));
            });
            noteDetail.replaceChildren(h('h4', { className: 'tuner-section-title', text: label(midi) + ' の詳細' }), dl, h('p', { className: 'tuner-detail-line', text: 'セッションごとの推移' }), list);
        });

        function table(rows, headings) {
            var t = h('table', { className: 'tuner-table' });
            var head = h('tr');
            headings.forEach(function (x) { head.appendChild(h('th', { scope: 'col', text: x })); });
            t.appendChild(head);
            rows.forEach(function (r) {
                var tr = h('tr');
                r.forEach(function (x) { tr.appendChild(h('td', { text: x })); });
                t.appendChild(tr);
            });
            return h('div', { className: 'tuner-table-wrap' }, [t]);
        }

        function summaryRow(name, s) {
            return [name, signed(s.meanCents) + ' cent', typeof s.sdBetweenEventsCents === 'number' ? s.sdBetweenEventsCents.toFixed(1) + ' cent' : '—', s.nEvents + '音・' + s.nSessions + '回', STATUS_TEXT[s.status] || TENDENCY_TEXT[s.tendency]];
        }

        function renderCategories(cats) {
            categories.replaceChildren();
            var names = {
                register: { low: '低音域', mid: '中音域', high: '高音域' },
                direction: { up: '上行の直後', down: '下行の直後', leap: '跳躍の直後', repeat: '同じ音の反復' },
                dynamics: { p: 'p', mp: 'mp', mf: 'mf', f: 'f', crescendo: 'クレッシェンド', decrescendo: 'デクレッシェンド' },
                instrument: {},
            };
            var titles = { register: '音域', direction: '音程の動き', dynamics: '強弱の指定', instrument: '楽器' };
            Object.keys(titles).forEach(function (k) {
                var group = cats && cats[k] ? cats[k] : {};
                var rows = Object.keys(group).map(function (key) { return summaryRow(names[k][key] || key, group[key]); });
                categories.appendChild(h('p', { className: 'tuner-detail-line', text: titles[k] }));
                categories.appendChild(rows.length ? table(rows, ['分類', '平均', '音符の間のばらつき', '件数', '判定']) : h('p', { className: 'tuner-section-label', text: '記録がありません。' }));
            });
        }

        function renderPeriods(p) {
            periods.replaceChildren();
            if (!p) { periods.appendChild(h('p', { className: 'tuner-section-label', text: '「期間の区切り」を選ぶと表示します。' })); return; }
            var rows = Object.keys(p).sort().map(function (k) { return summaryRow(k, p[k]); });
            periods.appendChild(rows.length ? table(rows, ['期間', '平均', '音符の間のばらつき', '件数', '判定']) : h('p', { className: 'tuner-section-label', text: '記録がありません。' }));
        }

        function renderImprovement(key) {
            improvement.replaceChildren();
            var boundary = ctx.utcNow() - 30 * 86400000;
            var mine = events.filter(function (ev) { return ev.conditionsKey === key; });
            var recent = mine.filter(function (ev) { return ev.startedAt >= boundary; });
            var past = mine.filter(function (ev) { return ev.startedAt < boundary; });
            var res = L.intonationProfile.improvement(recent, past);
            var text = {
                closer: '直近のほうが目標に近づいています',
                further: '直近のほうが目標から離れています',
                'no-clear-change': 'はっきりした変化はありません',
                insufficient: '比べるためのデータが不足しています',
                'not-comparable': '解析・統計の版が違う記録が混ざるため比べません',
            }[res.status];
            improvement.appendChild(h('p', { className: 'tuner-detail-line', text: text + (typeof res.changeCents === 'number' ? '（差 ' + signed(res.changeCents) + ' cent、95%区間 ' + signed(res.interval95[0]) + '～' + signed(res.interval95[1]) + '）' : '') }));
            improvement.appendChild(h('p', { className: 'tuner-detail-line', text: '使った回数が増えただけでは「上達」とは判定しません。' }));
        }

        function renderWeak(w) {
            weak.replaceChildren();
            if (!w || (!w.byDeviation.length && !w.bySpread.length)) { weak.appendChild(h('p', { className: 'tuner-section-label', text: '判定できるだけのデータがある音がまだありません。' })); return; }
            weak.appendChild(h('p', { className: 'tuner-detail-line', text: '目標からの差が大きい順：' + w.byDeviation.map(function (r) { return label(r.key) + '（' + signed(r.medianCents) + '）'; }).join('、') }));
            weak.appendChild(h('p', { className: 'tuner-detail-line', text: 'セッション間のばらつきが大きい順：' + w.bySpread.map(function (r) { return label(r.key) + '（' + r.sdBetweenSessionsCents.toFixed(1) + '）'; }).join('、') }));
        }

        function renderSuggestions(list) {
            suggestions.replaceChildren();
            if (!list || !list.length) { suggestions.appendChild(h('p', { className: 'tuner-section-label', text: '今のデータからは提案はありません。' })); return; }
            var ul = h('ul', { className: 'tuner-suggestion-list' });
            list.forEach(function (s) {
                var reason = s.reason ? Object.keys(s.reason).map(function (k) { var v = s.reason[k]; return k + '=' + (Array.isArray(v) ? v.map(signed).join('～') : (typeof v === 'number' ? (Number.isInteger(v) ? v : v.toFixed(1)) : v)); }).join('、') : '';
                ul.appendChild(h('li', { text: s.text + (reason ? '（根拠：' + reason + '）' : '') }));
            });
            suggestions.appendChild(ul);
        }

        account.addEventListener('click', function () {
            if (!ctx.remote || !condition.value) return;
            status.textContent = 'アカウントの記録を集計しています…';
            ctx.remote.diagnosis(condition.value).then(function (res) {
                if (!res.ok) { status.textContent = 'アカウントの記録を集計できませんでした（' + res.code + '）。'; return; }
                renderMap(res.data.data.notes);
                status.textContent = res.data.data.comparable ? 'アカウントに保存した要約で集計しました。' : '解析・統計の版が違う記録が含まれます（比べる際は注意してください）。';
            });
        });
        reload.addEventListener('click', loadDetails);
        condition.addEventListener('change', run);
        period.addEventListener('change', run);
        var off = ctx.on(function (type) {
            if (type === 'cleared') { details = []; events = []; map.replaceChildren(); noteDetail.replaceChildren(); categories.replaceChildren(); status.textContent = ''; }
            if (type === 'save-status') { /* a new saved session: reload on the next visit */ }
        });

        // With history saving off nothing is opened or requested automatically
        // (no storage access, no network); the button still opens old records.
        return {
            show: function () {
                if (!details.length && ctx.historyPrefs().frequency !== 'none') loadDetails();
                else if (!details.length) status.textContent = '履歴の保存はオフです。保存した記録がある場合は「保存した記録から診断する」を押してください。';
            },
            render: function () {},
            destroy: function () { off(); },
        };
    }

    var api = { toProfileEvents: toProfileEvents, describeConditions: describeConditions, createDiagnosisView: createDiagnosisView };

    lib.releases = lib.releases || {};
    lib.viewDiagnosis = api;
    lib.releases.view_diagnosis = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
