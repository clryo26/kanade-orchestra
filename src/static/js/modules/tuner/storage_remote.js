// Tuner: client for the personal history API (/api/tuner, Phase 4).
//
// - Only summaries are sent (sessions, note-event statistics, results,
//   instruments, presets). Audio, PCM, the pitch series and spectrograms are
//   never part of a request (sanitizeSession enforces the field whitelist).
// - The owner is resolved by the server from the signed-in member; the
//   client never chooses it. Every request carries the owner context it was
//   started with; after logout / owner change its result is discarded and
//   in-flight requests are aborted.
// - Responses are not stored in the portal's shared GET cache (personal data
//   on a shared device), and errors never raise portal-wide alerts: a failed
//   upload must not stop measurement.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-b0635dde6c4d'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)
    var SCHEMA_VERSION = 1;
    var BASE = '/api/tuner';
    var TIMEOUT_MS = 15000;
    var MAX_PART_EVENTS = 500;
    var MAX_PART_BYTES = 1024 * 1024;

    var SESSION_FIELDS = ['sessionId', 'startedAt', 'endedAt', 'durationMs', 'kind', 'status', 'conditionKey', 'conditions',
        'instrumentSnapshot', 'targetSnapshot', 'versions', 'summary', 'result', 'eventCount'];
    var EVENT_FIELDS = ['eventId', 'ordinal', 'startMs', 'endMs', 'target', 'stats', 'quality'];

    function pick(source, fields) {
        var out = {};
        fields.forEach(function (f) { if (source && source[f] !== undefined) out[f] = source[f]; });
        return out;
    }

    // Removes non-finite numbers (JSON must not carry NaN/Infinity) and any
    // typed array (never sent).
    function clean(value) {
        if (value === null || value === undefined) return null;
        if (typeof value === 'number') return Number.isFinite(value) ? value : null;
        if (ArrayBuffer.isView && ArrayBuffer.isView(value)) return null;
        if (value instanceof ArrayBuffer) return null;
        if (Array.isArray(value)) return value.map(clean);
        if (typeof value === 'object') {
            var out = {};
            Object.keys(value).forEach(function (k) { out[k] = clean(value[k]); });
            return out;
        }
        return value;
    }

    function sanitizeSession(session) { return clean(pick(session, SESSION_FIELDS)); }
    function sanitizeEvent(event) { return clean(pick(event, EVENT_FIELDS)); }

    function hashText(text) {
        // FNV-1a 32-bit (integrity check of parts, not security).
        var h = 0x811c9dc5;
        for (var i = 0; i < text.length; i += 1) { h ^= text.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
        return ('00000000' + h.toString(16)).slice(-8);
    }

    // Splits events into parts of <= 500 events and <= 1 MiB of JSON.
    function partition(events) {
        var parts = [];
        var current = [];
        var size = 2;
        (events || []).forEach(function (ev) {
            var text = JSON.stringify(sanitizeEvent(ev));
            if (current.length && (current.length >= MAX_PART_EVENTS || size + text.length + 1 > MAX_PART_BYTES)) {
                parts.push(current);
                current = [];
                size = 2;
            }
            current.push(sanitizeEvent(ev));
            size += text.length + 1;
        });
        if (current.length) parts.push(current);
        return parts.map(function (list, index) {
            var body = JSON.stringify(list);
            return { index: index, events: list, hash: hashText(body), bytes: body.length };
        });
    }

    function errorCode(status, detail) {
        if (status === 0) return 'network';
        if (status === 401) return 'unauthenticated';
        if (status === 403) return 'account-storage-unavailable';
        if (status === 404) return 'not-found';
        if (status === 409) return detail === 'STORAGE_LIMIT' ? 'storage-limit' : 'conflict';
        if (status === 410) return 'deleted';
        if (status === 413) return 'too-large';
        if (status === 400 || status === 422) return 'invalid';
        if (status >= 500) return 'unavailable';
        return 'failed';
    }

    // env: { request (default: the browser's fetch), deviceId(), setTimeout, clearTimeout }
    function createRemoteClient(env) {
        var ownerEpoch = 0;
        var controllers = [];

        function abortAll() {
            controllers.forEach(function (c) { try { c.abort(); } catch (_) { /* ignore */ } });
            controllers = [];
        }

        // Logout / owner change: abort in-flight requests and make their
        // results stale.
        function invalidate() {
            ownerEpoch += 1;
            abortAll();
        }

        function call(method, path, body, epoch) {
            var startedEpoch = epoch === undefined ? ownerEpoch : epoch;
            var send = typeof env.request === 'function' ? env.request : (typeof globalObj.fetch === 'function' ? globalObj.fetch.bind(globalObj) : null);
            if (!send) return Promise.resolve({ ok: false, status: 0, code: 'network' });
            var controller = typeof AbortController === 'function' ? new AbortController() : null;
            if (controller) controllers.push(controller);
            var timer = env.setTimeout(function () { if (controller) controller.abort(); }, TIMEOUT_MS);
            var headers = { Accept: 'application/json' };
            var device = typeof env.deviceId === 'function' ? env.deviceId() : '';
            if (device) headers['X-Device-Id'] = device;
            if (body !== undefined) headers['Content-Type'] = 'application/json';
            var finish = function () {
                env.clearTimeout(timer);
                controllers = controllers.filter(function (c) { return c !== controller; });
            };
            return Promise.resolve()
                .then(function () {
                    return send(BASE + path, {
                        method: method,
                        headers: headers,
                        body: body === undefined ? undefined : JSON.stringify(clean(body)),
                        signal: controller ? controller.signal : undefined,
                        cache: 'no-store',
                        credentials: 'same-origin',
                    });
                })
                .then(function (response) {
                    return response.text().then(function (text) {
                        finish();
                        var data = null;
                        try { data = text ? JSON.parse(text) : null; } catch (_) { data = null; }
                        if (startedEpoch !== ownerEpoch) return { ok: false, status: response.status, code: 'stale-owner' };
                        if (!response.ok) {
                            var detail = data && data.detail;
                            var code = detail && typeof detail === 'object' ? detail.code : detail;
                            return { ok: false, status: response.status, code: errorCode(response.status, code), detail: code || null };
                        }
                        return { ok: true, status: response.status, data: data };
                    });
                }, function () {
                    finish();
                    return { ok: false, status: 0, code: startedEpoch !== ownerEpoch ? 'stale-owner' : 'network' };
                });
        }

        function envelope(payload, ctx) {
            return Object.assign({ schemaVersion: SCHEMA_VERSION, historyEpoch: ctx && ctx.historyEpoch ? ctx.historyEpoch : 0 }, payload);
        }

        return {
            invalidate: invalidate,
            epoch: function () { return ownerEpoch; },
            identity: function () { return call('GET', '/identity'); },
            getPreferences: function () { return call('GET', '/preferences'); },
            putPreferences: function (ctx, prefs, revision) { return call('PUT', '/preferences', envelope({ revision: revision || 0, preferences: prefs }, ctx)); },
            listInstruments: function () { return call('GET', '/instruments'); },
            createInstrument: function (ctx, profile) { return call('POST', '/instruments', envelope({ instrument: profile }, ctx)); },
            updateInstrument: function (ctx, id, profile, revision) { return call('PATCH', '/instruments/' + encodeURIComponent(id), envelope({ instrument: profile, revision: revision }, ctx)); },
            deleteInstrument: function (ctx, id) { return call('DELETE', '/instruments/' + encodeURIComponent(id)); },
            listPresets: function () { return call('GET', '/presets'); },
            createPreset: function (ctx, preset) { return call('POST', '/presets', envelope({ preset: preset }, ctx)); },
            deletePreset: function (ctx, id) { return call('DELETE', '/presets/' + encodeURIComponent(id)); },
            createSession: function (ctx, session, operationId) {
                return call('POST', '/sessions', envelope({ clientOperationId: operationId, session: sanitizeSession(session) }, ctx));
            },
            putPart: function (ctx, sessionId, part) {
                return call('PUT', '/sessions/' + encodeURIComponent(sessionId) + '/parts/' + part.index, envelope({ hash: part.hash, events: part.events }, ctx));
            },
            finalize: function (ctx, sessionId, parts, eventCount) {
                return call('POST', '/sessions/' + encodeURIComponent(sessionId) + '/finalize', envelope({ partCount: parts.length, eventCount: eventCount, partHashes: parts.map(function (p) { return p.hash; }) }, ctx));
            },
            listSessions: function (query) {
                var q = query || {};
                var params = [];
                ['from', 'to', 'instrument', 'kind', 'condition', 'cursor', 'limit'].forEach(function (k) {
                    if (q[k] !== undefined && q[k] !== null && q[k] !== '') params.push(k + '=' + encodeURIComponent(q[k]));
                });
                return call('GET', '/sessions' + (params.length ? '?' + params.join('&') : ''));
            },
            getSession: function (id, cursor) { return call('GET', '/sessions/' + encodeURIComponent(id) + (cursor ? '?cursor=' + encodeURIComponent(cursor) : '')); },
            diagnosis: function (conditionKey) { return call('GET', '/diagnosis?condition=' + encodeURIComponent(conditionKey)); },
            exportData: function (format, cursor) { return call('GET', '/export?format=' + (format === 'csv' ? 'csv' : 'json') + (cursor ? '&cursor=' + encodeURIComponent(cursor) : '')); },
            deleteSession: function (ctx, id) { return call('DELETE', '/sessions/' + encodeURIComponent(id)); },
            deleteHistory: function (ctx) { return call('DELETE', '/history'); },
            raw: call,
        };
    }

    // Processes queued operations of one owner (oldest first). Stops on
    // authentication problems; drops operations of an older history epoch
    // or of deleted sessions; keeps them on network errors.
    // deps: { local, remote, ctx (owner context fixed at start), isCurrent(ctx) }
    function syncOutbox(deps) {
        var ctx = deps.ctx;
        var report = { sent: 0, dropped: 0, kept: 0, stoppedBy: null };
        if (!ctx || ctx.kind !== 'account') return Promise.resolve(Object.assign(report, { stoppedBy: 'no-account' }));
        return deps.local.outbox(ctx).then(function (ops) {
            var chain = Promise.resolve();
            ops.forEach(function (op) {
                chain = chain.then(function () {
                    if (report.stoppedBy) return null;
                    if (!deps.isCurrent(ctx)) { report.stoppedBy = 'stale-owner'; return null; }
                    if ((op.historyEpoch || 0) !== (ctx.historyEpoch || 0)) {
                        // Queued before a full deletion: never re-sent.
                        report.dropped += 1;
                        return deps.local.removeOperation(ctx, op.operationId);
                    }
                    return runOperation(deps, ctx, op).then(function (result) {
                        if (!deps.isCurrent(ctx)) { report.stoppedBy = 'stale-owner'; return null; }
                        if (result.ok) {
                            report.sent += 1;
                            return deps.local.removeOperation(ctx, op.operationId);
                        }
                        if (result.code === 'unauthenticated' || result.code === 'account-storage-unavailable' || result.code === 'stale-owner') {
                            report.stoppedBy = result.code;
                            return null;
                        }
                        if (result.code === 'conflict' && result.detail === 'HISTORY_EPOCH') report.epochConflict = true;
                        if (result.code === 'deleted' || result.code === 'invalid' || result.code === 'too-large' || result.code === 'not-found' || (result.code === 'conflict' && result.detail === 'HISTORY_EPOCH')) {
                            report.dropped += 1;
                            return deps.local.removeOperation(ctx, op.operationId);
                        }
                        report.kept += 1;
                        return deps.local.updateOperation(ctx, Object.assign({}, op, { attempts: (op.attempts || 0) + 1, lastError: result.code }));
                    });
                });
            });
            return chain.then(function () { return report; });
        });
    }

    function runOperation(deps, ctx, op) {
        var remote = deps.remote;
        if (op.type === 'upload-session') {
            return deps.local.getSession(ctx, op.sessionId).then(function (detail) {
                if (!detail) return { ok: false, code: 'deleted' };
                var parts = partition(detail.events);
                return remote.createSession(ctx, Object.assign({}, detail.session, { eventCount: detail.events.length }), op.operationId).then(function (created) {
                    if (!created.ok) return created;
                    var chain = Promise.resolve({ ok: true });
                    parts.forEach(function (part) {
                        chain = chain.then(function (prev) {
                            if (!prev.ok) return prev;
                            if (!deps.isCurrent(ctx)) return { ok: false, code: 'stale-owner' };
                            return remote.putPart(ctx, op.sessionId, part);
                        });
                    });
                    return chain.then(function (prev) {
                        if (!prev.ok) return prev;
                        return remote.finalize(ctx, op.sessionId, parts, detail.events.length);
                    });
                });
            });
        }
        if (op.type === 'delete-session') return remote.deleteSession(ctx, op.sessionId);
        if (op.type === 'delete-history') return remote.deleteHistory(ctx);
        if (op.type === 'put-instrument') return remote.createInstrument(ctx, op.instrument);
        return Promise.resolve({ ok: false, code: 'invalid' });
    }

    var api = {
        SCHEMA_VERSION: SCHEMA_VERSION,
        BASE: BASE,
        MAX_PART_EVENTS: MAX_PART_EVENTS,
        MAX_PART_BYTES: MAX_PART_BYTES,
        SESSION_FIELDS: SESSION_FIELDS,
        EVENT_FIELDS: EVENT_FIELDS,
        sanitizeSession: sanitizeSession,
        sanitizeEvent: sanitizeEvent,
        partition: partition,
        hashText: hashText,
        errorCode: errorCode,
        createRemoteClient: createRemoteClient,
        syncOutbox: syncOutbox,
    };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.storageRemote = api;
    lib.releases.storage_remote = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
