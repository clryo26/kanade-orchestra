// Tuner: display-only correction of pitch measurements (smoothing,
// hysteresis, hold). Raw analysis values are never modified here; this module
// only derives what the screen shows from them. Analysis, storage and the
// vibrato fit always use the unsmoothed frames (measurement_store.js).
//
// Smoothing runs on log-frequency in cents (1200 * log2(Hz)) so that equal
// pitch differences are treated equally across the range and a change of the
// reference A4 does not look like a jump in the input.
//
// Judgment: the target comes from target_model.resolve(). In equal
// temperament (auto) the nearest note (with hysteresis) is the target; a
// fixed note, a just-intonation role or a pitch-class temperament give their
// own target. The detected note and the deviation from the equal-tempered
// target note are still reported for the auxiliary display.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-e9e90e4b853c'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    var music = lib.music || (typeof require === 'function' ? require('./music.js') : null);
    if (!music) throw new Error('tuner display_filter.js requires music.js to be loaded first');
    var temperament = lib.temperament || (typeof require === 'function' ? require('./temperament.js') : null);
    if (!temperament) throw new Error('tuner display_filter.js requires temperament.js to be loaded first');
    var targetModel = lib.targetModel || (typeof require === 'function' ? require('./target_model.js') : null);
    if (!targetModel) throw new Error('tuner display_filter.js requires target_model.js to be loaded first');

    var DEFAULTS = {
        holdMs: 1000,
        enterInTuneCents: 3,
        exitInTuneCents: 4,
        noteSwitchMarginCents: 3,
        jumpResetCents: 30,
        // A new note (after silence or a jump) is shown only once
        // onsetConfirmFrames consecutive raw values agree within
        // onsetConfirmCents (design: same candidate within 30 cent). Attacks and
        // the first frame after start-up can be far off.
        onsetConfirmCents: 30,
        onsetConfirmFrames: 2,
        // ...but never wait more than this many frames (wide vibrato may
        // never produce agreeing frames). Defaults to onsetConfirmFrames.
        onsetMaxPendingFrames: null,
        smoothingTimeMs: 120,
        meterRangeCents: 50,
    };

    var JUDGMENT_LABELS = {
        flat: '低い',
        'in-tune': '合っています',
        sharp: '高い',
    };

    // Temperaments whose target is chosen per detected note (auto) unless a
    // note is fixed.
    var PER_NOTE = { equal: true, pythagorean: true, custom: true };

    function toLogCents(frequency) {
        return 1200 * Math.log2(frequency);
    }

    function fromLogCents(value) {
        return Math.pow(2, value / 1200);
    }

    function roundCents(value) {
        var rounded = Math.round(value);
        return rounded === 0 ? 0 : rounded; // avoid displaying "-0"
    }

    function roundTenth(value) {
        var rounded = Math.round(value * 10) / 10;
        return rounded === 0 ? 0 : rounded;
    }

    function resolveOptions(options) {
        var opts = Object.assign({}, DEFAULTS, options || {});
        if (!(opts.onsetConfirmFrames >= 1)) opts.onsetConfirmFrames = 1;
        if (opts.onsetMaxPendingFrames === null || opts.onsetMaxPendingFrames === undefined) {
            opts.onsetMaxPendingFrames = opts.onsetConfirmFrames;
        }
        if (!(opts.exitInTuneCents >= opts.enterInTuneCents)) opts.exitInTuneCents = opts.enterInTuneCents + 1;
        return opts;
    }

    // Legacy judgment config { mode, rootMidi } -> target_model config.
    function legacyToTarget(config) {
        var mode = config && temperament.MODES[config.mode] ? config.mode : temperament.DEFAULT_MODE;
        var rootMidi = config && temperament.isValidRoot(config.rootMidi) ? config.rootMidi : temperament.DEFAULT_ROOT_MIDI;
        return { temperament: mode, rootMidi: rootMidi };
    }

    function createDisplayFilter(options) {
        var opts = resolveOptions(options);
        var smoothed = null;
        var lastRaw = null;
        var lastValidAt = -Infinity;
        var currentMidi = null;
        var inTune = false;
        var lastState = 'none';
        var pending = []; // raw log-cent values waiting for confirmation
        var judgmentConfig = { mode: temperament.DEFAULT_MODE, rootMidi: temperament.DEFAULT_ROOT_MIDI };
        var targetConfig = legacyToTarget(judgmentConfig);

        function reset() {
            pending = [];
            smoothed = null;
            lastRaw = null;
            lastValidAt = -Infinity;
            currentMidi = null;
            inTune = false;
            lastState = 'none';
        }

        // Note choice with hysteresis: keep the current note until the pitch
        // passes the semitone midpoint by an extra margin. When the note
        // changes because of the input (not the reference), restart smoothing
        // from the raw value so the needle does not slide over from the old note.
        function selectNote(referenceA4, rawForReset) {
            var position = music.fractionalMidi(fromLogCents(smoothed), referenceA4);
            if (currentMidi === null) {
                currentMidi = Math.round(position);
                inTune = false;
                return;
            }
            var limit = 0.5 + opts.noteSwitchMarginCents / 100;
            if (Math.abs(position - currentMidi) <= limit) return;
            if (rawForReset !== null) {
                smoothed = rawForReset;
                position = music.fractionalMidi(fromLogCents(smoothed), referenceA4);
            }
            var next = Math.round(position);
            if (next !== currentMidi) {
                currentMidi = next;
                inTune = false;
            }
        }

        function resolveTarget(referenceA4, frequency) {
            var cfg = Object.assign({}, targetConfig, { a4Hz: referenceA4, a4Tenths: undefined });
            if (PER_NOTE[cfg.temperament] && !targetModel.isValidMidi(cfg.fixedMidi)) cfg.fixedMidi = currentMidi;
            var target = targetModel.isValidMidi(cfg.fixedMidi) || !PER_NOTE[cfg.temperament]
                ? targetModel.resolve(cfg, frequency)
                : null;
            if (!target) {
                // Outside the standard range (C1..C8): equal temperament of the
                // detected note, so the reading is still shown.
                var hz = music.noteFrequency(currentMidi, referenceA4);
                target = { temperament: 'equal', targetHz: hz, equalHz: hz, midi: currentMidi, spelling: music.describeNote(currentMidi), fixed: false };
            }
            return target;
        }

        function snapshot(referenceA4, state) {
            var frequency = fromLogCents(smoothed);
            var detectedNote = music.describeNote(currentMidi);
            var target = resolveTarget(referenceA4, frequency);
            var just = temperament.justTarget(judgmentConfig.mode, judgmentConfig.rootMidi, referenceA4);
            if (targetConfig.temperament !== judgmentConfig.mode) just = null;
            var targetHz = target.targetHz;
            var equalReference = target.equalHz;
            var cents = music.centsBetween(frequency, targetHz);
            var equalCents = music.centsBetween(frequency, equalReference);
            var magnitude = Math.abs(cents);
            if (inTune) {
                if (magnitude > opts.exitInTuneCents) inTune = false;
            } else if (magnitude <= opts.enterInTuneCents) {
                inTune = true;
            }
            var judgment = inTune ? 'in-tune' : (cents < 0 ? 'flat' : 'sharp');
            var range = opts.meterRangeCents;
            var nonEqualTarget = target.temperament !== 'equal' || target.fixed;
            return {
                state: state,
                mode: just ? judgmentConfig.mode : (target.temperament === 'equal' ? 'equal' : target.temperament),
                frequency: frequency,
                // Detected (nearest) note, shown in every mode.
                note: detectedNote,
                targetNote: just ? just.target : (target.spelling || detectedNote),
                targetFrequency: targetHz,
                equalTargetFrequency: equalReference,
                target: target,
                just: just,
                comparesToEqual: Boolean(just) || (nonEqualTarget && target.temperament !== 'equal'),
                // Deviation from the equal-tempered version of the same target note.
                equalCents: equalCents,
                equalCentsRounded: roundCents(equalCents),
                // Internal value is kept even beyond the meter (hysteresis can
                // push it there); only the needle position is clamped.
                cents: cents,
                centsRounded: roundCents(cents),
                centsTenth: roundTenth(cents),
                meterRangeCents: range,
                needleCents: Math.max(-range, Math.min(range, cents)),
                // Needle position in percent of the meter width.
                needlePercent: 50 + (50 * Math.max(-range, Math.min(range, cents))) / range,
                toleranceCents: opts.enterInTuneCents,
                inTune: inTune,
                judgment: judgment,
                judgmentLabel: JUDGMENT_LABELS[judgment],
            };
        }

        function confirmPending(raw) {
            pending.push(raw);
            var need = opts.onsetConfirmFrames;
            if (pending.length >= need) {
                var recent = pending.slice(pending.length - need);
                var agree = recent.every(function (value) { return Math.abs(value - raw) < opts.onsetConfirmCents; });
                if (agree) return true;
            }
            // Never wait forever (wide vibrato).
            return pending.length > opts.onsetMaxPendingFrames;
        }

        function push(measurement, now, referenceA4) {
            if (measurement && measurement.valid && measurement.frequency > 0) {
                var raw = toLogCents(measurement.frequency);
                var stale = now - lastValidAt > opts.holdMs;
                // The jump test uses the unsmoothed previous value, per spec.
                var jumped = lastRaw !== null && Math.abs(raw - lastRaw) >= opts.jumpResetCents;
                if (pending.length > 0 || smoothed === null || stale || jumped) {
                    var confirmed = confirmPending(raw);
                    if (!confirmed) {
                        lastRaw = raw;
                        // Keep showing the old reading only while it is within the hold time.
                        if (smoothed !== null && !stale) {
                            lastState = 'held';
                            return snapshot(referenceA4, lastState);
                        }
                        if (smoothed !== null) {
                            smoothed = null;
                            currentMidi = null;
                            inTune = false;
                        }
                        lastState = 'none';
                        return { state: 'none' };
                    }
                    pending = [];
                    if (stale || smoothed === null) currentMidi = null;
                    smoothed = raw;
                } else {
                    var dt = Math.max(0, now - lastValidAt);
                    var alpha = opts.smoothingTimeMs > 0 ? 1 - Math.exp(-dt / opts.smoothingTimeMs) : 1;
                    smoothed += alpha * (raw - smoothed);
                }
                lastRaw = raw;
                lastValidAt = now;
                selectNote(referenceA4, raw);
                lastState = 'active';
                return snapshot(referenceA4, lastState);
            }
            pending = [];
            if (smoothed !== null && now - lastValidAt <= opts.holdMs) {
                lastState = 'held';
                return snapshot(referenceA4, lastState);
            }
            reset();
            return { state: 'none' };
        }

        // Immediate recalculation after the reference changes, from the latest
        // displayed frequency, without waiting for the next analysis result and
        // without treating the change as an input jump.
        function recompute(now, referenceA4) {
            if (smoothed === null || now - lastValidAt > opts.holdMs) return { state: 'none' };
            // The target moved (new A4): judge it afresh with the enter threshold
            // instead of keeping the old target's hysteresis state.
            inTune = false;
            selectNote(referenceA4, null);
            return snapshot(referenceA4, lastState === 'none' ? 'active' : lastState);
        }

        // Legacy judgment mode / root change (equal, just thirds).
        function setJudgment(config, now, referenceA4) {
            judgmentConfig = { mode: legacyToTarget(config).temperament, rootMidi: legacyToTarget(config).rootMidi };
            targetConfig = legacyToTarget(config);
            inTune = false;
            currentMidi = null;
            return recompute(now, referenceA4);
        }

        // Any target_model configuration (temperament, role, fixed note...).
        // The old target's in-tune state and note hysteresis are not carried
        // over; the frequency smoothing itself is target-independent.
        function setTarget(config, now, referenceA4) {
            targetConfig = targetModel.normalizeConfig(config);
            if (temperament.MODES[targetConfig.temperament]) {
                judgmentConfig = { mode: targetConfig.temperament, rootMidi: temperament.isValidRoot(targetConfig.rootMidi) ? targetConfig.rootMidi : temperament.DEFAULT_ROOT_MIDI };
            } else {
                judgmentConfig = { mode: targetConfig.temperament, rootMidi: targetConfig.rootMidi };
            }
            inTune = false;
            currentMidi = null;
            return recompute(now, referenceA4);
        }

        // Response speed / tolerance / meter range (display settings only).
        function setOptions(next, now, referenceA4) {
            opts = resolveOptions(Object.assign({}, opts, next || {}, { onsetMaxPendingFrames: next && next.onsetMaxPendingFrames !== undefined ? next.onsetMaxPendingFrames : null }));
            inTune = false;
            pending = [];
            if (now === undefined) return null;
            return recompute(now, referenceA4);
        }

        function getJudgment() {
            return { mode: judgmentConfig.mode, rootMidi: judgmentConfig.rootMidi };
        }

        return {
            push: push,
            recompute: recompute,
            reset: reset,
            setJudgment: setJudgment,
            setTarget: setTarget,
            setOptions: setOptions,
            getJudgment: getJudgment,
            getTargetConfig: function () { return JSON.parse(JSON.stringify(targetConfig)); },
            options: opts,
            getOptions: function () { return Object.assign({}, opts); },
        };
    }

    // Screen-reader announcements: only a note that stayed the same for a
    // while, never per-frame numbers, and not more often than minIntervalMs.
    function createAnnouncer(options) {
        var opts = Object.assign({ stableMs: 800, minIntervalMs: 2000 }, options || {});
        var candidate = null;
        var candidateSince = 0;
        var lastAnnounced = null;
        var lastAnnouncedAt = -Infinity;

        return {
            update: function (label, now) {
                if (!label) {
                    candidate = null;
                    lastAnnounced = null;
                    return null;
                }
                if (label !== candidate) {
                    candidate = label;
                    candidateSince = now;
                    return null;
                }
                if (label === lastAnnounced) return null;
                if (now - candidateSince < opts.stableMs || now - lastAnnouncedAt < opts.minIntervalMs) return null;
                lastAnnounced = label;
                lastAnnouncedAt = now;
                return label;
            },
            reset: function () {
                candidate = null;
                lastAnnounced = null;
                lastAnnouncedAt = -Infinity;
            },
        };
    }

    var api = {
        DEFAULTS: DEFAULTS,
        JUDGMENT_LABELS: JUDGMENT_LABELS,
        toLogCents: toLogCents,
        roundCents: roundCents,
        roundTenth: roundTenth,
        createDisplayFilter: createDisplayFilter,
        createAnnouncer: createAnnouncer,
    };

    lib.releases = lib.releases || {};
    lib.displayFilter = api;
    lib.releases.display_filter = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
