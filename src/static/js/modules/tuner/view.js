// Tuner: screen markup, button handling and screen-reader output.
// Readings and controls are HTML; only the spectrum is drawn on a canvas, so
// note, Hz, cent and judgment stay readable without the graph. The screen
// shows no internal file names or storage locations (future member use).
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-e945264406d5'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};

    var MINUS = '−';

    var TEMPLATE = [
        '<div class="tuner" data-tuner-root>',
        '  <p class="tuner-guide">一度に一つの音を、長めに鳴らしてください</p>',
        '  <div class="tuner-status" data-tuner-status role="status" aria-live="polite" hidden>',
        '    <p class="tuner-status-title" data-tuner-status-title></p>',
        '    <p class="tuner-status-detail" data-tuner-status-detail></p>',
        '    <button type="button" class="btn btn-primary tuner-action" data-tuner-action hidden></button>',
        '  </div>',
        '  <div class="tuner-readout" data-tuner-readout data-state="none">',
        '    <div class="tuner-note"><span class="tuner-note-name" data-tuner-note>' + '—' + '</span><span class="tuner-note-solfege" data-tuner-solfege></span></div>',
        '    <div class="tuner-frequency" data-tuner-frequency>' + '—' + ' Hz</div>',
        '  </div>',
        '  <div class="tuner-meter" data-tuner-meter data-judgment="none">',
        '    <div class="tuner-meter-scale" aria-hidden="true">',
        '      <span class="tuner-meter-zone"></span>',
        '      <span class="tuner-meter-center"></span>',
        '      <span class="tuner-meter-needle" data-tuner-needle></span>',
        '    </div>',
        '    <div class="tuner-meter-labels" aria-hidden="true"><span>' + MINUS + '50 低い</span><span>0</span><span>高い +50</span></div>',
        '    <div class="tuner-meter-result">',
        '      <span class="tuner-cents" data-tuner-cents>' + '—' + ' cent</span>',
        '      <span class="tuner-judgment" data-tuner-judgment>音を待っています</span>',
        '    </div>',
        '  </div>',
        '  <div class="tuner-graph">',
        '    <canvas class="tuner-graph-canvas" data-tuner-canvas role="img" aria-label="周波数ごとの音の強さ（スペクトラム）"></canvas>',
        '    <p class="tuner-graph-legend"><span class="tuner-legend-fundamental">実線：検出した基音</span><span class="tuner-legend-target">破線：正しい音程の周波数</span><span class="tuner-legend-harmonic">▼：倍音（基音の整数倍）</span></p>',
        '  </div>',
        '  <div class="tuner-reference" role="group" aria-label="基準周波数">',
        '    <button type="button" class="tuner-step" data-tuner-step="-1" aria-label="基準周波数を下げる">' + MINUS + '</button>',
        '    <output class="tuner-reference-value" data-tuner-reference>A4 = 442 Hz</output>',
        '    <button type="button" class="tuner-step" data-tuner-step="1" aria-label="基準周波数を上げる">＋</button>',
        '  </div>',
        '  <p class="tuner-reference-note" data-tuner-reference-note hidden>この端末に基準周波数を保存できませんでした。この画面を開いている間は変更後の値で測定します。</p>',
        '  <div class="visually-hidden" aria-live="polite" data-tuner-announcer></div>',
        '</div>',
    ].join('\n');

    var JUDGMENT_TEXT = {
        flat: '◀ 低い',
        'in-tune': '● 合っています',
        sharp: '高い ▶',
    };

    function formatCents(rounded) {
        if (rounded > 0) return '+' + rounded + ' cent';
        if (rounded < 0) return MINUS + Math.abs(rounded) + ' cent';
        return '0 cent';
    }

    function formatFrequency(frequency) {
        return frequency.toFixed(1) + ' Hz';
    }

    function createTunerView(host, handlers) {
        if (!host.querySelector('[data-tuner-root]')) host.innerHTML = TEMPLATE;
        var root = host.querySelector('[data-tuner-root]');
        function q(selector) { return root.querySelector(selector); }
        var el = {
            status: q('[data-tuner-status]'),
            statusTitle: q('[data-tuner-status-title]'),
            statusDetail: q('[data-tuner-status-detail]'),
            action: q('[data-tuner-action]'),
            readout: q('[data-tuner-readout]'),
            note: q('[data-tuner-note]'),
            solfege: q('[data-tuner-solfege]'),
            frequency: q('[data-tuner-frequency]'),
            meter: q('[data-tuner-meter]'),
            needle: q('[data-tuner-needle]'),
            cents: q('[data-tuner-cents]'),
            judgment: q('[data-tuner-judgment]'),
            canvas: q('[data-tuner-canvas]'),
            reference: q('[data-tuner-reference]'),
            referenceNote: q('[data-tuner-reference-note]'),
            decrease: q('[data-tuner-step="-1"]'),
            increase: q('[data-tuner-step="1"]'),
            announcer: q('[data-tuner-announcer]'),
        };
        var actionKind = 'none';

        // Rebinding per start keeps handlers pointing at the current session.
        var current = handlers;
        if (root.dataset.tunerBound !== 'true') {
            root.dataset.tunerBound = 'true';
            el.decrease.addEventListener('click', function () { root._tunerHandlers.onStep(-1); });
            el.increase.addEventListener('click', function () { root._tunerHandlers.onStep(1); });
            // The restart path must create/resume the AudioContext inside this
            // click, before any await, so it goes straight to the handler.
            el.action.addEventListener('click', function () {
                var kind = el.action.dataset.kind;
                if (kind === 'reload') root._tunerHandlers.onReload();
                else root._tunerHandlers.onRestart();
            });
        }
        root._tunerHandlers = current;

        var graph = lib.graph.createSpectrumGraph(el.canvas, { height: 200 });

        function setAction(kind) {
            actionKind = kind;
            var labels = { retry: 'もう一度試す', resume: 'タップして測定を再開', reload: 'ページを再読み込み' };
            if (!labels[kind]) {
                el.action.hidden = true;
                el.action.dataset.kind = '';
                return;
            }
            el.action.hidden = false;
            el.action.dataset.kind = kind;
            el.action.textContent = labels[kind];
        }

        function setStatus(info) {
            var state = info.state;
            root.dataset.state = state;
            if (state === 'measuring' || state === 'hidden') {
                el.status.hidden = true;
                el.statusTitle.textContent = '';
                el.statusDetail.textContent = '';
                setAction('none');
                return;
            }
            el.status.hidden = false;
            if (state === 'starting') {
                el.statusTitle.textContent = 'マイクを準備しています。許可を求められたら『許可』を選んでください';
                el.statusDetail.textContent = '';
                setAction('none');
                return;
            }
            var message = lib.errors.messageFor(state === 'resume-required' ? 'resume-required' : info.code);
            el.statusTitle.textContent = message.title;
            el.statusDetail.textContent = message.detail;
            setAction(message.action);
        }

        function showReading(snapshot) {
            if (!snapshot || snapshot.state === 'none') {
                el.readout.dataset.state = 'none';
                el.note.textContent = '—';
                el.solfege.textContent = '';
                el.frequency.textContent = '— Hz';
                el.cents.textContent = '— cent';
                el.judgment.textContent = '音を待っています';
                el.meter.dataset.judgment = 'none';
                el.needle.style.left = '50%';
                el.needle.hidden = true;
                return;
            }
            el.readout.dataset.state = snapshot.state;
            el.note.textContent = snapshot.note.label;
            el.solfege.textContent = '（' + snapshot.note.solfege + '）';
            el.frequency.textContent = formatFrequency(snapshot.frequency);
            el.cents.textContent = formatCents(snapshot.centsRounded);
            el.judgment.textContent = JUDGMENT_TEXT[snapshot.judgment];
            el.meter.dataset.judgment = snapshot.judgment;
            el.needle.hidden = false;
            el.needle.style.left = (50 + snapshot.needleCents) + '%';
        }

        function setReference(value, canDecrease, canIncrease, saveFailed) {
            el.reference.textContent = 'A4 = ' + value + ' Hz';
            el.decrease.disabled = !canDecrease;
            el.increase.disabled = !canIncrease;
            el.referenceNote.hidden = !saveFailed;
        }

        function announce(text) {
            // Clearing first makes repeated identical text be read again.
            el.announcer.textContent = '';
            el.announcer.textContent = text;
        }

        return {
            root: root,
            graph: graph,
            setStatus: setStatus,
            showReading: showReading,
            setReference: setReference,
            announce: announce,
            actionKind: function () { return actionKind; },
            bind: function (next) { root._tunerHandlers = next; },
        };
    }

    var api = { createTunerView: createTunerView, formatCents: formatCents, formatFrequency: formatFrequency };

    lib.releases = lib.releases || {};
    lib.view = api;
    lib.releases.view = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
