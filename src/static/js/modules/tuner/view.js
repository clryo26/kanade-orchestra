    function meterMarkerPercent(cents, range) {
        if (!(range > 0) || Math.abs(cents) > range) return null;
        return 50 + 50 * cents / range;
    }

    function formatCents(rounded) {
        if (rounded > 0) return '+' + rounded + ' cent';
        if (rounded < 0) return MINUS + Math.abs(rounded) + ' cent';
        return '0 cent';
    }

    function formatFrequency(frequency) {
        return frequency.toFixed(1) + ' Hz';
    }

    function noteText(note) {
        return note.label + '（' + note.solfege + '）';
    }

    function targetLineText(just) {
        return '根音 ' + just.root.label + ' → ' + just.intervalLabel + ' ' + just.target.label +
            '（目標 ' + just.targetFrequency.toFixed(2) + ' Hz）';
    }

