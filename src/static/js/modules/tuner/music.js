// Tuner: 12-tone equal temperament note naming and cent arithmetic.
// Concert pitch only (transposing instruments show the sounding note).
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-5c2ad5661ae9'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    // Spelling is fixed by the specification; German names are intentionally absent.
    var NOTE_NAMES = [
        { letter: 'C', solfege: 'ド' },
        { letter: 'C♯', solfege: 'ド♯' },
        { letter: 'D', solfege: 'レ' },
        { letter: 'E♭', solfege: 'ミ♭' },
        { letter: 'E', solfege: 'ミ' },
        { letter: 'F', solfege: 'ファ' },
        { letter: 'F♯', solfege: 'ファ♯' },
        { letter: 'G', solfege: 'ソ' },
        { letter: 'A♭', solfege: 'ラ♭' },
        { letter: 'A', solfege: 'ラ' },
        { letter: 'B♭', solfege: 'シ♭' },
        { letter: 'B', solfege: 'シ' },
    ];

    var A4_MIDI = 69;

    // Correct frequency = reference A4 * 2^((n - 69) / 12).
    function noteFrequency(midi, referenceA4) {
        return referenceA4 * Math.pow(2, (midi - A4_MIDI) / 12);
    }

    // cent = 1200 * log2(measured / correct).
    function centsBetween(frequency, reference) {
        return 1200 * Math.log2(frequency / reference);
    }

    // Continuous note number (69 = A4 at the reference); the integer part
    // selects the note and the fraction is the deviation in semitones.
    function fractionalMidi(frequency, referenceA4) {
        return A4_MIDI + 12 * Math.log2(frequency / referenceA4);
    }

    function nearestMidi(frequency, referenceA4) {
        return Math.round(fractionalMidi(frequency, referenceA4));
    }

    function describeNote(midi) {
        var index = ((midi % 12) + 12) % 12;
        var octave = Math.floor(midi / 12) - 1;
        var name = NOTE_NAMES[index];
        return {
            midi: midi,
            letter: name.letter,
            solfege: name.solfege,
            octave: octave,
            label: name.letter + octave,
        };
    }

    function analyzeFrequency(frequency, referenceA4) {
        var midi = nearestMidi(frequency, referenceA4);
        var target = noteFrequency(midi, referenceA4);
        return {
            note: describeNote(midi),
            targetFrequency: target,
            cents: centsBetween(frequency, target),
        };
    }

    var api = {
        NOTE_NAMES: NOTE_NAMES,
        A4_MIDI: A4_MIDI,
        noteFrequency: noteFrequency,
        centsBetween: centsBetween,
        fractionalMidi: fractionalMidi,
        nearestMidi: nearestMidi,
        describeNote: describeNote,
        analyzeFrequency: analyzeFrequency,
    };

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    lib.releases = lib.releases || {};
    lib.music = api;
    lib.releases.music = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
