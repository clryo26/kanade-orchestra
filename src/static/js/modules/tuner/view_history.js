        function filters() {
            var f = {};
            if (from.value) f.from = new Date(from.value + 'T00:00:00+09:00').getTime();
            if (to.value) {
                // Exclusive next JST midnight includes the final fractional second.
                f.before = new Date(to.value + 'T00:00:00+09:00').getTime() + 86400000;
            }
            if (kindFilter.value) f.kind = kindFilter.value;
            if (instrumentFilter.value) f.instrumentId = instrumentFilter.value;
            return f;
        }

