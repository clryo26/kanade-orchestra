    // Session list -> totals per period (H-004 / H-005), pure.
    function periodTotals(details, period) {
        var key = lib.intonationProfile.periodKey;
        var out = {};
        (details || []).forEach(function (d) {
            var s = d.session;
            var k = key(s.startedAt, period);
            var row = out[k] || (out[k] = { sessions: 0, seconds: 0, absMedian: [], events: 0 });
            row.sessions += 1;
            row.seconds += (s.summary && s.summary.durationMs ? s.summary.durationMs : (s.frameCount || 0) * 33) / 1000;
            (d.events || []).forEach(function (ev) {
                if (ev.stats && typeof ev.stats.medianCents === 'number') { row.absMedian.push(Math.abs(ev.stats.medianCents)); row.events += 1; }
            });
        });
        Object.keys(out).forEach(function (k) {
            var v = out[k].absMedian.sort(function (a, b) { return a - b; });
            out[k].medianAbsCents = v.length ? v[Math.floor(v.length / 2)] : null;
            delete out[k].absMedian;
        });
        return out;
    }

    // ----- comparisons per judging condition (pure) ---------------------------
    // A saved note event judged under other conditions than its session (A4 /
    // target changed during the session) carries target.conditionKey. Every
    // comparison is made per condition key, never over all notes of a session.
    function eventConditionKey(d, ev) {
        return (ev && ev.target && ev.target.conditionKey) || d.session.conditionKey || null;
    }

    function medianAbsOf(events) {
        var v = (events || []).map(function (ev) { return ev.stats && typeof ev.stats.medianCents === 'number' && Number.isFinite(ev.stats.medianCents) ? Math.abs(ev.stats.medianCents) : null; })
            .filter(function (x) { return x !== null; }).sort(function (a, b) { return a - b; });
        return v.length ? v[Math.floor(v.length / 2)] : null;
    }

    // { key: { events, conditions } } of one saved session.
    function conditionGroups(d) {
        var out = {};
        (d.events || []).forEach(function (ev) {
            var key = eventConditionKey(d, ev);
            if (!key) return;
            if (!out[key]) {
                var t = ev.target || {};
                var own = t.conditionKey && t.conditionKey !== d.session.conditionKey;
                out[key] = { events: [], conditions: own ? Object.assign({}, d.session.conditions, { a4Tenths: t.a4Tenths || (d.session.conditions || {}).a4Tenths, temperament: t.definition ? t.definition.temperament : (t.temperament || (d.session.conditions || {}).temperament) }) : d.session.conditions };
            }
            out[key].events.push(ev);
        });
        return out;
    }

    // For each condition of session d: its median and the latest earlier
    // session that has notes under the same condition (median of those notes only).
    function sameConditionComparison(details, d) {
        var groups = conditionGroups(d);
        return Object.keys(groups).map(function (key) {
            var prev = null;
            (details || []).forEach(function (x) {
                if (x === d || !(x.session.startedAt < d.session.startedAt)) return;
                var g = conditionGroups(x)[key];
                if (!g || !g.events.length) return;
                if (!prev || x.session.startedAt > prev.session.startedAt) prev = { session: x.session, events: g.events };
            });
            return {
                key: key,
                conditions: groups[key].conditions,
                isSessionCondition: key === d.session.conditionKey,
                events: groups[key].events.length,
                current: medianAbsOf(groups[key].events),
                previous: prev ? medianAbsOf(prev.events) : null,
                previousAt: prev ? prev.session.startedAt : null,
            };
        }).sort(function (a, b) { return (b.isSessionCondition ? 1 : 0) - (a.isSessionCondition ? 1 : 0) || b.events - a.events; });
    }

    // Growth series of one condition: sessions in time order, the median of
    // the notes under that condition only.
    function growthSeries(details, key) {
        var points = [];
        (details || []).forEach(function (d) {
            var g = conditionGroups(d)[key];
            if (!g) return;
            var m = medianAbsOf(g.events);
            if (m !== null) points.push({ startedAt: d.session.startedAt, value: m });
        });
        return points.sort(function (a, b) { return a.startedAt - b.startedAt; });
    }

    // Condition keys of all sessions with their note counts (largest first).
    function conditionKeys(details) {
        var counts = {};
        (details || []).forEach(function (d) {
            var groups = conditionGroups(d);
            Object.keys(groups).forEach(function (k) {
                counts[k] = counts[k] || { key: k, events: 0, sessions: 0, conditions: groups[k].conditions };
                counts[k].events += groups[k].events.length;
                counts[k].sessions += 1;
            });
        });
        return Object.keys(counts).map(function (k) { return counts[k]; }).sort(function (a, b) { return b.events - a.events; });
    }

