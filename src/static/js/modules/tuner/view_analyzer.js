    function h(tag, attrs, children) {
        var el = globalObj.document.createElement(tag);
        Object.keys(attrs || {}).forEach(function (k) {
            if (k === 'text') el.textContent = attrs[k];
            else if (k === 'className') el.className = attrs[k];
            else if (k.indexOf('data-') === 0 || k.indexOf('aria-') === 0 || k === 'for' || k === 'role') el.setAttribute(k, attrs[k]);
            else el[k] = attrs[k];
        });
        (children || []).forEach(function (c) { if (c) el.appendChild(typeof c === 'string' ? globalObj.document.createTextNode(c) : c); });
        return el;
    }

    function fmt(value, digits, unit) {
        if (typeof value !== 'number' || !Number.isFinite(value)) return '測定できず';
        var text = Math.abs(value).toFixed(digits === undefined ? 1 : digits);
        var sign = value > 0 && unit === 'cent' ? '+' : (value < 0 ? MINUS : '');
        return sign + text + (unit ? ' ' + unit : '');
    }

    function seconds(value) {
        return typeof value === 'number' && Number.isFinite(value) ? value.toFixed(2) + ' 秒' : '測定できず';
    }

    // Series -> graph data in the current target's cents (pure, testable).
    function graphData(snapshot, targetConfig, a4Hz, lib_) {
        var s = snapshot.series;
        var n = s.frame2.length;
        var sr = s.sampleRate || 48000;
        var times = new Float64Array(n);
        var cents = new Float64Array(n);
        var hz = new Float64Array(n);
        var dbfs = new Float64Array(n);
        var cache = {};
        var music = lib_.music;
        var tm = lib_.targetModel;
        for (var i = 0; i < n; i += 1) {
            times[i] = s.frame2[i] / 2 / sr;
            dbfs[i] = Number.isFinite(s.rms[i]) ? s.rms[i] : NaN;
            var f = s.hz[i];
            var usable = f > 0 && !s.reason[i] && !(s.flags[i] & 1);
            hz[i] = usable ? f : NaN;
            if (!usable) { cents[i] = NaN; continue; }
            var midi = music.nearestMidi(f, a4Hz);
            var key = String(midi);
            if (!(key in cache)) {
                var r = tm.resolve(Object.assign({}, targetConfig, { a4Hz: a4Hz, a4Tenths: undefined, fixedMidi: targetConfig.fixedMidi === null || targetConfig.fixedMidi === undefined ? midi : targetConfig.fixedMidi }), f);
                cache[key] = r ? r.targetHz : music.noteFrequency(midi, a4Hz);
            }
            cents[i] = 1200 * Math.log2(f / cache[key]);
        }
        var hop = s.expectedHop2 ? s.expectedHop2 / 2 / sr : 0.05;
        return { times: times, cents: cents, hz: hz, dbfs: dbfs, maxGap: 2.5 * hop, now: n ? times[n - 1] : 0 };
    }

