        function currentData() {
            var snap = ctx.store.recent(Math.max(130, graph.getView().windowSeconds + 5));
            if (!snap) return null;
            var epoch = ctx.epoch();
            var rate = { full: 30, low: 20, high: 40, vibrato: 40 }[ctx.body.getPrefs().registerProfile] || 30;
            snap.series.expectedHop2 = epoch ? (2 * epoch.sampleRate) / rate : 3200;
            return graphData(snap, ctx.body.getTargetConfig(), ctx.body.getA4(), L);
        }

        function selectedSnapshot() {
            var sel = graph.getSelection();
            var range = sel || (function () { var r = graph.visibleRange(); return { from: r[0], to: r[1] }; })();
            var epoch = ctx.epoch();
            if (!epoch) return null;
            var sr = epoch.sampleRate;
            var snap = ctx.store.snapshot({ from2: range.from * 2 * sr, to2: range.to * 2 * sr });
            var rate = { full: 30, low: 20, high: 40, vibrato: 40 }[ctx.body.getPrefs().registerProfile] || 30;
            snap.series.sampleRate = sr;
            snap.series.expectedHop2 = (2 * sr) / rate;
            return { snapshot: snap, range: range };
        }

