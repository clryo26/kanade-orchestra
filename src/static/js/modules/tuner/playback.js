// Tuner: reference-tone playback (sine) and its input validation.
//
// Ownership: the playback engine owns its own AudioContext, OscillatorNode,
// GainNode and timers for one playback session. It never shares the capture
// AudioContext or its zero-gain path, so the measurement teardown cannot close
// the playback context and playback cannot leak into the capture graph.
// The context is created and resumed synchronously inside the "再生" tap
// (iOS Safari only starts audio there); start() must therefore be called
// directly from the click handler, before any await.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-e8d471ab55a0'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    var music = lib.music || (typeof require === 'function' ? require('./music.js') : null);
    if (!music) throw new Error('tuner playback.js requires music.js to be loaded first');

    var MIN_HZ = 32;
    var MAX_HZ = 4400;
    var NOTE_MIN_MIDI = 24; // C1 (disabled when below 32 Hz for the current A4)
    var NOTE_MAX_MIDI = 108; // C8
    var DEFAULT_MIDI = 69; // A4
    // Volume slider (percent) -> gain: gain = percent / 100 * MAX_GAIN.
    // Default 40 % = gain 0.1 (about -20 dBFS): audible but restrained.
    var MAX_GAIN = 0.25;
    var DEFAULT_VOLUME_PERCENT = 40;
    // Short ramps keep start/stop/changes free of clicks.
    var FADE_IN_SECONDS = 0.02;
    var FADE_OUT_SECONDS = 0.03;
    var FREQUENCY_GLIDE_SECONDS = 0.03;
    var VOLUME_RAMP_SECONDS = 0.02;
    // The context is closed a little after the fade-out has finished.
    var CLOSE_AFTER_STOP_MS = Math.round((FADE_OUT_SECONDS + 0.05) * 1000);

    function isPlayableFrequency(frequency) {
        return typeof frequency === 'number' && Number.isFinite(frequency) && frequency >= MIN_HZ && frequency <= MAX_HZ;
    }

    function volumeToGain(percent) {
        var value = Number(percent);
        if (!Number.isFinite(value)) value = DEFAULT_VOLUME_PERCENT;
        value = Math.max(0, Math.min(100, value));
        return (value / 100) * MAX_GAIN;
    }

    // Typed input: 32.0-4400.0 Hz in 0.1 Hz steps. Full-width digits are
    // accepted (NFKC) because iPhone keyboards may produce them.
    function parseHzInput(text) {
        var raw = String(text == null ? '' : text).normalize('NFKC').trim();
        if (raw === '') return { ok: false, reason: 'empty', message: '周波数を入力してください。' };
        if (!/^[0-9]+(\.[0-9])?$/.test(raw)) {
            return { ok: false, reason: 'format', message: '数字で入力してください（小数は1桁まで）。' };
        }
        var value = Number(raw);
        if (!isPlayableFrequency(value)) {
            return { ok: false, reason: 'range', message: '32.0～4,400.0 Hz の範囲で入力してください。' };
        }
        return { ok: true, value: value };
    }

    function noteOptions(referenceA4) {
        var list = [];
        for (var midi = NOTE_MIN_MIDI; midi <= NOTE_MAX_MIDI; midi += 1) {
            var frequency = music.noteFrequency(midi, referenceA4);
            list.push({ note: music.describeNote(midi), frequency: frequency, enabled: isPlayableFrequency(frequency) });
        }
        return list;
    }

    // settings: { source: 'note', midi } | { source: 'hz', hz, origin }
    // Note mode follows the A4 reference; Hz mode keeps its value exactly
    // (just-intonation values are passed unrounded).
    function resolveFrequency(settings, referenceA4) {
        if (!settings) return { ok: false, reason: 'empty', message: '再生する音を指定してください。' };
        if (settings.source === 'note') {
            if (!Number.isInteger(settings.midi)) return { ok: false, reason: 'empty', message: '音名を選んでください。' };
            var frequency = music.noteFrequency(settings.midi, referenceA4);
            if (!isPlayableFrequency(frequency)) {
                return { ok: false, reason: 'range', message: 'この音名は現在の基準では再生範囲（32.0～4,400.0 Hz）外です。' };
            }
            return { ok: true, frequency: frequency, note: music.describeNote(settings.midi) };
        }
        if (settings.source === 'hz') {
            if (settings.error) return { ok: false, reason: settings.error.reason, message: settings.error.message };
            if (!isPlayableFrequency(settings.hz)) {
                return { ok: false, reason: 'range', message: '32.0～4,400.0 Hz の範囲で入力してください。' };
            }
            return { ok: true, frequency: settings.hz, note: null };
        }
        return { ok: false, reason: 'empty', message: '再生する音を指定してください。' };
    }

    // env: { createContext(), setTimeout, clearTimeout, onInterrupted() }
    function createPlaybackEngine(env) {
        var session = null;
        var sessionCount = 0;

        function rampParam(param, ctx, value, seconds, exponential) {
            var t = ctx.currentTime;
            param.cancelScheduledValues(t);
            param.setValueAtTime(param.value, t);
            if (exponential) param.exponentialRampToValueAtTime(value, t + seconds);
            else param.linearRampToValueAtTime(value, t + seconds);
        }

        function closeContext(ctx) {
            if (!ctx) return;
            ctx.onstatechange = null;
            try {
                if (typeof ctx.close === 'function' && ctx.state !== 'closed') {
                    var closing = ctx.close();
                    if (closing && typeof closing.catch === 'function') closing.catch(function () {});
                }
            } catch (_) { /* best effort */ }
        }

        // Immediate, idempotent release of one session (also used by dispose).
        function release(target) {
            if (!target || target.released) return;
            target.released = true;
            if (target.closeTimer !== null) env.clearTimeout(target.closeTimer);
            target.closeTimer = null;
            try { target.oscillator.stop(); } catch (_) { /* already stopped */ }
            try { target.oscillator.disconnect(); } catch (_) { /* ignore */ }
            try { target.gain.disconnect(); } catch (_) { /* ignore */ }
            closeContext(target.ctx);
            if (session === target) session = null;
        }

        // Synchronous: call from the tap handler. Repeated taps never create a
        // second oscillator; a running tone is updated instead.
        function start(frequency, gainValue) {
            if (!isPlayableFrequency(frequency)) return { started: false, reason: 'range' };
            if (session && !session.stopping) {
                setFrequency(frequency);
                setGain(gainValue);
                return { started: false, reason: 'already-playing' };
            }
            if (session) release(session); // a fade-out still running: end it now
            var ctx = env.createContext();
            try {
                var resumed = ctx.resume();
                if (resumed && typeof resumed.catch === 'function') resumed.catch(function () {});
            } catch (_) { /* resume outside a gesture may throw */ }
            var gain = ctx.createGain();
            var t = ctx.currentTime;
            gain.gain.setValueAtTime(0, t);
            gain.gain.linearRampToValueAtTime(gainValue, t + FADE_IN_SECONDS);
            var oscillator = ctx.createOscillator();
            oscillator.type = 'sine';
            oscillator.frequency.setValueAtTime(frequency, t);
            oscillator.connect(gain);
            gain.connect(ctx.destination);
            oscillator.start(t);
            sessionCount += 1;
            var current = { id: sessionCount, ctx: ctx, gain: gain, oscillator: oscillator, stopping: false, released: false, closeTimer: null };
            session = current;
            // A phone call / Siri interrupts the context: treat as a stop.
            ctx.onstatechange = function () {
                if (session !== current || current.stopping) return;
                if (ctx.state === 'interrupted' || ctx.state === 'closed') {
                    release(current);
                    if (env.onInterrupted) env.onInterrupted();
                }
            };
            return { started: true, sessionId: current.id };
        }

        function setFrequency(frequency) {
            if (!session || session.stopping || !isPlayableFrequency(frequency)) return false;
            rampParam(session.oscillator.frequency, session.ctx, frequency, FREQUENCY_GLIDE_SECONDS, true);
            return true;
        }

        function setGain(gainValue) {
            if (!session || session.stopping) return false;
            rampParam(session.gain.gain, session.ctx, Math.max(0, gainValue), VOLUME_RAMP_SECONDS, false);
            return true;
        }

        // Fade out, then release. Idempotent; returns false when nothing plays.
        function stop() {
            if (!session || session.stopping) return false;
            var current = session;
            current.stopping = true;
            var t = current.ctx.currentTime;
            rampParam(current.gain.gain, current.ctx, 0, FADE_OUT_SECONDS, false);
            try { current.oscillator.stop(t + FADE_OUT_SECONDS + 0.01); } catch (_) { /* ignore */ }
            current.closeTimer = env.setTimeout(function () {
                current.closeTimer = null;
                release(current);
            }, CLOSE_AFTER_STOP_MS);
            return true;
        }

        // Leaving the screen: stop at once (no fade wait) and close the context.
        function dispose() {
            if (session) release(session);
            session = null;
        }

        return {
            start: start,
            setFrequency: setFrequency,
            setGain: setGain,
            stop: stop,
            dispose: dispose,
            isPlaying: function () { return Boolean(session) && !session.stopping; },
            isActive: function () { return Boolean(session); },
        };
    }

    var api = {
        MIN_HZ: MIN_HZ,
        MAX_HZ: MAX_HZ,
        NOTE_MIN_MIDI: NOTE_MIN_MIDI,
        NOTE_MAX_MIDI: NOTE_MAX_MIDI,
        DEFAULT_MIDI: DEFAULT_MIDI,
        MAX_GAIN: MAX_GAIN,
        DEFAULT_VOLUME_PERCENT: DEFAULT_VOLUME_PERCENT,
        FADE_IN_SECONDS: FADE_IN_SECONDS,
        FADE_OUT_SECONDS: FADE_OUT_SECONDS,
        FREQUENCY_GLIDE_SECONDS: FREQUENCY_GLIDE_SECONDS,
        VOLUME_RAMP_SECONDS: VOLUME_RAMP_SECONDS,
        CLOSE_AFTER_STOP_MS: CLOSE_AFTER_STOP_MS,
        isPlayableFrequency: isPlayableFrequency,
        volumeToGain: volumeToGain,
        parseHzInput: parseHzInput,
        noteOptions: noteOptions,
        resolveFrequency: resolveFrequency,
        createPlaybackEngine: createPlaybackEngine,
    };

    lib.releases = lib.releases || {};
    lib.playback = api;
    lib.releases.playback = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
