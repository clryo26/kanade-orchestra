// Tuner: note events from the level envelope and the raw pitch frames.
//
// Boundaries (docs/TUNER_ADVANCED_DESIGN.md 8.2):
// - onset/offset and re-attacks come from the RMS envelope (onset.js);
// - a pitch change inside a sounding note (legato) splits it when the
//   medians on both sides of a time differ (see DEFAULTS); vibrato swings
//   around one centre do not split;
// - a target/condition change splits without counting a new attack or a new
//   repetition (boundaryType 'targetChange');
// - an input gap ends the event; nothing is bridged across it.
// Event start/end are envelope times; the first valid pitch is NOT called
// the true onset. The observed note is independent of the practice target.
(function (globalObj) {
    'use strict';

    var TUNER_RELEASE_ID = 't-b0635dde6c4d'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)
    var SEGMENTER_VERSION = 1;

    var lib = globalObj.PortalTunerLib = globalObj.PortalTunerLib || {};
    var onset = lib.onset || (typeof require === 'function' ? require('./onset.js') : null);
    if (!onset) throw new Error('tuner note_events.js requires onset.js to be loaded first');

    var DEFAULTS = {
        thresholdDbfs: -60,
        // Pitch change inside a sounding note, judged offline with windows on
        // both sides of each time (never against a reference that follows a
        // vibrato swing):
        // - large step: medians of the 100 ms before/after differ >= 120 cent;
        // - semitone-size change: medians of the 350 ms before/after (longer
        //   than one 3 Hz vibrato cycle) differ > 50 cent.
        // The split is placed at the strongest difference; splits are at
        // least minSplitMs apart. All values are tuning values.
        largeStepCents: 120,
        largeStepMs: 100,
        pitchChangeCents: 50,
        pitchChangeWindowMs: 350,
        minSplitMs: 100,
        minWindowFill: 0.8,
        a4Hz: 440,
    };

    function absCents(hz, a4) {
        return 1200 * Math.log2(hz / a4);
    }

    function median(values) {
        return onset.median(values);
    }

    function isUsable(series, i) {
        var hz = series.hz[i];
        if (!(hz > 0) || !Number.isFinite(hz)) return false;
        if (series.reason && series.reason[i]) return false;
        if (series.flags && (series.flags[i] & 1)) return false; // input gap
        return true;
    }

    // Lower bound: first index with frame2 >= value.
    function lowerBound(arr, value) {
        var lo = 0;
        var hi = arr.length;
        while (lo < hi) {
            var mid = (lo + hi) >> 1;
            if (arr[mid] < value) lo = mid + 1;
            else hi = mid;
        }
        return lo;
    }

    // args: { series, envelope, sampleRate, options, boundaries: [{frame2,
    //   type}], gaps: [frame2] }
    function segment(args) {
        var opts = Object.assign({}, DEFAULTS, args.options || {});
        var series = args.series;
        var sr = args.sampleRate || series.sampleRate;
        var notes = onset.detectNotes(args.envelope || [], Object.assign({ thresholdDbfs: opts.thresholdDbfs }, opts.onset || {}), args.gaps || []);
        var boundaries = (args.boundaries || []).slice().sort(function (a, b) { return a.frame2 - b.frame2; });
        var events = [];

        notes.forEach(function (note) {
            var pieces = [{ start: note.startFrame2, end: note.endFrame2, startType: note.startCause === 'reattack' ? 'reattack' : 'onset', endType: note.endCause }];
            // Pitch changes (offline, symmetric windows).
            var i0 = lowerBound(series.frame2, note.startFrame2);
            var i1 = lowerBound(series.frame2, note.endFrame2) - 1;
            var splits = pitchSplits(series, i0, i1, sr, opts);
            splits.forEach(function (at) { pieces = splitPieces(pieces, at, 'pitchChange'); });
            boundaries.forEach(function (b) {
                if (b.frame2 > note.startFrame2 && b.frame2 < note.endFrame2) pieces = splitPieces(pieces, b.frame2, b.type || 'targetChange');
            });
            pieces.forEach(function (p) {
                var a = lowerBound(series.frame2, p.start);
                var z = lowerBound(series.frame2, p.end) - 1;
                var vals = [];
                for (var k = a; k <= z; k += 1) if (isUsable(series, k)) vals.push(absCents(series.hz[k], opts.a4Hz));
                var med = vals.length ? median(vals) : null;
                events.push({
                    startFrame2: p.start,
                    endFrame2: p.end,
                    i0: a,
                    i1: z,
                    startBoundary: p.startType,
                    endBoundary: p.endType,
                    // A target change only re-labels the same sound.
                    attackEligible: p.startType === 'onset' || p.startType === 'reattack' || p.startType === 'pitchChange',
                    countsAsAttempt: p.startType !== 'targetChange',
                    observedMidi: med === null ? null : Math.round(69 + med / 100),
                    observedCents: med,
                    usableCount: vals.length,
                    durationSeconds: (p.end - p.start) / 2 / sr,
                    segmenterVersion: SEGMENTER_VERSION,
                });
            });
        });
        return events;
    }

    function windowMedian(times, values, from, to) {
        var vals = [];
        for (var i = 0; i < times.length; i += 1) if (times[i] >= from && times[i] < to) vals.push(values[i]);
        return vals.length ? { median: median(vals), count: vals.length } : null;
    }

    // Candidate split times (frame2) inside one sounding note.
    function pitchSplits(series, i0, i1, sr, opts) {
        var times = [];
        var values = [];
        for (var i = i0; i <= i1; i += 1) {
            if (!isUsable(series, i)) continue;
            times.push(series.frame2[i] / 2 / sr);
            values.push(absCents(series.hz[i], opts.a4Hz));
        }
        if (times.length < 4) return [];
        var hop = (times[times.length - 1] - times[0]) / Math.max(1, times.length - 1);
        var scored = [];
        [[opts.largeStepMs / 1000, opts.largeStepCents], [opts.pitchChangeWindowMs / 1000, opts.pitchChangeCents]].forEach(function (rule) {
            var w = rule[0];
            var minCount = Math.max(2, Math.floor((w / Math.max(hop, 1e-6)) * opts.minWindowFill));
            for (var k = 1; k < times.length; k += 1) {
                var t = (times[k - 1] + times[k]) / 2;
                // Both windows must lie inside the sounding note.
                if (t - w < times[0] - hop || t + w > times[times.length - 1] + hop) continue;
                var left = windowMedian(times, values, t - w, t);
                var right = windowMedian(times, values, t, t + w);
                if (!left || !right || left.count < minCount || right.count < minCount) continue;
                var diff = Math.abs(right.median - left.median);
                if (diff > rule[1]) scored.push({ t: t, score: diff / rule[1], separation: Math.max(w, opts.minSplitMs / 1000) });
            }
        });
        // Strongest candidates first (non-maximum suppression): a candidate
        // within the window of a stronger one belongs to the same change.
        scored.sort(function (a, b) { return b.score - a.score; });
        var chosen = [];
        scored.forEach(function (c) {
            if (chosen.every(function (x) { return Math.abs(x.t - c.t) >= Math.max(x.separation, c.separation) * 0.9; })) chosen.push(c);
        });
        // Localise each change with the short windows (the long windows only
        // decide that there is one).
        var shortW = opts.largeStepMs / 1000;
        var located = chosen.map(function (c) {
            var bestT = c.t;
            var bestDiff = -1;
            for (var k = 1; k < times.length; k += 1) {
                var t = (times[k - 1] + times[k]) / 2;
                if (Math.abs(t - c.t) > c.separation / 2) continue;
                var left = windowMedian(times, values, t - shortW, t);
                var right = windowMedian(times, values, t, t + shortW);
                if (!left || !right || left.count < 2 || right.count < 2) continue;
                var diff = Math.abs(right.median - left.median);
                if (diff > bestDiff + 1e-9) { bestDiff = diff; bestT = t; }
            }
            return bestT;
        });
        return located.sort(function (a, b) { return a - b; }).map(function (t) { return Math.round(t * sr * 2); });
    }

    function splitPieces(pieces, at, type) {
        var out = [];
        pieces.forEach(function (p) {
            if (at > p.start && at < p.end) {
                out.push({ start: p.start, end: at, startType: p.startType, endType: type });
                out.push({ start: at, end: p.end, startType: type, endType: p.endType });
            } else {
                out.push(p);
            }
        });
        return out;
    }

    var api = { SEGMENTER_VERSION: SEGMENTER_VERSION, DEFAULTS: DEFAULTS, segment: segment, lowerBound: lowerBound };

    lib.releases = lib.releases || {};
    lib.noteEvents = api;
    lib.releases.note_events = TUNER_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
