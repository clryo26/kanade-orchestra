// Tuner: statistics Worker (classic Worker, dependencies via importScripts).
// Heavy, non-live work only: note segmentation, event statistics, vibrato
// fits and diagnosis summaries. It never sees audio: it receives copies of
// the numeric measurement series (never the live ring buffers). Requests of
// the same kind are collapsed to the latest one, so a burst of updates while
// a tab is open cannot queue up work behind the live analysis.
'use strict';

var TUNER_RELEASE_ID = 't-5c2ad5661ae9'; // tuner-release-id (generated by scripts/generate_tuner_release.mjs)
var TUNER_PROTOCOL = 2;

var depsLoaded = false;
(function loadDependencies() {
    var query = self.location && self.location.search ? self.location.search : '';
    try {
        importScripts('music.js' + query, 'target_model.js' + query, 'onset.js' + query, 'note_events.js' + query, 'analysis_stats.js' + query, 'intonation_profile.js' + query);
        depsLoaded = true;
    } catch (error) {
        depsLoaded = false;
    }
})();

var pending = {};
var scheduled = false;

function reply(message) {
    message.release = TUNER_RELEASE_ID;
    message.protocol = TUNER_PROTOCOL;
    self.postMessage(message);
}

function lib() {
    return self.PortalTunerLib || {};
}

function releasesMatch() {
    var releases = lib().releases || {};
    return ['music', 'target_model', 'onset', 'note_events', 'analysis_stats', 'intonation_profile'].every(function (name) {
        return releases[name] === TUNER_RELEASE_ID;
    });
}

function seriesFrom(snapshot) {
    var s = snapshot.series;
    return {
        frame2: s.frame2,
        hz: s.hz,
        conf: s.conf,
        rms: s.rms,
        reason: s.reason,
        flags: s.flags,
        windowSamples: s.windowSamples,
        sampleRate: s.sampleRate,
        expectedHop2: s.expectedHop2,
    };
}

// Output intervals (playback / metronome) excluded from statistics.
function playbackTest(snapshot) {
    var intervals = (snapshot.intervals || []).filter(function (it) { return it.kind === 'output'; });
    if (!intervals.length) return null;
    var f2 = snapshot.series.frame2;
    return function (i) {
        var t = f2[i];
        for (var k = 0; k < intervals.length; k += 1) {
            var it = intervals[k];
            if (t >= it.startFrame2 && t <= it.endFrame2) return true;
        }
        return false;
    };
}

function targetFor(config, observedHz) {
    var model = lib().targetModel;
    if (!model || !(observedHz > 0)) return null;
    var resolved = model.resolve(config || { temperament: 'equal' }, observedHz);
    return resolved || null;
}

function segment(request) {
    var stats = lib().analysisStats;
    var notes = lib().noteEvents;
    var snapshot = request.snapshot;
    var series = seriesFrom(snapshot);
    var isPlayback = playbackTest(snapshot);
    var events = notes.segment({
        series: series,
        envelope: snapshot.envelope || [],
        sampleRate: series.sampleRate,
        gaps: snapshot.gaps || [],
        boundaries: (snapshot.boundaries || []).map(function (b) { return { frame2: b.frame2, type: b.type }; }),
        options: request.segmentOptions || {},
    });
    var out = events.map(function (ev) {
        var observedHz = ev.observedCents === null ? null : (request.segmentOptions && request.segmentOptions.a4Hz ? request.segmentOptions.a4Hz : 440) * Math.pow(2, ev.observedCents / 1200);
        // Judge each event against the conditions (A4, target definition,
        // tolerance) of its own time, recorded as boundaries in the store.
        var cond = stats.conditionAt(snapshot.conditions, ev.startFrame2);
        var config = cond ? cond.targetConfig : request.targetConfig;
        var tolerance = cond ? cond.toleranceCents : request.toleranceCents;
        var target = targetFor(config, observedHz);
        var st = target ? stats.eventStats({
            series: series,
            i0: ev.i0,
            i1: ev.i1,
            startFrame2: ev.startFrame2,
            endFrame2: ev.endFrame2,
            targetHz: target.targetHz,
            toleranceCents: tolerance,
            isPlayback: isPlayback,
        }) : null;
        var vibrato = st && request.vibrato ? stats.analyzeVibrato(st.observations, request.vibratoOptions || {}) : null;
        if (st) delete st.observations;
        return Object.assign({}, ev, { observedHz: observedHz, target: target ? { targetHz: target.targetHz, midi: target.midi, label: target.spelling ? target.spelling.label : null, temperament: target.temperament, a4Tenths: config && config.a4Tenths ? config.a4Tenths : null, toleranceCents: tolerance, definition: config || null } : null, stats: st, vibrato: vibrato });
    });
    return { events: out };
}

function eventStats(request) {
    var stats = lib().analysisStats;
    var series = seriesFrom(request.snapshot);
    var isPlayback = playbackTest(request.snapshot);
    return {
        stats: (request.items || []).map(function (item) {
            var st = stats.eventStats({
                series: series,
                i0: item.i0,
                i1: item.i1,
                startFrame2: item.startFrame2,
                endFrame2: item.endFrame2,
                targetHz: item.targetHz,
                toleranceCents: item.toleranceCents,
                requestedSeconds: item.requestedSeconds,
                isPlayback: isPlayback,
            });
            var vibrato = item.vibrato ? stats.analyzeVibrato(st.observations, item.vibratoOptions || {}) : null;
            delete st.observations;
            st.vibrato = vibrato;
            return st;
        }),
    };
}

function diagnose(request) {
    var profile = lib().intonationProfile;
    var events = request.events || [];
    var key = request.conditionKey;
    var notes = profile.noteMap(events, key, request.options || {});
    var categories = {
        register: profile.categoryMap(events, key, 'register', request.options || {}),
        direction: profile.categoryMap(events, key, 'direction', request.options || {}),
        dynamics: profile.categoryMap(events, key, 'dynamics', request.options || {}),
        instrument: profile.categoryMap(events, key, 'instrument', request.options || {}),
    };
    return {
        notes: notes,
        categories: categories,
        periods: request.period ? profile.periodMap(events, key, request.period, request.options || {}) : null,
        weak: profile.weakRanking(notes, 5),
        suggestions: profile.suggestions(notes, categories),
    };
}

var HANDLERS = { segment: segment, eventStats: eventStats, diagnose: diagnose };

function run() {
    scheduled = false;
    var kinds = Object.keys(pending);
    var batch = pending;
    pending = {};
    kinds.forEach(function (kind) {
        var request = batch[kind];
        try {
            var result = HANDLERS[kind](request);
            reply({ type: 'result', kind: kind, requestId: request.requestId, revision: request.revision, statsVersion: lib().analysisStats.STATS_VERSION, result: result });
        } catch (error) {
            reply({ type: 'error', kind: kind, requestId: request.requestId, revision: request.revision });
        }
    });
}

self.onmessage = function (event) {
    var message = event.data || {};
    if (message.type === 'hello') {
        if (!depsLoaded) { reply({ type: 'load-failed' }); return; }
        if (message.release !== TUNER_RELEASE_ID || message.protocol !== TUNER_PROTOCOL || !releasesMatch()) { reply({ type: 'version-mismatch' }); return; }
        reply({ type: 'ready' });
        return;
    }
    if (message.type === 'stop') {
        pending = {};
        self.close();
        return;
    }
    if (message.type !== 'analyze' || !HANDLERS[message.kind]) return;
    // Latest request of each kind wins.
    pending[message.kind] = message;
    if (!scheduled) {
        scheduled = true;
        setTimeout(run, 0);
    }
};

if (typeof module !== 'undefined' && module.exports) {
    module.exports = { HANDLERS: HANDLERS, run: run };
}
