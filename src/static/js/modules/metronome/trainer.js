// Metronome: practice programs, tempo steps and the tempo guessing exercise
// (design 12, phase 03).
//
// A program is a list of steps. Each step plays a preset (or the setting
// being edited) until its end condition (bars / active seconds / repeats /
// manual), optionally raising or lowering the tempo in steps. Between steps
// the click stops; the next step starts only from the user's tap (the
// program never starts sound by itself, design 12).
//
// Generations (design 12, DC-13/17/19): every start creates a new attemptId.
// Results carry the attemptId they were created for; a newer attempt never
// cancels the save of an older one, and a result arriving for an attempt
// that is no longer current only updates its own record, never the screen.
//
// Active time counts only performing playback: count-in, pause, fermata
// waiting and rests are excluded. It is measured on the audio clock (frame
// deltas while the transport keeps running), so sparse display ticks never
// undercount it (R-09). One record lasts at most 1800 s of playing time:
// then it is closed once, the program and the click go on, and a new record
// starts only from the user's tap (startNewRecord).
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};

    var LIMITS = {
        maxSteps: 256,
        maxProgramRepeat: 100,
        maxEndBars: 10000,
        maxEndSeconds: 7200,
        maxEndRepeats: 1000,
        maxRestSeconds: 600,
        maxTempoEvery: 1000,
        maxRecordSeconds: 1800, // one record (R-09); the program itself may run longer
    };
    var END_KINDS = ['bars', 'activeSeconds', 'repeats', 'manual'];
    var STEP_AT = ['bars', 'seconds', 'repeats'];
    var ON_LIMIT = ['stop', 'hold', 'reverse'];
    var EXERCISES = ['play', 'tempoGuess'];
    // Placeholder id of "the setting being edited" (not a stored preset).
    var CURRENT_PRESET_ID = '00000000-0000-4000-8000-00000000b001';

    var UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

    function isPlainObject(x) {
        return Boolean(x) && typeof x === 'object' && !Array.isArray(x) && Object.getPrototypeOf(x) === Object.prototype;
    }

    function keysOk(obj, allowed, path, errors) {
        if (!isPlainObject(obj)) {
            errors.push({ path: path, code: 'not-object' });
            return false;
        }
        Object.keys(obj).forEach(function (k) {
            if (k === '__proto__' || k === 'prototype' || k === 'constructor') errors.push({ path: path + '.' + k, code: 'forbidden-key' });
            else if (allowed.indexOf(k) < 0) errors.push({ path: path + '.' + k, code: 'unknown-field' });
        });
        return true;
    }

    function int(x, min, max, path, errors) {
        if (!Number.isInteger(x) || x < min || x > max) {
            errors.push({ path: path, code: 'out-of-range', min: min, max: max });
            return null;
        }
        return x;
    }

    function rationalOk(x) {
        return isPlainObject(x) && Number.isInteger(x.n) && Number.isInteger(x.d) && x.n > 0 && x.d > 0 && Object.keys(x).length === 2;
    }

    // Program schema (docs/METRONOME_DATA_API_DESIGN.md 4, practice.program).
    function validateProgram(program) {
        var errors = [];
        if (!keysOk(program, ['steps', 'repeat'], '$.program', errors)) return { ok: false, errors: errors };
        var repeat = program.repeat === undefined ? 1 : int(program.repeat, 1, LIMITS.maxProgramRepeat, '$.program.repeat', errors);
        if (!Array.isArray(program.steps) || program.steps.length < 1 || program.steps.length > LIMITS.maxSteps) {
            errors.push({ path: '$.program.steps', code: 'invalid-steps' });
            return { ok: false, errors: errors };
        }
        var ids = {};
        var steps = program.steps.map(function (s, i) {
            var p = '$.program.steps[' + i + ']';
            if (!keysOk(s, ['id', 'presetId', 'presetRevision', 'end', 'countInBars', 'tempoStep', 'startBpmTenths', 'mute', 'restSeconds', 'beatFeel', 'exercise'], p, errors)) return null;
            if (typeof s.id !== 'string' || !UUID_RE.test(s.id)) errors.push({ path: p + '.id', code: 'invalid-uuid' });
            else if (ids[s.id]) errors.push({ path: p + '.id', code: 'duplicate-id' });
            ids[s.id] = true;
            if (typeof s.presetId !== 'string' || !UUID_RE.test(s.presetId)) errors.push({ path: p + '.presetId', code: 'invalid-uuid' });
            int(s.presetRevision, 1, 2147483647, p + '.presetRevision', errors);
            var end = null;
            if (keysOk(s.end, ['kind', 'value'], p + '.end', errors)) {
                if (END_KINDS.indexOf(s.end.kind) < 0) errors.push({ path: p + '.end.kind', code: 'invalid-enum' });
                else if (s.end.kind === 'manual') {
                    if (s.end.value !== undefined) errors.push({ path: p + '.end.value', code: 'unexpected-value' });
                    end = { kind: 'manual' };
                } else {
                    var max = s.end.kind === 'bars' ? LIMITS.maxEndBars : s.end.kind === 'activeSeconds' ? LIMITS.maxEndSeconds : LIMITS.maxEndRepeats;
                    var v = int(s.end.value, 1, max, p + '.end.value', errors);
                    if (v !== null) end = { kind: s.end.kind, value: v };
                }
            }
            var out = { id: s.id, presetId: s.presetId, presetRevision: s.presetRevision, end: end, exercise: s.exercise === undefined ? 'play' : s.exercise };
            if (EXERCISES.indexOf(out.exercise) < 0) errors.push({ path: p + '.exercise', code: 'invalid-enum' });
            if (out.exercise === 'tempoGuess' && end && end.kind === 'manual') errors.push({ path: p + '.end.kind', code: 'tempo-guess-needs-length' });
            if (s.countInBars !== undefined) out.countInBars = int(s.countInBars, 0, 8, p + '.countInBars', errors);
            if (s.startBpmTenths !== undefined) out.startBpmTenths = int(s.startBpmTenths, 200, 3000, p + '.startBpmTenths', errors);
            if (s.restSeconds !== undefined) out.restSeconds = int(s.restSeconds, 0, LIMITS.maxRestSeconds, p + '.restSeconds', errors);
            if (s.mute !== undefined && keysOk(s.mute, ['playBars', 'muteBars'], p + '.mute', errors)) {
                var pb = int(s.mute.playBars, 1, 64, p + '.mute.playBars', errors);
                var mb = int(s.mute.muteBars, 1, 64, p + '.mute.muteBars', errors);
                if (pb !== null && mb !== null) out.mute = { playBars: pb, muteBars: mb };
            }
            if (s.beatFeel !== undefined && keysOk(s.beatFeel, ['pulse'], p + '.beatFeel', errors)) {
                if (!rationalOk(s.beatFeel.pulse)) errors.push({ path: p + '.beatFeel.pulse', code: 'invalid-rational' });
                else out.beatFeel = { pulse: { n: s.beatFeel.pulse.n, d: s.beatFeel.pulse.d } };
            }
            if (s.tempoStep !== undefined && keysOk(s.tempoStep, ['deltaBpmTenths', 'at', 'every', 'minBpmTenths', 'maxBpmTenths', 'onLimit'], p + '.tempoStep', errors)) {
                var t = s.tempoStep;
                var delta = t.deltaBpmTenths;
                if (!Number.isInteger(delta) || delta === 0 || Math.abs(delta) > 2800) errors.push({ path: p + '.tempoStep.deltaBpmTenths', code: 'out-of-range' });
                if (STEP_AT.indexOf(t.at) < 0) errors.push({ path: p + '.tempoStep.at', code: 'invalid-enum' });
                var every = int(t.every, 1, LIMITS.maxTempoEvery, p + '.tempoStep.every', errors);
                var lo = int(t.minBpmTenths, 200, 3000, p + '.tempoStep.minBpmTenths', errors);
                var hi = int(t.maxBpmTenths, 200, 3000, p + '.tempoStep.maxBpmTenths', errors);
                if (lo !== null && hi !== null && lo > hi) errors.push({ path: p + '.tempoStep', code: 'min-above-max' });
                if (ON_LIMIT.indexOf(t.onLimit) < 0) errors.push({ path: p + '.tempoStep.onLimit', code: 'invalid-enum' });
                out.tempoStep = { deltaBpmTenths: delta, at: t.at, every: every, minBpmTenths: lo, maxBpmTenths: hi, onLimit: t.onLimit };
            }
            return out;
        });
        return errors.length ? { ok: false, errors: errors } : { ok: true, program: { steps: steps, repeat: repeat }, errors: [] };
    }

    // One tempo step: the next tempo within [min, max]. At the limit:
    // stop -> ends the step; hold -> stays; reverse -> turns direction.
    function nextTempo(current, step, direction) {
        var dir = direction || 1;
        var next = current + dir * step.deltaBpmTenths;
        var lo = step.minBpmTenths;
        var hi = step.maxBpmTenths;
        if (next >= lo && next <= hi) return { bpmTenths: next, direction: dir, limit: null };
        var clamped = Math.max(lo, Math.min(hi, next));
        if (step.onLimit === 'stop') return { bpmTenths: clamped, direction: dir, limit: 'stop' };
        if (step.onLimit === 'hold') return { bpmTenths: clamped, direction: dir, limit: 'hold' };
        var back = current - dir * step.deltaBpmTenths;
        return { bpmTenths: Math.max(lo, Math.min(hi, back)), direction: -dir, limit: 'reverse' };
    }

    // Tempo guessing: the answer against the hidden tempo. No pass / fail
    // threshold before calibration (design 12): numbers only.
    function tempoGuessResult(truthTenths, answerBpm) {
        if (typeof answerBpm !== 'number' || !Number.isFinite(answerBpm) || answerBpm <= 0) return null;
        var truth = truthTenths / 10;
        var err = answerBpm - truth;
        return { truthBpm: truth, answerBpm: Math.round(answerBpm * 10) / 10, errorBpm: Math.round(err * 10) / 10, errorPercent: Math.round(1000 * err / truth) / 10 };
    }

    // Random hidden tempo for the guessing exercise (integer BPM in range).
    function hiddenTempo(minTenths, maxTenths, random) {
        var lo = Math.ceil(minTenths / 10);
        var hi = Math.floor(maxTenths / 10);
        var r = typeof random === 'function' ? random() : Math.random();
        return (lo + Math.floor(r * (hi - lo + 1))) * 10;
    }

    // Number of completed passes of the repeating part (loop: bars).
    function passesAt(snapshot, occurrence) {
        if (!snapshot || snapshot.loop) return occurrence;
        var occ = snapshot.occurrences || [];
        if (snapshot.loopFrom === null || snapshot.loopFrom === undefined) return occurrence >= occ.length ? 1 : 0;
        var len = occ.length - snapshot.loopFrom;
        if (occurrence < occ.length) return 0;
        return Math.floor((occurrence - occ.length) / len) + 1;
    }

    // env: { api (body api), uuid(), utcNow(), setTimeout, clearTimeout,
    //   resolvePreset(id, revision) -> draft fields | null, onUpdate(view),
    //   onResult(result) }
    function createProgramRunner(env) {
        var api = env.api;
        var program = null;
        var state = 'idle'; // idle | playing | resting | ready | guessing | done | stopped
        var stepIndex = 0;
        var iteration = 0;
        var attempt = null;
        var stepRun = null;
        var restTimer = null;
        var restLeft = 0;
        var ownStop = false;
        var off = null;
        var recordLimitReached = false;
        var lastRecord = null;

        function newAttempt() {
            return { attemptId: env.uuid(), programRunId: programRunId, kind: 'practice', startedAt: env.utcNow(), program: JSON.parse(JSON.stringify(program)), steps: [], status: 'running', activeFramesBefore: 0 };
        }
        var programRunId = null;

        // The part of the current step that belongs to the current record.
        function stepRecord(reason, frames) {
            var sr = stepRun.sampleRate || 48000;
            var part = frames === undefined ? stepRun.activeFrames - stepRun.recordOffsetFrames : frames;
            return {
                stepId: stepRun.stepId,
                index: stepRun.index,
                iteration: stepRun.iteration,
                endReason: reason,
                bars: stepRun.bars,
                activeSeconds: Math.round(10 * Math.max(0, part) / sr) / 10,
                startBpmTenths: stepRun.startBpmTenths,
                endBpmTenths: stepRun.bpmTenths,
                tempoChanges: stepRun.stepsApplied,
            };
        }

        function pushStep(reason) {
            var rec = stepRecord(reason);
            lastRecord = rec;
            if (!attempt) return rec;
            attempt.steps.push(rec);
            attempt.activeFramesBefore += Math.max(0, stepRun.activeFrames - stepRun.recordOffsetFrames);
            stepRun.recordOffsetFrames = stepRun.activeFrames;
            return rec;
        }

        // 1800 s of playing time in this record: close it once (click goes on).
        function checkRecordLimit() {
            if (!attempt || !stepRun) return;
            var sr = stepRun.sampleRate || 48000;
            var limit = LIMITS.maxRecordSeconds * sr;
            var used = attempt.activeFramesBefore + (stepRun.activeFrames - stepRun.recordOffsetFrames);
            if (used < limit) return;
            var part = limit - attempt.activeFramesBefore;
            attempt.steps.push(stepRecord('record-limit', part));
            stepRun.recordOffsetFrames = stepRun.activeFrames;
            recordLimitReached = true;
            finishAttempt('complete', 'record-limit');
            api.announce('記録が30分になったため区切りました。演奏はそのまま続きます');
        }

        function view() {
            var step = program && program.steps[stepIndex];
            return {
                state: state,
                stepIndex: stepIndex,
                stepCount: program ? program.steps.length : 0,
                iteration: iteration,
                repeat: program ? program.repeat : 0,
                exercise: step ? step.exercise : null,
                bars: stepRun ? stepRun.bars : 0,
                activeSeconds: stepRun ? stepRun.activeFrames / (stepRun.sampleRate || 48000) : 0,
                recording: Boolean(attempt),
                recordLimitReached: recordLimitReached,
                bpmTenths: stepRun && step && step.exercise !== 'tempoGuess' ? stepRun.bpmTenths : null,
                restLeft: restLeft,
                attemptId: attempt ? attempt.attemptId : null,
                lastGuess: attempt && attempt.steps.length ? attempt.steps[attempt.steps.length - 1].guess || null : null,
            };
        }

        function update() {
            if (typeof env.onUpdate === 'function') env.onUpdate(view());
        }

        function clearRest() {
            if (restTimer !== null) env.clearTimeout(restTimer);
            restTimer = null;
            restLeft = 0;
        }

        function finishAttempt(status, reason) {
            if (!attempt) return;
            var done = attempt;
            attempt = null;
            done.status = status;
            done.endReason = reason;
            done.endedAt = env.utcNow();
            if (typeof env.onResult === 'function') env.onResult(done);
        }

        function stopSound() {
            if (api.state() === 'stopped') return;
            ownStop = true;
            try { api.stop('program'); } finally { ownStop = false; }
        }

        // Synchronous: called inside the user's tap so that play() can
        // create / resume the audio output in the same gesture.
        function beginStep() {
            var step = program.steps[stepIndex];
            var fields = step.presetId === CURRENT_PRESET_ID ? {} : env.resolvePreset(step.presetId, step.presetRevision);
            if (fields === null) {
                api.showMessage('ステップ' + (stepIndex + 1) + 'のプリセットが見つかりません。', 'error');
                state = 'stopped';
                finishAttempt('incomplete', 'preset-missing');
                update();
                return false;
            }
            var draft = Object.assign({}, fields);
            var truth = null;
            if (step.exercise === 'tempoGuess') {
                truth = hiddenTempo(step.tempoStep ? step.tempoStep.minBpmTenths : 600, step.tempoStep ? step.tempoStep.maxBpmTenths : 1600, env.random);
                draft.bpmTenths = truth;
            } else if (step.startBpmTenths) {
                draft.bpmTenths = step.startBpmTenths;
            }
            api.setConcealTempo(step.exercise === 'tempoGuess');
            if (Object.keys(draft).length) api.setDraft(draft, 'program');
            var practice = {};
            if (step.mute) practice.mute = step.mute;
            if (step.beatFeel) practice.beatFeel = step.beatFeel;
            api.setPractice(Object.keys(practice).length ? practice : null);
            var d = api.getDraft();
            stepRun = {
                stepId: step.id,
                index: stepIndex,
                iteration: iteration,
                startBpmTenths: d.bpmTenths,
                bpmTenths: d.bpmTenths,
                truthTenths: truth,
                direction: 1,
                startOccurrence: null,
                lastOccurrence: null,
                lastFrame: null,
                bars: 0,
                passes: 0,
                activeFrames: 0,
                recordOffsetFrames: 0,
                lastRunning: false,
                sampleRate: null,
                stepsApplied: 0,
                stepsDue: 0,
                startedAt: env.utcNow(),
            };
            state = 'playing';
            api.play({ countInBars: step.countInBars });
            update();
            return true;
        }

        function endStep(reason) {
            if (state !== 'playing' || !stepRun) return;
            var step = program.steps[stepIndex];
            stopSound();
            pushStep(reason);
            if (step.exercise === 'tempoGuess') {
                state = 'guessing';
                update();
                return;
            }
            afterStep();
        }

        function afterStep() {
            var step = program.steps[stepIndex];
            var last = stepIndex === program.steps.length - 1;
            if (last && iteration + 1 >= program.repeat) {
                state = 'done';
                api.setConcealTempo(false);
                finishAttempt('complete', 'program-end');
                stepRun = null;
                update();
                return;
            }
            if (last) {
                iteration += 1;
                stepIndex = 0;
            } else {
                stepIndex += 1;
            }
            stepRun = null;
            var rest = step.restSeconds || 0;
            if (rest > 0) {
                state = 'resting';
                restLeft = rest;
                var tickRest = function () {
                    restTimer = null;
                    restLeft -= 1;
                    if (restLeft <= 0) {
                        restLeft = 0;
                        state = 'ready';
                    } else {
                        restTimer = env.setTimeout(tickRest, 1000);
                    }
                    update();
                };
                restTimer = env.setTimeout(tickRest, 1000);
            } else {
                state = 'ready';
            }
            update();
        }

        function applyTempoStep(step) {
            var ts = step.tempoStep;
            var r = nextTempo(stepRun.bpmTenths, ts, stepRun.direction);
            stepRun.direction = r.direction;
            if (r.bpmTenths !== stepRun.bpmTenths) {
                stepRun.bpmTenths = r.bpmTenths;
                stepRun.stepsApplied += 1;
                api.setDraft({ bpmTenths: r.bpmTenths }, 'program', 'nextBar');
                api.announce('テンポを ' + (r.bpmTenths / 10).toFixed(1) + ' にします');
            }
            if (r.limit === 'stop') endStep('tempo-limit');
        }

        function onTick(payload) {
            if (state !== 'playing' || !stepRun || !payload || !payload.position) return;
            var pos = payload.position;
            var step = program.steps[stepIndex];
            if (pos.ended || pos.occurrence === undefined || pos.occurrence < 0) return;
            if (typeof pos.score === 'object' && pos.score && pos.score.n < 0) return; // count-in
            if (stepRun.sampleRate === null) stepRun.sampleRate = api.sampleRate() || 48000;
            var transportState = api.state();
            if (stepRun.lastFrame !== null && stepRun.lastRunning && transportState === 'running') {
                // Audio frames played since the last tick (no cap: a slow
                // display does not stop the click).
                var delta = payload.frame - stepRun.lastFrame;
                if (delta > 0) stepRun.activeFrames += delta;
            }
            stepRun.lastFrame = payload.frame;
            stepRun.lastRunning = transportState === 'running';
            checkRecordLimit();
            if (stepRun.startOccurrence === null) stepRun.startOccurrence = pos.occurrence;
            var bars = pos.occurrence - stepRun.startOccurrence;
            var snap = api.transport() ? api.transport().getSnapshot() : null;
            var passes = passesAt(snap, pos.occurrence) - passesAt(snap, stepRun.startOccurrence);
            var seconds = stepRun.activeFrames / stepRun.sampleRate;
            if (step.tempoStep && step.exercise === 'play') {
                var ts = step.tempoStep;
                var measure = ts.at === 'bars' ? bars : ts.at === 'repeats' ? passes : Math.floor(seconds);
                var due = Math.floor(measure / ts.every);
                // One change per boundary crossed (a slow display tick may cross several).
                while (due > stepRun.stepsDue && state === 'playing') {
                    stepRun.stepsDue += 1;
                    applyTempoStep(step);
                }
            }
            if (state !== 'playing') return;
            stepRun.bars = bars;
            stepRun.passes = passes;
            var end = step.end;
            if (end.kind === 'bars' && bars >= end.value) endStep('bars');
            else if (end.kind === 'activeSeconds' && seconds >= end.value) endStep('active-seconds');
            else if (end.kind === 'repeats' && passes >= end.value) endStep('repeats');
            else update();
        }

        function onEvent(type, payload) {
            if (type === 'state' && payload && payload.state !== 'running' && stepRun) {
                // Pause / fermata / interruption: the playing-time count stops here.
                stepRun.lastFrame = null;
                stepRun.lastRunning = false;
            }
            if (type === 'tick') onTick(payload);
            else if (type === 'stopped' && !ownStop && state === 'playing') abort('user-stop');
            else if (type === 'state' && payload && payload.state === 'stopped' && payload.reason === 'ended' && state === 'playing') endStep('score-end');
            else if ((type === 'leave' || type === 'suspend' || type === 'cleared') && (state !== 'idle' && state !== 'done' && state !== 'stopped')) abort(type);
        }

        function abort(reason) {
            clearRest();
            if (state === 'playing') stopSound();
            state = 'stopped';
            api.setConcealTempo(false);
            if (stepRun && attempt) pushStep(reason);
            stepRun = null;
            finishAttempt('incomplete', reason);
            update();
        }

        if (typeof api.on === 'function') off = api.on(onEvent);

        return {
            // Starts a new attempt (inside the user's tap).
            start: function (nextProgram) {
                var v = validateProgram(nextProgram);
                if (!v.ok) return { ok: false, errors: v.errors };
                if (attempt) abort('superseded');
                clearRest();
                program = v.program;
                stepIndex = 0;
                iteration = 0;
                recordLimitReached = false;
                programRunId = env.uuid();
                attempt = newAttempt();
                return { ok: beginStep(), attemptId: attempt ? attempt.attemptId : null };
            },
            // After the 30-minute record was closed: a new record of the
            // running program (the user's explicit tap).
            startNewRecord: function () {
                if (attempt || !program || state === 'idle' || state === 'done' || state === 'stopped') return { ok: false };
                attempt = newAttempt();
                recordLimitReached = false;
                if (stepRun) stepRun.recordOffsetFrames = stepRun.activeFrames;
                update();
                return { ok: true, attemptId: attempt.attemptId };
            },
            // Next step after a rest / tempo guess (inside the user's tap).
            next: function () {
                if (state !== 'ready') return false;
                return beginStep();
            },
            // Manual end of the current step.
            endStepNow: function () {
                if (state === 'playing') endStep('manual');
            },
            submitGuess: function (answerBpm) {
                if (state !== 'guessing') return null;
                var rec = attempt && attempt.steps.length ? attempt.steps[attempt.steps.length - 1] : lastRecord;
                if (!rec) return null;
                var result = tempoGuessResult(rec.startBpmTenths, answerBpm);
                if (!result) return null;
                rec.guess = result;
                api.setConcealTempo(false);
                afterStep();
                return result;
            },
            stop: function () { if (state !== 'idle' && state !== 'done' && state !== 'stopped') abort('user-stop'); },
            view: view,
            destroy: function () {
                if (state === 'playing' || state === 'resting' || state === 'ready' || state === 'guessing') abort('leave');
                if (off) off();
            },
        };
    }

    var api = {
        LIMITS: LIMITS,
        CURRENT_PRESET_ID: CURRENT_PRESET_ID,
        validateProgram: validateProgram,
        nextTempo: nextTempo,
        tempoGuessResult: tempoGuessResult,
        hiddenTempo: hiddenTempo,
        passesAt: passesAt,
        createProgramRunner: createProgramRunner,
    };

    lib.releases = lib.releases || {};
    lib.trainer = api;
    lib.releases.trainer = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
