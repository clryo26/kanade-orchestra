// Metronome: event compiler — immutable snapshot + tempo map -> click events.
//
// Output events (design 7, data design 1):
//   { eventId, occurrence, score (R, absolute whole notes), barStart, offset,
//     layerId, kind, accentLevel, velocity, soundId, expected, emit, frame,
//     label }
// eventId is deterministic (revision / occurrence / layer / ordinal), so a
// redraw or recompilation of the same window yields the same ids. Muted
// events are still produced with emit=false: the expected beat stays for
// counting, display and timing analysis (design 7: "expected=trueでもmuteで
// emit=falseを許す").
//
// Frames are computed from the segment origin directly:
//   frame = originFrame + round(sampleRate * (T(s) - T(originScore)))
// so rounding never accumulates between events.
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};
    var R = lib.rational || (typeof require === 'function' ? require('./rational.js') : null);
    var SM = lib.scoreModel || (typeof require === 'function' ? require('./score_model.js') : null);
    var TM = lib.tempoMap || (typeof require === 'function' ? require('./tempo_map.js') : null);

    var COMPILER_VERSION = 1;
    var RANDOM_ALGORITHM_VERSION = 1;

    function CompileError(code, detail) {
        var e = new Error(code);
        e.name = 'MetronomeCompileError';
        e.code = code;
        e.detail = detail || null;
        return e;
    }

    // ----- deterministic counter hash (random mute, algorithm version 1) -----
    // Pure function of (seed, key): seeking never changes later choices.
    function hash32(seed, key) {
        var h = (seed ^ 0x9e3779b9) >>> 0;
        var s = String(key);
        for (var i = 0; i < s.length; i += 1) {
            h = Math.imul(h ^ s.charCodeAt(i), 0x85ebca6b);
            h = (h ^ (h >>> 13)) >>> 0;
        }
        h = Math.imul(h ^ (h >>> 16), 0x85ebca6b);
        h = Math.imul(h ^ (h >>> 13), 0xc2b2ae35);
        return (h ^ (h >>> 16)) >>> 0;
    }

    function unitRandom(seed, key) {
        return hash32(seed, key) / 4294967296;
    }

    // ----- bar occurrences ------------------------------------------------------

    // Occurrence k of a snapshot: { index, barStart, spec, iteration }.
    function occurrenceAt(snapshot, k) {
        if (snapshot.loop) {
            var t = snapshot.barTemplate;
            return { index: k, barStart: R.scale(t.length, k), spec: t, iteration: k };
        }
        var occ = snapshot.occurrences;
        if (k < occ.length) {
            var o = occ[k];
            return { index: k, barStart: o.start, spec: snapshot.bars[o.barIndex], iteration: o.iteration };
        }
        if (snapshot.loopFrom === null || snapshot.loopFrom === undefined) return null;
        // "untilStop": the section from loopFrom repeats after the end.
        var sectionLen = occ.length - snapshot.loopFrom;
        var sectionStart = occ[snapshot.loopFrom].start;
        var sectionLength = R.sub(snapshot.totalLength, sectionStart);
        var extra = k - occ.length;
        var round = Math.floor(extra / sectionLen) + 1;
        var within = occ[snapshot.loopFrom + (extra % sectionLen)];
        return {
            index: k,
            barStart: R.add(within.start, R.scale(sectionLength, round)),
            spec: snapshot.bars[within.barIndex],
            iteration: within.iteration + round,
        };
    }

    // Index of the occurrence containing score position s (s >= 0), or null
    // after the end of a finite score.
    function occurrenceIndexAt(snapshot, s) {
        if (snapshot.loop) return R.floorDiv(s, snapshot.barTemplate.length);
        var occ = snapshot.occurrences;
        if (R.lt(s, snapshot.totalLength)) {
            var lo = 0;
            var hi = occ.length - 1;
            while (lo < hi) {
                var mid = (lo + hi + 1) >> 1;
                if (R.le(occ[mid].start, s)) lo = mid; else hi = mid - 1;
            }
            return lo;
        }
        if (snapshot.loopFrom === null || snapshot.loopFrom === undefined) return null;
        var sectionStart = occ[snapshot.loopFrom].start;
        var sectionLength = R.sub(snapshot.totalLength, sectionStart);
        var beyond = R.sub(s, snapshot.totalLength);
        var round = R.floorDiv(beyond, sectionLength);
        var inSection = R.add(sectionStart, R.mod(beyond, sectionLength));
        var lo2 = snapshot.loopFrom;
        var hi2 = occ.length - 1;
        while (lo2 < hi2) {
            var mid2 = (lo2 + hi2 + 1) >> 1;
            if (R.le(occ[mid2].start, inSection)) lo2 = mid2; else hi2 = mid2 - 1;
        }
        var sectionLen = occ.length - snapshot.loopFrom;
        return occ.length + round * sectionLen + (lo2 - snapshot.loopFrom);
    }

    // ----- swing ------------------------------------------------------------------

    function swingFraction(swing) {
        // A:B with up to 3 decimals as an exact fraction.
        var a = Math.round(swing.a * 1000);
        var b = Math.round(swing.b * 1000);
        return R.make(a, a + b);
    }

    // Moves an offset inside its swing pair: both pair ends fixed, the
    // middle goes to A/(A+B); points in between are mapped piecewise
    // linearly (design 5: "pairの両端固定、内部境界=A/(A+B)").
    function applySwing(offsetInBar, swing) {
        var pairLen = R.scale(swing.pairUnit, 2);
        var pairIndex = R.floorDiv(offsetInBar, pairLen);
        var pairStart = R.scale(pairLen, pairIndex);
        var local = R.div(R.sub(offsetInBar, pairStart), pairLen);
        if (R.isZero(local)) return offsetInBar;
        var f = swingFraction(swing);
        var half = R.make(1, 2);
        var mapped = R.le(local, half)
            ? R.mul(local, R.scale(f, 2))
            : R.add(f, R.mul(R.sub(local, half), R.scale(R.sub(R.ONE, f), 2)));
        return R.add(pairStart, R.mul(mapped, pairLen));
    }

    function swingApplies(swing, layerId, insideTuplet) {
        if (!swing) return false;
        if (swing.layerIds.indexOf(layerId) < 0) return false;
        return !insideTuplet || swing.applyInsideTuplets;
    }

    // ----- per-bar meter layer -------------------------------------------------

    // Positions (offsets in the bar) with their accent classification.
    function meterPositions(spec, practice) {
        var map = {};
        function put(offset, level, index, velocity, label, inTuplet) {
            var key = R.toString(offset);
            var cur = map[key];
            var rank = { group: 0, pulse: 1, subdivision: 2 };
            if (!cur || rank[level] < rank[cur.level]) map[key] = { offset: offset, level: level, index: index, velocity: velocity, label: label, inTuplet: Boolean(inTuplet) };
        }
        spec.groupStarts.forEach(function (start, gi) { put(start, 'group', gi, spec.accent.group[gi], gi === 0 ? 'bar' : 'group'); });
        var pulse = practice && practice.beatFeel ? practice.beatFeel.pulse : spec.pulse;
        var feel = Boolean(practice && practice.beatFeel);
        var pc = SM.pulseCount(spec.length, pulse);
        for (var k = 0; k < pc; k += 1) {
            var v = feel ? (k === 0 ? spec.accent.group[0] : (spec.accent.pulse[1] !== undefined ? spec.accent.pulse[1] : 0.7)) : spec.accent.pulse[k];
            put(R.scale(pulse, k), 'pulse', k, v, 'pulse');
        }
        if (spec.subdivision) {
            var len = spec.subdivision.length;
            var count = Math.ceil(R.toNumber(R.div(spec.length, len)) - 1e-12);
            for (var j = 0; j < count; j += 1) {
                var off = R.scale(len, j);
                if (R.lt(off, spec.length)) put(off, 'subdivision', j, spec.accent.subdivision, 'subdivision', Boolean(spec.subdivision.tuplet));
            }
        }
        if (practice && practice.offbeat) {
            // Off-beat clicks are extra pulse-level events; the on-beat
            // expected positions stay (muted when muteOnBeat).
            for (var q = 0; q < pc; q += 1) {
                var ob = R.add(R.scale(pulse, q), practice.offbeat.offset);
                if (R.lt(ob, spec.length)) put(ob, 'pulse', q, spec.accent.pulse[q] !== undefined ? spec.accent.pulse[q] : 0.7, 'offbeat');
            }
        }
        return Object.keys(map).map(function (k) { return map[k]; }).sort(function (a, b) { return R.cmp(a.offset, b.offset); });
    }

    // ----- compiler -----------------------------------------------------------

    // options: { snapshot, tempoMap, revision, origin: { score, frame },
    //   sampleRate, from (R), to (R), muteOffsetBars (performance bar index
    //   offset for practice mute patterns) }
    function compile(options) {
        var snap = options.snapshot;
        var map = options.tempoMap;
        var sr = options.sampleRate;
        var from = options.from;
        var to = options.to;
        if (!R.lt(from, to)) return { events: [], fermata: null, end: false };
        var origin = options.origin;
        var originTime = map.timeAt(origin.score);
        var revision = options.revision === undefined ? 0 : options.revision;
        var practice = snap.practice || {};
        var events = [];
        var fermata = null;
        var ended = false;
        var limit = SM.LIMITS.maxCompileWindowEvents;

        function frameOf(s) {
            return origin.frame + Math.round(sr * (map.timeAt(s) - originTime));
        }

        function push(ev) {
            events.push(ev);
            if (events.length > limit) throw CompileError('window-too-dense', { limit: limit });
        }

        function barMuted(occ) {
            if (occ.spec.mute) return true;
            var k = occ.index + (options.muteOffsetBars || 0);
            if (practice.mute) {
                var cycle = practice.mute.playBars + practice.mute.muteBars;
                if ((k % cycle) >= practice.mute.playBars) return true;
            }
            if (practice.randomMute && practice.randomMute.unit === 'bar' && practice.randomMute.probability > 0) {
                if (unitRandom(practice.randomMute.seed, 'bar:' + k) < practice.randomMute.probability) return true;
            }
            return false;
        }

        // Fermatas of a finite score at absolute positions.
        var fermataPositions = [];
        if (!snap.loop && snap.events.fermatas.length) {
            var byBar = {};
            snap.occurrences.forEach(function (o) { (byBar[o.barId] = byBar[o.barId] || []).push(o); });
            snap.events.fermatas.forEach(function (f) {
                (byBar[f.at.barId] || []).forEach(function (o) {
                    fermataPositions.push({ score: R.add(o.start, f.at.offset), id: f.id, occurrence: o.index, resumeCountInPulses: f.resumeCountInPulses });
                });
            });
            fermataPositions.sort(function (a, b) { return R.cmp(a.score, b.score); });
        }
        // The first fermata at or after `from` (inclusive) limits the window:
        // its own event sounds, nothing after it is compiled (design 13).
        for (var fi = 0; fi < fermataPositions.length; fi += 1) {
            var fp = fermataPositions[fi];
            if (R.ge(fp.score, from) && R.lt(fp.score, to)) {
                fermata = fp;
                to = R.add(fp.score, R.make(1, 1000000000));
                break;
            }
        }

        // ---- meter layer, bar by bar ----
        var k = occurrenceIndexAt(snap, from);
        while (k !== null) {
            var occ = occurrenceAt(snap, k);
            if (!occ) {
                ended = true;
                break;
            }
            if (!R.lt(occ.barStart, to)) break;
            var muted = barMuted(occ);
            var positions = meterPositions(occ.spec, practice);
            for (var pi = 0; pi < positions.length; pi += 1) {
                var p = positions[pi];
                var offset = swingApplies(snap.swing, 'meter', p.inTuplet) ? applySwing(p.offset, snap.swing) : p.offset;
                var s = R.add(occ.barStart, offset);
                if (R.lt(s, from) || !R.lt(s, to)) continue;
                var emit = !muted && p.velocity > 0;
                if (practice.offbeat && practice.offbeat.muteOnBeat && p.label !== 'offbeat' && p.level !== 'subdivision') emit = false;
                if (emit && practice.randomMute && practice.randomMute.unit === 'event' && practice.randomMute.probability > 0) {
                    if (unitRandom(practice.randomMute.seed, 'ev:' + occ.index + ':' + R.toString(p.offset)) < practice.randomMute.probability) emit = false;
                }
                push({
                    eventId: revision + ':' + occ.index + ':meter:' + R.toString(p.offset),
                    occurrence: occ.index,
                    iteration: occ.iteration,
                    barId: occ.spec.id,
                    score: s,
                    barStart: occ.barStart,
                    offset: offset, // as played (after swing)
                    gridOffset: p.offset, // grid position before swing
                    layerId: 'meter',
                    kind: p.label,
                    accentLevel: p.level,
                    accentIndex: p.index,
                    velocity: p.velocity,
                    soundId: occ.spec.soundId || snap.sound.id,
                    expected: p.label !== 'offbeat',
                    emit: emit,
                    frame: frameOf(s),
                });
            }
            k += 1;
        }

        // ---- independent layers (poly / custom rhythm), from score origin ----
        snap.layers.forEach(function (layer) {
            var items = layer.rhythm && layer.rhythm.length ? layer.rhythm.map(function (it, i) {
                return { offset: it.offset, velocity: it.velocity, level: it.accentLevel, rest: it.rest, literal: it.timingMode === 'literal', ordinal: i };
            }) : null;
            if (!items) {
                items = [];
                var step = R.div(layer.cycle, R.make(layer.pulses, 1));
                for (var j = 0; j < layer.pulses; j += 1) items.push({ offset: R.scale(step, j), velocity: j === 0 ? 1 : 0.7, level: j === 0 ? 'group' : 'pulse', rest: false, literal: false, ordinal: j });
            }
            var cycleStart = R.floorDiv(R.sub(from, layer.phase), layer.cycle) - 1;
            for (var c = cycleStart; ; c += 1) {
                var base = R.add(layer.phase, R.scale(layer.cycle, c));
                if (!R.lt(base, to)) break;
                for (var ii = 0; ii < items.length; ii += 1) {
                    var it = items[ii];
                    var off = it.offset;
                    if (!it.literal && swingApplies(snap.swing, layer.id, false)) off = applySwing(off, snap.swing);
                    var sc = R.add(base, off);
                    if (R.lt(sc, R.ZERO) || R.lt(sc, from) || !R.lt(sc, to)) continue;
                    var occIndex = occurrenceIndexAt(snap, sc);
                    if (occIndex === null) continue; // after the end of a finite score
                    var occ2 = occurrenceAt(snap, occIndex);
                    var muted2 = barMuted(occ2);
                    push({
                        eventId: revision + ':' + layer.id + ':' + c + ':' + it.ordinal,
                        occurrence: occIndex,
                        iteration: occ2.iteration,
                        barId: occ2.spec.id,
                        score: sc,
                        barStart: occ2.barStart,
                        offset: R.sub(sc, occ2.barStart),
                        layerId: layer.id,
                        kind: 'layer',
                        accentLevel: it.level,
                        accentIndex: it.ordinal,
                        velocity: it.velocity * layer.volume,
                        soundId: layer.soundId || 'wood',
                        expected: !it.rest,
                        emit: !it.rest && !muted2 && it.velocity > 0 && layer.volume > 0,
                        frame: frameOf(sc),
                    });
                }
            }
        });

        // ---- cues (separate bus: they sound in muted bars too) ----
        if (!snap.loop && snap.events.cues.length) {
            var occByBar = {};
            snap.occurrences.forEach(function (o) { (occByBar[o.barId] = occByBar[o.barId] || []).push(o); });
            snap.events.cues.forEach(function (cue) {
                (occByBar[cue.target.barId] || []).forEach(function (o) {
                    var target = R.add(o.start, cue.target.offset);
                    for (var n = cue.before.count; n >= 1; n -= 1) {
                        var at;
                        if (cue.before.unit === 'bar') {
                            var idx = o.index - n;
                            if (idx < 0) continue; // before the start: warned at edit time, never moved
                            at = R.add(snap.occurrences[idx].start, cue.target.offset);
                        } else {
                            at = R.sub(target, R.scale(snap.bars[o.barIndex].pulse, n));
                            if (R.lt(at, R.ZERO)) continue;
                        }
                        if (R.lt(at, from) || !R.lt(at, to)) continue;
                        push({
                            eventId: revision + ':cue:' + cue.id + ':' + o.index + ':' + n,
                            occurrence: occurrenceIndexAt(snap, at),
                            iteration: o.iteration,
                            barId: cue.target.barId,
                            score: at,
                            barStart: null,
                            offset: null,
                            layerId: 'cue',
                            kind: 'cue',
                            accentLevel: 'group',
                            accentIndex: n,
                            velocity: 1,
                            soundId: cue.soundId || 'cue',
                            expected: false,
                            emit: true,
                            frame: frameOf(at),
                            label: String(n),
                        });
                    }
                });
            });
        }

        events.sort(function (a, b) { return a.frame - b.frame || (a.layerId < b.layerId ? -1 : a.layerId > b.layerId ? 1 : 0); });
        return { events: events, fermata: fermata, end: ended };
    }

    // Count-in before score position `start`: `bars` bars of the first bar's
    // meter at the tempo in force at `start`, ending exactly at originFrame.
    // Events are not expected beats (never analysed).
    function compileCountIn(options) {
        var snap = options.snapshot;
        var bars = options.bars || 0;
        var pulses = options.pulses || 0;
        if (!bars && !pulses) return [];
        var k = occurrenceIndexAt(snap, options.start);
        var spec = (k === null ? snap.barTemplate : occurrenceAt(snap, k).spec) || snap.barTemplate;
        var tempo = options.tempoMap.tempoAt(options.start);
        var wholePerSecond = tempo.bpm / 60 * R.toNumber(tempo.reference);
        var pulseSec = R.toNumber(spec.pulse) / wholePerSecond;
        var count = bars ? bars * spec.pulseCount : pulses;
        var out = [];
        for (var i = 0; i < count; i += 1) {
            var fromEnd = count - i;
            var inBar = bars ? i % spec.pulseCount : -1;
            out.push({
                eventId: (options.revision || 0) + ':countin:' + (options.label || '') + ':' + i,
                occurrence: -1,
                iteration: 0,
                barId: null,
                score: null,
                layerId: 'countIn',
                kind: 'countIn',
                accentLevel: inBar === 0 ? 'group' : 'pulse',
                accentIndex: i,
                velocity: inBar === 0 ? 1 : 0.7,
                soundId: 'countIn',
                expected: false,
                emit: true,
                frame: options.originFrame - Math.round(options.sampleRate * pulseSec * fromEnd),
                label: String(bars ? (inBar + 1) : fromEnd),
            });
        }
        return out;
    }

    // Density preflight (design 15): conservative events per second at the
    // highest tempo. Refuses before playing instead of thinning events.
    function preflight(snapshot, map) {
        var wps = TM.maxWholeNotesPerSecond(map);
        var bars = snapshot.loop ? [snapshot.barTemplate] : snapshot.bars;
        var practice = snapshot.practice || {};
        var perWholeMax = 0;
        bars.forEach(function (spec) {
            var n = meterPositions(spec, practice).length;
            var perWhole = n / R.toNumber(spec.length);
            if (perWhole > perWholeMax) perWholeMax = perWhole;
        });
        var layerPerWhole = 0;
        snapshot.layers.forEach(function (l) {
            var n = l.rhythm && l.rhythm.length ? l.rhythm.length : l.pulses;
            layerPerWhole += n / R.toNumber(l.cycle);
        });
        var eventsPerSecond = (perWholeMax + layerPerWhole) * wps;
        var max = SM.LIMITS.maxEventsPerSecond;
        return {
            ok: eventsPerSecond <= max,
            eventsPerSecond: eventsPerSecond,
            limit: max,
            reason: eventsPerSecond <= max ? null : 'too-many-events-per-second',
        };
    }

    // Grid size for showing poly layers together (LCM of cycles in units of
    // the common denominator). Large grids are shown per layer instead.
    // Example: 3 against 2 in one 3/4 cycle -> steps 1/4 and 3/8, grid step
    // gcd = 1/8, period lcm = 3/4, 6 cells; the sound is still 3 + 2 clicks.
    function polyGrid(layers) {
        if (!layers.length) return { cells: 0, period: null, step: null, perLayer: true };
        function lcmInt(a, b) { return a / R.gcd(a, b) * b; }
        var steps = layers.map(function (l) { return R.div(l.cycle, R.make(l.pulses, 1)); });
        var den = steps.concat(layers.map(function (l) { return l.cycle; })).reduce(function (acc, x) { return lcmInt(acc, x.d); }, 1);
        var stepNums = steps.map(function (x) { return x.n * (den / x.d); });
        var cycleNums = layers.map(function (l) { return l.cycle.n * (den / l.cycle.d); });
        var g = stepNums.reduce(function (acc, x) { return R.gcd(acc, x); }, 0);
        var period = cycleNums.reduce(function (acc, x) { return lcmInt(acc, x); }, 1);
        var cells = period / g;
        return { period: R.make(period, den), step: R.make(g, den), cells: cells, perLayer: !Number.isSafeInteger(cells) || cells > SM.LIMITS.lcmDisplayCells };
    }

    var api = {
        COMPILER_VERSION: COMPILER_VERSION,
        RANDOM_ALGORITHM_VERSION: RANDOM_ALGORITHM_VERSION,
        compile: compile,
        compileCountIn: compileCountIn,
        preflight: preflight,
        occurrenceAt: occurrenceAt,
        occurrenceIndexAt: occurrenceIndexAt,
        applySwing: applySwing,
        meterPositions: meterPositions,
        polyGrid: polyGrid,
        hash32: hash32,
        unitRandom: unitRandom,
        CompileError: CompileError,
    };

    lib.releases = lib.releases || {};
    lib.eventCompiler = api;
    lib.releases.event_compiler = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
