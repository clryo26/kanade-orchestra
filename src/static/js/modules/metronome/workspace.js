// Metronome: who owns the results and where they are kept (design 12,
// docs/METRONOME_DATA_API_DESIGN.md 5 / 6 / 8).
//
// - History is off by default (historyMode none). The policy lives in memory
//   only and starts as "off" on every visit; nothing is written before the
//   user chooses manual / auto and a destination (this device / account).
// - The owner comes from the server (/api/metronome/identity). A user
//   without account storage (hidden administrator) gets a device-only
//   owner bound to the signed-in device; it is never moved to an account.
// - Each attempt fixes its storage token when it starts (DC-14). Its result
//   is saved with that token even if a newer attempt started meanwhile
//   (DC-19), and is refused after a deletion, logout or consent change.
// - Account uploads go through the local outbox and carry only summaries
//   (storage_remote.js). Calibration values never leave the device.
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};

    var MEMORY_RESULTS = 20; // results kept on screen when history is off
    var MAX_MEMORY_BYTES = 4 * 1024 * 1024; // estimate, details are never kept in memory
    var MAX_PENDING = 10; // manual mode: results waiting for the save button
    var MAX_PENDING_BYTES = 32 * 1024 * 1024; // estimate (analysis results carry their details)
    var CONSENT_VERSION = 'metronome-history-v1';
    var PRACTICE_CONDITION = 'practice:v1';

    function hashText(text) {
        var h = 0x811c9dc5;
        for (var i = 0; i < text.length; i += 1) { h ^= text.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
        return ('00000000' + h.toString(16)).slice(-8);
    }

    // Practice result (trainer.js) -> stored session record (summary only).
    function practiceSession(result, sessionId) {
        var activeMs = Math.round(1000 * result.steps.reduce(function (s, x) { return s + (x.activeSeconds || 0); }, 0));
        var guesses = result.steps.filter(function (s) { return s.guess; }).map(function (s) { return { index: s.index, truthBpm: s.guess.truthBpm, answerBpm: s.guess.answerBpm, errorBpm: s.guess.errorBpm }; });
        var summary = {
            kind: 'practice',
            endReason: result.endReason,
            steps: result.steps.map(function (s) {
                return { index: s.index, iteration: s.iteration, endReason: s.endReason, bars: s.bars, activeSeconds: s.activeSeconds, startBpmTenths: s.startBpmTenths, endBpmTenths: s.endBpmTenths, tempoChanges: s.tempoChanges };
            }),
            tempoGuesses: guesses,
        };
        var scoreSummary = {
            kind: 'practice',
            stepCount: result.program.steps.length,
            repeat: result.program.repeat,
            exercises: result.program.steps.map(function (s) { return s.exercise; }),
        };
        var record = {
            sessionId: sessionId,
            attemptId: result.attemptId,
            programId: result.programRunId,
            kind: 'practice',
            status: result.status === 'complete' ? 'complete' : 'incomplete',
            startedAt: result.startedAt,
            endedAt: result.endedAt,
            activeDurationMs: activeMs,
            durationMs: activeMs,
            conditionKey: PRACTICE_CONDITION,
            versions: { schemaVersion: 1, trainerVersion: 1, compilerVersion: lib.eventCompiler ? lib.eventCompiler.COMPILER_VERSION : 1 },
            scoreSummary: scoreSummary,
            counts: { target: 0, valid: 0, localDetail: 0, extraDetail: 0, extraTotal: 0, groups: 0 },
            summary: summary,
            groups: [],
        };
        record.contentHash = hashText(JSON.stringify([record.scoreSummary, record.summary, record.counts]));
        return record;
    }

    // env: { local (storage_local), remote (storage_remote client), remoteLib,
    //   uuid(), utcNow(), deviceId(), onChange(state), channel? (BroadcastChannel-like) }
    function createWorkspace(env) {
        var policy = { historyMode: 'none', destination: 'local' };
        var identity = null; // { ownerId, kind: 'account' | 'device', historyEpoch, consentRevision, accountConsent }
        // Generations (R-05): each is checked after every await and right
        // before every write, so a write that has not started yet never
        // starts after its condition ended; a write already committed is
        // handled by the deletion itself.
        var ownerEpoch = 0; // logout / owner change
        var selectionEpoch = 0; // saving turned off / destination changed
        var consentEpoch = 0; // account consent changed
        var consentChanging = 0; // consent changes still waiting for the server (no new uploads meanwhile)
        var deleteCounter = 0; // local deletions seen by this page (hint; the DB token is the rule)
        var syncEpoch = 0; // account sync runs
        var attempts = {}; // attemptId -> { token Promise, epochs, destination }
        var memory = [];
        var memoryBytes = 0;
        var pending = []; // manual mode: results waiting for the save button
        var pendingBytes = 0;
        var syncing = null;

        function notify(extra) {
            if (typeof env.onChange === 'function') env.onChange(Object.assign({ policy: Object.assign({}, policy), identity: identity ? { kind: identity.kind, accountConsent: identity.accountConsent } : null, pending: pending.length, memory: memory.slice() }, extra || {}));
        }

        if (env.channel && typeof env.channel.addEventListener === 'function') {
            env.channel.addEventListener('message', function (event) {
                var msg = event && event.data;
                if (msg && msg.type === 'metronome-history-deleted' && identity && msg.ownerId === identity.ownerId) {
                    deleteCounter += 1; // a hint only; the DB token check is the rule
                    notify({ deletedElsewhere: true });
                }
            });
        }

        function deviceOwnerId() {
            var dev = typeof env.deviceId === 'function' ? env.deviceId() : '';
            return 'device-' + hashText('metronome:' + (dev || 'unknown')) + hashText((dev || 'unknown') + ':owner');
        }

        // Resolves the owner (server first; device-only owner otherwise).
        function resolveIdentity() {
            if (identity) return Promise.resolve(identity);
            var epoch = ownerEpoch;
            return env.remote.identity().then(function (r) {
                if (epoch !== ownerEpoch) throw new Error('stale-owner');
                var next;
                if (r.ok && r.data && r.data.accountStorageAvailable && r.data.ownerId) {
                    next = {
                        kind: 'account',
                        ownerId: r.data.ownerId,
                        historyEpoch: r.data.historyEpoch,
                        consentRevision: r.data.consentRevision,
                        accountConsent: r.data.accountConsent === true,
                        ownerBirthToken: r.data.memberBirthToken || null,
                    };
                } else if (r.ok || r.code === 'account-storage-unavailable') {
                    next = { kind: 'device', ownerId: deviceOwnerId(), historyEpoch: 0, consentRevision: 0, accountConsent: false, ownerBirthToken: null };
                } else {
                    throw new Error(r.code || 'identity-failed');
                }
                return env.local.setServerState(next.ownerId, next.historyEpoch, next.consentRevision).catch(function () { return null; }).then(function () {
                    if (epoch !== ownerEpoch) throw new Error('stale-owner');
                    identity = next;
                    return identity;
                });
            });
        }

        function historyOn() {
            return policy.historyMode !== 'none';
        }

        // Is the attempt's saving still wanted and valid?
        function alive(entry) {
            if (entry.ownerEpoch !== ownerEpoch) return 'stale-owner';
            if (entry.selectionEpoch !== selectionEpoch || !historyOn()) return 'SAVE_CANCELLED';
            if (entry.deleteCounter !== deleteCounter) return 'STALE_LOCAL_GENERATION';
            return null;
        }

        // Account sending is valid separately from local saving (round 3,
        // R-05): it needs the account destination, consent, an unchanged
        // consent generation and no consent change waiting for the server.
        // Evaluated again right before the outbox entry is written and before
        // a sync starts, never only once when saving began.
        function accountAllowed(entry) {
            return entry.destination === 'account' && Boolean(identity) && identity.kind === 'account' && Boolean(identity.accountConsent) && entry.consentEpoch === consentEpoch && consentChanging === 0;
        }

        // Called synchronously when an attempt starts (before results exist).
        // The deletion ticket is taken at once (its IndexedDB transaction
        // marks the start in the deletion order, IC-14 rev.); the token is
        // fixed when the identity is known, and the DB refuses an attempt whose
        // owner was deleted after the ticket. Returns a Promise that the
        // analysis waits for before collecting. options.observing: the attempt
        // already produces results (practice plays first); then a ticket that
        // could not be ordered (database not open yet) is not trusted.
        function beginAttempt(attemptId, options) {
            if (!historyOn()) return Promise.resolve({ ok: true, stored: false });
            var o = options && typeof options === 'object' ? options : {};
            var entry = { ownerEpoch: ownerEpoch, selectionEpoch: selectionEpoch, consentEpoch: consentEpoch, deleteCounter: deleteCounter, destination: policy.destination };
            var ticket = typeof env.local.ticket === 'function' ? env.local.ticket() : Promise.resolve(null);
            entry.token = Promise.all([resolveIdentity(), ticket]).then(function (got) {
                var id = got[0];
                var t = got[1];
                var why = alive(entry);
                if (why) throw Object.assign(new Error(why), { code: why });
                if (o.observing && t && !t.ordered) throw Object.assign(new Error('NOT_READY'), { code: 'NOT_READY' });
                return env.local.beginAttempt({ ownerId: id.ownerId, serverHistoryEpoch: id.historyEpoch, consentRevision: id.consentRevision, ownerBirthToken: id.ownerBirthToken }, t);
            });
            entry.token.catch(function () { /* reported when saving */ });
            attempts[attemptId] = entry;
            return entry.token.then(function () { return { ok: true, stored: true }; }, function (error) { return { ok: false, code: error && error.code ? error.code : 'identity-failed' }; });
        }

        function recordBytes(record) {
            try {
                return JSON.stringify(record).length * 2;
            } catch (_) {
                return MAX_PENDING_BYTES;
            }
        }

        // Results kept in memory (history off) are capped by count and size,
        // and never keep detail rows.
        function remember(record) {
            var light = Object.assign({}, record);
            delete light.details;
            var b = recordBytes(light);
            memory.unshift(light);
            memoryBytes += b;
            while (memory.length > MEMORY_RESULTS || (memoryBytes > MAX_MEMORY_BYTES && memory.length > 1)) {
                var gone = memory.pop();
                memoryBytes -= recordBytes(gone);
            }
        }

        function save(record) {
            var entry = attempts[record.attemptId];
            if (!entry) return Promise.resolve({ ok: false, code: 'no-token' });
            var why0 = alive(entry);
            if (why0) return Promise.resolve({ ok: false, code: why0 });
            return entry.token.then(function (token) {
                var why = alive(entry);
                if (why) return { ok: false, code: why };
                var heldBack = record.accountHold || null;
                var toAccount = false; // decided right before the final write
                var operationId = env.uuid();
                var details = record.details || null;
                var row = Object.assign({}, record);
                delete row.details;
                var opened = false;
                var chain = Promise.resolve({ ok: true });
                if (details && details.length) {
                    // Analysis: an open "recording" row, the detail rows in
                    // batches of <= 256 (one transaction each, token checked
                    // in every one), then the final row + upload in one step.
                    chain = env.local.saveSession(token, Object.assign({}, row, { status: 'recording' }), {}).then(function (r) { opened = r.ok; return r; });
                    var batch = 256;
                    for (var i = 0; i < details.length; i += batch) {
                        (function (start) {
                            chain = chain.then(function (prev) {
                                if (!prev.ok) return prev;
                                var w = alive(entry);
                                if (w) return { ok: false, code: w };
                                return env.local.appendDetails(token, row.sessionId, details.slice(start, start + batch), start);
                            });
                        })(i);
                    }
                }
                return chain.then(function (prev) {
                    if (!prev.ok) return prev;
                    var w = alive(entry);
                    if (w) return { ok: false, code: w };
                    toAccount = accountAllowed(entry) && !heldBack;
                    return env.local.saveSession(token, row, { enqueue: toAccount, operationId: operationId, summaryHash: record.contentHash, now: env.utcNow() });
                }).then(function (r) {
                    if (r.ok && toAccount && !accountAllowed(entry)) {
                        // Consent changed while the row was written: the local
                        // record stays, the upload entry is removed before any sync.
                        toAccount = false;
                        var removing = typeof env.local.removeOperation === 'function' ? env.local.removeOperation(token.ownerId, operationId) : null;
                        return Promise.resolve(removing).catch(function () { return null; }).then(function () {
                            return Object.assign({}, r, { consentChanged: true });
                        });
                    }
                    return r;
                }).then(function (r) {
                    delete attempts[record.attemptId];
                    if (!r.ok && opened && (r.code === 'SAVE_CANCELLED' || r.code === 'stale-owner')) {
                        // Saving was turned off half way: the open record is
                        // removed instead of being left as an unfinished row.
                        env.local.deleteSession(token.ownerId, row.sessionId, env.utcNow());
                    }
                    if (r.ok && toAccount) sync();
                    if (r.ok && entry.destination === 'account' && !toAccount) r.localOnly = heldBack || (r.consentChanged ? 'consent-changed' : 'no-consent');
                    return r;
                });
            }, function (error) {
                return { ok: false, code: error && error.code ? error.code : (error && error.message) || 'identity-failed' };
            });
        }

        // Result of an attempt (practice or analysis).
        function recordResult(result) {
            var record = result.kind === 'practice' ? practiceSession(result, env.uuid()) : result.record;
            remember(record);
            if (!historyOn() || !attempts[result.attemptId]) {
                var known = Boolean(attempts[result.attemptId]);
                delete attempts[result.attemptId];
                notify();
                return Promise.resolve({ ok: true, stored: false, reason: known || !historyOn() ? 'history-off' : 'no-token' });
            }
            if (policy.historyMode === 'manual') {
                var b = recordBytes(record);
                if (pending.length >= MAX_PENDING || pendingBytes + b > MAX_PENDING_BYTES) {
                    delete attempts[result.attemptId];
                    notify();
                    return Promise.resolve({ ok: false, stored: false, code: 'PENDING_FULL' });
                }
                pending.push(record);
                pendingBytes += b;
                notify();
                return Promise.resolve({ ok: true, stored: false, pending: true });
            }
            return save(record).then(function (r) { notify({ lastSave: r }); return r; });
        }

        function savePending() {
            var list = pending;
            pending = [];
            pendingBytes = 0;
            return Promise.all(list.map(save)).then(function (results) {
                notify({ lastSave: results[results.length - 1] || null });
                return results;
            });
        }

        function sync() {
            if (syncing || !identity || identity.kind !== 'account') return syncing || Promise.resolve(null);
            if (consentChanging > 0 || !identity.accountConsent) return Promise.resolve(null);
            syncEpoch += 1;
            var mySync = syncEpoch;
            var ctx = { ownerId: identity.ownerId, historyEpoch: identity.historyEpoch, consentRevision: identity.consentRevision };
            var epoch = ownerEpoch;
            var consent = consentEpoch;
            syncing = env.remoteLib.syncOutbox({
                local: env.local,
                remote: env.remote,
                ctx: ctx,
                isCurrent: function (c) { return epoch === ownerEpoch && consent === consentEpoch && consentChanging === 0 && mySync === syncEpoch && identity && c.ownerId === identity.ownerId && c.historyEpoch === identity.historyEpoch && c.consentRevision === identity.consentRevision; },
                buildUpload: function (row) { return env.remoteLib.prepareUpload(row, row.groups || [], row.summary); },
            }).then(function (report) {
                syncing = null;
                if (report.stoppedBy === 'HISTORY_EPOCH' || report.stoppedBy === 'CONSENT_REVISION' || report.stoppedBy === 'CONSENT_REQUIRED') {
                    // Refresh the identity; old uploads are dropped, not moved.
                    identity = null;
                    return resolveIdentity().then(function () { notify({ sync: report }); return report; }, function () { return report; });
                }
                notify({ sync: report });
                return report;
            }, function () { syncing = null; return null; });
            return syncing;
        }

        function setPolicy(next) {
            var before = policy;
            policy = { historyMode: ['none', 'manual', 'auto'].indexOf(next.historyMode) >= 0 ? next.historyMode : 'none', destination: next.destination === 'account' ? 'account' : 'local' };
            if (policy.historyMode !== before.historyMode || policy.destination !== before.destination) selectionEpoch += 1;
            if (policy.historyMode === 'none') {
                pending = [];
                pendingBytes = 0;
                attempts = {};
            }
            notify();
            if (!historyOn()) return Promise.resolve({ ok: true });
            return resolveIdentity().then(function (id) {
                notify();
                return { ok: true, kind: id.kind };
            }, function (error) {
                return { ok: false, code: error.message };
            });
        }

        function setAccountConsent(on) {
            consentEpoch += 1; // uploads prepared before this change are not sent
            // Until the server answered (and the identity was re-read), no new
            // outbox entry is written and no sync starts (round 3, R-05).
            consentChanging += 1;
            var finish = function () { consentChanging = Math.max(0, consentChanging - 1); };
            return resolveIdentity().then(function (id) {
                if (id.kind !== 'account') return { ok: false, code: 'account-storage-unavailable' };
                return env.remote.getPreferences().then(function (r) {
                    if (!r.ok) return r;
                    return env.remote.putPreferences(r.data.revision, on, CONSENT_VERSION);
                }).then(function (r) {
                    if (!r.ok) return r;
                    identity = null; // consent revision changed: re-read, drop old uploads
                    return resolveIdentity().then(function () { notify(); return { ok: true }; });
                });
            }).then(function (r) { finish(); return r; }, function (error) { finish(); throw error; });
        }

        function listHistory() {
            if (!historyOn()) return Promise.resolve({ items: [], off: true });
            return resolveIdentity().then(function (id) {
                return env.local.list(id.ownerId, 50).then(function (items) { return { items: items, kind: id.kind }; });
            });
        }

        function deleteSession(sessionId) {
            return resolveIdentity().then(function (id) {
                return env.local.deleteSession(id.ownerId, sessionId, env.utcNow()).then(function (r) {
                    if (r.ok && id.kind === 'account') env.remote.deleteSession({ historyEpoch: id.historyEpoch }, sessionId, env.uuid());
                    return r;
                });
            });
        }

        // scope: 'device' | 'account'. Only the metronome history; tuner
        // history, settings, presets and calibration stay.
        function deleteAll(scope) {
            return resolveIdentity().then(function (id) {
                deleteCounter += 1;
                pending = [];
                pendingBytes = 0;
                return env.local.deleteAll(id.ownerId).then(function (r) {
                    if (!r.ok || scope !== 'account' || id.kind !== 'account') return r;
                    return env.remote.deleteHistory({ historyEpoch: id.historyEpoch }, env.uuid()).then(function (res) {
                        identity = null; // new history epoch: re-read before any new upload
                        return resolveIdentity().then(function () { return res.ok ? { ok: true, account: true } : { ok: false, code: res.code }; });
                    });
                });
            }).then(function (r) { notify(); return r; });
        }

        // Logout / login / owner change: everything in flight becomes stale.
        function invalidateOwner() {
            ownerEpoch += 1;
            selectionEpoch += 1;
            consentEpoch += 1;
            syncEpoch += 1;
            identity = null;
            attempts = {};
            pending = [];
            pendingBytes = 0;
            memory = [];
            memoryBytes = 0;
            env.remote.invalidate();
            if (env.local && typeof env.local.close === 'function') env.local.close();
            policy = { historyMode: 'none', destination: 'local' };
            notify();
        }

        return {
            CONSENT_VERSION: CONSENT_VERSION,
            policy: function () { return Object.assign({}, policy); },
            identity: function () { return identity ? Object.assign({}, identity) : null; },
            resolveIdentity: function () { return resolveIdentity().then(function (id) { return Object.assign({}, id); }); },
            remote: function () { return env.remote; },
            ownerEpoch: function () { return ownerEpoch; },
            setPolicy: setPolicy,
            setAccountConsent: setAccountConsent,
            beginAttempt: beginAttempt,
            recordResult: recordResult,
            savePending: savePending,
            pendingCount: function () { return pending.length; },
            memory: function () { return memory.slice(); },
            listHistory: listHistory,
            usage: function () { return resolveIdentity().then(function (id) { return env.local.usage(id.ownerId); }); },
            canStore: function (n) { return env.local.canStore(n); },
            exportHistory: function () { return resolveIdentity().then(function (id) { return env.local.exportOwner(id.ownerId); }); },
            // Asked only from the user's explicit button (never automatically).
            requestPersist: function () {
                var st = env.storage;
                if (!st || typeof st.persist !== 'function') return Promise.resolve({ ok: false, code: 'unsupported' });
                return Promise.resolve(st.persist()).then(function (granted) { return { ok: true, granted: Boolean(granted) }; }, function () { return { ok: false, code: 'failed' }; });
            },
            persisted: function () {
                var st = env.storage;
                if (!st || typeof st.persisted !== 'function') return Promise.resolve(null);
                return Promise.resolve(st.persisted()).catch(function () { return null; });
            },
            deleteSession: deleteSession,
            deleteAll: deleteAll,
            sync: sync,
            invalidateOwner: invalidateOwner,
        };
    }

    // One workspace per metronome body (shared by the practice and analysis
    // screens). Logout clears it; the history modules are loaded by the caller
    // only after the user enabled history.
    function ensureWorkspace(bodyApi) {
        var shared = bodyApi.shared;
        if (shared.workspace) return shared.workspace;
        var deps = bodyApi.deps;
        var subscribers = [];
        var channel = null;
        try { channel = deps.BroadcastChannel ? new deps.BroadcastChannel('portal-metronome-history') : null; } catch (_) { channel = null; }
        var local = lib.storageLocal.createLocalHistory({
            indexedDB: deps.indexedDB,
            IDBKeyRange: deps.IDBKeyRange,
            estimate: deps.storageEstimate,
            now: deps.utcNow,
            broadcast: channel ? function (m) { channel.postMessage(m); } : null,
        });
        var remote = lib.storageRemote.createRemoteClient({ request: deps.request, deviceId: deps.deviceId, setTimeout: deps.setTimeout, clearTimeout: deps.clearTimeout });
        var ws = createWorkspace({
            local: local,
            remote: remote,
            remoteLib: lib.storageRemote,
            uuid: deps.uuid,
            utcNow: function () { return new Date(deps.utcNow()).toISOString(); },
            deviceId: deps.deviceId,
            storage: deps.storageManager || null,
            channel: channel,
            onChange: function (state) { subscribers.slice().forEach(function (fn) { try { fn(state); } catch (_) { /* views only */ } }); },
        });
        ws.subscribe = function (fn) {
            subscribers.push(fn);
            return function () { subscribers = subscribers.filter(function (x) { return x !== fn; }); };
        };
        bodyApi.on(function (type) {
            if (type === 'cleared') {
                ws.invalidateOwner();
                if (channel) { try { channel.close(); } catch (_) { /* closed */ } }
            }
        });
        shared.workspace = ws;
        return ws;
    }

    var api = {
        MEMORY_RESULTS: MEMORY_RESULTS,
        ensureWorkspace: ensureWorkspace,
        CONSENT_VERSION: CONSENT_VERSION,
        practiceSession: practiceSession,
        hashText: hashText,
        createWorkspace: createWorkspace,
    };

    lib.releases = lib.releases || {};
    lib.workspace = api;
    lib.releases.workspace = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
