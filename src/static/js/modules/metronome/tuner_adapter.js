// Metronome <-> tuner adapters (design 2.1).
//
// 1. createTunerDisplay: shows the existing tuner inside the metronome's
//    analysis screen. Mounting only shows a placeholder; the tuner (and its
//    microphone, a separate capture owner) starts only from an explicit tap.
//    Unmounting ends only a tuner run this adapter started; it never stops
//    the metronome output. Portal-wide exits (logout, other screens) end both
//    through the common exit (portalTunerLeave). While the tuner runs, every
//    metronome click that sounded is reported to the tuner (external output),
//    so its statistics exclude the click intervals (round 3, A). Playing the
//    tuner's tone together with the clicks needs the tuner's explicit
//    simultaneous + earphones choice (it allows the shared output to mix).
//    Shown to the user: the metronome's normal clicks are only excluded from
//    the tuner statistics; they are not filtered out of the microphone.
// 2. createTrainerClicks: the click / light beat of the tuner's "metronome"
//    exercise on the metronome engine (ScoreSnapshot + transport + one lease
//    of the shared output manager). One click stream only: a second start
//    while the metronome itself plays gets OUTPUT_BUSY (the user chooses).
//    The beat display follows the audio clock; output notifications go to
//    the tuner so its statistics keep excluding the click intervals.
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};
    var CONSUMER = 'tuner-trainer';
    var BASIC_ID = '00000000-0000-4000-8000-00000000e001';
    var DISPLAY_INTERVAL_MS = 30;

    // ----- 1. tuner display -------------------------------------------------------

    // env: { api (metronome body api), host, launcher()?, loadLauncher()?, tunerBody()? }
    function createTunerDisplay(env) {
        var host = env.host;
        var startedGeneration = null;
        var mounted = false;
        var doc = globalObj.document;
        var reportedFrame = null;
        var offTick = null;

        function tunerBody() {
            return typeof env.tunerBody === 'function' ? env.tunerBody() : (globalObj.PortalTunerBody || null);
        }

        // Clicks of the metronome that sounded since the last display tick.
        function reportClicks(frame) {
            var api = env.api;
            var body = tunerBody();
            var t = api.transport ? api.transport() : null;
            if (!body || typeof body.reportOutput !== 'function' || !t || api.state() !== 'running' || !Number.isFinite(frame)) {
                reportedFrame = null;
                return 0;
            }
            if (reportedFrame === null || frame < reportedFrame) {
                reportedFrame = frame;
                return 0;
            }
            var sr = api.sampleRate() || 48000;
            var n = 0;
            t.eventsBetween(reportedFrame, frame + 1).forEach(function (e) {
                if (!e.emit || e.frame < reportedFrame || e.frame > frame) return;
                n += 1;
                try { body.reportOutput({ type: 'click', external: true, sessionId: 'metronome', contextTime: e.frame / sr, frequencies: [] }); } catch (_) { /* the tuner decides */ }
            });
            reportedFrame = frame + 1;
            return n;
        }

        function listen() {
            if (offTick || !env.api || typeof env.api.on !== 'function') return;
            offTick = env.api.on(function (type, payload) {
                if (type === 'tick' && payload) reportClicks(payload.frame);
                if (type === 'state' && payload && payload.state !== 'running') reportedFrame = null;
            });
        }

        function launcher() {
            return typeof env.launcher === 'function' ? env.launcher() : (globalObj.PortalTunerLauncher || null);
        }

        function startTuner(button, status) {
            var l = launcher();
            if (!l) {
                status.textContent = 'チューナーを準備しています。もう一度押してください。';
                var load = typeof env.loadLauncher === 'function' ? env.loadLauncher : globalObj.ensurePortalTunerLauncherLoaded;
                if (typeof load === 'function') Promise.resolve(load()).catch(function () { status.textContent = 'チューナーを読み込めませんでした。'; });
                return;
            }
            // Inside the tap: the tuner's own capture context is primed here.
            if (l.prime() === null) {
                status.textContent = 'チューナーを使えません。';
                return;
            }
            button.disabled = true;
            startedGeneration = l.getGeneration();
            listen();
            void l.enter(host);
        }

        return {
            mount: function () {
                if (mounted) return Promise.resolve({ ok: true });
                mounted = true;
                var box = doc.createElement('div');
                box.className = 'metronome-tuner-placeholder';
                var p = doc.createElement('p');
                p.className = 'metronome-hint';
                p.textContent = 'チューナーは、下のボタンを押すとマイクを使って測定を始めます（メトロノームの解析とは別のマイク入力です）。メトロノームのクリックの前後は、チューナーの統計から除きます。チューナーの基準音とクリックを同時に鳴らすには、チューナーの音の画面で「同時に使う」と「イヤホン」を選んでください。';
                var b = doc.createElement('button');
                b.type = 'button';
                b.className = 'btn btn-primary';
                b.setAttribute('data-metronome-tuner-start', 'true');
                b.textContent = 'チューナーで測定を始める';
                var status = doc.createElement('p');
                status.className = 'metronome-hint';
                status.setAttribute('aria-live', 'polite');
                b.addEventListener('click', function () { startTuner(b, status); });
                box.appendChild(p);
                box.appendChild(b);
                box.appendChild(status);
                host.replaceChildren(box);
                return Promise.resolve({ ok: true });
            },
            // Ends only the tuner run started here (a newer run started
            // elsewhere has another generation and is left alone).
            unmount: function (reason) {
                mounted = false;
                if (offTick) { offTick(); offTick = null; }
                reportedFrame = null;
                var l = launcher();
                if (l && startedGeneration !== null && l.getGeneration() === startedGeneration) l.leave(reason || 'metronome-adapter');
                startedGeneration = null;
                host.replaceChildren();
            },
            startedGeneration: function () { return startedGeneration; },
            reportClicks: reportClicks,
        };
    }

    // ----- 2. clicks for the tuner's metronome exercise -------------------------------

    function snapshotFor(bpmTenths, beatsPerBar) {
        var SM = lib.scoreModel;
        var accentPulse = [];
        for (var i = 0; i < beatsPerBar; i += 1) accentPulse.push(i === 0 ? 1 : 0.7);
        var env = {
            schemaVersion: 1,
            id: BASIC_ID,
            revision: 1,
            kind: 'basic',
            title: 'チューナーの練習',
            payload: {
                tempo: { bpmTenths: bpmTenths, reference: { n: 1, d: 4 } },
                meter: { numerator: beatsPerBar, denominator: 4 },
                groups: accentPulse.map(function () { return 1; }),
                pulse: { n: 1, d: 4 },
                accent: { group: accentPulse.slice(), pulse: accentPulse.slice(), subdivision: 0.35 },
                sound: { kind: 'synth', id: 'click', volume: 1 },
            },
        };
        var v = SM.validatePreset(env);
        if (!v.ok) return { ok: false, errors: v.errors };
        var store = {};
        store[BASIC_ID] = { 1: v.preset };
        return { ok: true, snapshot: SM.buildSnapshot(store, BASIC_ID, 1) };
    }

    // env: { manager() -> page output manager, now() perf ms, setInterval,
    //        clearInterval, setTimeout, clearTimeout }
    function createTrainerClicks(env) {
        var run = null;

        function stop(attemptId) {
            if (!run || (attemptId !== undefined && run.attemptId !== attemptId)) return false;
            var r = run;
            run = null;
            if (r.display !== null) env.clearInterval(r.display);
            if (r.transport) r.transport.stop('trainer-stop');
            if (r.backend) r.backend.dispose();
            if (r.lease) r.manager.release(r.lease);
            if (r.outputOpen && typeof r.onOutput === 'function') r.onOutput({ type: 'end', sessionId: r.attemptId, contextTime: null });
            return true;
        }

        // Synchronous inside the tap (context unlock first).
        // o: { attemptId, bpmTenths, beatsPerBar, beats, audible, onBeat(i, accent), onOutput(event), onEnd() }
        function start(o) {
            if (run) stop();
            var m = env.manager();
            var u = m.unlockFromGesture();
            if (!u.ok) return { ok: false, code: 'unsupported' };
            if (!m.hasClaim()) {
                m.retain('tuner');
                return { ok: false, code: 'claim' };
            }
            var built = snapshotFor(o.bpmTenths, o.beatsPerBar);
            if (!built.ok) return { ok: false, code: 'invalid' };
            var current = { attemptId: o.attemptId, manager: m, lease: null, backend: null, transport: null, display: null, outputOpen: false, onOutput: o.onOutput, lastBeat: -1 };
            var got = m.acquire(CONSUMER, 1, {
                onRevoke: function (why, seq) {
                    if (run !== current) return;
                    if (current.backend) current.backend.revoke(seq);
                    stop(current.attemptId);
                    if (typeof o.onEnd === 'function') o.onEnd('interrupted');
                },
                concurrent: m.concurrentAllowed(),
                guard: 'unverified',
            });
            if (!got.ok) return { ok: false, code: got.code };
            current.lease = got.lease;
            var ctx = m.context();
            var bank = lib.sounds.createBank(ctx.sampleRate);
            var volume = o.audible ? 1 : 0; // light only: nothing sounds, the clock still runs
            current.backend = lib.playback.createMainBackend({ context: ctx, bus: got.lease.bus, bank: bank, volume: function () { return volume; }, now: function () { return Date.now(); } });
            run = current;
            current.backend.init();
            current.transport = lib.transport.createTransport({
                backend: current.backend,
                sampleRate: ctx.sampleRate,
                setTimeout: env.setTimeout,
                clearTimeout: env.clearTimeout,
                permit: function () { return m.permit(); },
                onState: function (info) {
                    if (run !== current) return;
                    if (info.state === 'stopped' || info.state === 'interrupted') {
                        var why = info.reason;
                        stop(current.attemptId);
                        if (typeof o.onEnd === 'function') o.onEnd(why);
                    }
                },
            });
            current.transport.load(built.snapshot, 1);
            var total = Math.max(1, o.beats || 1);
            m.renewPermit().then(function () {
                if (run !== current) return;
                current.transport.start({ countInBars: 0 });
                // Beat display and output notices from the audio clock.
                current.display = env.setInterval(function () {
                    if (run !== current) return;
                    var f = Math.round(ctx.currentTime * ctx.sampleRate);
                    var pos = current.transport.positionAt(f);
                    if (!pos || pos.ended || !pos.spec) return;
                    var beat = pos.occurrence * pos.spec.pulseCount + Math.floor(pos.offset / 0.25 + 1e-9);
                    if (beat === current.lastBeat) return;
                    current.lastBeat = beat;
                    if (beat >= total) {
                        stop(current.attemptId);
                        if (typeof o.onEnd === 'function') o.onEnd('done');
                        return;
                    }
                    if (typeof o.onBeat === 'function') o.onBeat(beat, beat % o.beatsPerBar === 0);
                    if (o.audible && typeof o.onOutput === 'function') {
                        current.outputOpen = true;
                        o.onOutput({ type: 'click', sessionId: current.attemptId, contextTime: ctx.currentTime, frequencies: [beat % o.beatsPerBar === 0 ? 1760 : 1320] });
                    }
                }, DISPLAY_INTERVAL_MS);
            });
            return { ok: true, attemptId: o.attemptId };
        }

        return {
            start: start,
            stop: stop,
            active: function () { return Boolean(run); },
        };
    }

    // The browser wiring used by the tuner page (page output manager).
    function browserTrainerClicks() {
        var audio = globalObj.PortalAudioLib && globalObj.PortalAudioLib.outputManager;
        if (!audio || typeof audio.getPageManager !== 'function') return null;
        if (!lib.transport || !lib.playback || !lib.sounds || !lib.scoreModel) return null;
        return createTrainerClicks({
            manager: function () {
                return audio.getPageManager(function () {
                    return {
                        now: function () { return Date.now(); },
                        setTimeout: globalObj.setTimeout.bind(globalObj),
                        clearTimeout: globalObj.clearTimeout.bind(globalObj),
                        setInterval: globalObj.setInterval.bind(globalObj),
                        clearInterval: globalObj.clearInterval.bind(globalObj),
                    };
                });
            },
            setTimeout: globalObj.setTimeout.bind(globalObj),
            clearTimeout: globalObj.clearTimeout.bind(globalObj),
            setInterval: globalObj.setInterval.bind(globalObj),
            clearInterval: globalObj.clearInterval.bind(globalObj),
        });
    }

    var api = {
        CONSUMER: CONSUMER,
        snapshotFor: snapshotFor,
        createTunerDisplay: createTunerDisplay,
        createTrainerClicks: createTrainerClicks,
        browserTrainerClicks: browserTrainerClicks,
    };

    lib.releases = lib.releases || {};
    lib.tunerAdapter = api;
    lib.releases.tuner_adapter = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
