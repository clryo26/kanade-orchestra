// Metronome: TAP tempo (design 11, tuning values).
//
// Taps are pointer event timestamps on the performance clock (ms). The
// estimate uses the last 8 intervals, removes outliers farther than
// max(3 * MAD, 10 % of the median) from the median, and needs at least 4
// valid intervals. A pause longer than max(3 s, 3 * recent median) starts
// over. The estimate is only applied when the user confirms it, so a few
// taps never change a running tempo by themselves.
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};
    var MAX_INTERVALS = 8;
    var MIN_VALID = 4;

    function median(values) {
        var v = values.slice().sort(function (a, b) { return a - b; });
        var m = v.length >> 1;
        return v.length % 2 ? v[m] : (v[m - 1] + v[m]) / 2;
    }

    function createTapTempo() {
        var taps = [];

        function intervals() {
            var out = [];
            for (var i = 1; i < taps.length; i += 1) out.push(taps[i] - taps[i - 1]);
            return out.slice(-MAX_INTERVALS);
        }

        // Returns the current estimate after this tap.
        function tap(timeMs) {
            if (typeof timeMs !== 'number' || !Number.isFinite(timeMs)) return estimate();
            if (taps.length && timeMs <= taps[taps.length - 1]) return estimate(); // out of order: refused
            if (taps.length >= 2) {
                var recent = median(intervals());
                if (timeMs - taps[taps.length - 1] > Math.max(3000, 3 * recent)) taps = [];
            } else if (taps.length === 1 && timeMs - taps[0] > 3000) {
                taps = [];
            }
            taps.push(timeMs);
            if (taps.length > MAX_INTERVALS + 1) taps = taps.slice(-(MAX_INTERVALS + 1));
            return estimate();
        }

        function estimate() {
            var iv = intervals();
            if (!iv.length) return { bpm: null, valid: 0, taps: taps.length, needed: MIN_VALID };
            var med = median(iv);
            var mad = median(iv.map(function (x) { return Math.abs(x - med); }));
            var limit = Math.max(3 * mad, 0.1 * med);
            var valid = iv.filter(function (x) { return Math.abs(x - med) <= limit; });
            if (valid.length < MIN_VALID) return { bpm: null, valid: valid.length, taps: taps.length, needed: MIN_VALID };
            var mean = valid.reduce(function (s, x) { return s + x; }, 0) / valid.length;
            return { bpm: 60000 / mean, valid: valid.length, excluded: iv.length - valid.length, taps: taps.length, needed: MIN_VALID };
        }

        return { tap: tap, estimate: estimate, reset: function () { taps = []; } };
    }

    var api = { MAX_INTERVALS: MAX_INTERVALS, MIN_VALID: MIN_VALID, createTapTempo: createTapTempo, median: median };

    lib.releases = lib.releases || {};
    lib.tap = api;
    lib.releases.tap = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
