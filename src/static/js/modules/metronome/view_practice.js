// Metronome: practice screen (design 11 / 12, phase 03).
//
// - Practice masks for the current click: play / mute bars, seeded random
//   mute, off-beat, beat feel. Mute changes only whether a click sounds; the
//   expected beats stay (design 12).
// - Accelerando / ritardando: a finite score with one seconds-domain tempo
//   curve ending at a score position (no stored duration, design 6).
// - Step programs and the tempo guessing exercise (trainer.js). The program
//   never starts sound by itself: every step begins from a tap.
// - History: off by default; this device or the account, chosen here.
//   The history modules are loaded only after the user enables history.
