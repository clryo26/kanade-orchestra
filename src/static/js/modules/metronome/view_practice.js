        function historyStatus(r) {
            if (!r) return;
            if (r.ok && r.stored === false && r.pending) historyMsg.textContent = '保存待ちの記録があります。';
            else if (r.ok && r.stored === false) historyMsg.textContent = '記録は保存していません（画面を離れると消えます）。';
            else if (r.ok && r.localOnly === 'too-long') historyMsg.textContent = 'この端末に保存しました（30分を超えるためアカウントには送りません）。';
            else if (r.ok && r.localOnly) historyMsg.textContent = 'この端末に保存しました（アカウントへの同意がないため送っていません）。';
            else if (r.ok) historyMsg.textContent = '保存しました。';
            else {
                var msgs = { STALE_LOCAL_GENERATION: '記録が削除されたため、この結果は保存しませんでした。', QUOTA: '端末の空き容量が足りないため保存できませんでした（再生には影響しません）。記録を書き出してから古い記録を削除してください。', BUDGET: 'この端末の記録の上限（64 MiB）に達したため保存できませんでした。記録を書き出してから古い記録を削除してください。', PENDING_FULL: '保存待ちの記録が多すぎます。先に保存するか、保存しない設定にしてください。', SAVE_CANCELLED: '保存しない設定に変わったため、保存しませんでした。', 'stale-owner': 'ログイン状態が変わったため保存しませんでした。', OWNER_MISMATCH: '本人確認が変わったため保存しませんでした。' };
                historyMsg.textContent = msgs[r.code] || '保存できませんでした（再生には影響しません）。';
            }
        }

        function chip() {
            var p = workspace ? workspace.policy() : { historyMode: 'none' };
            api.setChip('save', p.historyMode === 'none' ? '記録：保存しない' : '記録：' + (p.destination === 'account' ? 'アカウント' : 'この端末') + (workspace && workspace.pendingCount() ? '（保存待ち ' + workspace.pendingCount() + '）' : ''));
        }

        function refreshUsage() {
            if (!workspace || workspace.policy().historyMode === 'none') { usageText.textContent = ''; return; }
            workspace.usage().then(function (u) {
                if (destroyed) return;
                var mib = function (b) { return (b / 1048576).toFixed(1); };
                usageText.textContent = 'この端末の記録：約 ' + mib(u.totalBytes) + ' MiB ／ 上限 ' + mib(u.budgetBytes) + ' MiB（見積り）。上限に近づいたら、書き出してから古い記録を削除してください。古い記録を自動では消しません。';
            }, function () { usageText.textContent = ''; });
            workspace.persisted().then(function (p) {
                if (destroyed || p === null) return;
                persistBtn.textContent = p ? 'ブラウザーに保持を求めています' : 'ブラウザーに記録を消さないよう求める';
            });
        }

        function refreshHistory() {
            if (!workspace) return;
            refreshUsage();
            workspace.listHistory().then(function (res) {
                if (destroyed) return;
                historyList.replaceChildren();
                if (res.off) return;
                if (!res.items.length) historyList.appendChild(h('p', { className: 'metronome-hint', text: '保存した記録はありません。' }));
                res.items.forEach(function (row) {
                    var started = String(row.startedAt || '').replace('T', ' ').slice(0, 16);
                    var steps = row.summary && row.summary.steps ? row.summary.steps.length : 0;
                    var guesses = row.summary && row.summary.tempoGuesses ? row.summary.tempoGuesses.map(function (g) { return '差' + (g.errorBpm > 0 ? '+' : '') + g.errorBpm; }).join(' ') : '';
                    var label = started + '　' + (row.kind === 'practice' ? '練習' : '解析') + '　' + steps + 'ステップ　' + Math.round((row.activeDurationMs || 0) / 1000) + '秒' + (row.status !== 'complete' ? '（途中）' : '') + (guesses ? '　' + guesses : '');
                    var del = h('button', { type: 'button', className: 'btn btn-outline-danger', 'aria-label': started + 'の記録を削除', text: '削除' });
                    del.addEventListener('click', function () {
                        workspace.deleteSession(row.sessionId).then(function () { refreshHistory(); });
                    });
                    historyList.appendChild(h('div', { className: 'metronome-preset' }, [h('span', { className: 'metronome-preset-title', text: label }), del]));
                });
            }, function () { historyMsg.textContent = '記録を読み込めませんでした。'; });
        }

        function onWorkspace(state) {
            if (destroyed) return;
            var p = state.policy;
            saveNow.disabled = !state.pending;
            var on = p.historyMode !== 'none';
            deleteDevice.disabled = !on;
            var account = state.identity && state.identity.kind === 'account';
            consent.disabled = !(on && p.destination === 'account' && account);
            consent.checked = Boolean(state.identity && state.identity.accountConsent);
            deleteAccount.disabled = !(on && account);
            exportBtn.disabled = !on;
            persistBtn.disabled = !on;
            if (on && p.destination === 'account' && state.identity && !account) historyMsg.textContent = 'このアカウントではアカウント保存を使えません。この端末に保存します。';
            if (state.deletedElsewhere) refreshHistory();
            chip();
        }

        function ensureHistory() {
            if (workspace) return Promise.resolve(workspace);
            return Promise.resolve(deps.ensureGroup(HISTORY_GROUP)).then(function () {
                if (destroyed) return null;
                workspace = L.workspace.ensureWorkspace(api);
                wsOff = workspace.subscribe(onWorkspace);
                return workspace;
            });
        }

        function changePolicy() {
            var next = { historyMode: historyMode.value, destination: historyDest.value };
            if (next.historyMode === 'none' && !workspace) { chip(); return; }
            ensureHistory().then(function (ws) {
                if (!ws) return;
                return ws.setPolicy(next).then(function (r) {
                    if (!r.ok) historyMsg.textContent = '本人情報を確認できないため、記録を保存できません。';
                    else historyMsg.textContent = next.historyMode === 'none' ? '記録を保存しません。' : (r.kind === 'device' && next.destination === 'account' ? 'このアカウントではアカウント保存を使えません。この端末に保存します。' : '記録の保存方法を変更しました。');
                    refreshHistory();
                    chip();
                });
            }, function () { historyMsg.textContent = '記録の機能を読み込めませんでした。'; });
        }
        historyMode.addEventListener('change', changePolicy);
        historyDest.addEventListener('change', changePolicy);
        consent.addEventListener('change', function () {
            if (!workspace) return;
            var want = consent.checked;
            workspace.setAccountConsent(want).then(function (r) {
                historyMsg.textContent = r.ok ? (want ? '同意しました。今後の記録の要約をアカウントへ送ります。' : '同意を取り消しました。送信していない記録はアカウントへ送りません。') : '同意の変更を保存できませんでした。';
            });
        });
        saveNow.addEventListener('click', function () {
            if (!workspace) return;
            workspace.savePending().then(function (results) { historyStatus(results[results.length - 1]); refreshHistory(); });
        });
        function confirmDelete(text) {
            return typeof globalObj.confirm !== 'function' || globalObj.confirm(text);
        }
        exportBtn.addEventListener('click', function () {
            if (!workspace) return;
            workspace.exportHistory().then(function (data) {
                if (typeof deps.download === 'function') deps.download('metronome-history.json', JSON.stringify(data), 'application/json');
                historyMsg.textContent = data.sessions.length + ' 件の記録を書き出しました。';
            }, function () { historyMsg.textContent = '書き出せませんでした。'; });
        });
        persistBtn.addEventListener('click', function () {
            if (!workspace) return;
            workspace.requestPersist().then(function (r) {
                historyMsg.textContent = !r.ok ? 'このブラウザーでは求められませんでした。' : (r.granted ? 'ブラウザーが記録を保持するようになりました（バックアップではありません）。' : 'ブラウザーが求めに応じませんでした。容量が足りなくなると消えることがあります。書き出しもご利用ください。');
                refreshUsage();
            });
        });
        deleteDevice.addEventListener('click', function () {
            if (!workspace || !confirmDelete('この端末のメトロノームの記録をすべて削除します。チューナーの記録・設定・プリセットは残ります。よろしいですか。')) return;
            workspace.deleteAll('device').then(function (r) { historyMsg.textContent = r.ok ? 'この端末の記録を削除しました。' : '削除できませんでした。'; refreshHistory(); });
        });
        deleteAccount.addEventListener('click', function () {
            if (!workspace || !confirmDelete('この端末とアカウントのメトロノームの記録をすべて削除します。チューナーの記録・設定・プリセットは残ります。よろしいですか。')) return;
            workspace.deleteAll('account').then(function (r) { historyMsg.textContent = r.ok ? 'この端末とアカウントの記録を削除しました。' : 'アカウントの記録を削除できませんでした（' + (r.code || '通信') + '）。'; refreshHistory(); });
        });

