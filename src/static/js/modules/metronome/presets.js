// Metronome: named presets on this device (data design 3).
//
// IndexedDB "portalMetronomePresets" (version 1), store "presets" keyed by
// [id, revision]. Presets are written only when the user saves one; they
// never go to localStorage (shared, small) and never to the account
// automatically. Caps (tuning values): 60 presets, 256 KiB each, 2 MiB in
// total — the strictest applies; nothing is moved or deleted silently.
// Every record is validated on save AND on load; an unknown schema or a
// failed upgrade leaves the data untouched (read-only).
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var DB_NAME = 'portalMetronomePresets';
    var DB_VERSION = 1;
    var LIMITS = { count: 60, bytesEach: 256 * 1024, bytesTotal: 2 * 1024 * 1024, importBytes: 2 * 1024 * 1024 };
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};

    function byteLength(text) {
        return lib.settings ? lib.settings.utf8Bytes(text) : unescape(encodeURIComponent(text)).length;
    }

    // env: { indexedDB, validate(envelope) -> { ok, errors } }
    function createPresetStore(env) {
        var db = null;
        var status = 'closed';

        function open() {
            if (db) return Promise.resolve({ ok: status === 'open', status: status });
            var factory = env.indexedDB;
            if (!factory || typeof factory.open !== 'function') {
                status = 'unavailable';
                return Promise.resolve({ ok: false, status: status });
            }
            return new Promise(function (resolve) {
                var req;
                try {
                    req = factory.open(DB_NAME, DB_VERSION);
                } catch (_) {
                    status = 'unavailable';
                    resolve({ ok: false, status: status });
                    return;
                }
                req.onupgradeneeded = function (event) {
                    if (event.oldVersion < 1) req.result.createObjectStore('presets', { keyPath: ['id', 'revision'] });
                };
                req.onsuccess = function () {
                    db = req.result;
                    status = db.objectStoreNames.contains('presets') ? 'open' : 'readonly';
                    db.onversionchange = function () { try { db.close(); } catch (_) { /* ignore */ } db = null; status = 'closed'; };
                    resolve({ ok: status === 'open', status: status });
                };
                req.onerror = function () {
                    status = req.error && req.error.name === 'VersionError' ? 'readonly' : 'unavailable';
                    resolve({ ok: false, status: status });
                };
            });
        }

        function all() {
            if (!db) return Promise.resolve([]);
            return new Promise(function (resolve, reject) {
                var req = db.transaction(['presets'], 'readonly').objectStore('presets').getAll();
                req.onsuccess = function () { resolve(req.result || []); };
                req.onerror = function () { reject(req.error); };
            });
        }

        // Latest valid revision of every preset; invalid records are reported, not deleted.
        function list() {
            return open().then(function () { return all(); }).then(function (rows) {
                var latest = {};
                var invalid = 0;
                rows.forEach(function (r) {
                    var v = env.validate(r.envelope);
                    if (!v.ok) { invalid += 1; return; }
                    if (!latest[r.id] || latest[r.id].revision < r.revision) latest[r.id] = r;
                });
                return { items: Object.keys(latest).map(function (k) { return latest[k]; }).sort(function (a, b) { return b.savedAt - a.savedAt; }), invalid: invalid };
            });
        }

        function save(envelope, savedAt) {
            var v = env.validate(envelope);
            if (!v.ok) return Promise.resolve({ ok: false, reason: 'invalid', errors: v.errors });
            var text = JSON.stringify(envelope);
            var bytes = byteLength(text);
            if (bytes > LIMITS.bytesEach) return Promise.resolve({ ok: false, reason: 'too-large' });
            return open().then(function (o) {
                if (!o.ok) return { ok: false, reason: o.status };
                return all().then(function (rows) {
                    var ids = {};
                    var total = 0;
                    rows.forEach(function (r) { ids[r.id] = true; total += r.bytes || 0; });
                    if (!ids[envelope.id] && Object.keys(ids).length >= LIMITS.count) return { ok: false, reason: 'too-many' };
                    if (total + bytes > LIMITS.bytesTotal) return { ok: false, reason: 'quota' };
                    return new Promise(function (resolve) {
                        var tx = db.transaction(['presets'], 'readwrite');
                        tx.objectStore('presets').put({ id: envelope.id, revision: envelope.revision, kind: envelope.kind, title: envelope.title, savedAt: savedAt, bytes: bytes, envelope: JSON.parse(text) });
                        tx.oncomplete = function () { resolve({ ok: true }); };
                        tx.onerror = function () { resolve({ ok: false, reason: tx.error && tx.error.name === 'QuotaExceededError' ? 'quota' : 'write-failed' }); };
                        tx.onabort = function () { resolve({ ok: false, reason: 'write-failed' }); };
                    });
                });
            });
        }

        // Deletes every revision of a preset (snapshots already used by a
        // performance are copies and stay valid).
        function remove(id) {
            return open().then(function (o) {
                if (!o.ok) return { ok: false, reason: o.status };
                return all().then(function (rows) {
                    return new Promise(function (resolve) {
                        var tx = db.transaction(['presets'], 'readwrite');
                        var store = tx.objectStore('presets');
                        rows.filter(function (r) { return r.id === id; }).forEach(function (r) { store.delete([r.id, r.revision]); });
                        tx.oncomplete = function () { resolve({ ok: true }); };
                        tx.onerror = function () { resolve({ ok: false, reason: 'write-failed' }); };
                    });
                });
            });
        }

        // Export / import as a JSON bundle ({ format, presets: [envelopes] }).
        function exportBundle() {
            return list().then(function (res) {
                return { format: 'portal-metronome-presets', schemaVersion: 1, presets: res.items.map(function (r) { return r.envelope; }) };
            });
        }

        function importBundle(text, savedAt) {
            if (typeof text !== 'string' || byteLength(text) > LIMITS.importBytes) return Promise.resolve({ ok: false, reason: 'too-large' });
            var data;
            try { data = JSON.parse(text); } catch (_) { return Promise.resolve({ ok: false, reason: 'invalid-json' }); }
            if (!data || data.format !== 'portal-metronome-presets' || !Array.isArray(data.presets)) return Promise.resolve({ ok: false, reason: 'invalid-format' });
            if (data.presets.length > LIMITS.count) return Promise.resolve({ ok: false, reason: 'too-many' });
            var invalid = data.presets.filter(function (p) { return !env.validate(p).ok; });
            if (invalid.length) return Promise.resolve({ ok: false, reason: 'invalid', count: invalid.length });
            var chain = Promise.resolve({ ok: true, imported: 0 });
            data.presets.forEach(function (p) {
                chain = chain.then(function (acc) {
                    if (!acc.ok) return acc;
                    return save(p, savedAt).then(function (r) { return r.ok ? { ok: true, imported: acc.imported + 1 } : r; });
                });
            });
            return chain;
        }

        return {
            open: open,
            list: list,
            save: save,
            remove: remove,
            exportBundle: exportBundle,
            importBundle: importBundle,
            status: function () { return status; },
            close: function () { if (db) { try { db.close(); } catch (_) { /* ignore */ } } db = null; status = 'closed'; },
        };
    }

    var api = { DB_NAME: DB_NAME, DB_VERSION: DB_VERSION, LIMITS: LIMITS, createPresetStore: createPresetStore };

    lib.releases = lib.releases || {};
    lib.presets = api;
    lib.releases.presets = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
