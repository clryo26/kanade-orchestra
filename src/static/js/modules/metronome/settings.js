// Metronome: device settings (data design 3).
//
// localStorage "portalMetronomeSettings" holds only small settings and is
// written ONLY after the user chose "この端末に設定を保存". Turning it off
// deletes the key (the current in-memory settings stay). Size cap 16 KiB
// (tuning value): localStorage is shared by the whole portal (login state
// lives there too), so a failed or oversized write never touches other
// keys and never stops playback. An unknown schemaVersion is left as is
// (read-only) instead of being overwritten.
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var KEY = 'portalMetronomeSettings';
    var SCHEMA_VERSION = 1;
    var MAX_BYTES = 16 * 1024;
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};

    var DEFAULTS = {
        applyMode: 'nextPulse', // immediate | nextPulse | nextBar
        countInBars: 0,
        volume: 0.6,
        soundId: 'click',
        visual: 'pendulum', // pendulum | dots | static
        wakeLock: false,
        vibration: false,
        timerMinutes: 0,
        theme: 'auto',
        lastBasic: null, // payload of the basic preset being edited
        backendMode: 'auto', // auto | worklet | main | chunk (comparison, design 7)
    };

    function utf8Bytes(text) {
        var n = 0;
        for (var i = 0; i < text.length; i += 1) {
            var c = text.charCodeAt(i);
            if (c < 0x80) n += 1;
            else if (c < 0x800) n += 2;
            else if (c >= 0xd800 && c <= 0xdbff) { n += 4; i += 1; }
            else n += 3;
        }
        return n;
    }

    function normalize(input) {
        var s = Object.assign({}, DEFAULTS);
        var x = input && typeof input === 'object' ? input : {};
        if (['immediate', 'nextPulse', 'nextBar'].indexOf(x.applyMode) >= 0) s.applyMode = x.applyMode;
        if (Number.isInteger(x.countInBars) && x.countInBars >= 0 && x.countInBars <= 8) s.countInBars = x.countInBars;
        if (typeof x.volume === 'number' && x.volume >= 0 && x.volume <= 1) s.volume = x.volume;
        if (typeof x.soundId === 'string' && x.soundId.length <= 64) s.soundId = x.soundId;
        if (['pendulum', 'dots', 'static'].indexOf(x.visual) >= 0) s.visual = x.visual;
        s.wakeLock = x.wakeLock === true;
        s.vibration = x.vibration === true;
        if (Number.isInteger(x.timerMinutes) && x.timerMinutes >= 0 && x.timerMinutes <= 120) s.timerMinutes = x.timerMinutes;
        if (['auto', 'light', 'dark'].indexOf(x.theme) >= 0) s.theme = x.theme;
        if (['auto', 'worklet', 'main', 'chunk'].indexOf(x.backendMode) >= 0) s.backendMode = x.backendMode;
        if (x.lastBasic && typeof x.lastBasic === 'object') s.lastBasic = x.lastBasic; // validated by score_model before use
        return s;
    }

    // storage: localStorage-like (getItem/setItem/removeItem), may throw.
    function createSettingsStore(storage) {
        var current = normalize(null);
        var persist = false;
        var readOnly = false;
        var lastError = null;

        function load() {
            readOnly = false;
            var raw = null;
            try { raw = storage ? storage.getItem(KEY) : null; } catch (_) { raw = null; }
            if (!raw) return getAll();
            var parsed = null;
            try { parsed = JSON.parse(raw); } catch (_) { parsed = null; }
            if (!parsed || typeof parsed !== 'object') return getAll();
            if (parsed.schemaVersion !== SCHEMA_VERSION) {
                readOnly = true; // a newer release wrote it: keep it untouched
                return getAll();
            }
            persist = parsed.persistSettings === true;
            current = normalize(parsed.settings);
            return getAll();
        }

        function write() {
            if (!persist || readOnly || !storage) return { ok: !persist, reason: readOnly ? 'read-only' : null };
            var text = JSON.stringify({ schemaVersion: SCHEMA_VERSION, persistSettings: true, settings: current });
            if (utf8Bytes(text) > MAX_BYTES) {
                lastError = 'too-large';
                return { ok: false, reason: 'too-large' };
            }
            try {
                storage.setItem(KEY, text); // only this key; other portal keys are never touched
                lastError = null;
                return { ok: true };
            } catch (_) {
                lastError = 'write-failed';
                return { ok: false, reason: 'write-failed' };
            }
        }

        function set(partial) {
            current = normalize(Object.assign({}, current, partial || {}));
            return write();
        }

        function setPersist(value) {
            if (readOnly) return { ok: false, reason: 'read-only' };
            persist = Boolean(value);
            if (!persist) {
                try { if (storage) storage.removeItem(KEY); } catch (_) { /* nothing else is touched */ }
                return { ok: true };
            }
            return write();
        }

        function getAll() {
            return JSON.parse(JSON.stringify(current));
        }

        return {
            load: load,
            get: getAll,
            set: set,
            setPersist: setPersist,
            isPersisting: function () { return persist; },
            isReadOnly: function () { return readOnly; },
            lastError: function () { return lastError; },
            reset: function () { current = normalize(null); return write(); },
        };
    }

    var api = { KEY: KEY, SCHEMA_VERSION: SCHEMA_VERSION, MAX_BYTES: MAX_BYTES, DEFAULTS: DEFAULTS, normalize: normalize, utf8Bytes: utf8Bytes, createSettingsStore: createSettingsStore };

    lib.releases = lib.releases || {};
    lib.settings = api;
    lib.releases.settings = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
