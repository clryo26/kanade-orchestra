// Metronome: synthesized click sounds (design 10).
//
// Every sound is generated in code (no audio files), so there is nothing to
// license or download. Each buffer is peak-normalised to 1.0; loudness is
// set only by gains (velocity x sound volume x bus x master), which keeps
// the clipping budget computable (design 4).
//
// A sound has variants per accent level: group (bar / group head), pulse
// and subdivision. Buffers are mono Float32Array for the given sample rate.
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)

    var LEVELS = ['group', 'pulse', 'subdivision'];
    // Attack 1 ms (no click from a hard edge), exponential decay; tail ends at
    // exactly 0 so overlapping voices never leave a step.
    var CATALOG = {
        click: { label: 'クリック', kind: 'tone', group: { hz: 1760, ms: 30 }, pulse: { hz: 1320, ms: 25 }, subdivision: { hz: 990, ms: 18 } },
        wood: { label: 'ウッド', kind: 'wood', group: { hz: 1100, ms: 40 }, pulse: { hz: 850, ms: 35 }, subdivision: { hz: 700, ms: 25 } },
        beep: { label: '電子音', kind: 'square', group: { hz: 1046.5, ms: 60 }, pulse: { hz: 880, ms: 50 }, subdivision: { hz: 660, ms: 35 } },
        soft: { label: 'やわらかい音', kind: 'tone', group: { hz: 880, ms: 70 }, pulse: { hz: 660, ms: 60 }, subdivision: { hz: 523.25, ms: 45 } },
        countIn: { label: 'カウント', kind: 'tone', group: { hz: 2093, ms: 40 }, pulse: { hz: 1568, ms: 35 }, subdivision: { hz: 1568, ms: 25 } },
        cue: { label: '出番の合図', kind: 'chirp', group: { hz: 1500, ms: 90 }, pulse: { hz: 1500, ms: 90 }, subdivision: { hz: 1500, ms: 90 } },
    };
    var SELECTABLE = ['click', 'wood', 'beep', 'soft'];

    // Deterministic noise (no Math.random: identical buffers on every load).
    function lcg(seed) {
        var state = seed >>> 0;
        return function () {
            state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
            return state / 4294967296 * 2 - 1;
        };
    }

    function render(kind, spec, sampleRate) {
        var n = Math.max(8, Math.round(sampleRate * spec.ms / 1000));
        var out = new Float32Array(n);
        var attack = Math.max(1, Math.round(sampleRate * 0.001));
        var noise = lcg(Math.round(spec.hz) * 7919);
        var lp = 0;
        for (var i = 0; i < n; i += 1) {
            var t = i / sampleRate;
            // Exponential decay to about -60 dB at the end, then forced to 0.
            var env = Math.exp(-6.9 * i / n) * (i < attack ? i / attack : 1);
            if (i === n - 1) env = 0;
            var v;
            if (kind === 'tone') {
                v = Math.sin(2 * Math.PI * spec.hz * t) * 0.8 + Math.sin(2 * Math.PI * spec.hz * 2 * t) * 0.2;
            } else if (kind === 'square') {
                v = Math.sin(2 * Math.PI * spec.hz * t) > 0 ? 0.6 : -0.6; // band-limited enough at these lengths
                v = v * 0.7 + Math.sin(2 * Math.PI * spec.hz * t) * 0.3;
            } else if (kind === 'wood') {
                // Resonant noise burst: one-pole low-pass of noise plus a decaying tone.
                lp += (noise() - lp) * 0.35;
                v = lp * 0.6 + Math.sin(2 * Math.PI * spec.hz * t) * 0.5;
            } else {
                // Chirp: rising tone, clearly different from the clicks.
                var f = spec.hz * (1 + 0.5 * i / n);
                v = Math.sin(2 * Math.PI * f * t);
            }
            out[i] = v * env;
        }
        // Peak normalisation to exactly 1.0.
        var peak = 0;
        for (var j = 0; j < n; j += 1) peak = Math.max(peak, Math.abs(out[j]));
        if (peak > 0) for (var k = 0; k < n; k += 1) out[k] /= peak;
        return out;
    }

    // Bank of buffers: index = soundIndex(soundId, level). Generated once per
    // sample rate; buffers are shared by all voices.
    function createBank(sampleRate) {
        var ids = Object.keys(CATALOG);
        var buffers = [];
        var index = {};
        ids.forEach(function (id) {
            LEVELS.forEach(function (level) {
                index[id + ':' + level] = buffers.length;
                buffers.push(render(CATALOG[id].kind, CATALOG[id][level], sampleRate));
            });
        });
        function soundIndex(soundId, level) {
            var key = (CATALOG[soundId] ? soundId : 'click') + ':' + (LEVELS.indexOf(level) >= 0 ? level : 'pulse');
            return index[key];
        }
        var maxLength = buffers.reduce(function (m, b) { return Math.max(m, b.length); }, 0);
        return { sampleRate: sampleRate, buffers: buffers, soundIndex: soundIndex, maxLength: maxLength };
    }

    var api = {
        CATALOG: CATALOG,
        SELECTABLE: SELECTABLE,
        LEVELS: LEVELS,
        render: render,
        createBank: createBank,
    };

    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};
    lib.releases = lib.releases || {};
    lib.sounds = api;
    lib.releases.sounds = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
