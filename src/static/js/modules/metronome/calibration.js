// Metronome: microphone capture and the round-trip calibration
// (design 14, docs/METRONOME_DATA_API_DESIGN.md 3).
//
// - The microphone uses its own AudioContext (input owner), never the
//   output manager's context, and is opened only by an explicit tap.
//   Stopping the analysis closes only this capture; the click continues.
// - R-07: every microphone start is its own capture session (context,
//   stream, node, clock mapper, generation). A late success, failure or
//   "ended" of an earlier session can never stop or update the current one.
// - Calibration profiles stay on this device (IDB portalMetronomeCalibration)
//   and only when the user chooses to keep them. They are keyed by an
//   app-made route key (route kind, sample rate, OS / browser family and
//   major version, a hash of the input device label); raw device ids are
//   not stored. A stored profile is only a candidate: it is used when the
//   key, the analyzer version and its age match AND the user confirms it.
//   A route / sample-rate change or an interruption invalidates it.
// - No samples are kept: each block is turned into envelope frames and
//   dropped (onset_adapter.js).
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};

    var DB_NAME = 'portalMetronomeCalibration';
    var DB_VERSION = 1;
    var MAX_PROFILE_AGE_MS = 30 * 24 * 3600 * 1000; // tuning value
    var ROUTES = [
        { value: 'speaker', label: '本体のスピーカーとマイク' },
        { value: 'wired', label: '有線イヤホン・外部スピーカー' },
        { value: 'bluetooth', label: 'Bluetooth' },
    ];
    var PROCESSOR_NAME = 'portal-metronome-capture-v1-' + METRONOME_RELEASE_ID;

    function hashText(text) {
        var h = 0x811c9dc5;
        for (var i = 0; i < text.length; i += 1) { h ^= text.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
        return ('00000000' + h.toString(16)).slice(-8);
    }

    function browserFamily(ua) {
        var s = String(ua || '');
        var m;
        if ((m = /Edg\/(\d+)/.exec(s))) return 'edge' + m[1];
        if ((m = /(?:CriOS|Chrome)\/(\d+)/.exec(s))) return 'chrome' + m[1];
        if ((m = /Firefox\/(\d+)/.exec(s))) return 'firefox' + m[1];
        if ((m = /Version\/(\d+).*Safari\//.exec(s))) return 'safari' + m[1];
        return 'other';
    }

    function osFamily(ua) {
        var s = String(ua || '');
        if (/iPhone|iPad|iPod/.test(s)) return 'ios';
        if (/Android/.test(s)) return 'android';
        if (/Mac OS X/.test(s)) return 'mac';
        if (/Windows/.test(s)) return 'windows';
        return 'other';
    }

    // inputLabel: the microphone track label (hashed, never stored as text).
    function routeKey(route, sampleRate, ua, inputLabel) {
        return [route, Math.round(sampleRate), osFamily(ua), browserFamily(ua), inputLabel ? hashText(String(inputLabel)) : 'nolabel'].join(':');
    }

    // Is a stored profile usable for this capture? Never without the user's
    // confirmation (the result is only "candidate").
    function checkProfile(profile, key, analyzerVersion, nowMs) {
        if (!profile) return { ok: false, reason: 'none' };
        if (profile.routeKey !== key) return { ok: false, reason: 'route-changed' };
        if (profile.analyzerVersion !== analyzerVersion) return { ok: false, reason: 'analyzer-changed' };
        var at = Date.parse(profile.measuredAt);
        if (!Number.isFinite(at) || nowMs - at > MAX_PROFILE_AGE_MS || at > nowMs + 60000) return { ok: false, reason: 'too-old' };
        if (!(profile.madMs >= 0) || !Number.isFinite(profile.offsetMs)) return { ok: false, reason: 'invalid' };
        return { ok: true, candidate: true };
    }

    // Device-only calibration profiles.
    function createCalibrationStore(env) {
        var idb = env.indexedDB;
        var dbPromise = null;

        function open() {
            if (!idb) return Promise.reject(new Error('unavailable'));
            if (!dbPromise) {
                dbPromise = new Promise(function (resolve, reject) {
                    var r = idb.open(DB_NAME, DB_VERSION);
                    r.onupgradeneeded = function (event) {
                        if (event.oldVersion < 1) r.result.createObjectStore('profiles', { keyPath: 'routeKey' });
                    };
                    r.onsuccess = function () {
                        r.result.onversionchange = function () { r.result.close(); dbPromise = null; };
                        resolve(r.result);
                    };
                    r.onerror = function () { dbPromise = null; reject(r.error || new Error('open-failed')); };
                });
            }
            return dbPromise;
        }

        function tx(mode, fn) {
            return open().then(function (db) {
                return new Promise(function (resolve, reject) {
                    var t = db.transaction(['profiles'], mode);
                    var out = fn(t.objectStore('profiles'));
                    t.oncomplete = function () { resolve(out && out.result !== undefined ? out.result : undefined); };
                    t.onabort = function () { reject(t.error || new Error('aborted')); };
                });
            });
        }

        return {
            get: function (key) { return tx('readonly', function (s) { return s.get(key); }); },
            save: function (profile) {
                var clean = {
                    routeKey: profile.routeKey,
                    route: profile.route,
                    sampleRate: profile.sampleRate,
                    browser: profile.browser,
                    analyzerVersion: profile.analyzerVersion,
                    offsetMs: profile.offsetMs,
                    madMs: profile.madMs,
                    matched: profile.matched,
                    method: 'loopback-clicks',
                    measuredAt: profile.measuredAt,
                };
                return tx('readwrite', function (s) { return s.put(clean); });
            },
            remove: function (key) { return tx('readwrite', function (s) { return s.delete(key); }); },
            clear: function () { return tx('readwrite', function (s) { return s.clear(); }); },
        };
    }

    // Microphone capture in its own context. Each begin() makes a session;
    // every callback of a session checks that it is still the current one.
    // env: { getUserMedia, AudioContext, moduleUrl, now() }
    function createCapture(env) {
        var current = null;
        var seq = 0;

        function close(session) {
            if (!session || session.closed) return;
            session.closed = true;
            if (session.node) { try { session.node.port.onmessage = null; session.node.disconnect(); } catch (_) { /* gone */ } }
            if (session.source) { try { session.source.disconnect(); } catch (_) { /* gone */ } }
            if (session.stream) session.stream.getTracks().forEach(function (t) { try { t.stop(); } catch (_) { /* stopped */ } });
            if (session.ctx && typeof session.ctx.close === 'function') { try { session.ctx.close(); } catch (_) { /* closed */ } }
            if (current === session) current = null;
        }

        // Synchronous part inside the tap (context creation / resume). A
        // previous session (still asking for permission, or running) ends.
        function begin() {
            if (!env.AudioContext || !env.getUserMedia) return { ok: false, code: 'unsupported' };
            if (current) close(current);
            var ctx;
            try {
                ctx = new env.AudioContext({ latencyHint: 'interactive' });
                if (typeof ctx.resume === 'function') ctx.resume();
            } catch (_) {
                return { ok: false, code: 'context-failed' };
            }
            seq += 1;
            current = { id: seq, ctx: ctx, stream: null, node: null, source: null, mapper: null, closed: false, label: '' };
            return { ok: true, session: current };
        }

        function isCurrent(session) {
            return session && session === current && !session.closed;
        }

        function start(session, onBlock, onEnded) {
            if (!isCurrent(session)) return Promise.reject(new Error('stale'));
            var c = session.ctx;
            session.mapper = lib.timingAnalysis.createClockMapper(c.sampleRate);
            return env.getUserMedia({ audio: { echoCancellation: false, noiseSuppression: false, autoGainControl: false } }).then(function (s) {
                if (!isCurrent(session)) {
                    s.getTracks().forEach(function (t) { t.stop(); });
                    throw new Error('stale');
                }
                session.stream = s;
                var track = s.getAudioTracks ? s.getAudioTracks()[0] : s.getTracks()[0];
                session.label = track && track.label ? track.label : '';
                s.getTracks().forEach(function (t) {
                    t.addEventListener('ended', function () { if (isCurrent(session) && onEnded) onEnded('track-ended', session); });
                });
                return c.audioWorklet.addModule(env.moduleUrl);
            }).then(function () {
                if (!isCurrent(session)) throw new Error('stale');
                session.source = c.createMediaStreamSource(session.stream);
                session.node = new globalObj.AudioWorkletNode(c, PROCESSOR_NAME, { numberOfInputs: 1, numberOfOutputs: 0 });
                session.node.port.onmessage = function (event) {
                    var m = event.data;
                    if (!isCurrent(session) || !m || m.type !== 'block') return;
                    session.mapper.observe(m.frame + m.samples.length, env.now());
                    onBlock(m.samples, m.frame, session);
                };
                session.source.connect(session.node);
                return { sampleRate: c.sampleRate, mapper: session.mapper, label: session.label, session: session };
            }, function (error) {
                // A failure of this session closes only this session.
                if (isCurrent(session)) close(session);
                throw error;
            });
        }

        return {
            begin: begin,
            start: start,
            stop: function (session) { close(session || current); },
            isCurrent: isCurrent,
            current: function () { return current; },
            active: function () { return Boolean(current && current.stream && !current.closed); },
            sampleRate: function () { return current ? current.ctx.sampleRate : null; },
            mapper: function () { return current ? current.mapper : null; },
        };
    }

    var api = {
        DB_NAME: DB_NAME,
        ROUTES: ROUTES,
        PROCESSOR_NAME: PROCESSOR_NAME,
        MAX_PROFILE_AGE_MS: MAX_PROFILE_AGE_MS,
        browserFamily: browserFamily,
        osFamily: osFamily,
        routeKey: routeKey,
        checkProfile: checkProfile,
        createCalibrationStore: createCalibrationStore,
        createCapture: createCapture,
    };

    lib.releases = lib.releases || {};
    lib.calibration = api;
    lib.releases.calibration = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
