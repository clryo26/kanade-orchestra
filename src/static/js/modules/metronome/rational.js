// Metronome: exact rational numbers for musical positions and note values.
//
// Why: score positions (in whole notes) are the single source of truth for
// the metronome. Floating ticks accumulate rounding error over long pieces,
// tuplets and dotted values; exact fractions do not. Values are plain
// objects { n, d } with d > 0 and gcd(|n|, d) = 1.
//
// Every intermediate product is checked against Number.MAX_SAFE_INTEGER and
// throws RangeError('rational-overflow') instead of silently losing
// precision (design 5: "安全整数を超える有理数はエラーとして説明し、黙って丸めない").
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var MAX = Number.MAX_SAFE_INTEGER;
    // Stored values (presets, history) are limited further (design: |n|, d <= 2^31-1).
    var STORED_MAX = 2147483647;

    function checkSafe(value) {
        if (!Number.isSafeInteger(value)) throw new RangeError('rational-overflow');
        return value;
    }

    function gcd(a, b) {
        a = Math.abs(a);
        b = Math.abs(b);
        while (b) {
            var t = a % b;
            a = b;
            b = t;
        }
        return a;
    }

    function make(n, d) {
        if (d === undefined) d = 1;
        if (!Number.isInteger(n) || !Number.isInteger(d)) throw new TypeError('rational-not-integer');
        if (d === 0) throw new RangeError('rational-zero-denominator');
        checkSafe(n);
        checkSafe(d);
        if (d < 0) {
            n = -n;
            d = -d;
        }
        var g = gcd(n, d) || 1;
        return { n: n / g, d: d / g };
    }

    var ZERO = make(0, 1);
    var ONE = make(1, 1);

    function isRational(x) {
        return Boolean(x) && typeof x === 'object' && Number.isSafeInteger(x.n) && Number.isSafeInteger(x.d) && x.d > 0 && gcd(x.n, x.d) === 1;
    }

    // Accepts { n, d } (any sign of d, not necessarily reduced) or an integer.
    function from(x) {
        if (typeof x === 'number') return make(x, 1);
        if (!x || typeof x !== 'object') throw new TypeError('rational-invalid');
        return make(x.n, x.d);
    }

    // Product of two safe integers, refusing results beyond the safe range.
    function mulInt(a, b) {
        var p = a * b;
        if (!Number.isSafeInteger(p)) throw new RangeError('rational-overflow');
        return p;
    }

    function add(a, b) {
        if (a.d === b.d) return make(checkSafe(a.n + b.n), a.d);
        var g = gcd(a.d, b.d);
        var da = a.d / g;
        var db = b.d / g;
        return make(checkSafe(mulInt(a.n, db) + mulInt(b.n, da)), mulInt(a.d, db));
    }

    function neg(a) {
        return make(-a.n, a.d);
    }

    function sub(a, b) {
        return add(a, neg(b));
    }

    function mul(a, b) {
        // Cross-reduce first to keep intermediates small.
        var g1 = gcd(a.n, b.d) || 1;
        var g2 = gcd(b.n, a.d) || 1;
        return make(mulInt(a.n / g1, b.n / g2), mulInt(a.d / g2, b.d / g1));
    }

    function inv(a) {
        if (a.n === 0) throw new RangeError('rational-zero-division');
        return make(a.d, a.n);
    }

    function div(a, b) {
        return mul(a, inv(b));
    }

    function cmp(a, b) {
        if (a.d === b.d) return a.n === b.n ? 0 : (a.n < b.n ? -1 : 1);
        var g = gcd(a.d, b.d);
        var left = mulInt(a.n, b.d / g);
        var right = mulInt(b.n, a.d / g);
        return left === right ? 0 : (left < right ? -1 : 1);
    }

    function eq(a, b) { return cmp(a, b) === 0; }
    function lt(a, b) { return cmp(a, b) < 0; }
    function le(a, b) { return cmp(a, b) <= 0; }
    function gt(a, b) { return cmp(a, b) > 0; }
    function ge(a, b) { return cmp(a, b) >= 0; }
    function min(a, b) { return le(a, b) ? a : b; }
    function max(a, b) { return ge(a, b) ? a : b; }
    function isZero(a) { return a.n === 0; }
    function isPositive(a) { return a.n > 0; }

    // floor(a / b) as an integer (b > 0).
    function floorDiv(a, b) {
        var q = div(a, b);
        return Math.floor(q.n / q.d);
    }

    // a mod b in [0, b) for b > 0.
    function mod(a, b) {
        return sub(a, mul(b, make(floorDiv(a, b), 1)));
    }

    function scale(a, k) {
        return mul(a, make(k, 1));
    }

    function toNumber(a) {
        return a.n / a.d;
    }

    function toString(a) {
        return a.d === 1 ? String(a.n) : a.n + '/' + a.d;
    }

    // Value of d dots on a note value: base * (2 - 2^-dots).
    function dotted(base, dots) {
        if (!Number.isInteger(dots) || dots < 0) throw new RangeError('rational-invalid-dots');
        var p = Math.pow(2, dots);
        return mul(base, make(2 * p - 1, p));
    }

    // Values allowed in stored data (presets / history): reduced, d <= 2^31-1.
    function isStorable(a) {
        return isRational(a) && Math.abs(a.n) <= STORED_MAX && a.d <= STORED_MAX;
    }

    var api = {
        ZERO: ZERO,
        ONE: ONE,
        STORED_MAX: STORED_MAX,
        make: make,
        from: from,
        isRational: isRational,
        isStorable: isStorable,
        gcd: gcd,
        add: add,
        sub: sub,
        neg: neg,
        mul: mul,
        div: div,
        inv: inv,
        cmp: cmp,
        eq: eq,
        lt: lt,
        le: le,
        gt: gt,
        ge: ge,
        min: min,
        max: max,
        isZero: isZero,
        isPositive: isPositive,
        floorDiv: floorDiv,
        mod: mod,
        scale: scale,
        dotted: dotted,
        toNumber: toNumber,
        toString: toString,
        MAX_SAFE: MAX,
    };

    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};
    lib.releases = lib.releases || {};
    lib.rational = api;
    lib.releases.rational = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
