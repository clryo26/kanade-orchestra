// Metronome: exchangeable playback backends (design 7).
//
// All backends take the same compiled events and implement the same
// contract, so the transport and the views never branch on the backend:
//   init() -> Promise<{ kind, guard }>
//   schedule(events, generation)                append future clicks
//   replaceFrom(frame, events, generation) -> Promise<{ accepted, appliedFrame, late } | { stale }>
//   cancelFrom(frame, generation) -> Promise
//   stop(newGeneration) -> Promise               everything queued is gone
//   renewPermit(untilFrame, permit)              time-limited output guard
//   revoke(seq)                                  permit withdrawn (claim lost / context suspended)
//   currentFrame()                               context clock in frames
//   telemetry() -> { late, rejected, queued, voices }
//   dispose()
//
// Shared rules (R-03): a fence in the past is applied at "now" (late) and
// voices that started at or after the requested fence fade out (5 ms);
// voices before it keep ringing. A replacement that cannot be stored is
// rejected without touching the old queue. Without a current permit nothing
// new starts; a revocation fades everything and needs a newer permit.
//
// "main": look-ahead scheduling of AudioBufferSourceNodes.
// "worklet": click_processor.js renders clicks in the audio thread.
// "chunk": short pre-rendered buffers (CHUNK_SECONDS) for the comparison of
//   design 7; cancelling inside a chunk that already plays closes that
//   chunk's gain at the cut (its tails before the cut are cut too).
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var METRONOME_PROTOCOL = 2;
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};
    var ACK_TIMEOUT_MS = 1000; // tuning value (design 15)
    var STOP_FADE_SECONDS = 0.005;
    var CHUNK_SECONDS = 0.5; // comparison candidate, not an adopted value

    function toVoices(events, bank, volume) {
        var out = [];
        for (var i = 0; i < events.length; i += 1) {
            var e = events[i];
            if (!e.emit) continue;
            var gain = e.velocity * volume;
            if (!(gain > 0)) continue;
            out.push({ frame: e.frame, sound: bank.soundIndex(e.soundId, e.accentLevel), gain: gain });
        }
        return out;
    }

    function permitValid(permit, untilFrame, frame, nowUtc, revokedSeq) {
        if (!permit || permit.seq <= revokedSeq) return false;
        if (frame >= untilFrame) return false;
        return nowUtc <= permit.expiresAtUtcMs;
    }

    // ----- main-thread look-ahead backend --------------------------------------

    // env: { context, bus (AudioNode), bank, volume(), now() UTC ms }
    function createMainBackend(env) {
        var ctx = env.context;
        var sr = ctx.sampleRate;
        var buffers = [];
        var live = []; // { frame, src, gain }
        var generation = 0;
        var late = 0;
        var rejected = 0;
        var permitUntil = 0;
        var permit = null;
        var revokedSeq = 0;
        var utc = typeof env.now === 'function' ? env.now : function () { return Date.now(); };

        function init() {
            buffers = env.bank.buffers.map(function (data) {
                var b = ctx.createBuffer(1, data.length, sr);
                if (typeof b.copyToChannel === 'function') b.copyToChannel(data, 0);
                else b.getChannelData(0).set(data);
                return b;
            });
            // Scheduled sources keep playing while this page is frozen, so this
            // backend cannot prove the time guard by itself (unverified).
            return Promise.resolve({ kind: 'main', guard: 'unverified' });
        }

        function forget(item) {
            var i = live.indexOf(item);
            if (i >= 0) live.splice(i, 1);
            try { item.src.disconnect(); } catch (_) { /* already */ }
            try { item.gain.disconnect(); } catch (_) { /* already */ }
        }

        function startOne(v) {
            var when = v.frame / sr;
            if (when < ctx.currentTime) {
                late += 1; // past: dropped, never squeezed into "now"
                return;
            }
            if (!permitValid(permit, permitUntil, v.frame, utc(), revokedSeq)) {
                rejected += 1; // not permitted
                return;
            }
            var src = ctx.createBufferSource();
            src.buffer = buffers[v.sound];
            var g = ctx.createGain();
            g.gain.value = v.gain;
            src.connect(g);
            g.connect(env.bus);
            var item = { frame: v.frame, src: src, gain: g };
            src.onended = function () { forget(item); };
            src.start(when);
            live.push(item);
        }

        function schedule(events, gen) {
            if (gen !== generation) return 0;
            var voices = toVoices(events, env.bank, env.volume());
            voices.forEach(startOne);
            return voices.length;
        }

        function fadeOrStop(item, nowFrame) {
            try {
                if (item.frame > nowFrame) item.src.stop(0);
                else {
                    item.gain.gain.setTargetAtTime(0, ctx.currentTime, STOP_FADE_SECONDS / 3);
                    item.src.stop(ctx.currentTime + STOP_FADE_SECONDS);
                }
            } catch (_) { /* already stopped */ }
            forget(item);
        }

        // Removes every voice that starts at or after `fromFrame` (fading
        // the ones already sounding).
        function cancelItems(fromFrame) {
            var nowFrame = ctx.currentTime * sr;
            live.slice().forEach(function (item) {
                if (item.frame >= fromFrame) fadeOrStop(item, nowFrame);
            });
        }

        function replaceFrom(frame, events, gen) {
            if (gen !== generation) return Promise.resolve({ stale: true });
            var nowFrame = Math.ceil(ctx.currentTime * sr);
            var lateFence = frame < nowFrame;
            cancelItems(frame);
            schedule(events.filter(function (e) { return e.frame >= (lateFence ? nowFrame : frame); }), gen);
            return Promise.resolve({ accepted: true, appliedFrame: lateFence ? nowFrame : frame, late: lateFence });
        }

        function cancelFrom(frame, gen) {
            if (gen !== generation) return Promise.resolve({ stale: true });
            cancelItems(frame);
            return Promise.resolve({ renderedFrame: Math.round(ctx.currentTime * sr) });
        }

        function stop(newGeneration) {
            if (newGeneration > generation) generation = newGeneration;
            permitUntil = 0;
            var nowFrame = ctx.currentTime * sr;
            live.slice().forEach(function (item) { fadeOrStop(item, nowFrame); });
            return Promise.resolve({ renderedFrame: Math.round(ctx.currentTime * sr) });
        }

        return {
            kind: 'main',
            init: init,
            setGeneration: function (gen) { if (gen > generation) generation = gen; },
            schedule: schedule,
            replaceFrom: replaceFrom,
            cancelFrom: cancelFrom,
            stop: stop,
            renewPermit: function (until, p) {
                if (!p || p.seq <= revokedSeq) return;
                permit = p;
                if (until > permitUntil) permitUntil = until;
            },
            revoke: function (seq) {
                if (seq > revokedSeq) revokedSeq = seq;
                permit = null;
                permitUntil = 0;
                var nowFrame = ctx.currentTime * sr;
                live.slice().forEach(function (item) { fadeOrStop(item, nowFrame); });
            },
            currentFrame: function () { return Math.round(ctx.currentTime * sr); },
            telemetry: function () { return { late: late, rejected: rejected, queued: live.length, voices: live.length }; },
            dispose: function () { stop(generation + 1); buffers = []; },
        };
    }

    // ----- short-buffer (chunk) backend ----------------------------------------

    // env: { context, bus, bank, volume(), now() }
    function createChunkBackend(env) {
        var ctx = env.context;
        var sr = ctx.sampleRate;
        var chunkFrames = Math.round(sr * CHUNK_SECONDS);
        var maxTail = env.bank.buffers.reduce(function (m, b) { return Math.max(m, b.length); }, 0);
        var voices = []; // { frame, sound, gain } in the plan
        var chunks = {}; // index -> { src, gain, start }
        var generation = 0;
        var permitUntil = 0;
        var permit = null;
        var revokedSeq = 0;
        var late = 0;
        var rejected = 0;
        var utc = typeof env.now === 'function' ? env.now : function () { return Date.now(); };

        function stopChunk(index, atTime) {
            var c = chunks[index];
            if (!c) return;
            delete chunks[index];
            try {
                if (atTime === undefined || c.start >= ctx.currentTime) c.src.stop(0);
                else {
                    c.gain.gain.setTargetAtTime(0, atTime, STOP_FADE_SECONDS / 3);
                    c.src.stop(atTime + STOP_FADE_SECONDS);
                }
            } catch (_) { /* already */ }
        }

        // (Re)renders every chunk from `fromIndex` that has not started yet.
        function render(fromIndex) {
            var nowFrame = ctx.currentTime * sr;
            var byChunk = {};
            voices.forEach(function (v) {
                var first = Math.floor(v.frame / chunkFrames);
                var last = Math.floor((v.frame + maxTail) / chunkFrames);
                for (var k = Math.max(first, fromIndex); k <= last; k += 1) (byChunk[k] = byChunk[k] || []).push(v);
            });
            Object.keys(byChunk).forEach(function (key) {
                var k = Number(key);
                var start = k * chunkFrames;
                if (start < nowFrame) return; // already playing: cannot change
                if (!permitValid(permit, permitUntil, start, utc(), revokedSeq)) {
                    rejected += 1;
                    return;
                }
                stopChunk(k);
                var buf = ctx.createBuffer(1, chunkFrames, sr);
                var data = buf.getChannelData(0);
                byChunk[key].forEach(function (v) {
                    var sample = env.bank.buffers[v.sound];
                    for (var i = 0; i < sample.length; i += 1) {
                        var at = v.frame + i - start;
                        if (at >= 0 && at < chunkFrames) data[at] += sample[i] * v.gain;
                    }
                });
                var src = ctx.createBufferSource();
                src.buffer = buf;
                var g = ctx.createGain();
                src.connect(g);
                g.connect(env.bus);
                src.start(start / sr);
                chunks[k] = { src: src, gain: g, start: start / sr };
            });
        }

        function cutFrom(frame) {
            voices = voices.filter(function (v) { return v.frame < frame; });
            var k = Math.floor(frame / chunkFrames);
            Object.keys(chunks).forEach(function (key) {
                var idx = Number(key);
                if (idx > k) stopChunk(idx);
                else if (idx === k) stopChunk(idx, frame / sr);
            });
            render(k);
        }

        return {
            kind: 'chunk',
            init: function () { return Promise.resolve({ kind: 'chunk', guard: 'unverified' }); },
            setGeneration: function (gen) { if (gen > generation) generation = gen; },
            schedule: function (events, gen) {
                if (gen !== generation) return 0;
                var nowFrame = ctx.currentTime * sr;
                var add = toVoices(events, env.bank, env.volume()).filter(function (v) {
                    if (v.frame < nowFrame) { late += 1; return false; }
                    return true;
                });
                if (!add.length) return 0;
                voices = voices.concat(add).sort(function (a, b) { return a.frame - b.frame; });
                render(Math.floor(add[0].frame / chunkFrames));
                return add.length;
            },
            replaceFrom: function (frame, events, gen) {
                if (gen !== generation) return Promise.resolve({ stale: true });
                var nowFrame = Math.ceil(ctx.currentTime * sr);
                var lateFence = frame < nowFrame;
                cutFrom(lateFence ? nowFrame : frame);
                this.schedule(events, gen);
                return Promise.resolve({ accepted: true, appliedFrame: lateFence ? nowFrame : frame, late: lateFence });
            },
            cancelFrom: function (frame, gen) {
                if (gen !== generation) return Promise.resolve({ stale: true });
                cutFrom(Math.max(frame, Math.ceil(ctx.currentTime * sr)));
                return Promise.resolve({ renderedFrame: Math.round(ctx.currentTime * sr) });
            },
            stop: function (newGeneration) {
                if (newGeneration > generation) generation = newGeneration;
                permitUntil = 0;
                voices = [];
                Object.keys(chunks).forEach(function (k) { stopChunk(Number(k), ctx.currentTime); });
                return Promise.resolve({ renderedFrame: Math.round(ctx.currentTime * sr) });
            },
            renewPermit: function (until, p) {
                if (!p || p.seq <= revokedSeq) return;
                permit = p;
                if (until > permitUntil) permitUntil = until;
            },
            revoke: function (seq) {
                if (seq > revokedSeq) revokedSeq = seq;
                permit = null;
                permitUntil = 0;
                voices = [];
                Object.keys(chunks).forEach(function (k) { stopChunk(Number(k), ctx.currentTime); });
            },
            currentFrame: function () { return Math.round(ctx.currentTime * sr); },
            telemetry: function () { return { late: late, rejected: rejected, queued: voices.length, voices: Object.keys(chunks).length }; },
            dispose: function () { this.stop(generation + 1); },
        };
    }

    // ----- AudioWorklet backend ----------------------------------------------

    // env: { context, bus, bank, volume(), moduleUrl, release, setTimeout, clearTimeout, onMessage(m) }
    function createWorkletBackend(env) {
        var ctx = env.context;
        var sr = ctx.sampleRate;
        var node = null;
        var generation = 0;
        var seq = 0;
        var pending = {};
        var stats = { late: 0, rejected: 0, queued: 0, voices: 0 };
        var release = env.release || METRONOME_RELEASE_ID;

        function post(message, transfer) {
            node.port.postMessage(Object.assign({ release: release, protocol: METRONOME_PROTOCOL }, message), transfer || []);
        }

        function request(type, payload, transfer) {
            seq += 1;
            var id = seq;
            return new Promise(function (resolve, reject) {
                var timer = env.setTimeout(function () {
                    delete pending[id];
                    reject(new Error('ACK_TIMEOUT'));
                }, ACK_TIMEOUT_MS);
                pending[id] = { resolve: resolve, timer: timer };
                post(Object.assign({ type: type, requestId: id }, payload), transfer);
            });
        }

        function onMessage(event) {
            var m = event.data || {};
            if (m.release !== release || m.protocol !== METRONOME_PROTOCOL) return;
            if (m.type === 'telemetry') {
                stats = { late: m.late, rejected: m.rejected, unpermitted: m.unpermitted || 0, queued: m.queued, voices: m.voices };
            }
            if (m.requestId && pending[m.requestId]) {
                var p = pending[m.requestId];
                delete pending[m.requestId];
                env.clearTimeout(p.timer);
                p.resolve(m);
            }
            if (typeof env.onMessage === 'function') env.onMessage(m);
        }

        function pack(events) {
            var voices = toVoices(events, env.bank, env.volume());
            var arr = new Float64Array(voices.length * 3);
            voices.forEach(function (v, i) {
                arr[i * 3] = v.frame;
                arr[i * 3 + 1] = v.sound;
                arr[i * 3 + 2] = v.gain;
            });
            return arr;
        }

        function init() {
            return ctx.audioWorklet.addModule(env.moduleUrl).then(function () {
                node = new globalObj.AudioWorkletNode(ctx, 'portal-metronome-click-v1-' + release, {
                    numberOfInputs: 0,
                    numberOfOutputs: 1,
                    outputChannelCount: [1],
                    processorOptions: { release: release, capacity: 4096, maxVoices: 64 },
                });
                node.port.onmessage = onMessage;
                node.connect(env.bus);
                return request('init', { buffers: env.bank.buffers, generation: generation });
            }).then(function (ready) {
                if (!ready || ready.type !== 'ready') throw new Error('VERSION_MISMATCH');
                // The wall-clock check in process() is the verified time guard.
                return { kind: 'worklet', capacity: ready.capacity, guard: ready.wallClock ? 'verified' : 'unverified' };
            });
        }

        return {
            kind: 'worklet',
            init: init,
            setGeneration: function (gen) {
                if (gen <= generation) return;
                generation = gen;
                if (node) post({ type: 'stop', newGeneration: gen });
            },
            schedule: function (events, gen) {
                if (gen !== generation || !node) return 0;
                var arr = pack(events);
                if (arr.length) post({ type: 'append', generation: gen, events: arr }, [arr.buffer]);
                return arr.length / 3;
            },
            replaceFrom: function (frame, events, gen) {
                if (gen !== generation || !node) return Promise.resolve({ stale: true });
                return request('replaceFrom', { generation: gen, frame: frame, events: pack(events) }).then(function (m) {
                    if (m.type === 'stale' || gen !== generation) return { stale: true };
                    return { accepted: m.accepted === true, appliedFrame: m.appliedFrame, late: Boolean(m.late), code: m.code || null };
                });
            },
            cancelFrom: function (frame, gen) {
                if (gen !== generation || !node) return Promise.resolve({ stale: true });
                return request('cancelFrom', { generation: gen, frame: frame });
            },
            stop: function (newGeneration) {
                if (newGeneration > generation) generation = newGeneration;
                if (!node) return Promise.resolve({});
                return request('stop', { newGeneration: newGeneration }).catch(function () { return {}; });
            },
            renewPermit: function (until, p) {
                if (node && p) post({ type: 'permit', generation: generation, until: until, seq: p.seq, expiresAtUtcMs: p.expiresAtUtcMs, claimGeneration: p.claimGeneration });
            },
            revoke: function (s) {
                if (node) post({ type: 'revoke', seq: s });
            },
            currentFrame: function () { return Math.round(ctx.currentTime * sr); },
            telemetry: function () { return Object.assign({}, stats); },
            dispose: function () {
                Object.keys(pending).forEach(function (id) { env.clearTimeout(pending[id].timer); });
                pending = {};
                if (node) {
                    try { post({ type: 'stop', newGeneration: generation + 1 }); } catch (_) { /* closed */ }
                    try { node.disconnect(); } catch (_) { /* already */ }
                    node.port.onmessage = null;
                }
                node = null;
            },
        };
    }

    function workletSupported(globalScope, ctx) {
        return Boolean(ctx && ctx.audioWorklet && typeof ctx.audioWorklet.addModule === 'function' && typeof globalScope.AudioWorkletNode === 'function' && globalScope.isSecureContext !== false);
    }

    var api = {
        PROTOCOL: METRONOME_PROTOCOL,
        ACK_TIMEOUT_MS: ACK_TIMEOUT_MS,
        CHUNK_SECONDS: CHUNK_SECONDS,
        toVoices: toVoices,
        permitValid: permitValid,
        createMainBackend: createMainBackend,
        createChunkBackend: createChunkBackend,
        createWorkletBackend: createWorkletBackend,
        workletSupported: workletSupported,
    };

    lib.releases = lib.releases || {};
    lib.playback = api;
    lib.releases.playback = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
