// Metronome: attack (onset) detection for the timing analysis (design 14).
//
// Same contract as the tuner's level detector (10 ms RMS envelope, an
// onset is confirmed when the level stays above the threshold for 20 ms),
// with a finer hop (2.5 ms) and a rise fit: the reported time is where the
// rise crosses half of its height in dB, searched backwards from the
// confirmed candidate. The 20 ms confirmation is never subtracted blindly.
// Slow attacks (legato, low strings / brass) get attack "unknown" quality
// instead of a guessed time.
//
// Input samples are processed block by block and dropped at once; no audio
// is kept or sent (only times and levels leave this module).
//
// Times are "effectiveFrame2" (twice the input frame index, so half samples
// stay integers) of the input context; timing_analysis maps them to the
// performance clock.
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};

    var ANALYZER_VERSION = 'onset-rise-v1';
    var DEFAULTS = {
        hopMs: 2.5,
        windowMs: 10,
        thresholdDbfs: -50,
        riseDb: 9,
        riseWindowMs: 50,
        confirmMs: 20,
        offsetMs: 30,
        minInterOnsetMs: 50,
        slowAttackMs: 60,
        clipLevel: 0.99,
    };

    function median(values) {
        if (!values.length) return null;
        var s = values.slice().sort(function (a, b) { return a - b; });
        var m = Math.floor(s.length / 2);
        return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
    }

    // Streaming RMS envelope: push(samples, firstFrame) -> frames
    // { effectiveFrame2, rmsDbfs, clipped }.
    function createEnvelope(sampleRate, options) {
        var o = Object.assign({}, DEFAULTS, options || {});
        var hop = Math.max(1, Math.round(sampleRate * o.hopMs / 1000));
        var win = Math.max(hop, Math.round(sampleRate * o.windowMs / 1000));
        var ring = new Float32Array(win);
        var ringPos = 0;
        var filled = 0;
        var sumSq = 0;
        var sinceHop = 0;
        var clipped = false;
        var nextFrame = null;
        return {
            hop: hop,
            window: win,
            push: function (samples, firstFrame) {
                var out = [];
                if (nextFrame !== null && firstFrame !== nextFrame) {
                    // Discontinuous input (dropped block): restart the window.
                    ring.fill(0);
                    sumSq = 0;
                    filled = 0;
                    sinceHop = 0;
                    out.push({ gap: true, effectiveFrame2: firstFrame * 2 });
                }
                for (var i = 0; i < samples.length; i += 1) {
                    var x = samples[i];
                    if (x >= o.clipLevel || x <= -o.clipLevel) clipped = true;
                    var old = ring[ringPos];
                    sumSq += x * x - old * old;
                    ring[ringPos] = x;
                    ringPos = (ringPos + 1) % win;
                    if (filled < win) filled += 1;
                    sinceHop += 1;
                    if (sinceHop >= hop && filled >= win) {
                        sinceHop = 0;
                        var rms = Math.sqrt(Math.max(0, sumSq) / win);
                        // Centre of the window, in half frames.
                        var centre2 = 2 * (firstFrame + i) - (win - 1);
                        out.push({ effectiveFrame2: centre2, rmsDbfs: rms > 1e-9 ? 20 * Math.log10(rms) : -180, clipped: clipped });
                        clipped = false;
                    }
                }
                nextFrame = firstFrame + samples.length;
                return out;
            },
        };
    }

    // Streaming detector over envelope frames -> attacks
    // { effectiveFrame2, rmsDbfs, riseMs, quality: 'ok'|'slow-attack'|'clipped' }.
    function createDetector(sampleRate, options) {
        var o = Object.assign({}, DEFAULTS, options || {});
        var hopFrames2 = 2 * Math.max(1, Math.round(sampleRate * o.hopMs / 1000));
        var riseN = Math.max(1, Math.round(o.riseWindowMs / o.hopMs));
        var confirmN = Math.max(1, Math.round(o.confirmMs / o.hopMs));
        var offN = Math.max(1, Math.round(o.offsetMs / o.hopMs));
        var minGap2 = 2 * Math.round(sampleRate * o.minInterOnsetMs / 1000);
        var peakHoldN = Math.max(1, Math.round(10 / o.hopMs)); // 10 ms without a new peak ends the rise
        var maxRiseN = Math.max(1, Math.round(200 / o.hopMs)); // a rise is followed for 200 ms at most
        var history = [];
        var state = 'off';
        var candidate = null;
        var above = 0;
        var below = 0;
        var lastOnset2 = -Infinity;
        var clipSeen = false;

        function refine(cand) {
            // Rise fit: from the quiet base before the candidate to the peak
            // seen during confirmation, the time where the level crossed the
            // middle of that rise (in dB). Linear interpolation between frames.
            var base = cand.base;
            var peak = cand.peak;
            var mid = base + (peak - base) / 2;
            var pts = cand.points;
            for (var i = 1; i < pts.length; i += 1) {
                if (pts[i].db >= mid && pts[i - 1].db < mid) {
                    var f = (mid - pts[i - 1].db) / (pts[i].db - pts[i - 1].db);
                    return Math.round(pts[i - 1].t2 + f * (pts[i].t2 - pts[i - 1].t2));
                }
            }
            return cand.t2;
        }

        function riseMs(cand) {
            // Time from 10 % to 90 % of the rise of the linear RMS level (a
            // dB scale would make every rise look fast).
            var amp = function (db) { return Math.pow(10, db / 20); };
            var a0 = amp(cand.base);
            var a1 = amp(cand.peak);
            var lo = a0 + 0.1 * (a1 - a0);
            var hi = a0 + 0.9 * (a1 - a0);
            var tLo = null;
            var tHi = null;
            cand.points.forEach(function (p) {
                var a = amp(p.db);
                if (tLo === null && a >= lo) tLo = p.t2;
                if (tHi === null && a >= hi) tHi = p.t2;
            });
            return tLo === null || tHi === null ? null : (tHi - tLo) / 2 / sampleRate * 1000;
        }

        function emit(cand, out) {
            var t2 = refine(cand);
            var rise = riseMs(cand);
            out.push({
                effectiveFrame2: t2,
                rmsDbfs: cand.peak,
                riseMs: rise,
                quality: clipSeen ? 'clipped' : (rise !== null && rise > o.slowAttackMs ? 'slow-attack' : 'ok'),
            });
            lastOnset2 = t2;
        }

        function push(frame) {
            var out = [];
            if (frame.gap) {
                history = [];
                state = 'off';
                candidate = null;
                above = 0;
                below = 0;
                return out;
            }
            var db = frame.rmsDbfs;
            if (frame.clipped) clipSeen = true;
            if (state === 'off') {
                var base = median(history.slice(-riseN));
                if (!candidate) {
                    if (db >= o.thresholdDbfs && (base === null || db >= base + o.riseDb) && frame.effectiveFrame2 - lastOnset2 >= minGap2) {
                        // Keep the last few quiet frames for the rise fit.
                        var back = history.slice(-4).map(function (d, i, arr) { return { t2: frame.effectiveFrame2 - (arr.length - i) * hopFrames2, db: d }; });
                        candidate = { t2: frame.effectiveFrame2, base: base === null ? o.thresholdDbfs - o.riseDb : base, peak: db, points: back.concat([{ t2: frame.effectiveFrame2, db: db }]) };
                        above = 1;
                        clipSeen = frame.clipped === true;
                    }
                } else if (db >= o.thresholdDbfs) {
                    above += 1;
                    candidate.points.push({ t2: frame.effectiveFrame2, db: db });
                    if (db > candidate.peak) candidate.peak = db;
                } else {
                    candidate = null;
                    above = 0;
                }
                if (candidate && above >= confirmN) {
                    // Confirmed: follow the rise to its peak before reporting,
                    // so that the rise time (and slow attacks) can be judged.
                    state = 'rising';
                    candidate.sincePeak = 0;
                    candidate.riseFrames = above;
                    below = 0;
                }
                history.push(db);
                if (history.length > riseN * 4) history.shift();
                return out;
            }
            if (state === 'rising') {
                candidate.points.push({ t2: frame.effectiveFrame2, db: db });
                candidate.riseFrames += 1;
                if (db > candidate.peak + 0.1) {
                    candidate.peak = db;
                    candidate.sincePeak = 0;
                } else {
                    candidate.sincePeak += 1;
                }
                if (candidate.sincePeak >= peakHoldN || candidate.riseFrames >= maxRiseN || db < o.thresholdDbfs) {
                    emit(candidate, out);
                    candidate = null;
                    state = 'on';
                    history.push(db);
                    if (history.length > riseN * 4) history.shift();
                }
                return out;
            }
            if (db < o.thresholdDbfs) {
                below += 1;
                if (below >= offN) {
                    state = 'off';
                    history = [db];
                    below = 0;
                }
            } else {
                below = 0;
                // Re-attack without silence: a fast rise from a dip.
                history.push(db);
                if (history.length > riseN * 4) history.shift();
                var recentMin = Math.min.apply(null, history.slice(-riseN));
                if (db >= recentMin + o.riseDb && frame.effectiveFrame2 - lastOnset2 >= Math.max(minGap2, 2 * Math.round(sampleRate * 0.08))) {
                    state = 'off';
                    history = history.slice(-riseN, -1);
                    return push(frame);
                }
            }
            return out;
        }

        return {
            push: push,
            setThreshold: function (dbfs) { if (typeof dbfs === 'number' && Number.isFinite(dbfs)) o.thresholdDbfs = dbfs; },
            options: o,
        };
    }

    // Noise floor from a quiet period (median level + 12 dB margin).
    function thresholdFromNoise(levels) {
        var m = median(levels.filter(function (x) { return Number.isFinite(x); }));
        if (m === null) return DEFAULTS.thresholdDbfs;
        return Math.max(-70, Math.min(-20, m + 12));
    }

    // Whole buffer helper (tests / offline): samples -> attacks.
    function detect(samples, sampleRate, options) {
        var env = createEnvelope(sampleRate, options);
        var det = createDetector(sampleRate, options);
        var out = [];
        var block = 128;
        for (var i = 0; i < samples.length; i += block) {
            env.push(samples.subarray(i, Math.min(samples.length, i + block)), i).forEach(function (f) {
                det.push(f).forEach(function (a) { out.push(a); });
            });
        }
        return out;
    }

    var api = {
        ANALYZER_VERSION: ANALYZER_VERSION,
        DEFAULTS: DEFAULTS,
        median: median,
        createEnvelope: createEnvelope,
        createDetector: createDetector,
        thresholdFromNoise: thresholdFromNoise,
        detect: detect,
    };

    lib.releases = lib.releases || {};
    lib.onsetAdapter = api;
    lib.releases.onset_adapter = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
