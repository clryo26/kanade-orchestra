// Metronome: AudioWorklet click renderer (design 7, data design 2).
//
// Runs in the audio rendering thread, so drawing or garbage collection on
// the main thread cannot delay a click that is already queued. The main
// thread sends batches of { frame, sound, gain } well ahead of time; this
// processor places each click at its exact sample frame.
//
// Rules:
// - process() allocates nothing: fixed-capacity typed arrays and cursors.
// - A click whose frame is already past is dropped and counted, never
//   squeezed into "now" (design 7: 追い付き連打を禁止).
// - Generations only move forward: a message of an older generation (also a
//   late "stop") never changes the current queue.
// - replaceFrom is all-or-nothing: when the new batch does not fit, the old
//   queue is kept and the request is rejected (accepted: false).
// - Output needs a current permit (time-limited output guard, data design
//   3.1): permitUntil (frames) AND expiresAtUtcMs (wall clock, checked every
//   render quantum, because the frame clock does not advance while the
//   context is suspended). A revocation latches silence until a permit with
//   a newer sequence number arrives; a wall clock that jumps backwards also
//   latches silence.
// - Cancelling (pause / late fence / stop) fades voices that started at or
//   after the cut (5 ms), the same rule as the main-thread backend.
// - Block length is read from the output array each call (not fixed 128).
/* global registerProcessor, AudioWorkletProcessor, currentFrame, sampleRate */
var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
var METRONOME_PROTOCOL = 2;

class PortalMetronomeClickProcessor extends AudioWorkletProcessor {
    constructor(options) {
        super();
        var o = (options && options.processorOptions) || {};
        this.release = o.release || '';
        this.capacity = o.capacity || 4096;
        this.maxVoices = o.maxVoices || 64;
        this.qFrame = new Float64Array(this.capacity);
        this.qSound = new Int32Array(this.capacity);
        this.qGain = new Float32Array(this.capacity);
        this.qHead = 0;
        this.qCount = 0;
        this.vSound = new Int32Array(this.maxVoices);
        this.vPos = new Int32Array(this.maxVoices);
        this.vGain = new Float32Array(this.maxVoices);
        this.vFade = new Float32Array(this.maxVoices); // 1 = full, decreasing during a fade
        this.vFading = new Uint8Array(this.maxVoices);
        this.vStart = new Float64Array(this.maxVoices);
        this.voices = 0;
        this.buffers = [];
        this.generation = -1;
        this.permitUntil = 0;
        this.permitExpiresAt = 0;
        this.permitSeq = 0;
        this.revokedSeq = 0;
        this.lastWall = 0;
        this.clockBroken = false;
        this.fadeStep = 1 / Math.max(1, Math.round(sampleRate * 0.005)); // 5 ms stop fade (tuning value)
        this.late = 0;
        this.rejected = 0;
        this.unpermitted = 0; // queued clicks discarded because no valid permit was there
        this.permitExpired = false;
        this.nextTelemetry = 0;
        this.telemetryInterval = Math.round(sampleRate * 0.1); // 10 Hz
        this.wallClock = typeof Date === 'function' && typeof Date.now === 'function' && Date.now() > 0;
        this.port.onmessage = this.onMessage.bind(this);
    }

    reply(message) {
        message.release = this.release;
        message.protocol = METRONOME_PROTOCOL;
        this.port.postMessage(message);
    }

    // Compacts the ring so that queued events start at index 0.
    compact() {
        if (this.qHead === 0) return;
        for (var i = 0; i < this.qCount; i += 1) {
            this.qFrame[i] = this.qFrame[this.qHead + i];
            this.qSound[i] = this.qSound[this.qHead + i];
            this.qGain[i] = this.qGain[this.qHead + i];
        }
        this.qHead = 0;
    }

    // Number of queued events before `frame` (binary search).
    countBefore(frame) {
        var lo = this.qHead;
        var hi = this.qHead + this.qCount;
        while (lo < hi) {
            var mid = (lo + hi) >> 1;
            if (this.qFrame[mid] < frame) lo = mid + 1; else hi = mid;
        }
        return lo - this.qHead;
    }

    truncateFrom(frame) {
        this.qCount = this.countBefore(frame);
    }

    // events: Float64Array [frame, sound, gain, ...]; false when it does not fit.
    append(events) {
        var n = Math.floor(events.length / 3);
        if (this.qCount + n > this.capacity) return false;
        this.compact();
        var tail = this.qCount ? this.qFrame[this.qCount - 1] : -Infinity;
        for (var i = 0; i < n; i += 1) {
            var f = events[i * 3];
            var at = this.qCount;
            if (f < tail) {
                while (at > 0 && this.qFrame[at - 1] > f) {
                    this.qFrame[at] = this.qFrame[at - 1];
                    this.qSound[at] = this.qSound[at - 1];
                    this.qGain[at] = this.qGain[at - 1];
                    at -= 1;
                }
            } else {
                tail = f;
            }
            this.qFrame[at] = f;
            this.qSound[at] = events[i * 3 + 1];
            this.qGain[at] = events[i * 3 + 2];
            this.qCount += 1;
        }
        return true;
    }

    // Voices that started at or after `frame` fade out (already sounding
    // clicks of the cancelled part are not left ringing).
    fadeFrom(frame) {
        for (var v = 0; v < this.voices; v += 1) if (this.vStart[v] >= frame) this.vFading[v] = 1;
    }

    fadeAll() {
        for (var v = 0; v < this.voices; v += 1) this.vFading[v] = 1;
    }

    silence() {
        this.qHead = 0;
        this.qCount = 0;
        this.fadeAll();
    }

    onMessage(event) {
        var m = event.data || {};
        if (m.release !== this.release || m.protocol !== METRONOME_PROTOCOL) {
            this.reply({ type: 'error', code: 'VERSION_MISMATCH', requestId: m.requestId });
            return;
        }
        if (m.type === 'init') {
            this.buffers = m.buffers || [];
            this.generation = m.generation;
            this.permitUntil = 0;
            this.qHead = 0;
            this.qCount = 0;
            this.voices = 0;
            this.reply({ type: 'ready', requestId: m.requestId, capacity: this.capacity, maxVoices: this.maxVoices, generation: m.generation, wallClock: this.wallClock });
            return;
        }
        if (m.type === 'revoke') {
            if (m.seq > this.revokedSeq) this.revokedSeq = m.seq;
            this.permitUntil = 0;
            this.permitExpiresAt = 0;
            this.silence();
            this.reply({ type: 'revoked', requestId: m.requestId, seq: this.revokedSeq, renderedFrame: currentFrame });
            return;
        }
        if (m.type === 'permit') {
            // Older than a revocation or the current permit: ignored.
            if (m.seq <= this.revokedSeq || m.seq < this.permitSeq || m.generation !== this.generation) return;
            this.permitSeq = m.seq;
            this.permitUntil = m.until;
            this.permitExpiresAt = m.expiresAtUtcMs;
            this.clockBroken = false;
            this.permitExpired = false;
            return;
        }
        if (m.type === 'stop') {
            if (m.newGeneration <= this.generation) {
                this.reply({ type: 'stopped', requestId: m.requestId, generation: this.generation, renderedFrame: currentFrame, stale: true });
                return;
            }
            this.generation = m.newGeneration;
            this.permitUntil = 0;
            this.silence();
            this.reply({ type: 'stopped', requestId: m.requestId, generation: m.newGeneration, renderedFrame: currentFrame });
            return;
        }
        if (m.generation !== this.generation) {
            if (m.requestId) this.reply({ type: 'stale', requestId: m.requestId, generation: this.generation });
            return;
        }
        if (m.type === 'append') {
            var ok = this.append(m.events);
            if (!ok) this.rejected += 1;
            this.reply({ type: ok ? 'accepted' : 'rejected', requestId: m.requestId, generation: m.generation, queued: this.qCount, code: ok ? null : 'QUEUE_FULL' });
            return;
        }
        if (m.type === 'replaceFrom') {
            // All-or-nothing: check the space first, keep the old queue when it does not fit.
            var lateFence = m.frame < currentFrame;
            var cut = lateFence ? currentFrame : m.frame;
            var keep = this.countBefore(cut);
            var n = Math.floor(m.events.length / 3);
            if (keep + n > this.capacity) {
                this.rejected += 1;
                this.reply({ type: 'replaced', requestId: m.requestId, generation: m.generation, fenceFrame: m.frame, accepted: false, code: 'QUEUE_FULL', queued: this.qCount });
                return;
            }
            this.qCount = keep;
            this.append(m.events);
            if (lateFence) this.fadeFrom(m.frame);
            this.reply({ type: 'replaced', requestId: m.requestId, generation: m.generation, fenceFrame: m.frame, appliedFrame: cut, late: lateFence, accepted: true, queued: this.qCount });
            return;
        }
        if (m.type === 'cancelFrom') {
            this.truncateFrom(m.frame);
            this.fadeFrom(m.frame);
            this.reply({ type: 'cancelled', requestId: m.requestId, generation: m.generation, renderedFrame: currentFrame });
        }
    }

    startVoice(sound, offset, gain, frame) {
        if (this.voices >= this.maxVoices) {
            this.rejected += 1;
            return;
        }
        var v = this.voices;
        this.vSound[v] = sound;
        this.vPos[v] = -offset; // starts `offset` samples into this block
        this.vGain[v] = gain;
        this.vFade[v] = 1;
        this.vFading[v] = 0;
        this.vStart[v] = frame;
        this.voices += 1;
    }

    permitted(frame0) {
        if (frame0 >= this.permitUntil) return false;
        if (this.clockBroken) return false;
        if (this.wallClock) {
            var wall = Date.now();
            if (this.lastWall && wall < this.lastWall - 1000) {
                this.clockBroken = true; // the clock went back: not trusted until a new permit
                return false;
            }
            this.lastWall = wall;
            if (wall > this.permitExpiresAt) return false;
        }
        return true;
    }

    process(inputs, outputs) {
        var output = outputs[0];
        if (!output || !output.length) return true;
        var ch0 = output[0];
        var len = ch0.length;
        var frame0 = currentFrame;
        var allowed = this.permitted(frame0);
        if (!allowed && (this.qCount || this.voices)) {
            // Permit expired / revoked: silence and clear (counted, never played later).
            this.unpermitted += this.qCount;
            this.qHead = 0;
            this.qCount = 0;
            this.fadeAll();
            if (!this.permitExpired) {
                this.permitExpired = true;
                this.reply({ type: 'permit-expired', renderedFrame: frame0 });
            }
        }
        // Start queued events falling inside this block.
        while (allowed && this.qCount > 0) {
            var f = this.qFrame[this.qHead];
            if (f >= frame0 + len) break;
            var offset = Math.round(f - frame0);
            if (offset < 0) {
                this.late += 1; // past: dropped, counted
            } else if (this.buffers[this.qSound[this.qHead]]) {
                this.startVoice(this.qSound[this.qHead], offset, this.qGain[this.qHead], f);
            }
            this.qHead += 1;
            this.qCount -= 1;
        }
        if (this.qCount === 0) this.qHead = 0;
        for (var i = 0; i < len; i += 1) ch0[i] = 0;
        var v = 0;
        while (v < this.voices) {
            var buf = this.buffers[this.vSound[v]];
            var pos = this.vPos[v];
            var gain = this.vGain[v];
            var fade = this.vFade[v];
            var fading = this.vFading[v] === 1;
            for (var s = 0; s < len; s += 1) {
                if (pos >= 0) {
                    if (pos >= buf.length) break;
                    if (fading) {
                        fade -= this.fadeStep;
                        if (fade <= 0) { fade = 0; pos = buf.length; break; }
                    }
                    ch0[s] += buf[pos] * gain * fade;
                } else if (fading) {
                    pos = buf.length; // not started yet: never starts
                    break;
                }
                pos += 1;
            }
            this.vPos[v] = pos;
            this.vFade[v] = fade;
            if (pos >= buf.length) {
                // Remove voice v (swap with the last).
                this.voices -= 1;
                this.vSound[v] = this.vSound[this.voices];
                this.vPos[v] = this.vPos[this.voices];
                this.vGain[v] = this.vGain[this.voices];
                this.vFade[v] = this.vFade[this.voices];
                this.vFading[v] = this.vFading[this.voices];
                this.vStart[v] = this.vStart[this.voices];
            } else {
                v += 1;
            }
        }
        for (var c = 1; c < output.length; c += 1) output[c].set(ch0);
        if (frame0 >= this.nextTelemetry) {
            this.nextTelemetry = frame0 + this.telemetryInterval;
            this.reply({ type: 'telemetry', renderedFrame: frame0 + len, queued: this.qCount, voices: this.voices, late: this.late, rejected: this.rejected, unpermitted: this.unpermitted, generation: this.generation, permitted: allowed });
        }
        return true;
    }
}

// Node test hook (the AudioWorklet global scope has no module object).
if (typeof module !== 'undefined' && module.exports) module.exports = { PortalMetronomeClickProcessor: PortalMetronomeClickProcessor, PROTOCOL: METRONOME_PROTOCOL };
if (typeof registerProcessor === 'function') registerProcessor('portal-metronome-click-v1-' + METRONOME_RELEASE_ID, PortalMetronomeClickProcessor);
