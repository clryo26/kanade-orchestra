        var managerOff = [];

        function emit(type, payload) {
            listeners.forEach(function (fn) { try { fn(type, payload); } catch (_) { /* views never break playback */ } });
        }

        // ----- draft (basic preset payload) -----------------------------------------

        function initialDraft() {
            var d = {
                bpmTenths: 1200,
                reference: '1/4',
                meter: [4, 4],
                groups: [1, 1, 1, 1],
                pulse: '1/4',
                subdivision: 'none',
                accent: defaultAccents(4, 4),
                soundId: settings.soundId,
                meterPreset: '4/4',
            };
            if (settings.lastBasic) {
                var candidate = Object.assign({}, d, settings.lastBasic);
                if (buildBasicEnvelope(candidate).ok) d = candidate;
            }
            return d;
        }

        function pulseCountOf(d) {
            return SM.pulseCount(R.make(d.meter[0], d.meter[1]), parseRational(d.pulse));
        }

        function basicPayload(d) {
            var payload = {
                tempo: { bpmTenths: d.bpmTenths, reference: parseRational(d.reference) },
                meter: { numerator: d.meter[0], denominator: d.meter[1] },
                groups: d.groups.slice(),
                pulse: parseRational(d.pulse),
                accent: { group: d.accent.group.slice(), pulse: d.accent.pulse.slice(), subdivision: d.accent.subdivision },
                sound: { kind: 'synth', id: d.soundId, volume: 1 },
            };
            var sub = subdivisionFrom(d.subdivision);
            if (sub) payload.subdivision = sub;
            var p = Object.assign({ countInBars: settings.countInBars }, practice || {});
            if (Object.keys(p).length) payload.practice = p;
            return payload;
        }

        var BASIC_ID = '00000000-0000-4000-8000-00000000b001';
        var ADV_ID = '00000000-0000-4000-8000-00000000a001';
        var SCORE_ID = '00000000-0000-4000-8000-00000000c001';

        function buildBasicEnvelope(d) {
            var env = { schemaVersion: 1, id: BASIC_ID, revision: 1, kind: 'basic', title: '編集中', payload: basicPayload(d) };
            var v = SM.validatePreset(env);
            return { ok: v.ok, envelope: env, preset: v.preset, errors: v.errors };
        }

        // The snapshot of what is being edited: basic, plus the advanced
        // layers and the score when those screens are in use.
        function buildSnapshot() {
            var store = {};
            var b = buildBasicEnvelope(draft);
            if (!b.ok) return { ok: false, errors: b.errors };
            store[BASIC_ID] = { 1: b.preset };
            var topId = BASIC_ID;
            if (advanced && advanced.layers && (advanced.layers.length || advanced.swing)) {
                var adv = { schemaVersion: 1, id: ADV_ID, revision: 1, kind: 'advanced', title: '編集中', payload: { basePresetId: BASIC_ID, baseRevision: 1, layers: advanced.layers } };
                if (advanced.swing) adv.payload.swing = advanced.swing;
                var va = SM.validatePreset(adv);
                if (!va.ok) return { ok: false, errors: va.errors };
                store[ADV_ID] = { 1: va.preset };
                topId = ADV_ID;
            }
            if (scoreDoc && scoreDoc.enabled) {
                var sc = { schemaVersion: 1, id: SCORE_ID, revision: 1, kind: 'score', title: scoreDoc.title || '楽曲', payload: { basePresetId: topId, baseRevision: 1, bars: scoreDoc.bars, tempoMap: scoreDoc.tempoMap, events: scoreDoc.events } };
                if (scoreDoc.conductor) sc.payload.conductor = scoreDoc.conductor;
                var vs = SM.validatePreset(sc);
                if (!vs.ok) return { ok: false, errors: vs.errors };
                store[SCORE_ID] = { 1: vs.preset };
                topId = SCORE_ID;
            }
            try {
                var snap = SM.buildSnapshot(store, topId, 1, { revision: revision });
                // The tempo map is checked here too (curve order, tempos after
                // a metric modulation), so play / edit never meet a throw.
                L.tempoMap.fromSnapshot(snap);
                return { ok: true, snapshot: snap };
            } catch (error) {
                return { ok: false, errors: error.errors || [{ code: error.code || error.message }] };
            }
        }

