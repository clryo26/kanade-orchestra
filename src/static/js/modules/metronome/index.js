    function parseRational(text) {
        var m = /^(\d+)\/(\d+)$/.exec(String(text));
        if (!m) return null;
        return lib.rational.make(Number(m[1]), Number(m[2]));
    }

    function rationalText(r) {
        return r.n + '/' + r.d;
    }

    function subdivisionFrom(value) {
        if (!value || value === 'none') return undefined;
        var parts = String(value).split(':');
        var u = parseRational(parts[0]);
        if (!u) return undefined;
        var out = { unit: { n: u.n, d: u.d } };
        if (parts.length === 3) {
            var n = Number(parts[1]);
            var m = Number(parts[2]);
            var g = lib.rational.gcd(n, m);
            out.tuplet = { n: n / g, m: m / g };
        }
        return out;
    }

    // Default accents: bar head strong, the rest medium.
    function defaultAccents(groupsCount, pulseCount) {
        var group = [];
        for (var i = 0; i < groupsCount; i += 1) group.push(i === 0 ? 1 : 0.8);
        var pulse = [];
        for (var k = 0; k < pulseCount; k += 1) pulse.push(k === 0 ? 1 : 0.7);
        return { group: group, pulse: pulse, subdivision: 0.35 };
    }

