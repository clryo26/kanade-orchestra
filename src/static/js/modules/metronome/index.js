        // State that was last accepted for playing (restored when an edit is
        // refused by a guard, so the editor never shows unplayed settings).
        function rememberApplied() {
            lastApplied = JSON.stringify({ draft: draft, advanced: advanced, scoreDoc: scoreDoc, practice: practice });
        }

        function restoreApplied() {
            if (!lastApplied) return;
            var s = JSON.parse(lastApplied);
            draft = s.draft;
            advanced = s.advanced;
            scoreDoc = s.scoreDoc;
            practice = s.practice;
            renderModels();
        }

        var BOUNDARY_TEXT = { nextBar: '次の小節', immediate: '次の刻み', nextPulse: '次の拍' };

        // Applies the draft: validated; while running, at the chosen boundary.
        // The change is shown as "適用予定" until the backend confirmed the
        // fence (R-03); only then it is announced as applied.
        function applyDraft(source, modeOverride) {
            var built = buildSnapshot();
            if (!built.ok) {
                if (rhythmView) rhythmView.setError(errorText(built.errors));
                shell.showMessage(errorText(built.errors), 'error');
                return Promise.resolve({ ok: false });
            }
            // Guards of running features (timing analysis: target rate) are
            // asked before anything changes (R-04).
            for (var i = 0; i < editGuards.length; i += 1) {
                var g = editGuards[i](built.snapshot);
                if (g && g.ok === false) {
                    restoreApplied();
                    shell.showMessage(g.message || 'この変更は今は使えません。', 'error');
                    return Promise.resolve({ ok: false, code: 'guard' });
                }
            }
            if (rhythmView) rhythmView.setError('');
            shell.showMessage('');
            revision += 1;
            var rev = revision;
            settingsStore.set({ lastBasic: JSON.parse(JSON.stringify(draft)) });
            emit('draft', { source: source });
            if (!transport) {
                rememberApplied();
                return Promise.resolve({ ok: true });
            }
            var mode = modeOverride || settings.applyMode;
            var running = transport.getState() === 'running';
            if (running) shell.showMessage('適用予定：' + BOUNDARY_TEXT[mode] + 'から反映します。', 'info');
            var t = transport;
            return t.edit(built.snapshot, rev, mode).then(function (fence) {
                // Stale: the run it was meant for stopped, paused or restarted
                // before it was applied. The editor returns to what is (or
                // will be) played; a new start loads the latest settings. A
                // newer edit already owns the editor and is left alone.
                if (!fence || fence.stale) {
                    if (rev === revision) restoreApplied();
                    return { ok: false, stale: true };
                }
                rememberApplied();
                if (fence.late) shell.showMessage('変更が少し遅れて反映されました。', 'info');
                else if (running) shell.showMessage('');
                if (fence.fenceFrame !== undefined && running) shell.announce('変更を' + BOUNDARY_TEXT[mode] + 'から反映しました');
                emit('applied', { revision: rev, fence: fence });
                return { ok: true, fence: fence };
            }, function (error) {
                var code = error.code || error.message;
                var text = {
                    'queue-full': '予約がいっぱいのため、変更を反映できませんでした。今の設定のまま続けます。',
                    'fence-rejected': '変更を反映できませんでした。今の設定のまま続けます。',
                    'ack-timeout': '変更の確認が取れなかったため、安全のため停止しました。',
                }[code];
                shell.showMessage(text || errorText([{ code: code }]), 'error');
                return { ok: false, code: code };
            });
        }

        // ----- output / backend ---------------------------------------------------------

        // The page-wide output manager (shared with the tuner).
        function ensureManager() {
            if (!manager) {
                var factory = deps.audioLib.outputManager.getPageManager || null;
                var envM = {
                    AudioContext: deps.AudioContext,
                    locks: deps.locks,
                    indexedDB: deps.indexedDB,
                    audioSession: deps.audioSession,
                    now: deps.utcNow,
                    setTimeout: deps.setTimeout,
                    clearTimeout: deps.clearTimeout,
                    setInterval: deps.setInterval,
                    clearInterval: deps.clearInterval,
                };
                manager = factory && deps.sharedManager !== false ? factory(envM) : deps.audioLib.outputManager.createOutputManager(envM);
                managerOff.push(manager.on('lost', function () {
                    claimState = 'none';
                    interrupt('claim-lost');
                    if (shell && mounted) shell.showMessage('別のタブが音を使い始めたため、このタブの再生を止めました。', 'info');
                }));
                managerOff.push(manager.on('interrupted', function () {
                    if (transport && ['running', 'waiting', 'paused'].indexOf(transport.getState()) >= 0) interrupt('audio-interrupted');
                }));
                managerOff.push(manager.on('ready', function () {
                    claimState = 'held';
                    if (shell && mounted) shell.showMessage('このタブで音を使えるようになりました。もう一度「再生」を押してください。', 'info');
                }));
            }
            return manager;
        }

        // options.keepMessage: do not replace the explanation already shown
        // (e.g. why a takeover was refused).
        function prepareClaim(options) {
            var keep = Boolean(options && options.keepMessage);
            var m = ensureManager();
            if (m.hasClaim()) {
                claimState = 'held';
                return Promise.resolve({ ok: true });
            }
            claimState = 'pending';
            var epoch = launchEpoch;
            return m.retain('metronome').then(function (r) {
                if (epoch !== launchEpoch || !mounted) return { ok: false, reason: 'stale-request' };
                claimState = r.ok ? 'held' : r.reason;
                observedClaim = r.observed || null;
                if (!r.ok && shell && !keep) {
                    if (r.reason === 'busy') shell.showMessage('別のタブでメトロノームまたはチューナーの音を使っています。そちらを止めてから再生してください。', 'info');
                    if (r.reason === 'stale') shell.showMessage('別のタブが応答しません。このタブで使う場合は「このタブで使う」を押してください。確認が取れるまで音は出ません。', 'info');
                    if (r.reason === 'pending-owner') shell.showMessage('前のタブの音が止まったことを確認しています。', 'info');
                    if (r.reason === 'unavailable') shell.showMessage('音声の調停ができないため、再生できません。ページを再読み込みしてください。', 'error');
                }
                if (shell) shell.setTakeover(claimState === 'stale');
                return r;
            });
        }

        // Explicit "use it in this tab" after a confirmation. Never plays by
        // itself: the user taps play again once the old tab is confirmed silent.
        function takeover() {
            var m = ensureManager();
            if (claimState !== 'stale' || !observedClaim) return;
            claimState = 'pending';
            if (shell) shell.setTakeover(false);
            shell.showMessage('前のタブの音が止まったことを確認しています…', 'info');
            var epoch = launchEpoch;
            m.takeoverClaim(observedClaim).then(function (r) {
                if (epoch !== launchEpoch || !mounted) return;
                if (r.ok) {
                    claimState = 'held';
                    shell.showMessage('このタブで音を使えるようになりました。もう一度「再生」を押してください。', 'info');
                } else if (r.reason === 'changed') {
                    claimState = 'none';
                    shell.showMessage('別のタブの状態が変わったため、引き継ぎませんでした（そのタブはまだ動いています）。', 'info');
                    prepareClaim({ keepMessage: true });
                } else if (r.reason === 'waiting-old-tab' || r.reason === 'waiting-old-permit') {
                    claimState = 'pending-owner';
                    shell.showMessage(r.reason === 'waiting-old-tab'
                        ? '前のタブの音が止まったことを確認できていません。前のタブを閉じるか、そのタブで停止してください。確認できるまで音は出ません。'
                        : '前のタブの再生許可が切れるのを待っています。', 'info');
                } else {
                    claimState = 'none';
                    shell.showMessage('引き継げませんでした。', 'error');
                }
            });
        }

        function voicesOf(snapshot) {
            return 1 + (snapshot.layers ? snapshot.layers.length : 0) + (snapshot.loop ? 0 : 1);
        }

        function createBackend(kind, envB) {
            if (kind === 'chunk') return L.playback.createChunkBackend(envB);
            if (kind === 'main') return L.playback.createMainBackend(envB);
            return L.playback.createWorkletBackend(envB);
        }

        function prepareOutput(snapshot) {
            var m = ensureManager();
            if (lease && backend) {
                m.setVoices(lease, voicesOf(snapshot));
                return Promise.resolve(backend);
            }
            var got = m.acquire('metronome', voicesOf(snapshot), {
                // Can share the output when the user chose simultaneous use
                // (the manager decides; off by default).
                concurrent: true,
                onRevoke: function (why, seq) {
                    if (backend) backend.revoke(seq);
                    if (transport && ['running', 'waiting', 'paused'].indexOf(transport.getState()) >= 0) interrupt(why === 'claim-lost' ? 'claim-lost' : 'audio-interrupted');
                },
            });
            if (!got.ok) return Promise.reject(new Error(got.code));
            lease = got.lease;
            var ctx = m.context();
            var bank = L.sounds.createBank(ctx.sampleRate);
            var envB = { context: ctx, bus: lease.bus, bank: bank, volume: function () { return settings.volume; }, moduleUrl: deps.workletUrl, release: deps.release, setTimeout: deps.setTimeout, clearTimeout: deps.clearTimeout, now: deps.utcNow };
            var wanted = settings.backendMode || 'auto';
            var useWorklet = L.playback.workletSupported(globalObj, ctx) && deps.workletUrl;
            var kind = wanted === 'auto' ? (useWorklet ? 'worklet' : 'main') : (wanted === 'worklet' && !useWorklet ? 'main' : wanted);
            var candidate = createBackend(kind, envB);
            return candidate.init().catch(function () {
                // Worklet unavailable (old browser, load failure): the
                // look-ahead backend is used before playing starts — never
                // switched in the middle of a performance.
                candidate.dispose();
                candidate = L.playback.createMainBackend(envB);
                return candidate.init();
            }).then(function (info) {
                backend = candidate;
                // The guard capability of this tab is part of the claim record
                // (data design 3.1): a takeover may rely on it only when verified.
                m.setLeaseGuard(lease, info && info.guard);
                transport = L.transport.createTransport({
                    backend: backend,
                    sampleRate: ctx.sampleRate,
                    setTimeout: deps.setTimeout,
                    clearTimeout: deps.clearTimeout,
                    onState: onTransportState,
                    permit: function () { return m.permit(); },
                    onWarning: function (code) {
                        emit('warning', code);
                        if (code === 'no-permit' && transport && transport.getState() === 'running') {
                            // Not verified as the owner: nothing more sounds (R-02).
                            m.renewPermit();
                        }
                    },
                });
                emit('backend', { kind: backend.kind, guard: info && info.guard });
                return m.renewPermit().then(function () { return backend; });
            });
        }

        // Ends this body's output (lease, backend, transport). The page
        // manager closes the context after its idle time when no lease is left.
        function releaseOutput() {
            var t = transport;
            transport = null;
            if (t) t.stop('release');
            if (backend) backend.dispose();
            backend = null;
            if (manager && lease) manager.release(lease);
            lease = null;
        }

        function cancelIdle() {
            if (idleTimer !== null) deps.clearTimeout(idleTimer);
            idleTimer = null;
        }

        // Stopped: the lease is released at once; the page manager keeps the
        // context and the claim for IDLE_RELEASE_MS (60 s) before closing them.
        function scheduleIdle() {
            cancelIdle();
            idleTimer = deps.setTimeout(function () {
                idleTimer = null;
                if (transport && transport.getState() === 'stopped') {
                    releaseOutput();
                    if (shell) shell.setState('stopped');
                }
            }, 0);
        }

        // ----- transport state ---------------------------------------------------------

        function onTransportState(info) {
            if (!shell) return;
            if (info.fencePending || info.fenceApplied || info.fenceRejected) {
                emit('state', info);
                return;
            }
            shell.setState(info.state, info);
            if (info.state === 'running') {
                cancelIdle();
                if (timerStartedAt === null) timerStartedAt = deps.now();
                startDisplay();
                requestWakeLock();
            } else {
                if (timerStartedAt !== null) {
                    timerUsedMs += deps.now() - timerStartedAt;
                    timerStartedAt = null;
                }
                releaseWakeLock();
                if (info.state === 'stopped') {
                    stopDisplay();
                    shell.setPosition('—');
                    scheduleIdle();
                    if (info.reason === 'ended') shell.announce('最後まで再生しました');
                    if (info.reason === 'timer') shell.announce('練習タイマーで停止しました');
                }
                if (info.state === 'waiting') shell.announce('フェルマータです。再開ボタンで続けます');
                if (info.state === 'interrupted') {
                    stopDisplay();
                    shell.announce('中断しました。続きから再生できます');
                    if (info.reason === 'ack-timeout') shell.showMessage('再生の確認が取れなかったため、安全のため止めました。', 'error');
                }
            }
            emit('state', info);
        }

        // ----- play / stop ---------------------------------------------------------------

        function screenShowing() {
            return mounted && deps.isAllowed() && deps.isDocumentVisible() && deps.hostVisible(host);
        }

        // Inside the tap: synchronous part first. options.from: resume position.
        function play(options) {
            if (!mounted) return;
            var fromScore = options && options.from ? options.from : R.ZERO;
            var state = transport ? transport.getState() : 'stopped';
            if (state === 'running' || state === 'waiting') {
                stopPlayback('stop');
                return;
            }
            if (claimState === 'stale' || claimState === 'pending-owner') {
                shell.showMessage(claimState === 'stale' ? '別のタブが応答しません。「このタブで使う」を押してから再生してください。' : '前のタブの音が止まったことを確認しています。確認できてから再生してください。', 'info');
                return;
            }
            var unlocked = ensureManager().unlockFromGesture();
            if (!unlocked.ok) {
                shell.showMessage('この端末・ブラウザーでは音を鳴らせません。', 'error');
                return;
            }
            var built = buildSnapshot();
            if (!built.ok) {
                shell.showMessage(errorText(built.errors), 'error');
                return;
            }
            var pf = L.eventCompiler.preflight(built.snapshot, L.tempoMap.fromSnapshot(built.snapshot));
            if (!pf.ok) {
                shell.showMessage(errorText([{ code: 'too-dense' }]), 'error');
                return;
            }
            cancelIdle();
            startEpoch += 1;
            var epoch = startEpoch;
            var mountEpoch = launchEpoch;
            shell.setPreparing(true);
            shell.setState('preparing');
            var claim = claimState === 'held' && manager.hasClaim() ? Promise.resolve({ ok: true }) : prepareClaim();
            claim.then(function (r) {
                if (epoch !== startEpoch || mountEpoch !== launchEpoch) return null;
                if (!r.ok) {
                    // Another tab plays (or ownership is unconfirmed): nothing sounds.
                    shell.setState(r.reason === 'busy' ? 'busy' : 'stopped');
                    return null;
                }
                claimState = 'held';
                return prepareOutput(built.snapshot);
            }).then(function (b) {
                shell.setPreparing(false);
                if (!b) return;
                if (epoch !== startEpoch || mountEpoch !== launchEpoch || !screenShowing()) {
                    // Left during preparation: nothing sounds.
                    releaseOutput();
                    return;
                }
                if (!manager.permit()) {
                    // Ownership could not be verified: no output (R-02).
                    shell.setState('stopped');
                    shell.showMessage('このタブが音を使えることを確認できませんでした。もう一度お試しください。', 'error');
                    releaseOutput();
                    return;
                }
                transport.load(built.snapshot, revision);
                rememberApplied();
                timerUsedMs = 0;
                timerStartedAt = null;
                lastVibratedFrame = -1;
                resumeFrom = null;
                var countIn = options && Number.isInteger(options.countInBars) ? options.countInBars : settings.countInBars;
                transport.start({ countInBars: countIn, from: fromScore });
                emit('started', { snapshot: built.snapshot, revision: revision });
            }).catch(function (error) {
                shell.setPreparing(false);
                shell.setState('stopped');
                var code = error && error.message;
                shell.showMessage(code === 'OUTPUT_BUSY' ? 'ほかの機能が音を使っています。' : '再生を準備できませんでした。もう一度お試しください。', 'error');
                releaseOutput();
            });
        }

        function stopPlayback(reason) {
            startEpoch += 1;
            if (transport) transport.stop(reason || 'stop');
            emit('stopped', { reason: reason || 'stop' });
        }

        function pauseOrResume() {
            if (!transport) {
                if (resumeFrom) play({ from: resumeFrom });
                return;
            }
            var state = transport.getState();
            if (state === 'running') {
                transport.pause();
                return;
            }
            if (state === 'paused' || state === 'interrupted') {
                var unlocked = ensureManager().unlockFromGesture();
                if (!unlocked.ok || !manager.hasClaim() || !lease) {
                    // The output was released (idle / interrupt): start the normal way.
                    var from = transport.getPosition();
                    releaseOutput();
                    play({ from: from });
                    return;
                }
                manager.renewPermit().then(function (p) {
                    if (!transport || !p) {
                        shell.showMessage('このタブが音を使えることを確認できませんでした。', 'error');
                        return;
                    }
                    transport.resume({ countInBars: settings.countInBars });
                });
            }
        }

        function resumeFermata() {
            if (!transport || transport.getState() !== 'waiting') return;
            ensureManager().unlockFromGesture();
            transport.resumeFermata();
        }

        function interrupt(reason) {
            startEpoch += 1;
            if (transport) transport.interrupt(reason);
        }

        // ----- display (audio clock) ---------------------------------------------------

        function currentFrame() {
            if (!manager || !manager.context()) return null;
            var ctx = manager.context();
            var ts = manager.outputTimestamp();
            if (ts) return Math.round((ts.contextTime + (deps.now() - ts.performanceTime) / 1000) * ctx.sampleRate);
            var latency = (ctx.outputLatency || 0) + (ctx.baseLatency || 0);
            return Math.round((ctx.currentTime - latency) * ctx.sampleRate);
        }

        function draw(nowMs) {
            rafId = null;
            if (!transport || !shell) return;
            var state = transport.getState();
            if (state !== 'running' && state !== 'waiting') return;
            if (nowMs - lastDraw >= DISPLAY_INTERVAL_MS) {
                lastDraw = nowMs;
                var f = currentFrame();
                if (f !== null) {
                    var pos = transport.positionAt(f);
                    renderPosition(pos, f);
                    vibrateIfDue(f);
                    checkTimer();
                    // Extension screens (practice program, score, analysis)
                    // follow the same audio-clock position.
                    emit('tick', { position: pos, frame: f });
                }
            }
            rafId = deps.requestAnimationFrame(draw);
        }

        function startDisplay() {
            if (rafId === null) rafId = deps.requestAnimationFrame(draw);
        }

        function stopDisplay() {
            if (rafId !== null) deps.cancelAnimationFrame(rafId);
            rafId = null;
            if (basicView) {
                basicView.beat.replaceChildren();
                basicView.pendulum.style.setProperty('--metronome-swing', '0');
            }
        }

        function renderPosition(pos, f) {
            if (!pos || pos.ended || !pos.spec) return;
            var spec = pos.spec;
            var pulse = R.toNumber(spec.pulse);
            var pulseIndex = Math.min(spec.pulseCount - 1, Math.floor(pos.offset / pulse + 1e-9));
            var phase = (pos.offset - pulseIndex * pulse) / pulse;
            shell.setPosition((pos.occurrence + 1) + '小節 ' + (pulseIndex + 1) + '拍');
            if (!basicView) return;
            var visual = deps.reducedMotion() ? 'static' : settings.visual;
            basicView.pendulum.hidden = visual !== 'pendulum';
            if (visual === 'pendulum') {
                // Swings from side to side once per pulse: -1 .. 1.
                var side = pulseIndex % 2 === 0 ? 1 : -1;
                basicView.pendulum.style.setProperty('--metronome-swing', String(side * Math.cos(Math.PI * phase)));
            }
            var beat = basicView.beat;
            if (beat.childElementCount !== spec.pulseCount || beat.getAttribute('data-bar') !== spec.id) {
                beat.replaceChildren();
                beat.setAttribute('data-bar', spec.id);
                for (var i = 0; i < spec.pulseCount; i += 1) beat.appendChild(V.h('span', { className: 'metronome-beat-dot' }));
            }
            Array.prototype.forEach.call(beat.children, function (d, i) {
                d.setAttribute('data-current', i === pulseIndex && visual !== 'static' ? 'true' : 'false');
            });
            beat.setAttribute('data-text', visual === 'static' ? String(pulseIndex + 1) : '');
        }

        // Vibration is an aid: started on the display tick nearest the bar /
        // group head (not sample-accurate, design 9).
        function vibrateIfDue(f) {
            if (!settings.vibration || typeof deps.vibrate !== 'function') return;
            var events = transport.eventsBetween(lastVibratedFrame + 1, f + 1);
            var due = events.filter(function (e) { return e.emit && e.accentLevel === 'group' && (e.layerId === 'meter' || e.kind === 'countIn'); });
            if (due.length) {
                try { deps.vibrate(25); } catch (_) { /* aid only */ }
            }
            lastVibratedFrame = f;
        }

        function checkTimer() {
            if (!settings.timerMinutes || !basicView) return;
            var used = timerUsedMs + (timerStartedAt !== null ? deps.now() - timerStartedAt : 0);
            var left = settings.timerMinutes * 60000 - used;
            basicView.setTimerLeft(left > 0 ? '残り ' + Math.ceil(left / 1000) + ' 秒' : '');
            if (left <= 0) stopPlayback('timer');
        }

        // ----- Wake Lock -----------------------------------------------------------------

        function requestWakeLock() {
            if (!settings.wakeLock || !deps.wakeLock || wakeLock) return;
            wakeRequestSeq += 1;
            var seq = wakeRequestSeq;
            Promise.resolve().then(function () { return deps.wakeLock.request('screen'); }).then(function (lock) {
                // A late grant after stop / leave is released at once.
                var playing = transport && transport.getState() === 'running';
                if (seq !== wakeRequestSeq || !playing || !mounted) {
                    try { lock.release(); } catch (_) { /* already */ }
                    return;
                }
                wakeLock = lock;
                if (lock && typeof lock.addEventListener === 'function') lock.addEventListener('release', function () { if (wakeLock === lock) wakeLock = null; });
            }).catch(function () {
                if (shell && seq === wakeRequestSeq) shell.showMessage('画面の消灯を止められませんでした（再生は続きます）。', 'info');
            });
        }

        function releaseWakeLock() {
            wakeRequestSeq += 1;
            if (wakeLock) {
                var lock = wakeLock;
                wakeLock = null;
                try { lock.release(); } catch (_) { /* already */ }
            }
        }

