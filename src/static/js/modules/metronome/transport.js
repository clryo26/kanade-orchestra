// Metronome: transport — playback state, generations and change fences.
//
// States (design 8): stopped | running | paused | waiting (fermata) |
// interrupted. Every start/stop/seek/interrupt advances transportGeneration;
// a backend reply or timer of an older generation never acts on the current
// one.
//
// A running performance is a "segment": { snapshot, map, revision,
// originScore, originFrame }. Event frames are derived from the segment
// origin; edits while running end the old segment at a boundary score
// position and start a new one there (design 8 fence), so the beat never
// jumps and nothing already scheduled before the boundary changes.
//
// Boundary modes: 'immediate' = next grid point (finest of pulse /
// subdivision) after the guard, 'nextPulse', 'nextBar'. "Immediate" never
// reaches into audio that can no longer be cancelled.
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};
    var R = lib.rational || (typeof require === 'function' ? require('./rational.js') : null);
    var TM = lib.tempoMap || (typeof require === 'function' ? require('./tempo_map.js') : null);
    var EC = lib.eventCompiler || (typeof require === 'function' ? require('./event_compiler.js') : null);

    // Tuning values (design 15). Look-ahead values are comparison candidates
    // until MT-07/MT-08 decide; they are not adopted product values.
    var DEFAULTS = {
        horizonSeconds: { main: 0.3, worklet: 1.0 },
        timerMs: 25,
        startDelaySeconds: 0.1,
        guardSeconds: { main: 0.03, worklet: 0.06 },
        permitSeconds: 2,
        tailSeconds: 0.15,
    };

    function TransportError(code) {
        var e = new Error(code);
        e.name = 'MetronomeTransportError';
        e.code = code;
        return e;
    }

    // A float score position as a rational lower bound (for locating the
    // bar / grid around "now"; exact positions always come from the grid).
    function approxScore(x) {
        var K = 1048576;
        return R.make(Math.floor(Math.max(0, x) * K), K);
    }

    // Is the bar structure the same (only tempo / accent / sound / mute differ)?
    function sameStructure(a, b) {
        if (a.loop !== b.loop) return false;
        if (!a.loop) return JSON.stringify(a.occurrences.map(function (o) { return [o.barId, o.start]; })) === JSON.stringify(b.occurrences.map(function (o) { return [o.barId, o.start]; }));
        var ta = a.barTemplate;
        var tb = b.barTemplate;
        if (!R.eq(ta.length, tb.length) || JSON.stringify(ta.groups) !== JSON.stringify(tb.groups)) return false;
        if (JSON.stringify(a.layers.map(function (l) { return [l.id, l.cycle, l.pulses, l.phase]; })) !== JSON.stringify(b.layers.map(function (l) { return [l.id, l.cycle, l.pulses, l.phase]; }))) return false;
        return true;
    }

    // env: { backend, sampleRate, setTimeout, clearTimeout, onState(info),
    //        onWarning(code, detail), permit() -> current output permit | null,
    //        options }
    function createTransport(env) {
        var opts = Object.assign({}, DEFAULTS, env.options || {});
        var kind = env.backend.kind === 'worklet' ? 'worklet' : 'main';
        var horizon = typeof opts.horizonSeconds === 'number' ? opts.horizonSeconds : (opts.horizonSeconds[env.backend.kind] || opts.horizonSeconds[kind]);
        var guard = typeof opts.guardSeconds === 'number' ? opts.guardSeconds : (opts.guardSeconds[env.backend.kind] || opts.guardSeconds[kind]);
        var sr = env.sampleRate;
        var state = 'stopped';
        var reason = null;
        var generation = 0;
        var seg = null; // the segment being filled
        var segs = []; // committed segments of this run (for positions before a fence)
        var current = null; // { snapshot, map, revision } used when not running
        var position = R.ZERO; // score position while stopped / paused
        var frontier = null;
        var pendingFermata = null;
        var waitingFermata = null;
        var ended = false;
        var lastFrame = 0;
        var timer = null;
        var timeline = []; // scheduled events (for display / analysis), bounded
        var muteOffsetBars = 0;
        var editing = null; // { generation, fenceFrame } while a fence waits for its ack
        var editChain = Promise.resolve();
        var noPermitWarned = false;

        function emitState(extra) {
            if (typeof env.onState === 'function') env.onState(Object.assign({ state: state, reason: reason, generation: generation }, extra || {}));
        }

        function now() { return env.backend.currentFrame(); }

        function frameOf(s, segment) {
            var g = segment || seg;
            return g.originFrame + Math.round(sr * (g.map.timeAt(s) - g.map.timeAt(g.originScore)));
        }

        function scoreAtFrame(f, segment) {
            var g = segment || seg;
            var t = g.map.timeAt(g.originScore) + (f - g.originFrame) / sr;
            return g.map.scoreAt(t);
        }

        // The committed segment that plays frame f.
        function segmentAt(f) {
            for (var i = segs.length - 1; i >= 0; i -= 1) if (f >= segs[i].originFrame) return segs[i];
            return segs[0] || seg;
        }

        function occurrenceAtScore(snapshot, s) {
            var k = EC.occurrenceIndexAt(snapshot, s);
            return k === null ? null : EC.occurrenceAt(snapshot, k);
        }

        // Next grid point strictly after score s (mode: immediate / nextPulse / nextBar).
        function boundaryAfter(snapshot, s, mode) {
            var occ = occurrenceAtScore(snapshot, s);
            if (!occ) return null;
            var barEnd = R.add(occ.barStart, occ.spec.length);
            if (mode === 'nextBar') return barEnd;
            var unit = occ.spec.pulse;
            if (mode === 'immediate' && occ.spec.subdivision && R.lt(occ.spec.subdivision.length, unit)) unit = occ.spec.subdivision.length;
            var local = R.sub(s, occ.barStart);
            var k = R.floorDiv(local, unit) + 1;
            var cand = R.add(occ.barStart, R.scale(unit, k));
            return R.lt(cand, barEnd) ? cand : barEnd;
        }

        function chunkUnit(snapshot, s) {
            var occ = occurrenceAtScore(snapshot, s);
            return occ ? occ.spec.pulse : R.make(1, 4);
        }

        // Every event remembers the revision / segment that produced it, so
        // display and analysis use the conditions the click was played with.
        function tag(events, segment) {
            for (var i = 0; i < events.length; i += 1) {
                events[i].revision = segment.revision;
                events[i].generation = generation;
                events[i].segmentOrigin = segment.originFrame;
            }
            return events;
        }

        function remember(events) {
            for (var i = 0; i < events.length; i += 1) timeline.push(events[i]);
            var cutoff = now() - sr * 6;
            if (timeline.length > 4096 || (timeline.length && timeline[0].frame < cutoff)) {
                timeline = timeline.filter(function (e) { return e.frame >= cutoff; }).slice(-4096);
            }
        }

        function dropTimelineFrom(frame) {
            timeline = timeline.filter(function (e) { return e.frame < frame; });
        }

        function compileRange(segment, from, to) {
            return EC.compile({ snapshot: segment.snapshot, tempoMap: segment.map, revision: segment.revision, origin: { score: segment.originScore, frame: segment.originFrame }, sampleRate: sr, from: from, to: to, muteOffsetBars: muteOffsetBars });
        }

        // Events of the current segment from the frontier up to (not
        // including) the boundary b: they belong to the old settings and
        // must still sound, even if b lies beyond the look-ahead horizon.
        function flushUntil(b) {
            if (!R.lt(frontier, b)) return;
            var res = compileRange(seg, frontier, b);
            if (res.events.length) {
                tag(res.events, seg);
                env.backend.schedule(res.events, generation);
                remember(res.events);
            }
            frontier = b;
        }

        // Compiles a segment from `from` until targetFrame is covered.
        // Pure with respect to the transport (returns the new fill state).
        function fillSegment(segment, from, targetFrame) {
            var out = [];
            var f = from;
            var fermata = null;
            var end = false;
            var last = 0;
            var guardCount = 0;
            while (frameOf(f, segment) < targetFrame) {
                guardCount += 1;
                if (guardCount > 10000) break;
                var to = R.add(f, chunkUnit(segment.snapshot, f));
                var res = compileRange(segment, f, to);
                for (var i = 0; i < res.events.length; i += 1) out.push(res.events[i]);
                if (res.events.length) last = Math.max(last, res.events[res.events.length - 1].frame);
                if (res.fermata) {
                    fermata = res.fermata;
                    f = res.fermata.score;
                    break;
                }
                if (res.end) {
                    end = true;
                    break;
                }
                f = to;
            }
            return { events: tag(out, segment), frontier: f, fermata: fermata, ended: end, lastFrame: last };
        }

        function fill(targetFrame) {
            if (ended || pendingFermata) return [];
            var r = fillSegment(seg, frontier, targetFrame);
            frontier = r.frontier;
            if (r.lastFrame) lastFrame = Math.max(lastFrame, r.lastFrame);
            if (r.fermata) pendingFermata = r.fermata;
            if (r.ended) ended = true;
            return r.events;
        }

        function scheduleTimer() {
            if (timer !== null) env.clearTimeout(timer);
            timer = env.setTimeout(tick, opts.timerMs);
        }

        function stopTimer() {
            if (timer !== null) env.clearTimeout(timer);
            timer = null;
        }

        // Permit from the output manager (ownership verified); without one
        // nothing is renewed and the backend stays silent.
        function renew(f) {
            var p = typeof env.permit === 'function' ? env.permit() : { seq: 1, expiresAtUtcMs: Infinity, claimGeneration: 1 };
            if (!p) {
                if (!noPermitWarned && typeof env.onWarning === 'function') env.onWarning('no-permit', null);
                noPermitWarned = true;
                return false;
            }
            noPermitWarned = false;
            env.backend.renewPermit(f + Math.round(sr * opts.permitSeconds), p);
            return true;
        }

        function tick() {
            timer = null;
            if (state !== 'running') return;
            var f = now();
            renew(f);
            // While a fence waits for its ack nothing new is filled: the old
            // plan up to the fence is already queued.
            if (!editing) {
                var events = fill(f + Math.round(sr * horizon));
                if (events.length) {
                    env.backend.schedule(events, generation);
                    remember(events);
                }
            }
            if (pendingFermata && f >= frameOf(pendingFermata.score)) {
                waitingFermata = pendingFermata;
                pendingFermata = null;
                state = 'waiting';
                reason = 'fermata';
                emitState({ fermata: { id: waitingFermata.id, score: waitingFermata.score, resumeCountInPulses: waitingFermata.resumeCountInPulses } });
                return;
            }
            if (ended && !editing && f >= lastFrame + Math.round(sr * opts.tailSeconds)) {
                state = 'stopped';
                reason = 'ended';
                position = R.ZERO;
                segs = [];
                emitState();
                return;
            }
            scheduleTimer();
        }

        function load(snapshot, revision) {
            current = { snapshot: snapshot, map: TM.fromSnapshot(snapshot), revision: revision || 0 };
            var pf = EC.preflight(snapshot, current.map);
            if (!pf.ok) throw TransportError('too-dense');
            return pf;
        }

        function begin(snapshot, map, revision, from, countIn) {
            stopTimer();
            generation += 1;
            editing = null;
            env.backend.stop(generation);
            env.backend.setGeneration(generation);
            var f0 = now() + Math.round(sr * opts.startDelaySeconds);
            var lead = countIn.length ? -countIn[0].frame : 0;
            var originFrame = f0 + lead;
            countIn.forEach(function (e) { e.frame += originFrame; });
            seg = { snapshot: snapshot, map: map, revision: revision, originScore: from, originFrame: originFrame };
            segs = [seg];
            frontier = from;
            pendingFermata = null;
            waitingFermata = null;
            ended = false;
            lastFrame = originFrame;
            timeline = [];
            state = 'running';
            reason = null;
            renew(now());
            if (countIn.length) {
                tag(countIn, seg);
                env.backend.schedule(countIn, generation);
                remember(countIn);
            }
            return { originFrame: originFrame, lead: lead };
        }

        // Starts at `position` (or opts.from). Must run after the backend is
        // ready; the caller is inside the user's tap.
        function start(options) {
            var o = options || {};
            if (!current) throw TransportError('no-snapshot');
            var from = o.from || position;
            var countInBars = o.countInBars !== undefined ? o.countInBars : current.snapshot.countInBars;
            var countIn = EC.compileCountIn({ snapshot: current.snapshot, tempoMap: current.map, start: from, bars: countInBars, pulses: o.countInPulses || 0, originFrame: 0, sampleRate: sr, revision: current.revision, label: generation + 1 });
            muteOffsetBars = o.muteOffsetBars || 0;
            var b = begin(current.snapshot, current.map, current.revision, from, countIn);
            emitState({ originFrame: b.originFrame, countInFrames: b.lead });
            tick();
            return { generation: generation, originFrame: b.originFrame, countInFrames: b.lead };
        }

        function stopInternal(nextState, why, keepPosition) {
            stopTimer();
            var at = null;
            if (seg && (state === 'running' || state === 'waiting')) {
                var playing = segmentAt(now());
                at = { score: approxScore(scoreAtFrame(now(), playing)), segment: playing };
            }
            generation += 1;
            editing = null;
            env.backend.stop(generation);
            state = nextState;
            reason = why || null;
            pendingFermata = null;
            waitingFermata = null;
            if (!keepPosition) position = R.ZERO;
            else if (at) position = snapToGrid(at.segment.snapshot, at.score);
            var keep = at ? at.segment : seg;
            if (keep) current = { snapshot: keep.snapshot, map: keep.map, revision: keep.revision };
            seg = null;
            segs = [];
            emitState();
        }

        // Grid point at or before s (pulse grid), used for "safe resume position".
        function snapToGrid(snapshot, s) {
            var occ = occurrenceAtScore(snapshot, s);
            if (!occ) return R.ZERO;
            var local = R.sub(s, occ.barStart);
            return R.add(occ.barStart, R.scale(occ.spec.pulse, R.floorDiv(local, occ.spec.pulse)));
        }

        function stop(why) {
            stopInternal('stopped', why || 'stop', false);
        }

        function interrupt(why) {
            if (state === 'stopped') return;
            stopInternal('interrupted', why || 'interrupted', true);
        }

        // Pause at the next safe grid point: everything from it is cancelled.
        // The state becomes "paused" at once (nothing new is scheduled); the
        // position is the cancel point. An unconfirmed cancel interrupts.
        function pause() {
            if (state !== 'running') return Promise.resolve(null);
            var guardFrame = now() + Math.round(sr * guard);
            var s = approxScore(scoreAtFrame(guardFrame));
            var b = boundaryAfter(seg.snapshot, s, 'immediate') || frontier;
            var fb = frameOf(b);
            if (!editing) flushUntil(b);
            stopTimer();
            var gen = generation;
            editing = null;
            state = 'paused';
            reason = 'pause';
            position = b;
            current = { snapshot: seg.snapshot, map: seg.map, revision: seg.revision };
            dropTimelineFrom(fb);
            emitState({ pauseFrame: fb });
            return env.backend.cancelFrom(fb, gen).then(function (r) {
                if (r && r.stale) return { score: b, frame: fb, stale: true };
                return { score: b, frame: fb, reply: r };
            }, function () {
                if (gen === generation && state === 'paused') {
                    generation += 1;
                    env.backend.stop(generation);
                    state = 'interrupted';
                    reason = 'ack-timeout';
                    emitState();
                }
                return { score: b, frame: fb, timeout: true };
            });
        }

        function resume(options) {
            if (state !== 'paused' && state !== 'interrupted') return null;
            var o = Object.assign({}, options || {});
            o.from = position;
            if (o.countInBars === undefined && o.countInPulses === undefined) o.countInBars = 0;
            return start(o);
        }

        // Fermata: continue from the next event after the held one (its own
        // event already sounded and is not repeated), optionally after
        // count-in pulses.
        function resumeFermata(countInPulses) {
            if (state !== 'waiting' || !waitingFermata) return null;
            var f = waitingFermata;
            var probe = compileRange(seg, R.add(f.score, R.make(1, 1000000000)), R.add(f.score, R.make(64, 1)));
            var next = probe.events.filter(function (e) { return e.layerId === 'meter' || e.kind === 'layer'; })[0];
            if (!next) {
                stop('ended');
                return null;
            }
            var pulses = countInPulses === undefined ? f.resumeCountInPulses : countInPulses;
            var countIn = EC.compileCountIn({ snapshot: seg.snapshot, tempoMap: seg.map, start: next.score, pulses: pulses, originFrame: 0, sampleRate: sr, revision: seg.revision, label: 'f' + (generation + 1) });
            var b = begin(seg.snapshot, seg.map, seg.revision, next.score, countIn);
            emitState({ originFrame: b.originFrame, resumedFrom: f.id });
            tick();
            return { generation: generation, originFrame: b.originFrame };
        }

        // Seek: stops (default) and sets the position; playing again is a
        // separate explicit start (design 8).
        function seek(score) {
            if (state === 'running' || state === 'waiting' || state === 'paused') stopInternal('stopped', 'seek', true);
            position = score;
            emitState({ position: score });
        }

        // Applies a new snapshot (design 8 fence, R-03):
        // prepare (fence, new events) -> backend ack -> commit.
        // Until the ack confirms the replacement, the old plan stays the truth
        // (positions, conditions, timeline); accepted:false keeps the old plan,
        // a timeout interrupts (neither plan can be confirmed), a reply for an
        // older generation is ignored. Edits run one after another.
        // An edit belongs to the generation in which it was requested: if the
        // performance stopped or restarted while it waited in the chain, it is
        // dropped (stale) and never applied to the new run (round 3, R-03).
        // The caller loads its latest settings when it starts again.
        function edit(snapshot, revision, mode) {
            var requestedIn = generation;
            var run = function () {
                if (generation !== requestedIn) return Promise.resolve({ stale: true, superseded: true });
                return doEdit(snapshot, revision, mode);
            };
            var p = editChain.then(run, run);
            editChain = p.then(function () {}, function () {});
            return p;
        }

        function doEdit(snapshot, revision, mode) {
            var map = TM.fromSnapshot(snapshot);
            var pf = EC.preflight(snapshot, map);
            if (!pf.ok) return Promise.reject(TransportError('too-dense'));
            // While a fermata holds, the resume point belongs to the current
            // snapshot; edits wait until the performance continues or stops.
            if (state === 'waiting') return Promise.reject(TransportError('fermata-waiting'));
            if (state !== 'running') {
                var structural = current && !sameStructure(current.snapshot, snapshot);
                if (structural && current.snapshot.loop && snapshot.loop && !R.isZero(position)) {
                    var occ = occurrenceAtScore(current.snapshot, position);
                    var k = occ ? occ.index + (R.eq(position, occ.barStart) ? 0 : 1) : 0;
                    position = R.scale(snapshot.barTemplate.length, k);
                } else if (structural) {
                    position = R.ZERO;
                }
                current = { snapshot: snapshot, map: map, revision: revision };
                return Promise.resolve({ applied: 'stopped', accepted: true });
            }
            var structuralChange = !sameStructure(seg.snapshot, snapshot);
            if (structuralChange && !(seg.snapshot.loop && snapshot.loop)) return Promise.reject(TransportError('stop-required'));
            var guardFrame = now() + Math.round(sr * guard);
            var s = approxScore(scoreAtFrame(guardFrame));
            var b = boundaryAfter(seg.snapshot, s, mode || 'nextPulse');
            if (!b) return Promise.reject(TransportError('no-boundary'));
            var fb = frameOf(b);
            var newScore = b;
            if (structuralChange) {
                var occB = occurrenceAtScore(seg.snapshot, b);
                var barIndex = occB ? occB.index + (R.eq(b, occB.barStart) ? 0 : 1) : 0;
                newScore = R.scale(snapshot.barTemplate.length, barIndex);
            }
            var gen = generation;
            flushUntil(b);
            var oldFrontier = frontier;
            var oldState = { pendingFermata: pendingFermata, ended: ended, lastFrame: lastFrame };
            var newSeg = { snapshot: snapshot, map: map, revision: revision, originScore: newScore, originFrame: fb };
            var prepared = fillSegment(newSeg, newScore, Math.max(now() + Math.round(sr * horizon), fb + 1));
            editing = { generation: gen, fenceFrame: fb };
            emitState({ fencePending: true, fenceFrame: fb, mode: mode || 'nextPulse', revision: revision });
            return env.backend.replaceFrom(fb, prepared.events, gen).then(function (r) {
                if (gen !== generation || !editing || editing.generation !== gen) return { stale: true };
                editing = null;
                if (!r || r.stale) return { stale: true };
                if (!r.accepted) {
                    // The old plan continues exactly as queued.
                    frontier = oldFrontier;
                    pendingFermata = oldState.pendingFermata;
                    ended = oldState.ended;
                    lastFrame = oldState.lastFrame;
                    if (typeof env.onWarning === 'function') env.onWarning('fence-rejected', { code: r.code || 'QUEUE_FULL' });
                    emitState({ fenceRejected: true, revision: seg.revision });
                    scheduleTimer();
                    throw TransportError(r.code === 'QUEUE_FULL' ? 'queue-full' : 'fence-rejected');
                }
                // Commit.
                seg = newSeg;
                segs.push(newSeg);
                if (segs.length > 8) segs = segs.slice(-8);
                frontier = prepared.frontier;
                pendingFermata = prepared.fermata;
                ended = prepared.ended;
                lastFrame = Math.max(prepared.lastFrame || 0, fb);
                current = { snapshot: snapshot, map: map, revision: revision };
                dropTimelineFrom(fb);
                remember(prepared.events);
                var applied = r.appliedFrame !== undefined ? r.appliedFrame : fb;
                if (r.late && typeof env.onWarning === 'function') env.onWarning('fence-late', { fenceFrame: fb, appliedFrame: applied });
                emitState({ fenceApplied: true, fenceFrame: fb, appliedFrame: applied, revision: revision });
                scheduleTimer();
                return { accepted: true, fenceFrame: fb, appliedFrame: applied, score: b, newScore: newScore, late: Boolean(r.late) };
            }, function (error) {
                if (gen !== generation) return { stale: true };
                editing = null;
                // Neither plan can be confirmed: stop safely (design 8).
                stopInternal('interrupted', 'ack-timeout', true);
                throw TransportError(error && error.message === 'ACK_TIMEOUT' ? 'ack-timeout' : 'fence-failed');
            });
        }

        // Display / analysis: where the performance is at frame f, using the
        // segment (tempo map, revision) that actually plays f.
        function positionAt(f) {
            if (!seg) return null;
            var g = segmentAt(f);
            var s = scoreAtFrame(f, g);
            var occ = occurrenceAtScore(g.snapshot, approxScore(s));
            if (!occ) return { score: s, ended: true, revision: g.revision };
            var local = s - R.toNumber(occ.barStart);
            return { score: s, occurrence: occ.index, barId: occ.spec.id, offset: local, barLength: R.toNumber(occ.spec.length), spec: occ.spec, tempo: g.map.tempoAt(approxScore(s)), revision: g.revision, segmentOrigin: g.originFrame };
        }

        function eventsBetween(f0, f1) {
            return timeline.filter(function (e) { return e.frame >= f0 && e.frame < f1; });
        }

        return {
            DEFAULTS: DEFAULTS,
            load: load,
            start: start,
            stop: stop,
            pause: pause,
            resume: resume,
            resumeFermata: resumeFermata,
            seek: seek,
            interrupt: interrupt,
            edit: edit,
            positionAt: positionAt,
            eventsBetween: eventsBetween,
            frameOf: function (s) { return seg ? frameOf(s) : null; },
            getState: function () { return state; },
            getReason: function () { return reason; },
            getGeneration: function () { return generation; },
            getPosition: function () { return position; },
            getSnapshot: function () { return seg ? seg.snapshot : (current ? current.snapshot : null); },
            getRevision: function () { return seg ? seg.revision : (current ? current.revision : null); },
            getTempoMap: function () { return seg ? seg.map : (current ? current.map : null); },
            getSegment: function () { return seg ? Object.assign({}, seg) : null; },
            isEditPending: function () { return Boolean(editing); },
            horizonSeconds: horizon,
            guardSeconds: guard,
        };
    }

    var api = {
        DEFAULTS: DEFAULTS,
        createTransport: createTransport,
        approxScore: approxScore,
        sameStructure: sameStructure,
        TransportError: TransportError,
    };

    lib.releases = lib.releases || {};
    lib.transport = api;
    lib.releases.transport = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
