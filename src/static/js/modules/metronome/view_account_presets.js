// Metronome: presets in the user's own account (data design 8, /api/metronome/presets).
//
// - Opened only by an explicit tap in the settings screen; the history
//   modules (identity, remote client) are loaded then.
// - Only what the user saves here goes to the account. Device presets are
//   never copied automatically; a device preset is sent only by its own
//   "アカウントに保存" button.
// - A user without account storage (hidden administrator) is told so.
// - Unknown versions are listed read-only; conflicts, the size / count
//   limits and offline errors are shown, the device presets are unaffected.
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};

    var ERROR_TEXT = {
        CONSENT_REQUIRED: 'アカウントへの保存に同意すると保存できます。',
        CONSENT_REVISION: '同意の状態が変わりました。もう一度お試しください。',
        HISTORY_EPOCH: '本人情報の状態が変わりました。もう一度お試しください。',
        REVISION_CONFLICT: '同じプリセットの別の内容がすでにあります。名前を変えて保存してください。',
        PRESET_IN_USE: 'ほかのプリセットが参照しているため削除できません。先にそちらを削除してください。',
        'too-large': 'アカウントのプリセットの上限（60件・各256 KiB）に達したか、大きすぎます。',
        'rate-limit': '操作が多すぎます。少し待ってからお試しください。',
        network: 'オフラインまたは通信できないため、アカウントに接続できません。この端末のプリセットはそのまま使えます。',
        unauthenticated: 'もう一度ログインしてください。',
        forbidden: 'この機能を使う権限がありません。',
        invalid: '内容が正しくないため保存できません。',
        unavailable: '現在アカウントに保存できません。',
    };

    function errorText(r) {
        return ERROR_TEXT[r.detail] || ERROR_TEXT[r.code] || 'アカウントに保存できませんでした（' + (r.detail || r.code) + '）。';
    }

    // Groups the flat account list into chains (score -> advanced -> basic).
    function chains(items) {
        var byKey = {};
        items.forEach(function (it) { byKey[it.id + '@' + it.revision] = it; });
        var referenced = {};
        items.forEach(function (it) {
            var p = it.preset && it.preset.payload;
            if (p && p.basePresetId) referenced[p.basePresetId + '@' + p.baseRevision] = true;
        });
        return items.filter(function (it) { return !referenced[it.id + '@' + it.revision]; }).map(function (top) {
            var list = [top.preset];
            var cur = top.preset;
            var guard = 0;
            while (cur && cur.payload && cur.payload.basePresetId && guard < 4) {
                guard += 1;
                var base = byKey[cur.payload.basePresetId + '@' + cur.payload.baseRevision];
                if (!base) return { top: top, list: null, missing: true };
                list.unshift(base.preset);
                cur = base.preset;
            }
            return { top: top, list: list, missing: false };
        });
    }

    function createAccountPresetsView(host, api) {
        var V = api.lib.view;
        var h = V.h;
        var ws = lib.workspace.ensureWorkspace(api);
        var remote = ws.remote();
        var destroyed = false;
        var identity = null;
        var epoch = ws.ownerEpoch();

        var status = h('p', { className: 'metronome-hint', 'aria-live': 'polite', 'data-metronome-account-presets-status': 'true' });
        var list = h('div', { className: 'metronome-preset-list', 'data-metronome-account-presets-list': 'true' });
        var name = h('input', { className: 'form-control metronome-input', type: 'text', maxlength: '120', autocomplete: 'off' });
        var saveBtn = h('button', { type: 'button', className: 'btn btn-primary', disabled: true, 'data-metronome-account-preset-save': 'true', text: '今の設定をアカウントに保存' });
        var consent = h('input', { type: 'checkbox' });
        var consentLabel = h('label', { className: 'metronome-check' }, [consent, 'アカウントへの保存に同意する（練習の記録の同意と共通です）']);
        var deviceList = h('div', { className: 'metronome-preset-list', 'data-metronome-device-to-account': 'true' });

        function stale() {
            return destroyed || epoch !== ws.ownerEpoch();
        }

        function ctx() {
            return { historyEpoch: identity.historyEpoch, consentRevision: identity.consentRevision };
        }

        function refresh() {
            remote.listPresets(60).then(function (r) {
                if (stale()) return;
                list.replaceChildren();
                if (!r.ok) {
                    status.textContent = errorText(r);
                    return;
                }
                var groups = chains(r.data.items || []);
                if (!groups.length) list.appendChild(h('p', { className: 'metronome-hint', text: 'アカウントのプリセットはありません。' }));
                groups.forEach(function (g) {
                    var env = g.top.preset || {};
                    var known = env.schemaVersion === 1 && !g.missing && g.list.every(function (e) { return api.validate(e).ok; });
                    var label = (env.title || '名前なし') + '（' + ({ basic: '基本', advanced: '高度なリズム', score: '楽曲' }[g.top.kind] || g.top.kind) + '）' + (known ? '' : (env.schemaVersion !== 1 ? '　新しい版のため読み取り専用' : '　参照先が足りないため使えません'));
                    var useBtn = h('button', { type: 'button', className: 'btn btn-outline-primary', disabled: !known, text: '呼び出す' });
                    var delBtn = h('button', { type: 'button', className: 'btn btn-outline-danger', text: '削除' });
                    useBtn.addEventListener('click', function () {
                        Promise.resolve(api.applyEnvelopes(g.list)).then(function (res) {
                            status.textContent = res && res.ok === false ? '呼び出せませんでした（停止してから操作してください）。' : '「' + env.title + '」を呼び出しました（アカウントの内容は変わりません）。';
                        });
                    });
                    delBtn.addEventListener('click', function () {
                        if (typeof globalObj.confirm === 'function' && !globalObj.confirm('アカウントのプリセット「' + env.title + '」を削除します。よろしいですか。')) return;
                        // Top of the chain first, then its bases (references).
                        var ids = g.list ? g.list.map(function (e) { return e.id; }).reverse() : [g.top.id];
                        ids.reduce(function (p, id) {
                            return p.then(function (prev) {
                                if (prev && !prev.ok) return prev;
                                return remote.deletePreset(ctx(), id, api.deps.uuid());
                            });
                        }, Promise.resolve(null)).then(function (res) {
                            if (stale()) return;
                            status.textContent = res && res.ok ? '削除しました。' : errorText(res || { code: 'failed' });
                            refresh();
                        });
                    });
                    list.appendChild(h('div', { className: 'metronome-preset' }, [h('span', { className: 'metronome-preset-title', text: label }), useBtn, delBtn]));
                });
            });
        }

        function send(envelopes) {
            if (!identity || identity.kind !== 'account') return Promise.resolve({ ok: false, code: 'account-storage-unavailable' });
            return envelopes.reduce(function (p, env) {
                return p.then(function (prev) {
                    if (prev && !prev.ok) return prev;
                    if (stale()) return { ok: false, code: 'stale-owner' };
                    return remote.createPreset(ctx(), env);
                });
            }, Promise.resolve(null));
        }

        saveBtn.addEventListener('click', function () {
            var built = api.currentEnvelopes(name.value);
            if (!built.ok) { status.textContent = api.errorText(built.errors); return; }
            saveBtn.disabled = true;
            send(built.envelopes).then(function (r) {
                if (stale()) return;
                saveBtn.disabled = false;
                status.textContent = r && r.ok ? 'アカウントに保存しました。' : errorText(r || { code: 'failed' });
                refresh();
            });
        });

        consent.addEventListener('change', function () {
            var want = consent.checked;
            ws.setAccountConsent(want).then(function (r) {
                if (stale()) return;
                if (!r.ok) { status.textContent = errorText(r); consent.checked = !want; return; }
                return ws.resolveIdentity().then(function (id) {
                    identity = id;
                    saveBtn.disabled = !id.accountConsent;
                    status.textContent = want ? '同意しました。' : '同意を取り消しました。アカウントへの新しい保存はできません。';
                });
            });
        });

        // Device presets: each can be sent on its own tap (never automatically).
        function renderDevice() {
            api.presets.list().then(function (res) {
                if (stale()) return;
                deviceList.replaceChildren();
                res.items.filter(function (it) { return it.envelope.kind === 'basic'; }).forEach(function (it) {
                    var b = h('button', { type: 'button', className: 'btn btn-outline-secondary', text: 'アカウントに保存' });
                    b.addEventListener('click', function () {
                        var copy = JSON.parse(JSON.stringify(it.envelope));
                        copy.id = api.deps.uuid(); // the account copy is a new preset
                        send([copy]).then(function (r) {
                            if (stale()) return;
                            status.textContent = r && r.ok ? '「' + it.title + '」をアカウントに保存しました。' : errorText(r || { code: 'failed' });
                            refresh();
                        });
                    });
                    deviceList.appendChild(h('div', { className: 'metronome-preset' }, [h('span', { className: 'metronome-preset-title', text: it.title + '（この端末）' }), b]));
                });
            }, function () { /* no device presets */ });
        }

        host.replaceChildren(status);
        ws.resolveIdentity().then(function (id) {
            if (stale()) return;
            identity = id;
            if (id.kind !== 'account') {
                status.textContent = 'このアカウントではアカウント保存を使えません。プリセットはこの端末に保存できます。';
                return;
            }
            consent.checked = id.accountConsent;
            saveBtn.disabled = !id.accountConsent;
            host.replaceChildren(
                status,
                consentLabel,
                V.field('名前', name),
                saveBtn,
                h('h4', { className: 'metronome-section-label', text: 'アカウントのプリセット' }),
                list,
                h('h4', { className: 'metronome-section-label', text: 'この端末のプリセットを1件ずつアカウントへ' }),
                deviceList
            );
            refresh();
            renderDevice();
        }, function (error) {
            if (stale()) return;
            status.textContent = error && error.message === 'network' ? ERROR_TEXT.network : '本人情報を確認できませんでした。';
        });

        return {
            destroy: function () { destroyed = true; },
        };
    }

    var api = {
        chains: chains,
        errorText: errorText,
        createAccountPresetsView: createAccountPresetsView,
    };

    lib.releases = lib.releases || {};
    lib.viewAccountPresets = api;
    lib.releases.view_account_presets = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
