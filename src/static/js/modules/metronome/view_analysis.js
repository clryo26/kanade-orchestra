// Metronome: timing analysis screen (design 11 / 14, phase 05).
//
// Flow: explicit "use the microphone" tap -> noise floor -> calibration
// with the metronome's own clicks (optional, device only) -> analysis of
// the chosen target layers while the click plays -> results.
//
// Rules from the design and the review (R-01 / R-04 / R-05 / R-07 / R-08 / R-09):
// - The click never needs the microphone; stopping the analysis closes only
//   the capture, the click keeps playing.
// - At most 2 target layers and 16 expected beats per second (highest count
//   in any one-second window of the compiled events, from the current
//   position). Above that the analysis is refused before it starts, and an
//   edit of the click is refused while analysing (the click alone may play).
// - Each microphone start is its own capture session; results of an older
//   session never touch the current one.
// - With history on, the saving token is fixed before collecting starts.
// - Collection is a stream with bounded memory (aligner); details are capped.
// - One recording lasts at most 30 minutes of playing time (audio frames);
//   then it is closed once and the click continues; a new recording needs a
//   new tap.
// - Without a valid calibration, or with too few beats, results are shown as
//   reference values with "保留" (hold). There is no pass / fail yet.
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};
    var NOISE_MS = 1000;
    var LOOKAHEAD_SECONDS = 0.25; // targets are taken this far ahead of the output position
    var ATTACK_DELAY_MS = 250; // attacks arrive at most this late (input blocks + main thread)
    var HOLD_TEXT = {
        'not-calibrated': '校正していないため、参考値です（保留）。',
        'too-few': '有効な拍が少ないため、参考値です（保留）。',
        'low-coverage': '聞き取れた拍の割合が低いため、参考値です（保留）。',
    };

    function signed(x, unit) {
        if (x === null || x === undefined) return '—';
        return (x > 0 ? '+' : '') + x.toFixed(1) + (unit || '');
    }

    // Output event frame -> performance ms (getOutputTimestamp when valid).
    function outputMapper(ctx) {
        return function (frame) {
            if (!ctx) return null;
            var t = frame / ctx.sampleRate;
            var ts = typeof ctx.getOutputTimestamp === 'function' ? ctx.getOutputTimestamp() : null;
            var perf = globalObj.performance;
            if (ts && ts.contextTime > 0 && ts.performanceTime > 0) return ts.performanceTime + 1000 * (t - ts.contextTime);
            var latency = (ctx.outputLatency || 0) + (ctx.baseLatency || 0);
            return perf.now() + 1000 * (t - ctx.currentTime + latency);
        };
    }

    function createAnalysisView(panel, api) {
        var V = api.lib.view;
        var h = V.h;
        var L = api.lib;
        var TA = L.timingAnalysis;
        var OA = L.onsetAdapter;
        var CAL = L.calibration;
        var deps = api.deps;
        var calStore = CAL.createCalibrationStore({ indexedDB: deps.indexedDB });
        var capture = CAL.createCapture({ getUserMedia: deps.getUserMedia, AudioContext: deps.AudioContext, moduleUrl: deps.captureUrl, now: deps.now });
        var micSession = null; // the session this screen asked for last
        var calibration = null; // { valid, offsetMs, madMs, routeKey, id, saved }
        var candidate = null; // stored profile waiting for the user's confirmation
        var calSeq = 0; // load / save / delete requests of calibration profiles
        var mode = 'idle'; // idle | mic | calibrating | analyzing | preparing
        var collect = null;
        var destroyed = false;
        var route = 'speaker';
        var guardOff = null;

        var micBtn = h('button', { type: 'button', className: 'btn btn-primary', 'data-metronome-mic': 'true', text: 'マイクを使う' });
        var micStop = h('button', { type: 'button', className: 'btn btn-outline-secondary', disabled: true, text: 'マイクを止める' });
        var micStatus = h('p', { className: 'metronome-hint', 'aria-live': 'polite', 'data-metronome-mic-status': 'true', text: 'クリックだけを使うときは、マイクは不要です。' });
        var routeSel = V.select({}, CAL.ROUTES, route);
        var calBtn = h('button', { type: 'button', className: 'btn btn-outline-primary', disabled: true, 'data-metronome-calibrate': 'true', text: '校正を始める' });
        var calSave = h('input', { type: 'checkbox' });
        var calUse = h('button', { type: 'button', className: 'btn btn-outline-primary', hidden: true, 'data-metronome-calibration-use': 'true', text: '保存した校正を使う' });
        var calStatus = h('p', { className: 'metronome-hint', 'aria-live': 'polite', 'data-metronome-calibration-status': 'true' });
        var calForget = h('button', { type: 'button', className: 'btn btn-outline-danger', text: 'この経路の保存した校正を削除' });
        var targetsBox = h('div', { className: 'metronome-inline', role: 'group', 'aria-label': '解析する層' });
        var startBtn = h('button', { type: 'button', className: 'btn btn-primary', disabled: true, 'data-metronome-analysis-start': 'true', text: '解析を始める' });
        var stopBtn = h('button', { type: 'button', className: 'btn btn-outline-secondary', disabled: true, 'data-metronome-analysis-stop': 'true', text: '解析を終える' });
        var runStatus = h('p', { className: 'metronome-hint', 'aria-live': 'polite', 'data-metronome-analysis-status': 'true' });
        var result = h('div', { className: 'metronome-analysis-result', 'data-metronome-analysis-result': 'true' });
        var tunerHost = h('div', { className: 'metronome-tuner-host', 'data-metronome-tuner-host': 'true' });

        function micOn() {
            return Boolean(micSession && capture.isCurrent(micSession) && micSession.stream);
        }

        function setMode(next) {
            mode = next;
            var on = micOn();
            micBtn.disabled = on || mode === 'preparing';
            micStop.disabled = !on;
            calBtn.disabled = !on || mode !== 'mic';
            startBtn.disabled = !on || mode !== 'mic';
            stopBtn.disabled = mode !== 'analyzing' && mode !== 'calibrating';
            routeSel.disabled = mode === 'analyzing' || mode === 'calibrating';
            api.setChip('input', on ? 'マイク：使用中（' + (mode === 'analyzing' ? '解析中' : mode === 'calibrating' ? '校正中' : '待機') + '）' : 'マイク：使っていません');
        }

        function routeKeyNow() {
            if (!micOn()) return null;
            return CAL.routeKey(route, micSession.ctx.sampleRate, globalObj.navigator && globalObj.navigator.userAgent, micSession.label);
        }

        function invalidateCalibration(reason) {
            calSeq += 1; // late load / save results of the old route are ignored
            if (calibration) calStatus.textContent = '経路または入力が変わったため、校正は使えなくなりました（' + reason + '）。';
            calibration = null;
            candidate = null;
            calUse.hidden = true;
        }

        function loadSavedCalibration() {
            var key = routeKeyNow();
            if (!key) return;
            calSeq += 1;
            var mySeq = calSeq;
            var session = micSession;
            calStore.get(key).then(function (p) {
                if (destroyed || mySeq !== calSeq || session !== micSession || key !== routeKeyNow()) return;
                var check = CAL.checkProfile(p, key, OA.ANALYZER_VERSION, deps.utcNow());
                if (!check.ok) {
                    if (p) calStatus.textContent = '保存した校正は使えません（' + { 'route-changed': '経路が違います', 'analyzer-changed': '解析の版が変わりました', 'too-old': '古くなりました', invalid: '内容が正しくありません' }[check.reason] + '）。校正し直してください。';
                    return;
                }
                candidate = { offsetMs: p.offsetMs, madMs: p.madMs, routeKey: key, measuredAt: p.measuredAt };
                calUse.hidden = false;
                calStatus.textContent = '保存した校正があります（' + String(p.measuredAt).slice(0, 10) + '、往復 ' + p.offsetMs.toFixed(1) + ' ms）。同じ経路なら「保存した校正を使う」を押してください。';
            }, function () { /* no saved calibration */ });
        }

        calUse.addEventListener('click', function () {
            if (!candidate || candidate.routeKey !== routeKeyNow()) { calUse.hidden = true; return; }
            calibration = { valid: true, offsetMs: candidate.offsetMs, madMs: candidate.madMs, routeKey: candidate.routeKey, id: 'saved:' + candidate.measuredAt, saved: true };
            candidate = null;
            calUse.hidden = true;
            calStatus.textContent = '保存した校正を使います。';
        });

        // Every input block -> envelope frames -> attacks (samples dropped).
        function onBlock(samples, firstFrame, session) {
            if (session !== micSession || !session.envelope) return;
            var perf = deps.now();
            session.envelope.push(samples, firstFrame).forEach(function (f) {
                if (session.noiseUntil !== null && perf < session.noiseUntil) {
                    if (!f.gap) session.noise.push(f.rmsDbfs);
                    return;
                }
                if (session.noiseUntil !== null) {
                    session.detector.setThreshold(OA.thresholdFromNoise(session.noise));
                    session.noiseUntil = null;
                    session.noise = [];
                    micStatus.textContent = 'マイクの準備ができました（周りの音の大きさを測りました）。';
                }
                session.detector.push(f).forEach(function (a) {
                    var ms = session.mapper.toPerformance(a.effectiveFrame2 / 2);
                    if (ms === null || !collect) return;
                    if (collect.kind === 'calibration') collect.attacks.push(ms);
                    else collect.aligner.addAttack({ timeMs: ms - collect.offsetMs, quality: a.quality });
                });
            });
        }

        function stopMic(reason, session) {
            if (session && session !== micSession) return; // an old session's end
            if (collect && collect.kind === 'analysis') finishAnalysis('mic-stopped');
            collect = null;
            if (micSession) capture.stop(micSession);
            micSession = null;
            invalidateCalibration(reason || '停止');
            setMode('idle');
            micStatus.textContent = 'マイクを止めました。クリックは続けて使えます。';
        }

        micBtn.addEventListener('click', function () {
            if (!deps.getUserMedia) { micStatus.textContent = 'この端末・ブラウザーではマイクを使えません。'; return; }
            var g = capture.begin(); // inside the tap; an older pending session ends
            if (!g.ok) { micStatus.textContent = 'マイクを準備できませんでした。'; return; }
            var session = g.session;
            micSession = session;
            var launch = api.launchEpoch();
            setMode('preparing');
            micStatus.textContent = 'マイクの許可を確認しています…';
            capture.start(session, onBlock, function (why, s) { stopMic(why, s); }).then(function (info) {
                if (destroyed || session !== micSession || launch !== api.launchEpoch() || !api.isShowing()) { capture.stop(session); return; }
                session.envelope = OA.createEnvelope(info.sampleRate);
                session.detector = OA.createDetector(info.sampleRate);
                session.noise = [];
                session.noiseUntil = deps.now() + NOISE_MS;
                micStatus.textContent = '周りの音の大きさを測っています。1秒ほど静かにしてください。';
                setMode('mic');
                loadSavedCalibration();
            }, function (error) {
                if (session !== micSession) return; // a newer start owns the screen
                micSession = null;
                setMode('idle');
                micStatus.textContent = error && error.name === 'NotAllowedError' ? 'マイクの使用が許可されませんでした。' : 'マイクを開始できませんでした。';
            });
        });
        micStop.addEventListener('click', function () { stopMic('停止'); });
        routeSel.addEventListener('change', function () {
            route = routeSel.value;
            invalidateCalibration('経路を変更');
            loadSavedCalibration();
        });

        // ----- expected beats from the click (same events as the sound) ------------------
        function selectedLayers() {
            var ids = [];
            Array.prototype.forEach.call(targetsBox.querySelectorAll('input[type=checkbox]'), function (cb) { if (cb.checked) ids.push(cb.value); });
            return ids;
        }

        function renderTargets() {
            if (mode === 'analyzing') return; // the target layers of a running analysis stay
            targetsBox.replaceChildren();
            var built = api.buildSnapshot();
            var layers = built.ok ? built.snapshot.layers : [];
            [{ id: 'meter', label: '拍子のクリック' }].concat(layers.map(function (l, i) { return { id: l.id, label: '層' + (i + 1) }; })).forEach(function (item, i) {
                var cb = h('input', { type: 'checkbox', value: item.id, checked: i === 0 });
                targetsBox.appendChild(h('label', { className: 'metronome-check' }, [cb, item.label]));
            });
        }

        function pullTargets() {
            var t = api.transport();
            var ctx = api.outputContext();
            if (!t || !ctx || !collect) return;
            var now = api.currentFrame();
            if (now === null) return;
            var map = outputMapper(ctx);
            var until = now + Math.round(ctx.sampleRate * LOOKAHEAD_SECONDS);
            t.eventsBetween(collect.lastFrame, until).forEach(function (e) {
                var key = e.generation + ':' + e.eventId;
                if (collect.seen[key]) return;
                collect.seen[key] = true;
                if (collect.kind === 'calibration') {
                    if (e.emit && (e.layerId === 'meter' || e.kind === 'countIn')) collect.targets.push(map(e.frame));
                    return;
                }
                if (!TA.isTargetEvent(e, collect.layers)) return;
                if (collect.aligner.full()) return;
                var pos = t.positionAt(e.frame);
                var cond = collect.tracker.target(e, { spec: pos && pos.spec });
                collect.aligner.addTarget({
                    timeMs: map(e.frame),
                    eventId: e.eventId,
                    layerId: e.layerId,
                    beatKey: 'b' + (e.accentIndex === undefined ? 0 : e.accentIndex),
                    conditionKey: cond.conditionKey,
                    bpm: pos && pos.tempo ? pos.tempo.bpm : 60,
                    excluded: cond.excluded,
                });
            });
            collect.lastFrame = until;
            if (collect.kind === 'analysis') collect.aligner.advance(deps.now() - ATTACK_DELAY_MS);
            // Seen-keys are only needed inside the look-ahead window.
            var keys = Object.keys(collect.seen);
            if (keys.length > 8192) collect.seen = {};
        }

        // Beats taken in ahead of time (LOOKAHEAD_SECONDS) that will not sound:
        // from a confirmed fence the old beats are withdrawn and the new ones
        // fetched again after it; at pause / stop the beats after the cancel
        // point are withdrawn so they are not counted as missed (round 3).
        function withdrawTargets(fromFrame, refetchFrom) {
            if (!collect || !Number.isFinite(fromFrame)) return;
            var ctx = api.outputContext();
            if (!ctx) return;
            var ms = outputMapper(ctx)(fromFrame);
            if (collect.kind === 'analysis') collect.aligner.withdrawFrom(ms);
            else collect.targets = collect.targets.filter(function (t) { return t < ms; });
            if (Number.isFinite(refetchFrom)) collect.lastFrame = Math.min(collect.lastFrame, refetchFrom);
        }

        // ----- calibration -------------------------------------------------------------------
        calBtn.addEventListener('click', function () {
            if (api.state() !== 'running') { calStatus.textContent = '先に「再生」でクリックを鳴らしてください。楽器は演奏しないでください。'; return; }
            collect = { kind: 'calibration', targets: [], attacks: [], seen: {}, lastFrame: api.currentFrame() || 0, session: micSession, routeKey: routeKeyNow(), seq: calSeq };
            setMode('calibrating');
            calStatus.textContent = 'クリックを ' + TA.LIMITS.calibrationClicks + ' 回聞き取ります。静かにしてください。';
        });
        calForget.addEventListener('click', function () {
            var key = routeKeyNow();
            if (!key) return;
            calSeq += 1; // a load still in flight must not bring the profile back
            calStore.remove(key).then(function () { calStatus.textContent = '保存した校正を削除しました。'; invalidateCalibration('削除'); }, function () { calStatus.textContent = '削除できませんでした。'; });
        });

        function finishCalibration() {
            var c = collect;
            collect = null;
            setMode(micOn() ? 'mic' : 'idle');
            if (c.session !== micSession || c.seq !== calSeq || c.routeKey !== routeKeyNow()) {
                calStatus.textContent = '校正の途中で経路やマイクが変わったため、結果を使いません。';
                return;
            }
            var r = TA.calibrate(c.targets.slice(0, TA.LIMITS.calibrationClicks), c.attacks);
            if (!r.ok) {
                calibration = null;
                calStatus.textContent = { 'no-clicks-heard': 'クリックが聞き取れませんでした。音量を上げるか、端末をスピーカーに近づけてください。', 'too-few-clicks': '聞き取れたクリックが少なすぎました（' + r.matched + '／' + r.clicks + '）。', 'spread-too-large': 'ばらつきが大きすぎました（' + r.madMs + ' ms）。静かな場所でもう一度お試しください。' }[r.code] || '校正できませんでした。';
                return;
            }
            var key = c.routeKey;
            var measuredAt = new Date(deps.utcNow()).toISOString();
            calibration = { valid: true, offsetMs: r.offsetMs, madMs: r.madMs, routeKey: key, id: 'cal:' + measuredAt, saved: false };
            calStatus.textContent = '校正しました（往復 ' + r.offsetMs.toFixed(1) + ' ms、ばらつき ' + r.madMs.toFixed(1) + ' ms、' + r.matched + ' 回）。';
            if (calSave.checked && key) {
                var mySeq = calSeq;
                var mine = calibration;
                calStore.save({ routeKey: key, route: route, sampleRate: micSession.ctx.sampleRate, browser: CAL.browserFamily(globalObj.navigator && globalObj.navigator.userAgent), analyzerVersion: OA.ANALYZER_VERSION, offsetMs: r.offsetMs, madMs: r.madMs, matched: r.matched, measuredAt: measuredAt }).then(function () {
                    if (destroyed || mySeq !== calSeq || calibration !== mine) return; // route changed or deleted meanwhile
                    mine.saved = true;
                    calStatus.textContent += 'この端末に保存しました。';
                }, function () { if (!destroyed && mySeq === calSeq) calStatus.textContent += '保存はできませんでした。'; });
            }
        }

        // ----- analysis ------------------------------------------------------------------------
        function rateGuard(layers) {
            return function (snapshot) {
                // Checked from the current playing position (the edit applies there).
                var t = api.transport();
                var pos = t ? t.positionAt(api.currentFrame() || 0) : null;
                var from = pos && !pos.ended && pos.score !== undefined ? L.transport.approxScore(pos.score) : undefined;
                var r = TA.targetRate(snapshot, layers, { from: from });
                if (r.ok) return { ok: true };
                return { ok: false, message: '解析中のため、この変更はできません（解析する拍が毎秒 ' + (r.rate || '?') + ' 回になり、上限 ' + r.limit + ' 回を超えます）。解析を終えてから変更してください。' };
            };
        }

        startBtn.addEventListener('click', function () {
            if (api.state() !== 'running') { runStatus.textContent = '先に「再生」でクリックを鳴らしてください。'; return; }
            var layers = selectedLayers();
            if (!layers.length) { runStatus.textContent = '解析する層を選んでください。'; return; }
            var t = api.transport();
            var snap = t ? t.getSnapshot() : null;
            if (!snap) { runStatus.textContent = '今の設定では解析できません。'; return; }
            var pos = t.positionAt(api.currentFrame() || 0);
            var from = pos && pos.score !== undefined && !pos.ended ? L.transport.approxScore(pos.score) : undefined;
            var rate = TA.targetRate(snap, layers, { from: from });
            if (!rate.ok) {
                runStatus.textContent = rate.code === 'too-many-layers'
                    ? '解析できる層は2つまでです。'
                    : '解析する拍が多すぎます（毎秒 ' + rate.rate + ' 回、上限 ' + rate.limit + ' 回）。テンポや細分・層を減らしてください。クリックはそのまま使えます。';
                return;
            }
            var attemptId = deps.uuid();
            var startedAtUtc = deps.utcNow();
            var ws = api.shared.workspace || null;
            var wantSave = Boolean(ws && ws.policy().historyMode !== 'none');
            setMode('preparing');
            runStatus.textContent = wantSave ? '記録の保存を準備しています…' : '';
            // R-05: the token (and the capacity) is checked BEFORE collecting.
            var ready = !wantSave ? Promise.resolve({ save: false }) : ws.canStore(TA.LIMITS.maxTargets + TA.LIMITS.maxExtraDetails).then(function (cap) {
                if (!cap.ok) return { save: false, reason: cap.code === 'BUDGET' ? 'この端末の記録の容量（64 MiB）が足りないため、今回は保存しません。古い記録を削除するか書き出してください。' : '端末の空き容量が足りないため、今回は保存しません。' };
                return ws.beginAttempt(attemptId).then(function (r) { return r.ok ? { save: true } : { save: false, reason: '記録を保存できないため、今回は保存しません（' + r.code + '）。' }; });
            });
            var session = micSession;
            ready.then(function (prep) {
                if (destroyed || session !== micSession || !micOn() || api.state() !== 'running') {
                    setMode(micOn() ? 'mic' : 'idle');
                    return;
                }
                collect = {
                    kind: 'analysis',
                    attemptId: attemptId,
                    save: prep.save,
                    layers: layers,
                    aligner: TA.createAligner(),
                    tracker: TA.createConditionTracker({ route: route, calibrationId: calibration && calibration.valid ? calibration.id : 'none', analyzerVersion: OA.ANALYZER_VERSION, outputKind: api.backendKind(), sampleRate: api.sampleRate() }),
                    seen: {},
                    lastFrame: api.currentFrame() || 0,
                    startedAt: new Date(startedAtUtc).toISOString(),
                    activeFrames: 0,
                    lastTickFrame: null,
                    offsetMs: calibration && calibration.valid ? calibration.offsetMs : 0,
                    calibration: calibration ? Object.assign({}, calibration) : null,
                };
                guardOff = api.addEditGuard(rateGuard(layers));
                setMode('analyzing');
                runStatus.textContent = (prep.reason ? prep.reason + ' ' : '') + '解析中です。30分で自動的に区切ります（クリックは続きます）。';
                result.replaceChildren();
            });
        });
        stopBtn.addEventListener('click', function () {
            if (mode === 'analyzing') finishAnalysis('user');
            else if (mode === 'calibrating') { collect = null; setMode('mic'); calStatus.textContent = '校正をやめました。'; }
        });

        function finishAnalysis(reason) {
            // Beats after the current output frame never sound in this record.
            if (collect && collect.kind === 'analysis') {
                var nowFrame = api.currentFrame();
                if (nowFrame !== null) withdrawTargets(nowFrame + 1, null);
            }
            var c = collect;
            collect = null;
            if (guardOff) { guardOff(); guardOff = null; }
            if (!c || c.kind !== 'analysis') return;
            setMode(micOn() ? 'mic' : 'idle');
            var res = TA.summarize(c.aligner.finish(), c.calibration);
            renderResult(res, reason);
            var activeMs = Math.min(TA.LIMITS.maxRecordingMs, Math.round(c.activeFrames / (api.sampleRate() || 48000) * 1000));
            var record = {
                sessionId: deps.uuid(),
                attemptId: c.attemptId,
                kind: 'analysis',
                status: reason === 'user' || reason === 'limit' ? 'complete' : 'incomplete',
                startedAt: c.startedAt,
                endedAt: new Date(deps.utcNow()).toISOString(),
                activeDurationMs: activeMs,
                durationMs: activeMs,
                conditionKey: res.groups.length ? res.groups[0].conditionKey : 'none',
                versions: { schemaVersion: 1, analyzerVersion: OA.ANALYZER_VERSION, statsVersion: TA.STATS_VERSION, compilerVersion: L.eventCompiler.COMPILER_VERSION },
                scoreSummary: { kind: 'analysis', layers: c.layers, calibrated: Boolean(c.calibration && c.calibration.valid), groupMode: res.groupMode },
                counts: res.counts,
                summary: res.summary,
                groups: res.accountGroups || [],
                localGroups: res.groups,
                accountHold: res.accountHold,
                details: res.details,
            };
            record.contentHash = L.workspace ? L.workspace.hashText(JSON.stringify([record.scoreSummary, record.summary, record.counts, record.groups])) : '';
            var ws = api.shared.workspace || null;
            if (ws && c.save) {
                ws.recordResult({ kind: 'analysis', attemptId: c.attemptId, record: record }).then(function (r) {
                    if (destroyed) return;
                    runStatus.textContent += r && r.ok && r.stored !== false ? '記録を保存しました。' : (r && r.pending ? '保存待ちにしました（練習タブで保存できます）。' : '記録は保存していません。');
                    if (r && r.localOnly === 'too-many-conditions') runStatus.textContent += '条件が多すぎるため、アカウントへの要約の送信は保留しました（この端末には保存しています）。';
                });
            }
        }

        function renderResult(res, reason) {
            var s = res.summary;
            result.replaceChildren();
            var lines = [
                ['平均的なずれ（中央値）', signed(s.medianMs, ' ms') + '（＋は遅れ）'],
                ['ばらつき（MAD／標準偏差）', (s.madMs === null ? '—' : s.madMs.toFixed(1)) + ' ／ ' + (s.sdMs === null ? '—' : s.sdMs.toFixed(1)) + ' ms'],
                ['テンポの安定（間隔の比）', s.ioiRatio ? s.ioiRatio.median.toFixed(3) + '（ばらつき ' + s.ioiRatio.mad.toFixed(3) + '、' + s.ioiRatio.n + ' 組）' : '—'],
                ['有効な拍', res.counts.valid + ' ／ ' + res.counts.target + '（' + Math.round(100 * (s.coverage || 0)) + '%）'],
                ['除外', '聞き取れない ' + s.excluded.missing + '、判別できない ' + s.excluded.ambiguous + '、ゆるやかな立ち上がり ' + s.excluded.slowAttack + '、条件の変わり目 ' + s.excluded.conditionBoundary],
                ['余分な音', String(res.counts.extraTotal) + (s.extraDetailsTruncated ? '（詳細は ' + res.counts.extraDetail + ' 件まで保存、以降は件数のみ）' : '')],
            ];
            var table = h('table', { className: 'metronome-table' }, [h('tbody', {}, lines.map(function (l) { return h('tr', {}, [h('th', { scope: 'row', text: l[0] }), h('td', { text: l[1] })]); }))]);
            result.appendChild(h('div', { className: 'metronome-table-wrap' }, [table]));
            result.appendChild(h('p', { className: 'metronome-hint', 'data-metronome-analysis-verdict': s.verdict, text: (s.hold ? HOLD_TEXT[s.hold] : '参考値です（合否の判定は、実際の楽器での確認後に有効にします）。') + (reason === 'limit' ? '30分に達したため記録を区切りました。' : '') + (res.groupMode === 'merged-beats' ? '条件が多いため、アカウントの要約は拍の位置をまとめています。' : '') }));
            if (res.groups.length) {
                var rows = res.groups.slice(0, 64).map(function (g) {
                    return h('tr', {}, [h('td', { text: g.layerKey === 'meter' ? '拍子' : g.layerKey }), h('td', { text: g.beatPositionKey.replace('b', '') }), h('td', { text: g.validCount + '/' + g.targetCount }), h('td', { text: signed(g.stats.medianMs, '') }), h('td', { text: g.stats.madMs === null ? '—' : g.stats.madMs.toFixed(1) })]);
                });
                result.appendChild(h('div', { className: 'metronome-table-wrap' }, [h('table', { className: 'metronome-table', 'aria-label': '拍の位置ごとの結果' }, [
                    h('thead', {}, [h('tr', {}, ['層', '拍', '有効', 'ずれ ms', 'ばらつき'].map(function (t) { return h('th', { scope: 'col', text: t }); }))]),
                    h('tbody', {}, rows),
                ])]));
                if (res.groups.length > 64) result.appendChild(h('p', { className: 'metronome-hint', text: '表示は64行までです（記録には ' + res.groups.length + ' 行すべてを残しています）。' }));
            }
        }

        var off = api.on(function (type, payload) {
            // The transport reports the commit synchronously (its timeline
            // already holds the new events).
            if (type === 'state' && collect && payload && payload.fenceApplied && Number.isFinite(payload.fenceFrame)) {
                var fence = payload;
                var applied = Number.isFinite(fence.appliedFrame) ? Math.max(fence.appliedFrame, fence.fenceFrame) : fence.fenceFrame;
                // A late fence: nothing sounded between the fence and the
                // applied frame (old cancelled, new too late).
                withdrawTargets(fence.fenceFrame, applied);
                pullTargets();
            }
            if (type === 'state' && collect && payload && Number.isFinite(payload.pauseFrame)) withdrawTargets(payload.pauseFrame, null);
            if (type === 'tick' && collect) {
                pullTargets();
                if (collect && collect.kind === 'analysis') {
                    // Playing time on the audio clock (R-09).
                    var f = payload.frame;
                    if (api.state() === 'running' && collect.lastTickFrame !== null && f > collect.lastTickFrame) collect.activeFrames += f - collect.lastTickFrame;
                    collect.lastTickFrame = api.state() === 'running' ? f : null;
                    var limitFrames = TA.LIMITS.maxRecordingMs / 1000 * (api.sampleRate() || 48000);
                    if (collect.activeFrames >= limitFrames || collect.aligner.full()) {
                        finishAnalysis('limit');
                        api.announce('30分に達したため、解析の記録を区切りました。クリックは続きます。');
                    }
                } else if (collect && collect.kind === 'calibration' && collect.targets.length >= TA.LIMITS.calibrationClicks) {
                    var last = collect.targets[TA.LIMITS.calibrationClicks - 1];
                    if (deps.now() > last + 600) finishCalibration();
                }
            }
            if (type === 'state' && payload && collect && collect.kind === 'analysis' && payload.state !== 'running') collect.lastTickFrame = null;
            if (type === 'state' && payload && (payload.state === 'stopped' || payload.state === 'interrupted') && collect) {
                if (collect.kind === 'analysis') finishAnalysis(payload.state === 'stopped' ? 'user' : 'interrupted');
                else { collect = null; setMode(micOn() ? 'mic' : 'idle'); calStatus.textContent = 'クリックが止まったため校正をやめました。'; }
            }
            if (type === 'state' && payload && payload.state === 'interrupted') invalidateCalibration('中断');
            if (type === 'draft') renderTargets();
            if (type === 'leave' || type === 'suspend' || type === 'cleared') stopMic('画面を離れた');
        });

        // Tuner side by side (adapter, design 2.1): mounted only on request.
        var tunerBtn = h('button', { type: 'button', className: 'btn btn-outline-primary', 'data-metronome-tuner-open': 'true', text: 'チューナーを表示する' });
        var tunerClose = h('button', { type: 'button', className: 'btn btn-outline-secondary', hidden: true, text: 'チューナーを閉じる' });
        var tunerStatus = h('p', { className: 'metronome-hint', 'aria-live': 'polite' });
        var tunerAdapter = null;
        tunerBtn.addEventListener('click', function () {
            var adapterLib = L.tunerAdapter;
            if (!adapterLib) { tunerStatus.textContent = 'チューナーとの併用を読み込めませんでした。'; return; }
            tunerAdapter = adapterLib.createTunerDisplay({ api: api, host: tunerHost });
            tunerStatus.textContent = '読み込んでいます…';
            tunerAdapter.mount().then(function (r) {
                if (destroyed) return;
                tunerStatus.textContent = r.ok ? 'チューナーを表示しています。メトロノームの再生中、チューナーの基準音は「同時に使う」と「イヤホン」を選んだ時だけ鳴ります。' : r.message;
                tunerBtn.hidden = r.ok;
                tunerClose.hidden = !r.ok;
            });
        });
        tunerClose.addEventListener('click', function () {
            if (tunerAdapter) tunerAdapter.unmount('close');
            tunerAdapter = null;
            tunerBtn.hidden = false;
            tunerClose.hidden = true;
            tunerStatus.textContent = 'チューナーを閉じました。';
        });

        panel.replaceChildren(
            h('p', { className: 'metronome-hint', text: '演奏を聞き取り、クリックとのずれを調べます。録音は保存も送信もしません。' }),
            h('div', { className: 'metronome-inline' }, [micBtn, micStop]),
            micStatus,
            h('h3', { className: 'metronome-section-title', text: '校正' }),
            V.field('音の経路', routeSel, '経路を変えたら校正し直してください。Bluetoothは遅れが変わることがあります。'),
            h('label', { className: 'metronome-check' }, [calSave, '校正の結果をこの端末に保存する']),
            h('div', { className: 'metronome-inline' }, [calBtn, calUse, calForget]),
            calStatus,
            h('h3', { className: 'metronome-section-title', text: '解析' }),
            targetsBox,
            h('p', { className: 'metronome-hint', text: '解析できるのは2層まで、合わせて毎秒16拍までです（1秒の中で最も多いところで数えます）。' }),
            h('div', { className: 'metronome-inline' }, [startBtn, stopBtn]),
            runStatus,
            result,
            h('h3', { className: 'metronome-section-title', text: 'チューナーとの併用' }),
            h('p', { className: 'metronome-hint', text: 'チューナーをこの画面に表示します。マイクはチューナーとこの解析で別々に使い、片方を止めても他方は止まりません。' }),
            h('div', { className: 'metronome-inline' }, [tunerBtn, tunerClose]),
            tunerStatus,
            tunerHost
        );
        renderTargets();
        setMode('idle');

        return {
            show: renderTargets,
            destroy: function () {
                destroyed = true;
                off();
                if (guardOff) guardOff();
                if (micSession) capture.stop(micSession);
                micSession = null;
                if (tunerAdapter) tunerAdapter.unmount('leave');
                api.setChip('input', 'マイク：使っていません');
            },
            // Test hooks (no audio objects).
            _state: function () { return { mode: mode, calibration: calibration, candidate: candidate, collecting: collect ? collect.kind : null }; },
        };
    }

    var api = {
        outputMapper: outputMapper,
        createAnalysisView: createAnalysisView,
    };

    lib.releases = lib.releases || {};
    lib.viewAnalysis = api;
    lib.releases.view_analysis = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
