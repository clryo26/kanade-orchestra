// Metronome: tempo map — score position (whole notes) <-> seconds.
//
// Design 6: a curve is a BPM that changes linearly or exponentially with
// ELAPSED SECONDS; its end is a score position. The duration is derived,
// never stored: with U = (s1 - s0) / reference beats,
//   constant     D = 60U / B0
//   linear       D = 120U / (B0 + B1),        a = (B1 - B0) / D
//   exponential  D = 60U ln(B1/B0) / (B1-B0), k = ln(B1/B0) / D
// Beats reached after t seconds u(t) and its inverse t(u) are closed forms,
// so every event time is computed directly from the piece start (no
// accumulated "next += interval" rounding).
//
// The map is a list of pieces covering [0, +inf) in absolute score
// positions; gaps between curves keep the previous BPM and reference.
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};
    var R = lib.rational || (typeof require === 'function' ? require('./rational.js') : null);

    // Relative BPM difference below which a curve is treated as constant
    // (tuning value: limits of log1p/expm1 cancellation).
    var CONSTANT_EPSILON = 1e-8;

    function TempoError(code, detail) {
        var e = new Error(code);
        e.name = 'MetronomeTempoError';
        e.code = code;
        e.detail = detail || null;
        return e;
    }

    function isNearlyConstant(b0, b1) {
        return Math.abs(b1 - b0) <= CONSTANT_EPSILON * Math.max(b0, b1);
    }

    // Duration in seconds of U beats.
    function durationOf(curve, b0, b1, U) {
        if (!(b0 > 0) || !(b1 > 0)) throw TempoError('invalid-bpm');
        if (curve === 'constant' || isNearlyConstant(b0, b1)) return 60 * U / b0;
        if (curve === 'linear') return 120 * U / (b0 + b1);
        if (curve === 'exponential') return 60 * U * Math.log(b1 / b0) / (b1 - b0);
        throw TempoError('invalid-curve');
    }

    // Seconds to reach u beats inside a piece.
    function timeOfBeats(piece, u) {
        if (u <= 0) return 0;
        var b0 = piece.b0;
        if (piece.kind === 'constant') return 60 * u / b0;
        if (piece.kind === 'linear') {
            var disc = b0 * b0 + 120 * piece.a * u;
            if (disc < 0) disc = 0; // only reachable beyond the end by rounding
            return 120 * u / (b0 + Math.sqrt(disc));
        }
        return Math.log1p(60 * piece.k * u / b0) / piece.k;
    }

    // Beats reached after t seconds inside a piece.
    function beatsAtTime(piece, t) {
        if (t <= 0) return 0;
        var b0 = piece.b0;
        if (piece.kind === 'constant') return b0 * t / 60;
        if (piece.kind === 'linear') return (b0 * t + piece.a * t * t / 2) / 60;
        return b0 * Math.expm1(piece.k * t) / (60 * piece.k);
    }

    function bpmAtTime(piece, t) {
        if (piece.kind === 'constant') return piece.b0;
        if (piece.kind === 'linear') return piece.b0 + piece.a * t;
        return piece.b0 * Math.exp(piece.k * t);
    }

    function makePiece(start, end, reference, b0, b1, curve) {
        var kind = curve === 'constant' || isNearlyConstant(b0, b1) ? 'constant' : curve;
        var piece = { start: start, end: end, reference: reference, b0: b0, b1: kind === 'constant' ? b0 : b1, kind: kind, a: 0, k: 0, beats: Infinity, duration: Infinity, t0: 0 };
        if (end) {
            var U = R.toNumber(R.div(R.sub(end, start), reference));
            if (!(U > 0)) throw TempoError('empty-segment');
            piece.beats = U;
            piece.duration = durationOf(kind, b0, piece.b1, U);
            if (kind === 'linear') piece.a = (piece.b1 - b0) / piece.duration;
            if (kind === 'exponential') piece.k = Math.log(piece.b1 / b0) / piece.duration;
        } else if (kind !== 'constant') {
            throw TempoError('open-curve'); // only a constant tempo may run without an end
        }
        return piece;
    }

    // segments: [{ start: R, end: R, reference: R, b0, b1, curve }] (absolute
    // positions, BPM numbers); steps: [{ at: R, bpm, reference }] where the
    // tempo jumps (metric modulation, tempo steps). initial: { bpm, reference }.
    function createTempoMap(spec) {
        var initial = spec.initial;
        if (!initial || !(initial.bpm > 0) || !R.isPositive(initial.reference)) throw TempoError('invalid-initial');
        var segs = (spec.segments || []).slice().sort(function (a, b) { return R.cmp(a.start, b.start); });
        var steps = (spec.steps || []).slice().sort(function (a, b) { return R.cmp(a.at, b.at); });
        for (var i = 0; i < segs.length; i += 1) {
            if (!R.lt(segs[i].start, segs[i].end)) throw TempoError('empty-segment', { index: i });
            if (i > 0 && R.lt(segs[i].start, segs[i - 1].end)) throw TempoError('overlapping-segments', { index: i });
        }
        steps.forEach(function (st) {
            segs.forEach(function (sg) {
                if (R.gt(st.at, sg.start) && R.lt(st.at, sg.end)) throw TempoError('step-inside-curve');
            });
        });
        var pieces = [];
        var pos = R.ZERO;
        var bpm = initial.bpm;
        var ref = initial.reference;
        var si = 0;
        var ti = 0;
        function pushConstantUntil(until) {
            if (until && !R.lt(pos, until)) return;
            pieces.push(makePiece(pos, until, ref, bpm, bpm, 'constant'));
            pos = until;
        }
        // Applies steps at or before `limit` (inclusive when atLimit).
        function applyStepsUpTo(limit) {
            while (ti < steps.length && (!limit || R.le(steps[ti].at, limit))) {
                var st = steps[ti];
                if (R.gt(st.at, pos)) pushConstantUntil(st.at);
                bpm = st.bpm;
                ref = st.reference || ref;
                ti += 1;
            }
        }
        while (si < segs.length) {
            var sg = segs[si];
            applyStepsUpTo(sg.start);
            if (R.gt(sg.start, pos)) pushConstantUntil(sg.start);
            pieces.push(makePiece(sg.start, sg.end, sg.reference, sg.b0, sg.b1, sg.curve));
            pos = sg.end;
            bpm = sg.b1;
            ref = sg.reference;
            si += 1;
        }
        applyStepsUpTo(null);
        pieces.push(makePiece(pos, null, ref, bpm, bpm, 'constant'));
        // Prefix times (compensated sum keeps long pieces accurate).
        var sum = 0;
        var c = 0;
        pieces.forEach(function (p) {
            p.t0 = sum;
            if (p.duration !== Infinity) {
                var y = p.duration - c;
                var t = sum + y;
                c = (t - sum) - y;
                sum = t;
            }
        });

        function pieceIndexAtScore(s) {
            var lo = 0;
            var hi = pieces.length - 1;
            while (lo < hi) {
                var mid = (lo + hi + 1) >> 1;
                if (R.le(pieces[mid].start, s)) lo = mid; else hi = mid - 1;
            }
            return lo;
        }

        function pieceIndexAtTime(t) {
            var lo = 0;
            var hi = pieces.length - 1;
            while (lo < hi) {
                var mid = (lo + hi + 1) >> 1;
                if (pieces[mid].t0 <= t) lo = mid; else hi = mid - 1;
            }
            return lo;
        }

        // Seconds from score position 0 to s (s >= 0).
        function timeAt(s) {
            if (R.lt(s, R.ZERO)) throw TempoError('negative-position');
            var p = pieces[pieceIndexAtScore(s)];
            var u = R.toNumber(R.div(R.sub(s, p.start), p.reference));
            // The exact end of a piece is its prefix sum (no inverse rounding).
            if (p.end && R.eq(s, p.end)) return p.t0 + p.duration;
            return p.t0 + timeOfBeats(p, u);
        }

        // Score position (as a number of whole notes) at t seconds.
        function scoreAt(t) {
            var p = pieces[pieceIndexAtTime(Math.max(0, t))];
            var local = Math.max(0, t - p.t0);
            if (p.duration !== Infinity) local = Math.min(local, p.duration);
            return R.toNumber(p.start) + beatsAtTime(p, local) * R.toNumber(p.reference);
        }

        function tempoAt(s) {
            var p = pieces[pieceIndexAtScore(s)];
            var u = R.toNumber(R.div(R.sub(s, p.start), p.reference));
            var t = timeOfBeats(p, u);
            return { bpm: bpmAtTime(p, t), reference: p.reference };
        }

        // Local duration in seconds of one reference beat at s (used for
        // "% of a beat" timing values, design 14).
        function beatSecondsAt(s) {
            return 60 / tempoAt(s).bpm;
        }

        return {
            pieces: pieces,
            timeAt: timeAt,
            scoreAt: scoreAt,
            tempoAt: tempoAt,
            beatSecondsAt: beatSecondsAt,
        };
    }

    // Absolute tempo map of a snapshot (score kind: curves per bar occurrence
    // and metric modulations; loop kinds: the base tempo).
    function fromSnapshot(snapshot, extraSteps) {
        var initial = { bpm: snapshot.tempo.bpmTenths / 10, reference: snapshot.tempo.reference };
        var segments = [];
        var steps = (extraSteps || []).slice();
        if (!snapshot.loop) {
            var occ = snapshot.occurrences;
            var firstByBar = {};
            occ.forEach(function (o) { (firstByBar[o.barId] = firstByBar[o.barId] || []).push(o); });
            var absolute = function (pos, after) {
                // The occurrence of pos.barId at or after `after` (start of the curve).
                var list = firstByBar[pos.barId] || [];
                for (var i = 0; i < list.length; i += 1) {
                    var at = R.add(list[i].start, pos.offset);
                    if (!after || R.ge(at, after)) return at;
                }
                return null;
            };
            snapshot.tempoMap.forEach(function (c, idx) {
                (firstByBar[c.start.barId] || []).forEach(function (o) {
                    var start = R.add(o.start, c.start.offset);
                    var end = absolute(c.end, start);
                    if (!end || !R.lt(start, end)) throw TempoError('curve-end-before-start', { index: idx });
                    segments.push({ start: start, end: end, reference: c.reference, b0: c.startBpmTenths / 10, b1: c.endBpmTenths / 10, curve: c.curve });
                });
            });
            // Metric modulation: old note value at the old tempo lasts as long
            // as the new note value at the new tempo (same reference):
            // Bnew = Bold * new / old (old 1/4 = new 3/16: 120 -> 90).
            var mods = [];
            snapshot.events.modulations.forEach(function (m) {
                (firstByBar[m.at.barId] || []).forEach(function (o) {
                    mods.push({ at: R.add(o.start, m.at.offset), ratio: R.toNumber(R.div(m.newValue, m.oldValue)) });
                });
            });
            mods.sort(function (a, b) { return R.cmp(a.at, b.at); });
            if (mods.length) {
                // Resolve each modulation against the tempo in force just before it.
                var partial = createTempoMap({ initial: initial, segments: segments, steps: steps });
                mods.forEach(function (m) {
                    var before = partial.tempoAt(m.at);
                    var probe = R.sub(m.at, R.make(1, 1000000));
                    if (R.ge(probe, R.ZERO)) before = partial.tempoAt(probe);
                    steps.push({ at: m.at, bpm: before.bpm * m.ratio, reference: before.reference });
                    partial = createTempoMap({ initial: initial, segments: segments, steps: steps });
                });
            }
        }
        var map = createTempoMap({ initial: initial, segments: segments, steps: steps });
        // Derived tempos (metric modulation, steps) stay inside the limits too.
        var limits = lib.scoreModel ? lib.scoreModel.LIMITS : { minBpmTenths: 200, maxBpmTenths: 3000 };
        map.pieces.forEach(function (p, i) {
            [p.b0, p.b1].forEach(function (b) {
                var tenths = Math.round(b * 10);
                if (tenths < limits.minBpmTenths || tenths > limits.maxBpmTenths) throw TempoError('bpm-out-of-range', { piece: i, bpm: b });
            });
        });
        return map;
    }

    // Highest BPM of the map expressed as whole notes per second (for the
    // density preflight).
    function maxWholeNotesPerSecond(map) {
        var max = 0;
        map.pieces.forEach(function (p) {
            var w = Math.max(p.b0, p.b1) / 60 * R.toNumber(p.reference);
            if (w > max) max = w;
        });
        return max;
    }

    var api = {
        maxWholeNotesPerSecond: maxWholeNotesPerSecond,
        CONSTANT_EPSILON: CONSTANT_EPSILON,
        durationOf: durationOf,
        createTempoMap: createTempoMap,
        fromSnapshot: fromSnapshot,
        TempoError: TempoError,
    };

    lib.releases = lib.releases || {};
    lib.tempoMap = api;
    lib.releases.tempo_map = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
