// Metronome launcher: loaded by the laboratory module (not by index.html,
// whose initial scripts stay unchanged).
//
// It owns the launch generation: every enter/leave bumps it, so a slow
// asset load that finishes after the user left never mounts the screen.
// Unlike the tuner it creates no AudioContext on entry: the metronome's
// context is created by the play button itself (inside that tap), and the
// basic click needs no microphone.
//
// Releases: metronome files carry m-<hash>, the shared audio files a-<hash>
// (scripts/generate_metronome_release.mjs). Every loaded file must report
// the expected id; a mixed cache stops with a reload hint (MT-19).
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var METRONOME_AUDIO_RELEASE_ID = 'a-bab6e0cd35e7'; // metronome-audio-release-id (generated by scripts/generate_metronome_release.mjs)
    var BASE_URL = '/static/js/modules/metronome/';
    var AUDIO_BASE_URL = '/static/js/modules/audio/';
    var CSS_URL = '/static/css/metronome.css';
    var AUDIO_SCRIPTS = ['output_manager'];
    // Ordered: later files depend on earlier ones.
    var MAIN_SCRIPTS = ['rational', 'score_model', 'tempo_map', 'event_compiler', 'sounds', 'playback', 'transport', 'settings', 'presets', 'tap', 'view', 'index'];
    // The click engine alone, for the tuner's metronome exercise (adapter).
    var ENGINE_SCRIPTS = ['rational', 'score_model', 'tempo_map', 'event_compiler', 'sounds', 'playback', 'transport', 'tuner_adapter'];
    var SYSTEM_ADMIN_PERMISSION = 'システム管理者';

    // env: { release, audioRelease, isAllowed(), hostVisible(host), isDocumentVisible(),
    //        loadAssets(names, kind), createBody(launcher), renderFallback(host, kind, retry) }
    function createMetronomeLauncher(env) {
        var release = env.release || METRONOME_RELEASE_ID;
        var generation = 0;
        var body = null;
        var activeHost = null;
        var loadPromise = null;
        var groupPromises = {};
        var suspended = false;

        function loadMain() {
            if (body) return Promise.resolve(body);
            if (!loadPromise) {
                loadPromise = Promise.resolve()
                    .then(function () { return env.loadAssets(AUDIO_SCRIPTS, 'audio'); })
                    .then(function () { return env.loadAssets(MAIN_SCRIPTS, 'metronome'); })
                    .then(function () {
                        if (!body) body = env.createBody(api);
                        return body;
                    })
                    .catch(function (error) {
                        loadPromise = null; // a retry requests only what failed
                        throw error;
                    });
            }
            return loadPromise;
        }

        function showing(host) {
            return env.isAllowed() && env.isDocumentVisible() && env.hostVisible(host);
        }

        function enter(host) {
            if (!host) return Promise.resolve(false);
            if (!env.isAllowed()) return Promise.resolve(false);
            generation += 1;
            var gen = generation;
            activeHost = host;
            suspended = false;
            if (body && body.isMounted()) return Promise.resolve(true); // already showing (repeated tap)
            return loadMain().then(function (b) {
                if (gen !== generation || !showing(host)) return false; // left while loading
                b.mount(host, gen);
                return true;
            }, function (error) {
                if (gen !== generation) return false;
                env.renderFallback(host, error && /release/.test(error.message) ? 'release-mismatch' : 'load-failed', function () { void enter(host); });
                return false;
            });
        }

        // Synchronous and idempotent; never waits for pending loads.
        function leave(reason) {
            generation += 1;
            suspended = false;
            if (body && body.isMounted()) body.leave(reason || 'leave');
            activeHost = null;
        }

        function onHidden() {
            if (body && body.isMounted() && !suspended) {
                suspended = true;
                body.suspend('background');
            }
        }

        function onVisible() {
            if (!suspended) return;
            suspended = false;
            if (body && body.isMounted() && activeHost && showing(activeHost)) body.resumeVisible();
        }

        // Lazily loaded screens (design 2: 遅延グループ). A failure is not cached.
        function ensureGroup(names) {
            var key = names.join(',');
            if (!groupPromises[key]) {
                groupPromises[key] = Promise.resolve(env.loadAssets(names, 'metronome')).catch(function (error) {
                    delete groupPromises[key];
                    throw error;
                });
            }
            return groupPromises[key];
        }

        // Loads only the engine (no screen, no audio, no microphone).
        var enginePromise = null;
        function loadEngine() {
            if (!enginePromise) {
                enginePromise = Promise.resolve()
                    .then(function () { return env.loadAssets(AUDIO_SCRIPTS, 'audio'); })
                    .then(function () { return env.loadAssets(ENGINE_SCRIPTS, 'metronome'); })
                    .catch(function (error) {
                        enginePromise = null;
                        throw error;
                    });
            }
            return enginePromise;
        }

        var api = {
            release: release,
            loadEngine: loadEngine,
            enter: enter,
            leave: leave,
            onHidden: onHidden,
            onVisible: onVisible,
            ensureGroup: ensureGroup,
            getBody: function () { return body; },
            getGeneration: function () { return generation; },
        };
        return api;
    }

    // ----- browser wiring ------------------------------------------------------------

    function browserIsAllowed() {
        var context = globalObj.portalRuntimeContext;
        var appState = context && context.appState;
        return Boolean(appState) && appState.portalAuthVerified === true && appState.currentUserPermission === SYSTEM_ADMIN_PERMISSION;
    }

    function browserHostVisible(host) {
        if (!host || !host.isConnected) return false;
        if (host.closest('[hidden]')) return false;
        return host.getClientRects().length > 0;
    }

    function browserLoadAssets(names, kind) {
        var doc = globalObj.document;
        var isAudio = kind === 'audio';
        var expected = isAudio ? METRONOME_AUDIO_RELEASE_ID : METRONOME_RELEASE_ID;
        var query = '?rev=' + encodeURIComponent(expected);
        if (!isAudio && !doc.querySelector('link[data-metronome-style]')) {
            var link = doc.createElement('link');
            link.rel = 'stylesheet';
            link.href = CSS_URL + '?rev=' + encodeURIComponent(METRONOME_RELEASE_ID);
            link.setAttribute('data-metronome-style', 'true');
            link.addEventListener('error', function () { link.remove(); }, { once: true });
            doc.head.appendChild(link);
        }
        var libName = isAudio ? 'PortalAudioLib' : 'PortalMetronomeLib';
        var releases = (globalObj[libName] && globalObj[libName].releases) || {};
        var pending = names.filter(function (name) { return releases[name] !== expected; });
        return Promise.all(pending.map(function (name) {
            return new Promise(function (resolve, reject) {
                var script = doc.createElement('script');
                script.src = (isAudio ? AUDIO_BASE_URL : BASE_URL) + name + '.js' + query;
                script.async = false; // keep execution order while downloading in parallel
                script.setAttribute('data-metronome-script', name);
                script.addEventListener('load', function () { resolve(); }, { once: true });
                script.addEventListener('error', function () {
                    script.remove();
                    reject(new Error('metronome script failed to load: ' + name));
                }, { once: true });
                doc.head.appendChild(script);
            });
        })).then(function () {
            var after = (globalObj[libName] && globalObj[libName].releases) || {};
            var mismatched = names.filter(function (name) { return after[name] !== expected; });
            if (mismatched.length) throw new Error('metronome release mismatch: ' + mismatched.join(', '));
        });
    }

    function browserRenderFallback(host, kind, onRetry) {
        var doc = globalObj.document;
        var box = doc.createElement('div');
        box.className = 'metronome-fallback';
        box.setAttribute('role', 'status');
        var p = doc.createElement('p');
        p.textContent = kind === 'release-mismatch'
            ? 'メトロノームの新しい版が配信されています。ページを再読み込みしてください。'
            : 'メトロノームを読み込めませんでした。通信状態を確認してから、もう一度お試しください。';
        box.appendChild(p);
        var b = doc.createElement('button');
        b.type = 'button';
        b.className = 'btn btn-outline-primary';
        b.textContent = kind === 'release-mismatch' ? '再読み込み' : 'もう一度読み込む';
        b.addEventListener('click', function () {
            if (kind === 'release-mismatch') globalObj.location.reload();
            else onRetry();
        });
        box.appendChild(b);
        host.replaceChildren(box);
    }

    function safeLocalStorage() {
        try { return globalObj.localStorage; } catch (_) { return null; }
    }

    // Device id of the signed-in device (sent as X-Device-Id like the tuner).
    function browserDeviceId() {
        var storage = safeLocalStorage();
        var context = globalObj.portalRuntimeContext;
        var key = context && context.PORTAL_DEVICE_ID_KEY;
        try {
            return storage && key ? storage.getItem(key) || '' : '';
        } catch (_) {
            return '';
        }
    }

    function browserCreateBody(launcher) {
        var nav = globalObj.navigator || {};
        var perf = globalObj.performance;
        var mql = typeof globalObj.matchMedia === 'function' ? globalObj.matchMedia('(prefers-reduced-motion: reduce)') : null;
        var lib = globalObj.PortalMetronomeLib;
        return lib.index.createMetronomeBody({
            lib: lib,
            audioLib: globalObj.PortalAudioLib,
            release: METRONOME_RELEASE_ID,
            storage: safeLocalStorage(),
            indexedDB: globalObj.indexedDB,
            IDBKeyRange: globalObj.IDBKeyRange,
            // History / account sync (loaded only after the user enables history).
            request: typeof globalObj.fetch === 'function' ? globalObj.fetch.bind(globalObj) : null,
            deviceId: browserDeviceId,
            BroadcastChannel: typeof globalObj.BroadcastChannel === 'function' ? globalObj.BroadcastChannel : null,
            storageEstimate: nav.storage && typeof nav.storage.estimate === 'function' ? function () { return nav.storage.estimate(); } : null,
            storageManager: nav.storage || null,
            // Microphone for the explicit timing analysis only (never for the click).
            getUserMedia: nav.mediaDevices && typeof nav.mediaDevices.getUserMedia === 'function' ? nav.mediaDevices.getUserMedia.bind(nav.mediaDevices) : null,
            now: function () { return perf.now(); },
            utcNow: function () { return Date.now(); },
            setTimeout: globalObj.setTimeout.bind(globalObj),
            clearTimeout: globalObj.clearTimeout.bind(globalObj),
            setInterval: globalObj.setInterval.bind(globalObj),
            clearInterval: globalObj.clearInterval.bind(globalObj),
            requestAnimationFrame: globalObj.requestAnimationFrame.bind(globalObj),
            cancelAnimationFrame: globalObj.cancelAnimationFrame.bind(globalObj),
            isDocumentVisible: function () { return globalObj.document.visibilityState === 'visible'; },
            hostVisible: browserHostVisible,
            isAllowed: browserIsAllowed,
            AudioContext: globalObj.AudioContext || globalObj.webkitAudioContext,
            locks: nav.locks,
            audioSession: nav.audioSession,
            wakeLock: nav.wakeLock,
            vibrate: typeof nav.vibrate === 'function' ? nav.vibrate.bind(nav) : null,
            reducedMotion: function () { return Boolean(mql && mql.matches); },
            workletUrl: BASE_URL + 'click_processor.js?rev=' + encodeURIComponent(METRONOME_RELEASE_ID),
            captureUrl: BASE_URL + 'capture_processor.js?rev=' + encodeURIComponent(METRONOME_RELEASE_ID),
            ensureGroup: launcher.ensureGroup,
            uuid: function () {
                var c = globalObj.crypto;
                if (c && typeof c.randomUUID === 'function') return c.randomUUID();
                var b = new Uint8Array(16);
                c.getRandomValues(b);
                b[6] = (b[6] & 0x0f) | 0x40;
                b[8] = (b[8] & 0x3f) | 0x80;
                var x = Array.prototype.map.call(b, function (v) { return ('0' + v.toString(16)).slice(-2); }).join('');
                return x.slice(0, 8) + '-' + x.slice(8, 12) + '-' + x.slice(12, 16) + '-' + x.slice(16, 20) + '-' + x.slice(20);
            },
            download: function (name, text, type) {
                var blob = new Blob([text], { type: type });
                var url = URL.createObjectURL(blob);
                var a = globalObj.document.createElement('a');
                a.href = url;
                a.download = name;
                a.click();
                globalObj.setTimeout(function () { URL.revokeObjectURL(url); }, 1000);
            },
        });
    }

    var api = {
        MAIN_SCRIPTS: MAIN_SCRIPTS,
        ENGINE_SCRIPTS: ENGINE_SCRIPTS,
        AUDIO_SCRIPTS: AUDIO_SCRIPTS,
        createMetronomeLauncher: createMetronomeLauncher,
    };
    if (typeof module !== 'undefined' && module.exports) module.exports = api;

    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};
    lib.releases = lib.releases || {};
    lib.releases.launcher = METRONOME_RELEASE_ID;

    if (typeof globalObj.document !== 'undefined' && globalObj.document && !globalObj.PortalMetronomeLauncher) {
        var launcher = createMetronomeLauncher({
            release: METRONOME_RELEASE_ID,
            isAllowed: browserIsAllowed,
            hostVisible: browserHostVisible,
            isDocumentVisible: function () { return globalObj.document.visibilityState === 'visible'; },
            loadAssets: browserLoadAssets,
            createBody: browserCreateBody,
            renderFallback: browserRenderFallback,
        });
        globalObj.PortalMetronomeLauncher = launcher;
        globalObj.document.addEventListener('visibilitychange', function () {
            if (globalObj.document.visibilityState === 'hidden') launcher.onHidden();
            else launcher.onVisible();
        });
        globalObj.addEventListener('pagehide', function () { launcher.onHidden(); });
    }
})(typeof window !== 'undefined' ? window : globalThis);
