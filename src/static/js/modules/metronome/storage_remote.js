// Metronome: client for the personal history API (/api/metronome,
// docs/METRONOME_DATA_API_DESIGN.md 8).
//
// - Only summaries are sent: the session statistics and at most 256 groups
//   per beat position / condition in a single part (index 0). Individual
//   observations, onset times, calibration values, audio and PCM are never
//   part of a request; unknown fields are dropped by the whitelists below.
// - The owner is resolved by the server; the client never chooses it.
//   Requests carry the owner epoch they started with; after logout / owner
//   change they are aborted and their results discarded.
// - Network timeout 10 s (tuning value) with AbortController; responses are
//   not cached (personal data on a possibly shared device).
(function (globalObj) {
    'use strict';

    var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
    var lib = globalObj.PortalMetronomeLib = globalObj.PortalMetronomeLib || {};

    var SCHEMA_VERSION = 1;
    var BASE = '/api/metronome';
    var TIMEOUT_MS = 10000;
    var LIMITS = {
        maxGroups: 256,
        groupsBytes: 128 * 1024,
        scoreSummaryBytes: 64 * 1024,
        summaryBytes: 32 * 1024,
        bodyBytes: 256 * 1024,
        groupBytes: 512,
    };

    var SESSION_FIELDS = ['sessionId', 'attemptId', 'programId', 'startedAt', 'durationMs', 'versions', 'scoreSummary', 'counts', 'conditionKey', 'contentHash'];
    var COUNT_FIELDS = ['target', 'valid', 'localDetail', 'extraDetail', 'extraTotal', 'groups'];
    var GROUP_FIELDS = ['ordinal', 'conditionKey', 'layerKey', 'beatPositionKey', 'targetCount', 'validCount', 'missingCount', 'extraTotal', 'excludedByReason', 'stats', 'quality'];
    var STATS_FIELDS = ['medianMs', 'madMs', 'sdMs', 'ioiRatioStats', 'verdict'];
    var QUALITY_FIELDS = ['calibrated', 'confidenceClass', 'extraDetailsTruncated'];

    function pick(source, fields) {
        var out = {};
        fields.forEach(function (f) { if (source && source[f] !== undefined) out[f] = source[f]; });
        return out;
    }

    // JSON must not carry NaN / Infinity or typed arrays.
    function clean(value) {
        if (value === null || value === undefined) return null;
        if (typeof value === 'number') return Number.isFinite(value) ? value : null;
        if (ArrayBuffer.isView && ArrayBuffer.isView(value)) return null;
        if (value instanceof ArrayBuffer) return null;
        if (Array.isArray(value)) return value.map(clean);
        if (typeof value === 'object') {
            var out = {};
            Object.keys(value).forEach(function (k) { out[k] = clean(value[k]); });
            return out;
        }
        return value;
    }

    function bytes(value) {
        var text = JSON.stringify(value);
        return typeof TextEncoder === 'function' ? new TextEncoder().encode(text).length : text.length * 3;
    }

    // FNV-1a 32-bit (integrity check, not security).
    function hashText(text) {
        var h = 0x811c9dc5;
        for (var i = 0; i < text.length; i += 1) { h ^= text.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
        return ('00000000' + h.toString(16)).slice(-8);
    }

    function sanitizeGroup(g) {
        var out = pick(g, GROUP_FIELDS);
        out.stats = clean(pick(g.stats || {}, STATS_FIELDS));
        out.quality = clean(pick(g.quality || {}, QUALITY_FIELDS));
        out.excludedByReason = clean(g.excludedByReason || {});
        return clean(out);
    }

    function sanitizeSession(s) {
        var out = clean(pick(s, SESSION_FIELDS));
        out.counts = clean(pick(s.counts || {}, COUNT_FIELDS));
        return out;
    }

    // Validates the summary before anything is sent (design 5.1.4). Over a
    // limit: the upload is held back locally with a reason, never truncated.
    function prepareUpload(session, groups, summary) {
        var s = sanitizeSession(session);
        var g = (groups || []).map(sanitizeGroup);
        var sum = clean(summary || {});
        if (g.length > LIMITS.maxGroups) return { ok: false, code: 'too-many-groups' };
        if (g.some(function (x) { return bytes(x) > LIMITS.groupBytes; })) return { ok: false, code: 'group-too-large' };
        if (bytes(g) > LIMITS.groupsBytes) return { ok: false, code: 'groups-too-large' };
        if (bytes(s.scoreSummary || {}) > LIMITS.scoreSummaryBytes) return { ok: false, code: 'score-summary-too-large' };
        if (bytes(sum) > LIMITS.summaryBytes) return { ok: false, code: 'summary-too-large' };
        var partText = JSON.stringify(g);
        var part = { index: 0, groups: g, hash: hashText(partText) };
        if (bytes({ session: s, groups: g, summary: sum }) > LIMITS.bodyBytes) return { ok: false, code: 'body-too-large' };
        return { ok: true, session: s, part: part, summary: sum };
    }

    function errorCode(status, code) {
        if (status === 0) return 'network';
        if (status === 401) return 'unauthenticated';
        if (status === 403) return code === 'ACCOUNT_STORAGE_UNAVAILABLE' ? 'account-storage-unavailable' : 'forbidden';
        if (status === 404) return 'not-found';
        if (status === 409) return code || 'conflict';
        if (status === 413) return 'too-large';
        if (status === 429) return 'rate-limit';
        if (status === 400 || status === 422) return 'invalid';
        if (status >= 500) return 'unavailable';
        return 'failed';
    }

    // env: { request (fetch), deviceId(), setTimeout, clearTimeout }
    function createRemoteClient(env) {
        var ownerEpoch = 0;
        var controllers = [];

        function invalidate() {
            ownerEpoch += 1;
            controllers.forEach(function (c) { try { c.abort(); } catch (_) { /* ignore */ } });
            controllers = [];
        }

        function call(method, path, body) {
            var startedEpoch = ownerEpoch;
            var send = typeof env.request === 'function' ? env.request : (typeof globalObj.fetch === 'function' ? globalObj.fetch.bind(globalObj) : null);
            if (!send) return Promise.resolve({ ok: false, status: 0, code: 'network' });
            var controller = typeof AbortController === 'function' ? new AbortController() : null;
            if (controller) controllers.push(controller);
            var timer = env.setTimeout(function () { if (controller) controller.abort(); }, TIMEOUT_MS);
            var headers = { Accept: 'application/json' };
            var device = typeof env.deviceId === 'function' ? env.deviceId() : '';
            if (device) headers['X-Device-Id'] = device;
            if (body !== undefined) headers['Content-Type'] = 'application/json';
            function finish() {
                env.clearTimeout(timer);
                controllers = controllers.filter(function (c) { return c !== controller; });
            }
            return Promise.resolve().then(function () {
                return send(BASE + path, {
                    method: method,
                    headers: headers,
                    body: body === undefined ? undefined : JSON.stringify(clean(body)),
                    signal: controller ? controller.signal : undefined,
                    cache: 'no-store',
                    credentials: 'same-origin',
                });
            }).then(function (response) {
                return response.text().then(function (text) {
                    finish();
                    var data = null;
                    try { data = text ? JSON.parse(text) : null; } catch (_) { data = null; }
                    if (startedEpoch !== ownerEpoch) return { ok: false, status: response.status, code: 'stale-owner' };
                    if (!response.ok) {
                        var detail = data && (data.detail || data.error);
                        var code = detail && typeof detail === 'object' ? detail.code : detail;
                        return { ok: false, status: response.status, code: errorCode(response.status, code), detail: code || null };
                    }
                    return { ok: true, status: response.status, data: data };
                });
            }, function () {
                finish();
                return { ok: false, status: 0, code: startedEpoch !== ownerEpoch ? 'stale-owner' : 'network' };
            });
        }

        function withEpoch(ctx, payload) {
            return Object.assign({ schemaVersion: SCHEMA_VERSION, historyEpoch: ctx.historyEpoch, consentRevision: ctx.consentRevision }, payload);
        }

        return {
            invalidate: invalidate,
            epoch: function () { return ownerEpoch; },
            identity: function () { return call('GET', '/identity'); },
            getPreferences: function () { return call('GET', '/preferences'); },
            putPreferences: function (expectedRevision, accountConsent, consentVersion) {
                return call('PUT', '/preferences', { schemaVersion: SCHEMA_VERSION, expectedRevision: expectedRevision, accountConsent: accountConsent === true, consentVersion: consentVersion || '' });
            },
            createSession: function (ctx, session) { return call('POST', '/sessions', withEpoch(ctx, sanitizeSession(session))); },
            putPart: function (ctx, sessionId, part) {
                return call('PUT', '/sessions/' + encodeURIComponent(sessionId) + '/parts/0', withEpoch(ctx, { payloadHash: part.hash, groups: part.groups }));
            },
            finalize: function (ctx, sessionId, part, summary, status, groupCount) {
                return call('POST', '/sessions/' + encodeURIComponent(sessionId) + '/finalize', withEpoch(ctx, { partHashes: [part.hash], eventCount: 0, groupCount: groupCount, summary: summary, status: status }));
            },
            listSessions: function (query) {
                var q = query || {};
                var params = [];
                ['from', 'to', 'condition', 'cursor', 'limit'].forEach(function (k) {
                    if (q[k] !== undefined && q[k] !== null && q[k] !== '') params.push(k + '=' + encodeURIComponent(q[k]));
                });
                return call('GET', '/sessions' + (params.length ? '?' + params.join('&') : ''));
            },
            getSession: function (id) { return call('GET', '/sessions/' + encodeURIComponent(id)); },
            deleteSession: function (ctx, id, operationId) { return call('DELETE', '/sessions/' + encodeURIComponent(id), { schemaVersion: SCHEMA_VERSION, operationId: operationId, historyEpoch: ctx.historyEpoch }); },
            deleteHistory: function (ctx, operationId) { return call('DELETE', '/history', { schemaVersion: SCHEMA_VERSION, operationId: operationId, historyEpoch: ctx.historyEpoch }); },
            // Account presets: only what the user explicitly saves (never the
            // device presets automatically).
            listPresets: function (limit) { return call('GET', '/presets?limit=' + encodeURIComponent(limit || 60)); },
            createPreset: function (ctx, envelope) { return call('POST', '/presets', withEpoch(ctx, { preset: envelope })); },
            deletePreset: function (ctx, id, operationId) { return call('DELETE', '/presets/' + encodeURIComponent(id), { schemaVersion: SCHEMA_VERSION, operationId: operationId, historyEpoch: ctx.historyEpoch }); },
            raw: call,
        };
    }

    // Sends the queued uploads of one owner (oldest first): create -> part 0
    // -> finalize, three writes per record. Operations of another epoch or
    // consent revision are dropped, never re-labelled (DC-16).
    // deps: { local, remote, ctx { ownerId, historyEpoch, consentRevision }, isCurrent(ctx), buildUpload(sessionRow) }
    function syncOutbox(deps) {
        var ctx = deps.ctx;
        var report = { sent: 0, dropped: 0, kept: 0, stoppedBy: null };
        return deps.local.outbox(ctx.ownerId).then(function (ops) {
            ops.sort(function (a, b) { return String(a.createdAt).localeCompare(String(b.createdAt)); });
            var chain = Promise.resolve();
            ops.forEach(function (op) {
                chain = chain.then(function () {
                    if (report.stoppedBy) return null;
                    if (!deps.isCurrent(ctx)) { report.stoppedBy = 'stale-owner'; return null; }
                    if (op.historyEpoch !== ctx.historyEpoch || op.consentRevision !== ctx.consentRevision) {
                        report.dropped += 1;
                        return deps.local.removeOperation(ctx.ownerId, op.operationId);
                    }
                    return upload(deps, ctx, op).then(function (result) {
                        if (!deps.isCurrent(ctx)) { report.stoppedBy = 'stale-owner'; return null; }
                        if (result.ok) {
                            report.sent += 1;
                            return deps.local.removeOperation(ctx.ownerId, op.operationId);
                        }
                        if (['unauthenticated', 'forbidden', 'account-storage-unavailable', 'stale-owner'].indexOf(result.code) >= 0) {
                            report.stoppedBy = result.code;
                            return null;
                        }
                        if (result.code === 'HISTORY_EPOCH' || result.code === 'CONSENT_REVISION' || result.code === 'CONSENT_REQUIRED') {
                            report.stoppedBy = result.code; // identity must be refreshed first
                            return null;
                        }
                        if (['not-found', 'invalid', 'too-large', 'SESSION_CONFLICT', 'PART_CONFLICT', 'deleted', 'too-many-groups', 'groups-too-large', 'body-too-large', 'group-too-large', 'summary-too-large', 'score-summary-too-large'].indexOf(result.code) >= 0) {
                            report.dropped += 1;
                            return deps.local.removeOperation(ctx.ownerId, op.operationId);
                        }
                        report.kept += 1;
                        return deps.local.updateOperation(Object.assign({}, op, { attempts: (op.attempts || 0) + 1, lastError: result.code }));
                    });
                });
            });
            return chain.then(function () { return report; });
        });
    }

    function upload(deps, ctx, op) {
        return deps.local.getSession(ctx.ownerId, op.sessionId).then(function (detail) {
            if (!detail) return { ok: false, code: 'deleted' };
            var built = deps.buildUpload(detail.session);
            if (!built.ok) return built;
            var remote = deps.remote;
            return remote.createSession(ctx, built.session).then(function (created) {
                if (!created.ok) return created;
                if (!deps.isCurrent(ctx)) return { ok: false, code: 'stale-owner' };
                return remote.putPart(ctx, op.sessionId, built.part).then(function (put) {
                    if (!put.ok) return put;
                    if (!deps.isCurrent(ctx)) return { ok: false, code: 'stale-owner' };
                    return remote.finalize(ctx, op.sessionId, built.part, built.summary, detail.session.status === 'complete' ? 'complete' : 'incomplete', built.part.groups.length);
                });
            });
        });
    }

    var api = {
        SCHEMA_VERSION: SCHEMA_VERSION,
        BASE: BASE,
        TIMEOUT_MS: TIMEOUT_MS,
        LIMITS: LIMITS,
        SESSION_FIELDS: SESSION_FIELDS,
        GROUP_FIELDS: GROUP_FIELDS,
        sanitizeSession: sanitizeSession,
        sanitizeGroup: sanitizeGroup,
        prepareUpload: prepareUpload,
        hashText: hashText,
        errorCode: errorCode,
        createRemoteClient: createRemoteClient,
        syncOutbox: syncOutbox,
    };

    lib.releases = lib.releases || {};
    lib.storageRemote = api;
    lib.releases.storage_remote = METRONOME_RELEASE_ID;
    if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
