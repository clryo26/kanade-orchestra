// Metronome: AudioWorklet microphone capture for the timing analysis.
//
// Runs in the input context only (never in the output manager's context).
// Collects mono input into a fixed buffer and posts a copy of every
// BLOCK_FRAMES frames together with the frame index of its first sample, so
// the main thread can place attacks on the input clock. The main thread
// turns the samples into envelope frames at once and drops them; nothing
// is stored or sent. Block length is read from the input each call.
/* global registerProcessor, AudioWorkletProcessor, currentFrame */
var METRONOME_RELEASE_ID = 'm-d398086cbcb2'; // metronome-release-id (generated by scripts/generate_metronome_release.mjs)
var BLOCK_FRAMES = 1024;

class PortalMetronomeCaptureProcessor extends AudioWorkletProcessor {
    constructor() {
        super();
        this.buffer = new Float32Array(BLOCK_FRAMES);
        this.fill = 0;
        this.firstFrame = 0;
    }

    process(inputs) {
        var input = inputs[0];
        var channel = input && input[0];
        if (!channel) return true;
        var n = channel.length;
        for (var i = 0; i < n; i += 1) {
            if (this.fill === 0) this.firstFrame = currentFrame + i;
            this.buffer[this.fill] = channel[i];
            this.fill += 1;
            if (this.fill === BLOCK_FRAMES) {
                // The copy is transferred; the fixed buffer is reused.
                var copy = this.buffer.slice(0);
                this.port.postMessage({ type: 'block', frame: this.firstFrame, samples: copy, release: METRONOME_RELEASE_ID }, [copy.buffer]);
                this.fill = 0;
            }
        }
        return true;
    }
}

registerProcessor('portal-metronome-capture-v1-' + METRONOME_RELEASE_ID, PortalMetronomeCaptureProcessor);
