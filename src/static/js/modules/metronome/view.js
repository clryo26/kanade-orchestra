    function h(tag, attrs, children) {
        var doc = globalObj.document;
        var el = doc.createElement(tag);
        Object.keys(attrs || {}).forEach(function (k) {
            var v = attrs[k];
            if (v === undefined || v === null || v === false) return;
            if (k === 'text') el.textContent = v;
            else if (k === 'className') el.className = v;
            else if (k === 'hidden') el.hidden = Boolean(v);
            else if (k === 'disabled') el.disabled = Boolean(v);
            else if (k === 'checked') el.checked = Boolean(v);
            else if (k === 'value') el.value = v;
            else el.setAttribute(k, v === true ? '' : String(v));
        });
        (children || []).forEach(function (c) {
            if (c === null || c === undefined) return;
            el.appendChild(typeof c === 'string' ? doc.createTextNode(c) : c);
        });
        return el;
    }

    function select(attrs, options, current) {
        var el = h('select', Object.assign({ className: 'form-select metronome-select' }, attrs));
        options.forEach(function (o) {
            var opt = h('option', { value: String(o.value), text: o.label });
            if (String(o.value) === String(current)) opt.selected = true;
            el.appendChild(opt);
        });
        return el;
    }

    function field(labelText, control, hint) {
        var id = control.id || ('metronome-f-' + Math.random().toString(36).slice(2, 9));
        control.id = id;
        return h('div', { className: 'metronome-field' }, [
            h('label', { for: id, text: labelText }),
            control,
            hint ? h('p', { className: 'metronome-hint', text: hint }) : null,
        ]);
    }

    function noteLabel(value) {
        var n = NOTE_VALUES.filter(function (x) { return x.value === value; })[0];
        return n ? n.symbol : value;
    }

