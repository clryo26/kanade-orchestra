    function createShell(host, handlers) {
        var root = h('div', { className: 'metronome', 'data-metronome-root': 'true' });
        var status = h('div', { className: 'metronome-statusbar', 'data-metronome-statusbar': 'true', 'aria-live': 'polite' }, [
            h('span', { className: 'metronome-chip', 'data-metronome-chip-state': 'true', text: '停止中' }),
            h('span', { className: 'metronome-chip', 'data-metronome-chip-input': 'true', text: 'マイク：使っていません' }),
            h('span', { className: 'metronome-chip', 'data-metronome-chip-save': 'true', text: '記録：保存しない' }),
        ]);
        var message = h('div', { className: 'metronome-message', role: 'status', 'data-metronome-message': 'true', hidden: true });
        var tabbar = h('div', { className: 'metronome-tabbar', role: 'tablist', 'aria-label': 'メトロノームの画面' });
        var panels = {};
        TABS.forEach(function (t, i) {
            var b = h('button', { type: 'button', className: 'metronome-tab', role: 'tab', id: 'metronomeTab-' + t.id, 'aria-controls': 'metronomePanel-' + t.id, 'aria-selected': i === 0 ? 'true' : 'false', 'data-metronome-tab': t.id, text: t.label });
            b.tabIndex = i === 0 ? 0 : -1;
            tabbar.appendChild(b);
            panels[t.id] = h('section', { className: 'metronome-panel', id: 'metronomePanel-' + t.id, role: 'tabpanel', 'aria-labelledby': 'metronomeTab-' + t.id, 'data-metronome-panel': t.id, hidden: i !== 0 });
        });
        var position = h('output', { className: 'metronome-position', 'data-metronome-position': 'true', text: '—' });
        var play = h('button', { type: 'button', className: 'btn btn-primary metronome-play', 'data-metronome-play': 'true', 'aria-pressed': 'false', text: '再生' });
        var pause = h('button', { type: 'button', className: 'btn btn-outline-secondary metronome-pause', 'data-metronome-pause': 'true', disabled: true, text: '一時停止' });
        var resumeF = h('button', { type: 'button', className: 'btn btn-warning metronome-resume-fermata', 'data-metronome-resume-fermata': 'true', hidden: true, text: 'フェルマータから再開' });
        var takeoverBtn = h('button', { type: 'button', className: 'btn btn-outline-warning metronome-takeover', 'data-metronome-takeover': 'true', hidden: true, text: 'このタブで使う' });
        var transportBar = h('div', { className: 'metronome-transport', 'data-metronome-transport': 'true' }, [position, play, pause, resumeF, takeoverBtn]);
        var announcer = h('div', { className: 'metronome-announcer', 'aria-live': 'polite', 'data-metronome-announcer': 'true' });
        root.appendChild(status);
        root.appendChild(message);
        root.appendChild(tabbar);
        TABS.forEach(function (t) { root.appendChild(panels[t.id]); });
        root.appendChild(transportBar);
        root.appendChild(announcer);
        host.replaceChildren(root);

        var current = 'basic';
        function selectTab(id, focus) {
            if (!panels[id]) return;
            current = id;
            Array.prototype.forEach.call(tabbar.children, function (b) {
                var active = b.getAttribute('data-metronome-tab') === id;
                b.setAttribute('aria-selected', active ? 'true' : 'false');
                b.tabIndex = active ? 0 : -1;
                if (active && focus) b.focus();
            });
            Object.keys(panels).forEach(function (k) { panels[k].hidden = k !== id; });
            if (handlers.onTab) handlers.onTab(id);
        }
        tabbar.addEventListener('click', function (e) {
            var b = e.target.closest('[data-metronome-tab]');
            if (b) selectTab(b.getAttribute('data-metronome-tab'), false);
        });
        tabbar.addEventListener('keydown', function (e) {
            var ids = TABS.map(function (t) { return t.id; });
            var i = ids.indexOf(current);
            var next = null;
            if (e.key === 'ArrowRight') next = ids[(i + 1) % ids.length];
            else if (e.key === 'ArrowLeft') next = ids[(i - 1 + ids.length) % ids.length];
            else if (e.key === 'Home') next = ids[0];
            else if (e.key === 'End') next = ids[ids.length - 1];
            if (next) { e.preventDefault(); selectTab(next, true); }
        });
        // pointerdown: the AudioContext must be created inside the gesture,
        // and "click" after a scroll is not always a valid activation (iOS).
        play.addEventListener('click', function () { handlers.onPlay(); });
        pause.addEventListener('click', function () { handlers.onPause(); });
        resumeF.addEventListener('click', function () { handlers.onResumeFermata(); });
        takeoverBtn.addEventListener('click', function () { handlers.onTakeover(); });

        var STATE_TEXT = { stopped: '停止中', running: '再生中', paused: '一時停止中', waiting: 'フェルマータで待機中', interrupted: '中断しました', preparing: '準備中', busy: '別のタブで使用中' };

        return {
            root: root,
            panels: panels,
            selectTab: selectTab,
            currentTab: function () { return current; },
            setState: function (state, info) {
                var chip = root.querySelector('[data-metronome-chip-state]');
                chip.textContent = STATE_TEXT[state] || state;
                root.setAttribute('data-state', state);
                var playing = state === 'running' || state === 'waiting';
                play.textContent = playing ? '停止' : (state === 'paused' || state === 'interrupted' ? '最初から再生' : '再生');
                play.setAttribute('aria-pressed', playing ? 'true' : 'false');
                pause.disabled = !(state === 'running' || state === 'paused' || state === 'interrupted');
                pause.textContent = state === 'paused' || state === 'interrupted' ? '続きから再生' : '一時停止';
                resumeF.hidden = state !== 'waiting';
                if (info && info.fermata) resumeF.textContent = info.fermata.resumeCountInPulses ? 'フェルマータから再開（予備拍 ' + info.fermata.resumeCountInPulses + '）' : 'フェルマータから再開';
            },
            // Shown only when another tab stopped answering (confirmed takeover).
            setTakeover: function (on) { takeoverBtn.hidden = !on; },
            setPreparing: function (preparing) {
                play.disabled = Boolean(preparing);
            },
            setChip: function (name, text) {
                var chip = root.querySelector('[data-metronome-chip-' + name + ']');
                if (chip) chip.textContent = text;
            },
            setPosition: function (text) { position.textContent = text; },
            showMessage: function (text, kind) {
                message.hidden = !text;
                message.textContent = text || '';
                message.setAttribute('data-kind', kind || 'info');
            },
            announce: function (text) { announcer.textContent = text; },
        };
    }

