    function renderRhythm(panel, model, handlers) {
        panel.replaceChildren();
        var num = select({ 'data-metronome-numerator': 'true' }, Array.from({ length: 32 }, function (_, i) { return { value: i + 1, label: String(i + 1) }; }), model.meter[0]);
        var den = select({ 'data-metronome-denominator': 'true' }, [1, 2, 4, 8, 16, 32].map(function (d) { return { value: d, label: String(d) }; }), model.meter[1]);
        var groups = h('input', { type: 'text', inputmode: 'numeric', className: 'form-control metronome-input', 'data-metronome-groups': 'true', autocomplete: 'off', value: model.groups.join('+') });
        var pulse = select({ 'data-metronome-pulse': 'true' }, NOTE_VALUES, model.pulse);
        var reference = select({ 'data-metronome-reference': 'true' }, NOTE_VALUES, model.reference);
        var keep = h('input', { type: 'checkbox', className: 'form-check-input', id: 'metronomeKeepSpeed', 'data-metronome-keep-speed': 'true', checked: true });
        var sub = select({ 'data-metronome-subdivision': 'true' }, SUBDIVISIONS, model.subdivision || 'none');
        var sound = select({ 'data-metronome-sound': 'true' }, (lib.sounds ? lib.sounds.SELECTABLE : ['click']).map(function (id) { return { value: id, label: lib.sounds ? lib.sounds.CATALOG[id].label : id }; }), model.soundId);
        var apply = select({ 'data-metronome-apply-mode': 'true' }, [
            { value: 'nextPulse', label: '次の拍から（初期）' },
            { value: 'nextBar', label: '次の小節から' },
            { value: 'immediate', label: 'すぐに（次の細かい刻みから）' },
        ], model.applyMode);
        var error = h('p', { className: 'metronome-error', role: 'alert', 'data-metronome-rhythm-error': 'true', hidden: true });
        var accents = h('div', { className: 'metronome-accents', role: 'group', 'aria-label': '拍ごとのアクセント', 'data-metronome-accents': 'true' });
        var groupsAccent = h('div', { className: 'metronome-accents', role: 'group', 'aria-label': '拍グループの先頭のアクセント', 'data-metronome-group-accents': 'true' });

        panel.appendChild(h('div', { className: 'metronome-grid' }, [field('拍子の分子', num), field('拍子の分母', den)]));
        panel.appendChild(field('拍グループ（例 2+2+3。合計が分子と同じ）', groups));
        panel.appendChild(field('刻み（クリックを鳴らす音価）', pulse));
        panel.appendChild(field('テンポの基準音符', reference));
        panel.appendChild(h('label', { className: 'metronome-check', for: 'metronomeKeepSpeed' }, [keep, ' 基準音符を変えても速さを保つ（数値を換算します）']));
        panel.appendChild(field('細分', sub));
        panel.appendChild(h('p', { className: 'metronome-section-label', text: '拍グループの先頭' }));
        panel.appendChild(groupsAccent);
        panel.appendChild(h('p', { className: 'metronome-section-label', text: '刻みごとのアクセント（押すと 強→中→弱→休）' }));
        panel.appendChild(accents);
        panel.appendChild(field('音色', sound));
        panel.appendChild(field('再生中の変更を反映する位置', apply));
        panel.appendChild(error);

        function levelLabel(v) {
            var best = ACCENT_LEVELS.reduce(function (a, b) { return Math.abs(b.value - v) < Math.abs(a.value - v) ? b : a; });
            return best.label;
        }

        function drawAccents(m) {
            accents.replaceChildren();
            m.accent.pulse.forEach(function (v, i) {
                accents.appendChild(h('button', { type: 'button', className: 'metronome-accent', 'data-metronome-accent': String(i), 'data-level': levelLabel(v), 'aria-label': (i + 1) + '番目の刻み：' + levelLabel(v), text: (i + 1) + ' ' + levelLabel(v) }));
            });
            groupsAccent.replaceChildren();
            m.accent.group.forEach(function (v, i) {
                groupsAccent.appendChild(h('button', { type: 'button', className: 'metronome-accent', 'data-metronome-group-accent': String(i), 'data-level': levelLabel(v), 'aria-label': (i + 1) + '番目の拍グループ：' + levelLabel(v), text: 'G' + (i + 1) + ' ' + levelLabel(v) }));
            });
        }
        drawAccents(model);

        function meterChange() { handlers.onMeter(Number(num.value), Number(den.value), groups.value); }
        num.addEventListener('change', meterChange);
        den.addEventListener('change', meterChange);
        groups.addEventListener('change', meterChange);
        pulse.addEventListener('change', function () { handlers.onPulse(pulse.value); });
        reference.addEventListener('change', function () { handlers.onReference(reference.value, keep.checked); });
        sub.addEventListener('change', function () { handlers.onSubdivision(sub.value); });
        sound.addEventListener('change', function () { handlers.onSound(sound.value); });
        apply.addEventListener('change', function () { handlers.onApplyMode(apply.value); });
        accents.addEventListener('click', function (e) {
            var b = e.target.closest('[data-metronome-accent]');
            if (b) handlers.onAccent('pulse', Number(b.getAttribute('data-metronome-accent')));
        });
        groupsAccent.addEventListener('click', function (e) {
            var b = e.target.closest('[data-metronome-group-accent]');
            if (b) handlers.onAccent('group', Number(b.getAttribute('data-metronome-group-accent')));
        });

        return {
            update: function (m) {
                num.value = String(m.meter[0]);
                den.value = String(m.meter[1]);
                if (globalObj.document.activeElement !== groups) groups.value = m.groups.join('+');
                pulse.value = m.pulse;
                reference.value = m.reference;
                sub.value = m.subdivision || 'none';
                sound.value = m.soundId;
                apply.value = m.applyMode;
                drawAccents(m);
            },
            setError: function (text) { error.hidden = !text; error.textContent = text || ''; },
        };
    }

