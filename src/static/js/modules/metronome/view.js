    function renderBasic(panel, model, handlers) {
        panel.replaceChildren();
        var bpm = h('output', { className: 'metronome-bpm', 'data-metronome-bpm': 'true', 'aria-live': 'off', text: (model.bpmTenths / 10).toFixed(1) });
        var ref = h('span', { className: 'metronome-bpm-ref', 'data-metronome-bpm-ref': 'true', text: noteLabel(model.reference) + ' =' });
        var stepButtons = h('div', { className: 'metronome-steps' }, [-10, -1, 1, 10].map(function (d) {
            return h('button', { type: 'button', className: 'btn btn-outline-primary metronome-step', 'data-metronome-bpm-step': String(d), 'aria-label': 'テンポを' + Math.abs(d) + (d < 0 ? '下げる' : '上げる'), text: (d > 0 ? '＋' : '−') + Math.abs(d) });
        }));
        var bpmInput = h('input', { type: 'text', inputmode: 'decimal', className: 'form-control metronome-input', 'data-metronome-bpm-input': 'true', autocomplete: 'off', value: (model.bpmTenths / 10).toFixed(1) });
        var bpmApply = h('button', { type: 'button', className: 'btn btn-outline-primary', 'data-metronome-bpm-apply': 'true', text: '適用' });
        var bpmError = h('p', { className: 'metronome-error', role: 'alert', 'data-metronome-bpm-error': 'true', hidden: true });
        var meter = select({ 'data-metronome-meter-preset': 'true' }, [{ value: 'custom', label: '（拍子・リズム画面で設定）' }].concat(METER_PRESETS), model.meterPreset || 'custom');
        var beat = h('div', { className: 'metronome-beat', 'data-metronome-beat': 'true', 'aria-hidden': 'true' });
        var pendulum = h('div', { className: 'metronome-pendulum', 'data-metronome-pendulum': 'true', 'aria-hidden': 'true' }, [h('span', { className: 'metronome-pendulum-bob' })]);
        var volume = h('input', { type: 'range', className: 'form-range', min: '0', max: '100', step: '1', value: String(Math.round(model.volume * 100)), 'data-metronome-volume': 'true' });
        var volumeValue = h('span', { 'data-metronome-volume-value': 'true', text: Math.round(model.volume * 100) + '%' });
        var countIn = select({ 'data-metronome-count-in': 'true' }, [0, 1, 2, 4].map(function (n) { return { value: n, label: n ? n + '小節' : 'なし' }; }), model.countInBars);
        var tap = h('button', { type: 'button', className: 'btn btn-outline-secondary metronome-tap', 'data-metronome-tap': 'true', text: 'TAP' });
        var tapResult = h('p', { className: 'metronome-hint', 'data-metronome-tap-result': 'true', 'aria-live': 'polite', text: '4分音符などの拍で5回以上たたいてください' });
        var tapApply = h('button', { type: 'button', className: 'btn btn-outline-primary', 'data-metronome-tap-apply': 'true', disabled: true, text: 'このテンポにする' });
        var tapReset = h('button', { type: 'button', className: 'btn btn-outline-secondary', 'data-metronome-tap-reset': 'true', text: 'やり直す' });
        var timer = select({ 'data-metronome-timer': 'true' }, [0, 5, 10, 15, 30, 60].map(function (n) { return { value: n, label: n ? n + '分で停止' : 'なし' }; }), model.timerMinutes);
        var timerLeft = h('span', { className: 'metronome-hint', 'data-metronome-timer-left': 'true' });

        panel.appendChild(h('div', { className: 'metronome-tempo' }, [h('div', { className: 'metronome-bpm-line' }, [ref, bpm]), stepButtons]));
        panel.appendChild(h('div', { className: 'metronome-inline' }, [field('テンポ（20.0～300.0、0.1刻み）', bpmInput), bpmApply]));
        panel.appendChild(bpmError);
        panel.appendChild(pendulum);
        panel.appendChild(beat);
        panel.appendChild(field('拍子', meter, '6/8・7/8などの拍の取り方は「拍子・リズム」で細かく変えられます。'));
        panel.appendChild(h('div', { className: 'metronome-field' }, [h('label', { for: 'metronomeVolume', text: '音量 ' }, [volumeValue]), volume]));
        volume.id = 'metronomeVolume';
        panel.appendChild(field('カウントイン', countIn));
        panel.appendChild(h('div', { className: 'metronome-tap-row' }, [tap, tapApply, tapReset]));
        panel.appendChild(tapResult);
        panel.appendChild(h('div', { className: 'metronome-inline' }, [field('練習タイマー（再生している時間で数えます）', timer), timerLeft]));

        panel.addEventListener('click', function (e) {
            var step = e.target.closest('[data-metronome-bpm-step]');
            if (step) handlers.onBpmStep(Number(step.getAttribute('data-metronome-bpm-step')));
            if (e.target.closest('[data-metronome-bpm-apply]')) handlers.onBpmInput(bpmInput.value);
            if (e.target.closest('[data-metronome-tap-apply]')) handlers.onTapApply();
            if (e.target.closest('[data-metronome-tap-reset]')) handlers.onTapReset();
        });
        bpmInput.addEventListener('keydown', function (e) { if (e.key === 'Enter') handlers.onBpmInput(bpmInput.value); });
        // TAP uses pointerdown timestamps (closest to the physical touch).
        tap.addEventListener('pointerdown', function (e) {
            if (e.isPrimary === false) return;
            handlers.onTap(e.timeStamp);
        });
        tap.addEventListener('keydown', function (e) { if (e.key === ' ' || e.key === 'Enter') { e.preventDefault(); handlers.onTap(e.timeStamp); } });
        meter.addEventListener('change', function () { handlers.onMeterPreset(meter.value); });
        volume.addEventListener('input', function () { volumeValue.textContent = volume.value + '%'; handlers.onVolume(Number(volume.value) / 100); });
        countIn.addEventListener('change', function () { handlers.onCountIn(Number(countIn.value)); });
        timer.addEventListener('change', function () { handlers.onTimer(Number(timer.value)); });

        return {
            setBpm: function (tenths, reference) {
                bpm.textContent = (tenths / 10).toFixed(1);
                ref.textContent = noteLabel(reference) + ' =';
                if (globalObj.document.activeElement !== bpmInput) bpmInput.value = (tenths / 10).toFixed(1);
            },
            // Tempo guessing: no digits of the hidden tempo in the DOM.
            concealBpm: function () {
                bpm.textContent = '？';
                bpmInput.value = '';
            },
            setBpmError: function (text) { bpmError.hidden = !text; bpmError.textContent = text || ''; },
            setTap: function (est) {
                if (est.bpm === null) {
                    tapResult.textContent = '有効なタップ間隔 ' + est.valid + ' ／ 必要 ' + est.needed;
                    tapApply.disabled = true;
                } else {
                    tapResult.textContent = '推定 ' + est.bpm.toFixed(1) + '（有効な間隔 ' + est.valid + (est.excluded ? '、外れ値 ' + est.excluded : '') + '）';
                    tapApply.disabled = false;
                }
            },
            setMeterPreset: function (value) { meter.value = value; },
            setTimerLeft: function (text) { timerLeft.textContent = text || ''; },
            beat: beat,
            pendulum: pendulum,
        };
    }

