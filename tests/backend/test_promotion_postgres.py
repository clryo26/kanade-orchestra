def test_concurrent_creates_and_replays_use_database_ids(promotion_pg):
    key = str(uuid4())
    def create(operation_id):
        return asyncio.run(service.mutate("POST", None, {"title": "Concurrent"}, ADMIN, operation_id))
    with ThreadPoolExecutor(max_workers=4) as executor:
        results = list(executor.map(create, [str(uuid4()) for _ in range(4)]))
    assert all(status == 200 for status, _ in results)
    assert len({body["id"] for _, body in results}) == 4
    with ThreadPoolExecutor(max_workers=2) as executor:
        list(executor.map(create, [key, key]))
    assert create(key)[0] == 200
    assert len(repo.list_items()) == 5


def test_concurrent_revision_and_expired_attempt(promotion_pg):
    _, body = asyncio.run(service.mutate("POST", None, {"title": "Initial"}, ADMIN, str(uuid4())))
    def update(title):
        return asyncio.run(service.mutate("PUT", body["id"], {"title": title, "expected_revision": 1}, ADMIN, str(uuid4())))
    with ThreadPoolExecutor(max_workers=2) as executor:
        outcomes = list(executor.map(update, ["First", "Second"]))
    assert sorted(status for status, _ in outcomes) == [200, 409]
    key = str(uuid4())
    op, _, _ = repo.reserve("actor", key, "POST", None, "a" * 64)
    with repo.transaction() as cur:
        cur.execute("UPDATE promotion_operations SET lease_until=clock_timestamp() WHERE operation_id=%s", (key,))
    new, claimed, _ = repo.reserve("actor", key, "POST", None, "a" * 64)
    assert claimed
    with repo.transaction() as cur:
        repo.finish(cur, new, 200, {"id": body["id"]})
    with pytest.raises(repo.LostAttempt):
        with repo.transaction() as cur:
            repo.finish(cur, op, 409, {"detail": "old attempt"})
    with pytest.raises(repo.LostAttempt):
        repo.release(op)
    assert service.current_result("actor", key)[0] == 200


def test_member_multipart_image_create_and_replay(promotion_pg, monkeypatch):
    # Existing PG tests used only the hidden administrator and no images.
    # Exercise member incarnation lookup and the image transaction on PostgreSQL.
    with repo.transaction() as cur:
        cur.execute("CREATE TABLE members (id BIGINT, organization_id TEXT, created_at TIMESTAMPTZ)")
        cur.execute("INSERT INTO members VALUES (1, 'default', clock_timestamp())")
    monkeypatch.setattr(service.images, "upload", lambda *args: 1)
    member = {"permission": "一般", "member_id": 1, "member_name": "Test"}
    key = str(uuid4())

    def create():
        file = UploadFile(io.BytesIO(b"\x89PNG\r\n\x1a\nimage"), filename="test.png",
                          headers=Headers({"content-type": "image/png"}))
        return asyncio.run(service.mutate("POST", None, {"title": "Image", "image_action": "replace",
                                                        "image_url_file": file}, member, key))

    status, body = create()
    assert status == 200, body
    assert "?asset=" in body["image_url"]
    assert create() == (status, body)
    assert len(repo.list_items()) == 1
