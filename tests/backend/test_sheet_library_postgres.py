def test_migration_runner_applies_001_through_021_and_repeats_safely():
    """Run the actual release runner against a new DB with legacy base tables.

    A separate database keeps public-schema trigger checks faithful to release
    behaviour and never changes the caller's existing tables or migration log.
    """
    dsn = os.environ.get("SHEET_TEST_DB_URL")
    if not dsn:
        pytest.skip("Set SHEET_TEST_DB_URL to an isolated PostgreSQL test instance")
    from src.backend.core.db_runtime import ensure_db_schema_compatibility

    name = "sheet_migrate_" + uuid4().hex
    with psycopg.connect(dsn, autocommit=True) as conn:
        conn.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(name)))
    try:
        isolated = make_conninfo(dsn, dbname=name)
        with psycopg.connect(isolated) as conn:
            ensure_db_schema_compatibility(conn)
            conn.execute("INSERT INTO performances (id,title) VALUES (1,'Kept concert')")
            conn.execute("INSERT INTO sheet_library (id,performance_id,name,source,path) VALUES "
                         "(41,1,'kept.pdf','local','sheets/kept.pdf')")
        env = {**os.environ, "DB_URL": isolated, "PYTHONUTF8": "1"}
        for _ in range(2):
            result = subprocess.run([sys.executable, "scripts/migrate_db.py"], env=env, capture_output=True,
                                    text=True, encoding="utf-8", timeout=120)
            assert result.returncode == 0, result.stdout + result.stderr
        with psycopg.connect(isolated) as conn:
            versions = conn.execute("SELECT version FROM schema_migrations ORDER BY version").fetchall()
            assert versions == [(f"{n:03d}",) for n in range(1, 22)]
            assert conn.execute("SELECT id,name,path FROM sheet_library").fetchall() == [(41, "kept.pdf", "sheets/kept.pdf")]
            assert conn.execute("SELECT COUNT(*) FROM sheet_files WHERE legacy").fetchone() == (1,)
            assert conn.execute("SELECT progress FROM sheet_zip_jobs").fetchall() == []
            assert conn.execute("SELECT count(*) FROM pg_trigger WHERE tgname IN "
                                "('trg_tuner_members_owner_guard_delete','trg_tuner_members_owner_guard_insert')").fetchone() == (2,)
    finally:
        assert name.startswith("sheet_migrate_") and len(name) == 46
        with psycopg.connect(dsn, autocommit=True) as conn:
            conn.execute(sql.SQL("DROP DATABASE {} WITH (FORCE)").format(sql.Identifier(name)))

