def test_cleanup_dry_run_is_read_only_in_postgres_and_keeps_shared_files(sheet_pg):
    removed = sheet_pg.request("DELETE", "/api/sheets", headers={**ADMIN, "Idempotency-Key": str(uuid4())},
                               json={"items": [{"id": 5, "expected_revision": 1}]})
    assert removed.status_code == 200
    query = "SELECT file_id,state,last_checked_at,next_attempt_at FROM sheet_files ORDER BY file_id"
    before = q(sheet_pg, query)
    # PostgreSQL read-only transactions reject any accidental UPDATE here.
    first = cleanup.run(execute=False)
    second = cleanup.run(execute=False)
    assert first == second
    assert first["files"][0]["kept"] == "referenced"
    assert q(sheet_pg, query) == before
    assert (sheet_pg.uploads / "sheets/1_Concert/Sym/old.pdf").exists()


def test_cleanup_does_not_abandon_a_job_resumed_after_candidate_selection(sheet_pg, monkeypatch):
    from src.backend.services import sheet_zip_service as zips

    job = sheet_pg.post("/api/sheets/zip-jobs", headers=ADMIN,
                        json={"performance_id": "1", "piece": "Sym"}).json()
    job_id = job["job_id"]
    q(sheet_pg, "UPDATE sheet_zip_jobs SET updated_at='2000-01-01T00:00:00+00:00' WHERE job_id=%s", (job_id,))
    original = repo.transaction
    resumed = []
    deleted = []

    class Cursor:
        def __init__(self, cursor):
            self.cursor = cursor

        def __getattr__(self, name):
            return getattr(self.cursor, name)

        def execute(self, statement, params=()):
            # Two real PG connections: selection saw an abandoned job, but
            # another request commits a live claim before cleanup updates it.
            if "SET state='failed',error_code='abandoned'" in statement and not resumed:
                resumed.append(True)
                claimed, _ = zips._claim(job_id, "system:hidden-admin:v1")
                assert claimed is not None
            return self.cursor.execute(statement, params)

    @contextmanager
    def racing_transaction(*args, **kwargs):
        with original(*args, **kwargs) as cursor:
            yield Cursor(cursor)

    monkeypatch.setattr(repo, "transaction", racing_transaction)
    monkeypatch.setattr(cleanup, "_delete_job_objects", lambda value: deleted.append(value["job_id"]) or True)
    report = cleanup.cleanup_jobs(execute=True)
    assert resumed and report == [] and deleted == []
    assert q(sheet_pg, "SELECT state,error_code FROM sheet_zip_jobs WHERE job_id=%s", (job_id,)) == [("building", None)]
    assert q(sheet_pg, "SELECT COUNT(*) FROM sheet_file_leases WHERE holder=%s AND expires_at>clock_timestamp()",
             (f"zip:{job_id}",)) == [(job["file_count"],)]


def q(client, query, params=()):
    with psycopg.connect(client.scoped, autocommit=True) as conn:
        cursor = conn.execute(query, params)
        return cursor.fetchall() if cursor.description else []


