def test_zip_job_on_postgres_is_built_in_steps_and_verified(sheet_pg):
    upload(sheet_pg, "z1.pdf")
    upload(sheet_pg, "z2.pdf")
    job = sheet_pg.post("/api/sheets/zip-jobs", headers=ADMIN, json={"performance_id": "1", "piece": "Sym"}).json()
    leased = q(sheet_pg, "SELECT COUNT(*) FROM sheet_file_leases WHERE holder=%s", (f"zip:{job['job_id']}",))
    assert leased == [(job["file_count"],)]
    for _ in range(20):
        if job["state"] != "building":
            break
        job = sheet_pg.post(f"/api/sheets/zip-jobs/{job['job_id']}/step", headers=ADMIN).json()
    assert job["state"] == "ready", job
    assert q(sheet_pg, "SELECT COUNT(*) FROM sheet_file_leases WHERE holder=%s", (f"zip:{job['job_id']}",)) == [(0,)]
    response = sheet_pg.get(f"/api/sheets/zip-jobs/{job['job_id']}/download", headers=ADMIN)
    import io
    import zipfile
    with zipfile.ZipFile(io.BytesIO(response.content)) as archive:
        assert archive.testzip() is None
        assert sorted(archive.namelist()) == ["Sym/old.pdf", "Sym/old_2.pdf", "Sym/z1.pdf", "Sym/z2.pdf"]


def test_rows_without_file_records_after_a_db_sync_still_zip_and_delete(sheet_pg):
    # The prod->test sync copies sheet_library but not sheet_files; an older
    # app version may also write a row without a file ID after a rollback.
    q(sheet_pg, "DELETE FROM sheet_files")
    q(sheet_pg, "UPDATE sheet_library SET file_id=NULL WHERE id=6")
    job = sheet_pg.post("/api/sheets/zip-jobs", headers=ADMIN, json={"performance_id": "1", "piece": "Sym"})
    assert job.status_code == 200, job.text
    assert q(sheet_pg, "SELECT COUNT(*) FROM sheet_files WHERE legacy AND sheet_id IN (5,6)") == [(2,)]
    assert q(sheet_pg, "SELECT file_id IS NOT NULL FROM sheet_library WHERE id=6") == [(True,)]
    sheet_pg.post(f"/api/sheets/zip-jobs/{job.json()['job_id']}/cancel", headers=ADMIN)
    removed = sheet_pg.request("DELETE", "/api/sheets", headers={**ADMIN, "Idempotency-Key": str(uuid4())},
                               json={"items": [{"id": 5, "expected_revision": 1}]})
    assert removed.status_code == 200, removed.text
    # Row 6 still refers to the same object: it is kept.
    from datetime import timedelta
    original = cleanup.RETIRED_GRACE
    cleanup.RETIRED_GRACE = timedelta(0)
    try:
        report = cleanup.cleanup_files(execute=True)
    finally:
        cleanup.RETIRED_GRACE = original
    assert [r.get("kept") for r in report] == ["referenced"]


def test_zip_steps_have_one_owner_and_continue_without_waiting_for_the_claim(sheet_pg, monkeypatch):
    import time as real_time
    from src.backend.services import sheet_storage_service as storage
    from src.backend.services import sheet_zip_service as zips
    upload(sheet_pg, "z1.pdf")
    upload(sheet_pg, "z2.pdf")
    job = sheet_pg.post("/api/sheets/zip-jobs", headers=ADMIN, json={"performance_id": "1", "piece": "Sym", "scope": "piece"}).json()
    original = storage.read_range

    def slow_read(*args, **kwargs):
        real_time.sleep(0.4)  # keeps a step running while the second request arrives
        return original(*args, **kwargs)

    monkeypatch.setattr(storage, "read_range", slow_read)
    monkeypatch.setattr(zips, "STEP_BUDGET_SECONDS", 0.0)  # one chunk per step
    with ThreadPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(lambda _: sheet_pg.post(f"/api/sheets/zip-jobs/{job['job_id']}/step", headers=ADMIN).json(), range(2)))
    assert sorted(bool(r.get("busy")) for r in results) == [False, True]
    started = real_time.monotonic()
    steps = 0
    state = results[0]
    while state["state"] == "building":
        state = sheet_pg.post(f"/api/sheets/zip-jobs/{job['job_id']}/step", headers=ADMIN).json()
        assert not state.get("busy")  # each finished step gave its claim back
        steps += 1
    assert state["state"] == "ready" and steps >= 3
    assert real_time.monotonic() - started < 30  # far less than the 240 s claim
    assert q(sheet_pg, "SELECT attempt_id, lease_until FROM sheet_zip_jobs WHERE job_id=%s", (job["job_id"],)) == [(None, None)]
