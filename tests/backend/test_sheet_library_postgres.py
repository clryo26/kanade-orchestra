def test_migration_keeps_rows_and_urls_and_backfills_file_identities(sheet_pg):
    rows = q(sheet_pg, "SELECT id, file_id, revision, path, object_name FROM sheet_library ORDER BY id")
    assert [r[0] for r in rows] == [5, 6, 9]
    assert all(r[1] is not None for r in rows) and len({r[1] for r in rows}) == 3
    assert {r[2] for r in rows} == {1}
    files = q(sheet_pg, "SELECT sheet_id, legacy, state, object_name FROM sheet_files ORDER BY sheet_id")
    assert files == [(5, True, "active", "sheets/1_Concert/Sym/old.pdf"), (6, True, "active", "sheets/1_Concert/Sym/old.pdf"),
                     (9, True, "active", "sheets/1_Concert/Ov/gcs.pdf")]
    assert q(sheet_pg, "SELECT list_version FROM sheet_library_state") == [(1,)]
    listed = sheet_pg.get("/api/sheets", headers=ADMIN).json()
    urls = {f["id"]: f["view_url"] for f in listed["files"]}
    assert urls[5] == "/api/sheets/view/sheets/1_Concert/Sym/old.pdf"
    assert urls[9] == "/api/sheets/cloud/view/sheets/1_Concert/Ov/gcs.pdf"
    # New IDs come from the database and never collide with old explicit IDs.
    created = upload(sheet_pg, "new.pdf").json()["file"]
    assert created["id"] > 9


def test_concurrent_uploads_get_distinct_ids_and_one_version_each(sheet_pg):
    with ThreadPoolExecutor(max_workers=6) as pool:
        results = list(pool.map(lambda i: upload(sheet_pg, f"c{i}.pdf"), range(6)))
    assert [r.status_code for r in results] == [200] * 6
    ids = {r.json()["file"]["id"] for r in results}
    versions = sorted(r.json()["list_version"] for r in results)
    assert len(ids) == 6
    assert versions == list(range(2, 8))
    listed = sheet_pg.get("/api/sheets", headers=ADMIN).json()
    assert listed["list_version"] == 7 and len(listed["files"]) == 9


