"""Generate the reviewed additive migration from existing schema constants."""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

# Existing core.__init__ exports the app factory; retain the main.py import
# order without executing a lifespan or opening any database connection.
from src.backend import app_core as _compat  # noqa: E402,F401
from src.backend.core.collection_clock_schema import CLOCK_COLLECTIONS, MAINTENANCE_ROLE, table_dependencies  # noqa: E402
from src.backend.core.db_schema import DB_CHILD_PARENT_KEYS, DB_CHILD_TABLES, JSON_COLLECTION_TABLES  # noqa: E402

TARGET = ROOT / "db/migrations/023_portal_collection_versions.sql"


def render() -> str:
    tables = table_dependencies()
    table_list = ", ".join("public." + name for name in tables)
    names = ",".join("'" + name + "'" for name in tables)
    collections = ",".join("('" + name + "')" for name in CLOCK_COLLECTIONS)
    initial_orgs = "SELECT 'default'::text AS organization_id UNION " + " UNION ".join(
        "SELECT organization_id FROM public." + name for name in tables)
    checks = []
    child_rules = []
    for collection, children in DB_CHILD_TABLES.items():
        if collection not in CLOCK_COLLECTIONS:
            continue
        parent = JSON_COLLECTION_TABLES[collection]
        for child in children:
            key = DB_CHILD_PARENT_KEYS[child]
            checks.append(f"""
  IF EXISTS (SELECT 1 FROM public.{child} c LEFT JOIN public.{parent} p ON p.id=c.{key}
             WHERE p.id IS NULL OR p.organization_id IS DISTINCT FROM c.organization_id) THEN
    RAISE EXCEPTION 'Child organization mismatch: {child}';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.contype='f' AND k.convalidated
       AND k.conrelid='public.{child}'::regclass AND k.confrelid='public.{parent}'::regclass
       AND array_position(k.conkey,(SELECT attnum FROM pg_attribute WHERE attrelid=k.conrelid AND attname='{key}'))
         = array_position(k.confkey,(SELECT attnum FROM pg_attribute WHERE attrelid=k.confrelid AND attname='id'))) THEN
    RAISE EXCEPTION 'Validated child foreign key required: {child}';
  END IF;""")
            child_rules.append(f"""
  IF TG_TABLE_NAME='{child}' AND TG_OP IN ('INSERT','UPDATE') THEN
    IF EXISTS (SELECT 1 FROM new_rows c LEFT JOIN public.{parent} p ON p.id=c.{key}
               WHERE p.id IS NULL OR p.organization_id IS DISTINCT FROM c.organization_id) THEN
      RAISE EXCEPTION 'Child organization mismatch';
    END IF;
  END IF;
  IF TG_TABLE_NAME='{parent}' AND TG_OP='UPDATE' THEN
    IF EXISTS (SELECT 1 FROM new_rows p JOIN public.{child} c ON p.id=c.{key}
               WHERE p.organization_id IS DISTINCT FROM c.organization_id) THEN
      RAISE EXCEPTION 'Parent organization mismatch';
    END IF;
  END IF;""")
    # Separate event triggers are required for transition relations. No role is
    # created/granted here: the independent operations-role migration is a gate.
    body = f"""-- Generated by scripts/generate_collection_clock_migration.py; do not hand edit.
-- PERF-R04. Apply only after backup and writer drain with a separate DDL owner.
SET LOCAL lock_timeout = '5s';
LOCK TABLE {table_list} IN SHARE ROW EXCLUSIVE MODE;
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[{names}] LOOP
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public'
       AND table_name=t AND column_name='organization_id' AND is_nullable='NO') THEN
      RAISE EXCEPTION 'Non-null organization column required: %', t;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_index WHERE indrelid=format('public.%I',t)::regclass AND indisprimary) THEN
      RAISE EXCEPTION 'Primary key required: %', t;
    END IF;
  END LOOP;
{''.join(checks)}
END $$;
CREATE TABLE public.portal_data_generation (
  singleton smallint PRIMARY KEY CHECK(singleton=1), generation uuid NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE TABLE public.portal_collection_versions (
  organization_id text NOT NULL, collection_name text NOT NULL,
  version bigint NOT NULL CHECK(version>0), updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY(organization_id,collection_name)
);
INSERT INTO public.portal_data_generation(singleton,generation) VALUES(1,gen_random_uuid());
INSERT INTO public.portal_collection_versions(organization_id,collection_name,version)
SELECT org.organization_id, names.name, 1 FROM ({initial_orgs}) org
CROSS JOIN (VALUES {collections}) names(name);
REVOKE ALL ON public.portal_data_generation, public.portal_collection_versions FROM PUBLIC;

CREATE FUNCTION public.portal_clock_maintenance_allowed() RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=pg_catalog,public AS $$
  SELECT EXISTS (SELECT 1 FROM pg_catalog.pg_roles r WHERE r.rolname='{MAINTENANCE_ROLE}'
                 AND pg_catalog.pg_has_role(session_user,r.oid,'MEMBER'))
$$;
REVOKE ALL ON FUNCTION public.portal_clock_maintenance_allowed() FROM PUBLIC;

CREATE FUNCTION public.portal_clock_bump() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
BEGIN
  IF current_setting('app.portal_sync_mode',true)='on' AND public.portal_clock_maintenance_allowed() THEN
    RETURN NULL;
  END IF;
{''.join(child_rules)}
  IF TG_OP='INSERT' THEN
    INSERT INTO public.portal_collection_versions AS clocks(organization_id,collection_name,version)
    SELECT DISTINCT organization_id,TG_ARGV[0],1 FROM new_rows ORDER BY organization_id
    ON CONFLICT(organization_id,collection_name) DO UPDATE
      SET version=clocks.version+1, updated_at=clock_timestamp();
  ELSIF TG_OP='DELETE' THEN
    INSERT INTO public.portal_collection_versions AS clocks(organization_id,collection_name,version)
    SELECT DISTINCT organization_id,TG_ARGV[0],1 FROM old_rows ORDER BY organization_id
    ON CONFLICT(organization_id,collection_name) DO UPDATE
      SET version=clocks.version+1, updated_at=clock_timestamp();
  ELSE
    INSERT INTO public.portal_collection_versions AS clocks(organization_id,collection_name,version)
    SELECT organization_id,TG_ARGV[0],1 FROM
      (SELECT organization_id FROM old_rows UNION SELECT organization_id FROM new_rows) org
    ORDER BY organization_id
    ON CONFLICT(organization_id,collection_name) DO UPDATE
      SET version=clocks.version+1, updated_at=clock_timestamp();
  END IF;
  RETURN NULL;
END $$;
REVOKE ALL ON FUNCTION public.portal_clock_bump() FROM PUBLIC;

CREATE FUNCTION public.portal_clock_truncate() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
BEGIN
  IF NOT public.portal_clock_maintenance_allowed() THEN
    RAISE EXCEPTION 'TRUNCATE requires the independent maintenance role' USING ERRCODE='42501';
  END IF;
  UPDATE public.portal_collection_versions SET version=version+1,updated_at=clock_timestamp();
  UPDATE public.portal_data_generation SET generation=gen_random_uuid(),updated_at=clock_timestamp();
  RETURN NULL;
END $$;
REVOKE ALL ON FUNCTION public.portal_clock_truncate() FROM PUBLIC;
"""
    for table, collection in tables.items():
        for event, relations in (("insert", "NEW TABLE AS new_rows"), ("delete", "OLD TABLE AS old_rows"),
                                 ("update", "OLD TABLE AS old_rows NEW TABLE AS new_rows")):
            body += (f"CREATE TRIGGER portal_clock_{event} AFTER {event.upper()} ON public.{table}\n"
                     f"REFERENCING {relations} FOR EACH STATEMENT EXECUTE FUNCTION public.portal_clock_bump('{collection}');\n")
        body += (f"CREATE TRIGGER portal_clock_truncate BEFORE TRUNCATE ON public.{table}\n"
                 "FOR EACH STATEMENT EXECUTE FUNCTION public.portal_clock_truncate();\n")
    return body


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            raise SystemExit("Collection-clock migration differs from schema constants")
    else:
        TARGET.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
