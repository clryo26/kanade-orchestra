CREATE TABLE IF NOT EXISTS cache_invalidation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cache_key TEXT NOT NULL,
    reason TEXT DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_cache_invalidation_events_created_at ON cache_invalidation_events(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_cache_invalidation_events_cache_key ON cache_invalidation_events(cache_key);
